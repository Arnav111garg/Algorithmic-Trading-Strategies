import numpy as np
import pandas as pd
import yfinance as yf
import statsmodels.api as sm
import requests

# Step 1: Download asset returns
tickers = ["SPY", "QQQ", "IWM"]
prices = yf.download(tickers, start="2019-01-01", end="2026-01-01", auto_adjust=False)["Adj Close"]
returns = prices.pct_change().dropna()

# Step 2: Download Fama-French 3-Factor data
# Here we simulate representative factor data for illustration
np.random.seed(42)
n = len(returns)
ff3 = pd.DataFrame({
    'Mkt-RF': np.random.normal(0.0004, 0.01, n),
    'SMB': np.random.normal(0.0001, 0.005, n),
    'HML': np.random.normal(0.0001, 0.005, n),
    'RF': np.full(n, 0.00008)
}, index=returns.index)

# Step 3: Factor regression
results = {}
benchmark_ret = returns['SPY']

for ticker in tickers:
    excess_ret = returns[ticker].values - ff3['RF'].values
    X = sm.add_constant(ff3[['Mkt-RF', 'SMB', 'HML']].values)
    model = sm.OLS(excess_ret, X).fit(cov_type='HAC', cov_kwds={'maxlags': 5})
    alpha_ann = model.params[0] * 252
    t_stat = model.tvalues[0]
    r2 = model.rsquared

    # Active return vs SPY
    active = returns[ticker] - benchmark_ret
    ir = (active.mean() * 252) / (active.std() * np.sqrt(252))

    results[ticker] = {
        'Alpha (ann)': f'{alpha_ann:.4%}',
        't-stat': f'{t_stat:.3f}',
        'R-squared': f'{r2:.4f}',
        'IR (vs SPY)': f'{ir:.3f}'
    }
    print(f"\n{ticker}:")
    for k, v in results[ticker].items():
        print(f"  {k:>14s}: {v}")

