import numpy as np
import pandas as pd
from scipy import stats

def compute_ic(signal_df: pd.DataFrame, forward_returns: pd.DataFrame, holding_period: int = 5) -> pd.Series:
    """
    Compute daily cross-sectional Information Coefficient.
    Parameters
    ----------
    signal_df : pd.DataFrame, shape (dates x assets), signal values
    forward_returns : pd.DataFrame, shape (dates x assets), raw returns
    holding_period : int, forward return horizon in days

    Returns
    -------
    ic_series : pd.Series of daily IC values
    """
    fwd_ret = forward_returns.shift(-holding_period) # forward-looking

    ic_series = {}
    for date in signal_df.index:
        if date not in fwd_ret.index:
            continue
        s = signal_df.loc[date].dropna()
        r = fwd_ret.loc[date].dropna()
        common = s.index.intersection(r.index)
        if len(common) < 20:
            continue
        ic, _ = stats.spearmanr(s[common], r[common])
        ic_series[date] = ic

    return pd.Series(ic_series)


def signal_report(signal_df, forward_returns, holding_period=5, name="Signal"):
    """Full signal diagnostic report."""
    ic = compute_ic(signal_df, forward_returns, holding_period)

    # Core metrics
    mean_ic = ic.mean()
    std_ic = ic.std()
    icir = mean_ic / std_ic if std_ic > 0 else np.nan
    t_stat = mean_ic / (std_ic / np.sqrt(len(ic)))
    pct_pos = (ic > 0).mean()

    print(f"\n{'='*50}")
    print(f" Signal Report : {name} (Horizon ={holding_period}d)")
    print(f"{'='*50}")
    print(f" Mean IC : {mean_ic:.4f} ({'** GOOD **' if abs(mean_ic) > 0.03 else 'weak'})")
    print(f" IC Std : {std_ic:.4f}")
    print(f" ICIR : {icir:.4f} ({'** GOOD **' if abs(icir) > 0.5 else 'unstable'})")
    print(f" t-stat : {t_stat:.3f} ({'** SIG **' if abs(t_stat) > 2.0 else 'not sig'})")
    print(f" % Positive : {pct_pos:.1%}")
    print(f"{'='*50}")

    return ic

def neutralize_signal(signal_df, sector_df=None):
    """
    Winsorize, standardize, and optionally sector-neutralize a signal.

    Parameters
    ----------
    signal_df : pd.DataFrame (dates x assets)
    sector_df : pd.DataFrame (dates x assets) with sector labels
    """
    result = signal_df.copy()

    for date in result.index:
        row = result.loc[date].dropna()
        if len(row) < 5:
            continue

        # 1. Winsorize at 1% / 99%
        lo, hi = row.quantile(0.01), row.quantile(0.99)
        row = row.clip(lo, hi)

        # 2. Sector-neutralize (demean within sector)
        if sector_df is not None and date in sector_df.index:
            sec = sector_df.loc[date]
            common = row.index.intersection(sec.index)
            for s in sec[common].unique():
                mask = sec[common] == s
                row[common[mask]] -= row[common[mask]].mean()

        # 3. Cross-sectionally standardize (z-score)
        mu, sigma = row.mean(), row.std()
        if sigma > 1e-8:
            row = (row - mu) / sigma

        result.loc[date, row.index] = row

    return result

