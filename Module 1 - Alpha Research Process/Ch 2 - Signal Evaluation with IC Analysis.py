np.random.seed(42)
dates = pd.date_range('2020-01-02', '2023-12-29', freq='B')
assets = [f'A{i:03d}' for i in range(100)]

# True IC ~0.04 (modest)
true_ic = 0.04
signal = pd.DataFrame(np.random.randn(len(dates), len(assets)), index=dates, columns=assets)
noise = pd.DataFrame(np.random.randn(len(dates), len(assets)), index=dates, columns=assets)
fwd_ret = true_ic * signal + np.sqrt(1 - true_ic**2) * noise

ic_series = signal_report(signal, fwd_ret, holding_period=5, name="Synthetic Momentum")
print(f"\n Rolling 63-day ICIR: {ic_series.rolling(63).mean().div(ic_series.rolling(63).std()).mean():.3f}")

