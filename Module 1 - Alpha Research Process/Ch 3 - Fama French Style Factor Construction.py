import numpy as np
import pandas as pd

def construct_factor(signal: pd.DataFrame,
                     returns: pd.DataFrame,
                     n_quantiles: int = 5,
                     sector: pd.DataFrame = None,
                     mktcap: pd.DataFrame = None,
                     value_weighted: bool = True) -> dict:
    """
    Construct a long-short factor portfolio from a cross-sectional signal.

    Parameters
    ----------
    signal : (dates x assets) signal DataFrame
    returns : (dates x assets) next-period returns
    n_quantiles : number of quantile buckets (default 5 = quintiles)
    sector : (dates x assets) sector codes for neutralization
    mktcap : (dates x assets) market caps for value-weighting
    value_weighted : use market-cap weights within each leg

    Returns
    -------
    dict with factor returns, quantile returns, IC series, Sharpe
    """
    fwd_ret = returns.shift(-1) # next period return
    long_leg_q = n_quantiles # top quintile
    short_leg_q = 1 # bottom quintile

    factor_returns = []
    quantile_ret = {q: [] for q in range(1, n_quantiles + 1)}
    dates_out = []

    for date in signal.index:
        s = signal.loc[date].dropna()
        r = fwd_ret.loc[date].dropna() if date in fwd_ret.index else pd.Series(dtype=float)
        common = s.index.intersection(r.index)

        if len(common) < n_quantiles * 5:
            continue

        s_c = s[common]
        r_c = r[common]

        # Sector-neutralize: rank within sector
        if sector is not None and date in sector.index:
            sec = sector.loc[date][common]
            ranks = pd.Series(dtype=float, index=common)
            for sec_name in sec.dropna().unique():
                mask = sec == sec_name
                sub = s_c[mask[common]]
                if len(sub) > 2:
                    ranks[sub.index] = sub.rank(pct=True)
            s_c = ranks.dropna()
            r_c = r_c[s_c.index]
            common = s_c.index

        # Quantile assignment
        q_labels = pd.qcut(s_c, n_quantiles, labels=False, duplicates='drop') + 1

        for q in range(1, n_quantiles + 1):
            idx_q = q_labels[q_labels == q].index
            if len(idx_q) == 0:
                quantile_ret[q].append(np.nan)
                continue
            if value_weighted and mktcap is not None and date in mktcap.index:
                mc = mktcap.loc[date][idx_q].clip(lower=1e6)
                wts = mc / mc.sum()
                q_r = (r_c[idx_q] * wts).sum()
            else:
                q_r = r_c[idx_q].mean()
            quantile_ret[q].append(q_r)

        # Factor return = long top - short bottom
        long_r = quantile_ret[long_leg_q][-1]
        short_r = quantile_ret[short_leg_q][-1]
        factor_returns.append(long_r - short_r if not (np.isnan(long_r) or np.isnan(short_r)) else np.nan)
        dates_out.append(date)

    factor_ret_s = pd.Series(factor_returns, index=dates_out)
    ann_ret = factor_ret_s.mean() * 252
    ann_vol = factor_ret_s.std() * np.sqrt(252)
    sharpe = ann_ret / ann_vol if ann_vol > 0 else np.nan
    max_dd = (factor_ret_s.cumsum() - factor_ret_s.cumsum().cummax()).min()

    print(f"\n Factor Statistics ")
    print(f" Annualized Return : {ann_ret:.2%} ")
    print(f" Annualized Vol : {ann_vol:.2%} ")
    print(f" Sharpe Ratio : {sharpe:.3f}")
    print(f" Max Drawdown : {max_dd:.2%} ")

    return {
        'factor_returns': factor_ret_s,
        'quantile_returns': {q: pd.Series(v, index=dates_out) for q, v in quantile_ret.items()},
        'sharpe': sharpe,
        'ann_ret': ann_ret,
        'ann_vol': ann_vol,
        'max_drawdown': max_dd
    }

