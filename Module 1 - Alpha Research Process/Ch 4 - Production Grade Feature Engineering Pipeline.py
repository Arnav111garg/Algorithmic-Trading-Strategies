import numpy as np
import pandas as pd
from typing import List, Optional, Dict

class QuantFeatureEngine:
    """
    Production-grade feature engineering pipeline for quant signals.

    Implements:
    - Price momentum at multiple lookbacks
    - Volatility features (realized, Parkinson, vol-of-vol)
    - Mean reversion features
    - Volume features
    - Cross-sectional normalization
    """

    LOOKBACKS = [5, 10, 21, 63, 126, 252] # days: 1W, 2W, 1M, 3M, 6M, 1Y

    def __init__(self, winsor_quantile: float = 0.01):
        self.winsor_quantile = winsor_quantile

    def compute_price_features(self, ohlcv: pd.DataFrame) -> pd.DataFrame:
        """
        ohlcv: DataFrame with columns [Open, High, Low, Close, Volume]
        """
        feats = pd.DataFrame(index=ohlcv.index)

        log_ret = np.log(ohlcv['Close'] / ohlcv['Close'].shift(1))

        # Momentum at multiple horizons
        for lb in self.LOOKBACKS:
            feats[f'mom_{lb}d'] = np.log(ohlcv['Close'] / ohlcv['Close'].shift(lb))

        # 12-1 month momentum (skip last month)
        feats['mom_12_1'] = np.log(ohlcv['Close'].shift(21) / ohlcv['Close'].shift(252))

        # Realized volatility
        for lb in [21, 63]:
            feats[f'rvol_{lb}d'] = log_ret.rolling(lb).std() * np.sqrt(252)

        # Parkinson volatility
        pk = np.log(ohlcv['High'] / ohlcv['Low']) ** 2
        feats['pvol_21d'] = np.sqrt(pk.rolling(21).mean() * 252 / (4 * np.log(2)))

        # Volatility of volatility
        rv5 = log_ret.rolling(5).std()
        feats['vol_of_vol'] = rv5.rolling(21).std()

        # Mean reversion features
        for lb in [5, 21]:
            ma = ohlcv['Close'].rolling(lb).mean()
            feats[f'price_vs_ma_{lb}'] = (ohlcv['Close'] - ma) / ma

        # Bollinger %B
        bb_mid = ohlcv['Close'].rolling(20).mean()
        bb_std = ohlcv['Close'].rolling(20).std()
        feats['bollinger_b'] = (ohlcv['Close'] - (bb_mid - 2 * bb_std)) / (4 * bb_std)

        # Volume features
        feats['vol_ratio'] = np.log(ohlcv['Volume'] / ohlcv['Volume'].rolling(21).mean())
        feats['vwap_dev'] = (
            ohlcv['Close'] /
            (ohlcv['Close'] * ohlcv['Volume']).rolling(5).sum() *
            ohlcv['Volume'].rolling(5).sum() - 1
        )

        # RSI
        feats['rsi_14'] = self._compute_rsi(log_ret, 14)

        return feats

    def _compute_rsi(self, ret: pd.Series, period: int = 14) -> pd.Series:
        """RSI using Wilder's smoothing."""
        gain = ret.clip(lower=0)
        loss = (-ret).clip(lower=0)
        avg_gain = gain.ewm(alpha=1/period, adjust=False).mean()
        avg_loss = loss.ewm(alpha=1/period, adjust=False).mean()
        rs = avg_gain / avg_loss.replace(0, np.nan)
        rsi = 100 - 100 / (1 + rs)
        return rsi

    def cross_sectional_normalize(self, feature_panel: pd.DataFrame) -> pd.DataFrame:
        """
        Normalize features cross-sectionally:
        1. Winsorize at winsor_quantile / (1 - winsor_quantile)
        2. Robust z-score using median and MAD
        3. Rank-based transform as alternative
        """
        result = feature_panel.copy()
        q_lo = self.winsor_quantile
        q_hi = 1 - self.winsor_quantile

        for date in result.index:
            row = result.loc[date].dropna()
            if len(row) < 5:
                continue
            # Winsorize
            lo, hi = row.quantile(q_lo), row.quantile(q_hi)
            row = row.clip(lo, hi)
            # Robust z-score
            med = row.median()
            mad = (row - med).abs().median()
            if mad > 1e-8:
                row = (row - med) / (mad * 1.4826) # 1.4826 = consistency factor
            result.loc[date, row.index] = row

        return result

    def build_feature_matrix(self, ohlcv_dict: Dict[str, pd.DataFrame]) -> pd.DataFrame:
        """
        Build a multi-asset feature matrix.
        ohlcv_dict: { ticker: ohlcv_df }
        Returns a MultiIndex DataFrame (date, feature) x asset
        """
        all_feats = {}
        for ticker, ohlcv in ohlcv_dict.items():
            f = self.compute_price_features(ohlcv)
            all_feats[ticker] = f

        # Stack into (date x asset) per feature
        panel = pd.concat(all_feats, axis=1) # MultiIndex columns
        panel.columns.names = ['ticker', 'feature']
        return panel

