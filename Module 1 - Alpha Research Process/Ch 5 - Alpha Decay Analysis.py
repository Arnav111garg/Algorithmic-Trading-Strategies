import numpy as np
import pandas as pd
from scipy import stats, optimize
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

def compute_ic_decay(signal: pd.DataFrame, returns_by_horizon: dict, max_horizon: int = 63) -> pd.Series:
    """
    Compute IC at each holding period from 1 to max_horizon days using simulated returns.
    """
    ic_by_horizon = {}
    for h in range(1, max_horizon + 1):
        fwd = pd.DataFrame(returns_by_horizon[h], index=signal.index, columns=signal.columns)
        daily_ic = []
        for date in signal.index:
            s = signal.loc[date].dropna()
            r = fwd.loc[date].dropna()
            c = s.index.intersection(r.index)
            if len(c) < 20:
                continue
            ic, _ = stats.spearmanr(s[c], r[c])
            daily_ic.append(ic)
        ic_by_horizon[h] = np.nanmean(daily_ic)
    return pd.Series(ic_by_horizon)


def fit_decay_model(ic_curve: pd.Series) -> dict:
    """
    Fit exponential decay: IC(h) = IC0 * exp(-h/tau)
    """
    h_vals = ic_curve.index.values.astype(float)
    ic_vals = ic_curve.values

    # Remove negative or zero IC values for log-linear fit
    mask = ic_vals > 0
    if mask.sum() < 3:
        return {'IC0': np.nan, 'tau': np.nan, 'half_life': np.nan}

    log_ic = np.log(ic_vals[mask])
    h_masked = h_vals[mask]

    slope, intercept, r, p, se = stats.linregress(h_masked, log_ic)
    ic0 = np.exp(intercept)
    tau = -1.0 / slope if slope < 0 else np.inf
    half_life = tau * np.log(2)

    print(f"\n IC Decay Model:")
    print(f" IC0 : {ic0:.4f}")
    print(f" Tau (days): {tau:.1f}")
    print(f" Half-Life : {half_life:.1f} days")
    print(f" R-squared : {r**2:.4f}")

    return {'IC0': ic0, 'tau': tau, 'half_life': half_life, 'r2': r**2}


def optimal_holding_period(ic_curve: pd.Series, cost_per_trade: float = 0.0005) -> int:
    """
    Find h* = argmax { IC(h) * sqrt(h) - cost / h }
    cost_per_trade : one-way transaction cost (e.g., 5bps = 0.0005)
    """
    horizons = ic_curve.index.values
    ic_vals = ic_curve.values
    objective = ic_vals * np.sqrt(horizons) - (2 * cost_per_trade / horizons)

    h_star = horizons[np.argmax(objective)]
    print(f"\n Optimal Holding Period: {h_star} days")
    print(f" (given {cost_per_trade * 1e4:.1f}bps one-way cost)")
    return h_star


