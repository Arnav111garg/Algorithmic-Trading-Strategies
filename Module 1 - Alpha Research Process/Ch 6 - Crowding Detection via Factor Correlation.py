import numpy as np
import pandas as pd

def compute_crowding_index(factor_returns: pd.DataFrame, window: int = 21) -> pd.Series:
    """
    Compute average pairwise factor return correlation as crowding proxy.

    Parameters
    ----------
    factor_returns : DataFrame (dates x factors) of daily factor returns
    window : rolling window for correlation

    Returns
    -------
    crowding_index : pd.Series higher means more crowded
    """
    factors = factor_returns.columns.tolist()
    K = len(factors)
    n_pairs = K * (K - 1) // 2

    crowding = pd.Series(dtype=float, index=factor_returns.index)
    for t in range(window, len(factor_returns)):
        sub = factor_returns.iloc[t - window : t]
        corr_m = sub.corr()
        # Average off-diagonal correlation
        total = 0
        count = 0
        for i in range(K):
            for j in range(i + 1, K):
                total += corr_m.iloc[i, j]
                count += 1
        crowding.iloc[t] = total / count if count > 0 else np.nan

    return crowding


def crowding_adjusted_signal(signal: pd.DataFrame, short_interest: pd.DataFrame, gamma: float = 0.5) -> pd.DataFrame:
    """
    Adjust signal by short interest crowding score.

    Parameters
    ----------
    signal : (dates x assets) raw signal
    short_interest : (dates x assets) short-interest / float ratio [0,1]
    gamma : crowding penalty strength
    """
    # Cross-sectionally normalize short interest to [0,1]
    si_norm = short_interest.apply(
        lambda col: (col - col.min()) / (col.max() - col.min() + 1e-8),
        axis=0
    )

    adj = signal * (1 - gamma * si_norm)
    return adj


def detect_cascade_event(factor_returns: pd.DataFrame, threshold_sigma: float = 3.0, corr_threshold: float = 0.6) -> pd.Series:
    """
    Flag potential quant cascade / unwind days.
    """
    rolling_mu = factor_returns.rolling(63).mean()
    rolling_sig = factor_returns.rolling(63).std()
    z_scores = (factor_returns - rolling_mu) / rolling_sig

    # Day is flagged if MAJORITY of factors have z < -threshold
    extreme_neg = (z_scores < -threshold_sigma).mean(axis=1)

    # AND cross-factor correlation is high
    corr_index = compute_crowding_index(factor_returns, window=5)

    cascade = (extreme_neg > 0.5) & (corr_index > corr_threshold)
    return cascade


# Simulate 5 factor returns with regime change
np.random.seed(7)
dates = pd.date_range('2020-01-02', periods=600, freq='B')

# Normal regime: low correlation (~0.1)
normal = np.random.multivariate_normal(
    [0.0002]*5,
    [[0.0001 if i == j else 0.00001 for i in range(5)] for j in range(5)],
    size=500
)

# Crowded regime: high correlation (~0.7)
cov_crowd = [[0.0004 if i == j else 0.00028 for i in range(5)] for j in range(5)]
crowded = np.random.multivariate_normal([0.0002]*5, cov_crowd, size=100)

factor_rets = pd.DataFrame(
    np.vstack([normal, crowded]),
    index=dates,
    columns=[f'Factor_{k}' for k in range(5)]
)

crowding_idx = compute_crowding_index(factor_rets, window=21)
cascades = detect_cascade_event(factor_rets)

print("\nCrowding Index Statistics:")
print(f" Normal period (t <500) : {crowding_idx.iloc[:500].mean():.3f}")
print(f" Crowded period (t >500) : {crowding_idx.iloc[500:].mean():.3f}")
print(f"\nCascade Events Detected : {cascades.sum()}")

