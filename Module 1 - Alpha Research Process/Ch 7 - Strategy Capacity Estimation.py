import numpy as np
import pandas as pd

class CapacityAnalyser:
    """
    Estimate strategy capacity using square-root market impact model.

    References
    ----------
    Almgren, R. et al. (2005), "Direct estimation of equity market impact"
    Grinold & Kahn (2000), "Active Portfolio Management"
    """

    def __init__(self,
                 eta: float = 0.15,               # market impact coefficient
                 target_sr_loss: float = 0.20,    # max tolerable Sharpe loss
                 participation_cap: float = 0.10): # max % of ADV
        self.eta = eta
        self.target_sr_loss = target_sr_loss
        self.participation_cap = participation_cap

    def market_impact_bps(self,
                          aum: float,
                          adv_usd: pd.Series,
                          stock_vols: pd.Series,
                          daily_turnover: float,
                          n_stocks: int) -> float:
        """
        Compute average daily market impact in bps.

        Parameters
        ----------
        aum : strategy AUM in USD
        adv_usd : average daily volume in USD per stock
        stock_vols : annualized volatility per stock
        daily_turnover : fraction of portfolio turned over daily
        n_stocks : number of holdings
        """
        daily_vol_usd = stock_vols / np.sqrt(252) # daily vol
        avg_adv = adv_usd.mean()
        avg_vol = daily_vol_usd.mean()

        # Daily trade size per stock
        trade_size_per_stock = (aum * daily_turnover) / n_stocks

        # Participation rate
        p = trade_size_per_stock / avg_adv

        # Market impact: eta * sigma * sqrt(participation)
        impact = self.eta * avg_vol * np.sqrt(p)

        # Participation check
        if p > self.participation_cap:
            print(f" WARNING: Participation {p:.1%} exceeds cap {self.participation_cap:.1%}")

        return impact * 1e4 # convert to bps

    def estimate_capacity(self,
                          sr0: float,
                          annual_turnover: float,
                          adv_usd: pd.Series,
                          stock_vols: pd.Series,
                          n_stocks: int,
                          aum_grid: np.ndarray = None) -> dict:
        """
        Estimate capacity C such that SR(C) >= (1 - target_sr_loss) * SR0.

        Returns
        -------
        dict with capacity estimate and SR vs AUM curve
        """
        if aum_grid is None:
            aum_grid = np.logspace(5, 10, 50) # $100K to $10B
        daily_turnover = annual_turnover / 252
        sr_by_aum = []

        for aum in aum_grid:
            mi_bps = self.market_impact_bps(aum, adv_usd, stock_vols, daily_turnover, n_stocks)
            # Annual cost = daily impact * 252 * 2 (round-trip)
            annual_cost_return = mi_bps / 1e4 * 252 * 2

            # Assume linear SR degradation (simplification)
            # More rigorous: model return as r0 - cost, vol unchanged
            # For small costs, this is approximately:
            sr_degraded = sr0 - annual_cost_return / 0.15 # assume vol = 15%
            sr_by_aum.append(max(0, sr_degraded))

        sr_series = pd.Series(sr_by_aum, index=aum_grid)
        capacity = sr_series[sr_series >= sr0 * (1 - self.target_sr_loss)].index
        cap_estimate = capacity[-1] if len(capacity) > 0 else 0.0

        print(f"\n Capacity Analysis ")
        print(f" Base Sharpe : {sr0:.2f}")
        print(f" Target Min SR : {sr0 * (1 - self.target_sr_loss):.2f} ({self.target_sr_loss:.0%} degradation)")
        print(f" Capacity Est : ${cap_estimate / 1e6:.0f}M")

        return {
            'capacity_usd': cap_estimate,
            'sr_curve': sr_series,
            'aum_grid': aum_grid
        }

    def participation_limit_capacity(self,
                                     adv_usd: pd.Series,
                                     n_stocks: int,
                                     daily_turnover: float) -> float:
        """
        Simple capacity bound from participation rate constraint alone.
        """
        total_tradeable = adv_usd.nlargest(n_stocks).sum()
        cap_part = total_tradeable * self.participation_cap / daily_turnover

        print(f"\n Participation-Constrained Capacity: ${cap_part / 1e6:.0f}M")
        return cap_part


# Example: Momentum Strategy Capacity
np.random.seed(1)
n_stocks = 200
# Simulate: S&P 500 universe, avg $50M ADV, 20% annual vol
adv = pd.Series(np.random.lognormal(np.log(50e6), 0.7, n_stocks))
vols = pd.Series(np.random.uniform(0.12, 0.35, n_stocks))

analyser = CapacityAnalyser(eta=0.15, target_sr_loss=0.20)
results = analyser.estimate_capacity(
    sr0=0.8,
    annual_turnover=6.0, # 600% annual (momentum: monthly rebal)
    adv_usd=adv,
    stock_vols=vols,
    n_stocks=n_stocks
)
cap_part = analyser.participation_limit_capacity(adv, n_stocks, daily_turnover=6/252)

