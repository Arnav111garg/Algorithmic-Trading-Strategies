import numpy as np
import pandas as pd
from scipy import stats
from sklearn.preprocessing import RobustScaler
from typing import Dict, List, Tuple

class QuantFeaturePipeline:
    """
    Production-grade feature engineering pipeline for equity alpha models.

    Design principles:
    - All features computed point-in-time (no look-ahead)
    - Cross-sectional normalization within each time period
    - Winsorization to handle return outliers
    - Sector / market neutralization of features
    """

    def __init__(
        self,
        forward_return_horizon: int = 21,  # trading days
        winsorize_pct: float = 0.01,       # 1% each tail
        min_history: int = 252             # 1yr min to compute features
    ):
        self.horizon = forward_return_horizon
        self.win_pct = winsorize_pct
        self.min_history = min_history

    # TARGET CONSTRUCTION
    def compute_forward_returns(
        self,
        prices: pd.DataFrame  # shape: (T, N), columns = assets, index = dates
    ) -> pd.DataFrame:
        """
        Compute forward returns with proper temporal alignment.
        Returns are shifted so index [t] contains r_{t -> t+h}.
        At prediction time t, we observe X_t and predict r_{t -> t+h}.
        """
        log_prices = np.log(prices)
        fwd_returns = log_prices.shift(-self.horizon) - log_prices
        # Drop last 'horizon' rows (no realized target yet)
        return fwd_returns.iloc[:-self.horizon]

    def neutralize_returns(
        self,
        returns: pd.DataFrame,
        sector_dummies: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Market + sector neutralize returns via OLS regression.
        Residuals are the 'pure stock' alpha signal.
        """
        neutralized = pd.DataFrame(
            index=returns.index, columns=returns.columns, dtype=float
        )
        for date in returns.index:
            r = returns.loc[date].dropna()
            S = sector_dummies.loc[date].reindex(r.index).fillna(0)
            X = np.column_stack([np.ones(len(r)), S.values])
            try:
                beta, _, _, _ = np.linalg.lstsq(X, r.values, rcond=None)
                residuals = r.values - X @ beta
                neutralized.loc[date, r.index] = residuals
            except np.linalg.LinAlgError:
                neutralized.loc[date, r.index] = r.values
        return neutralized

    # FEATURE ENGINEERING
    def compute_momentum_features(
        self, prices: pd.DataFrame
    ) -> Dict[str, pd.DataFrame]:
        """
        Momentum signals across multiple horizons.
        Note: Skip most recent month (1M) to avoid reversal contamination.
        """
        log_ret = np.log(prices / prices.shift(1))
        features = {}

        # Classic Fama-French momentum: 12M - 1M
        features['mom_12m_1m'] = (
            np.log(prices / prices.shift(252)) - np.log(prices / prices.shift(21))
        )
        # Short-term reversal
        features['reversal_1m'] = -log_ret.rolling(21).sum()
        # Medium-term momentum
        features['mom_6m'] = np.log(prices / prices.shift(126))
        features['mom_3m'] = np.log(prices / prices.shift(63))

        # Risk-adjusted momentum (Sharpe ratio of momentum)
        def rolling_sharpe(ret_df, window):
            return (
                ret_df.rolling(window).mean() / ret_df.rolling(window).std() * np.sqrt(252)
            )

        features['mom_sharpe_6m'] = rolling_sharpe(log_ret, 126)
        features['mom_sharpe_12m'] = rolling_sharpe(log_ret, 252)

        # 52-week high proximity (George & Hwang 2004)
        rolling_max = prices.rolling(252).max()
        features['nearness_52w_high'] = prices / rolling_max

        return features

    def compute_value_features(
        self,
        fundamentals: pd.DataFrame  # Multi-index (date, field)
    ) -> Dict[str, pd.DataFrame]:
        """
        Fundamental value signals.
        """
        features = {}
        # Book-to-market ratio
        if 'book_value' in fundamentals.columns and 'market_cap' in fundamentals.columns:
            features['bm_ratio'] = (
                fundamentals['book_value'] / fundamentals['market_cap']
            )
        # Earnings yield
        if 'earnings' in fundamentals.columns:
            features['earnings_yield'] = (
                fundamentals['earnings'] / fundamentals['market_cap']
            )
        return features

    def compute_volatility_features(
        self, prices: pd.DataFrame
    ) -> Dict[str, pd.DataFrame]:
        """
        Volatility and idiosyncratic risk features.
        Low-vol anomaly: low-vol stocks tend to outperform (Ang et al 2006).
        """
        log_ret = np.log(prices / prices.shift(1))
        features = {}

        features['vol_21d'] = log_ret.rolling(21).std() * np.sqrt(252)
        features['vol_63d'] = log_ret.rolling(63).std() * np.sqrt(252)
        features['vol_252d'] = log_ret.rolling(252).std() * np.sqrt(252)

        # Volatility-of-volatility
        vol_21d = log_ret.rolling(21).std()
        features['vol_of_vol'] = vol_21d.rolling(63).std()

        # Maximum drawdown (Bali et al 2011 MAX anomaly)
        features['max_daily_ret_1m'] = log_ret.rolling(21).max()

        # Skewness and kurtosis of returns
        features['skew_63d'] = log_ret.rolling(63).apply(
            lambda x: stats.skew(x), raw=True
        )
        features['kurt_63d'] = log_ret.rolling(63).apply(
            lambda x: stats.kurtosis(x), raw=True
        )
        return features

    def compute_technical_features(
        self, prices: pd.DataFrame, volumes: pd.DataFrame
    ) -> Dict[str, pd.DataFrame]:
        """
        Price-volume technical indicators.
        """
        log_ret = np.log(prices / prices.shift(1))
        features = {}

        # RSI
        def compute_rsi(ret_df, window=14):
            gains = ret_df.where(ret_df > 0, 0)
            losses = (-ret_df).where(ret_df < 0, 0)
            avg_gains = gains.ewm(span=window, adjust=False).mean()
            avg_losses = losses.ewm(span=window, adjust=False).mean()
            rs = avg_gains / (avg_losses + 1e-9)
            return 100 - (100 / (1 + rs))

        features['rsi_14'] = compute_rsi(log_ret, 14)

        # Moving average ratios
        features['price_ma50_ratio'] = prices / prices.rolling(50).mean()
        features['price_ma200_ratio'] = prices / prices.rolling(200).mean()
        features['ma50_ma200_ratio'] = (
            prices.rolling(50).mean() / prices.rolling(200).mean()
        )

        # Volume features
        features['volume_ratio_21d'] = volumes / volumes.rolling(21).mean()

        # Amihud (2002) illiquidity
        features['amihud_illiq'] = (
            log_ret.abs() / (volumes * prices + 1e-9)
        ).rolling(21).mean()

        # On-balance volume slope
        obv = (np.sign(log_ret) * volumes).cumsum()
        features['obv_slope_21d'] = obv.diff(21)

        return features

    # CROSS-SECTIONAL NORMALIZATION
    def cross_sectional_zscore(
        self, features: pd.DataFrame
    ) -> pd.DataFrame:
        """
        For each date, z-score the feature across all assets.
        This is critical for cross-sectional ML models.
        """
        # Winsorize first (per date)
        winsorized = features.copy()
        for date in features.index:
            row = features.loc[date].dropna()
            if len(row) > 0:
                lower = row.quantile(self.win_pct)
                upper = row.quantile(1 - self.win_pct)
                winsorized.loc[date, row.index] = row.clip(lower, upper)

        # Z-score (robust: use median and MAD)
        normalized = pd.DataFrame(
            index=features.index, columns=features.columns, dtype=float
        )
        for date in winsorized.index:
            row = winsorized.loc[date].dropna()
            if len(row) > 0:
                med = row.median()
                mad = (row - med).abs().median() * 1.4826  # scale to sigma
                normalized.loc[date, row.index] = (row - med) / (mad + 1e-9)
        return normalized

    # BUILD FULL FEATURE MATRIX
    def build_feature_matrix(
        self,
        prices: pd.DataFrame,
        volumes: pd.DataFrame,
        fundamentals: pd.DataFrame = None
    ) -> Tuple[pd.DataFrame, pd.DataFrame]:
        """
        Returns (X, y) where:
        - X: (T*N, K) feature matrix (stacked cross-sections)
        - y: (T*N,) forward return target
        """
        print("Computing forward returns ...")
        y = self.compute_forward_returns(prices)

        print("Computing momentum features ...")
        mom = self.compute_momentum_features(prices)

        print("Computing volatility features ...")
        vol = self.compute_volatility_features(prices)

        print("Computing technical features ...")
        tech = self.compute_technical_features(prices, volumes)

        all_features = {**mom, **vol, **tech}

        print("Cross-sectional normalizing ...")
        feature_dfs = []
        for fname, fdf in all_features.items():
            normed = self.cross_sectional_zscore(fdf)
            normed = normed.stack().rename(fname)
            feature_dfs.append(normed)

        X = pd.concat(feature_dfs, axis=1)
        y_stacked = y.stack().rename('forward_return')

        # Align
        common_idx = X.index.intersection(y_stacked.index)
        return X.loc[common_idx], y_stacked.loc[common_idx]

