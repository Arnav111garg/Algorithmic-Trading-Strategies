import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import roc_auc_score
from scipy.stats import spearmanr

class ClassificationAlphaModel:
    """
    Binary classification model : predict whether stock returns
    will be in top vs bottom quintile.

    Uses expanding-window walk-forward validation with purge gap.
    """

    def __init__(
        self,
        model_type: str = 'logistic',  # 'logistic', 'svm', 'mlp'
        train_years: int = 5,
        test_years: int = 1,
        purge_days: int = 21,          # embargo period between train and test
        min_train_samples: int = 2000,
        top_pct: float = 0.20,         # top quintile
        bot_pct: float = 0.20,         # bottom quintile
    ):
        self.model_type = model_type
        self.train_years = train_years
        self.test_years = test_years
        self.purge_days = purge_days
        self.min_samples = min_train_samples
        self.top_pct = top_pct
        self.bot_pct = bot_pct

    def _create_labels(
        self,
        returns: pd.Series,
        mode: str = 'top'  # 'top' or 'bottom'
    ) -> pd.Series:
        """
        Create binary labels : 1 for top quintile , 0 otherwise.
        Only includes extreme quintile observations in training
        (ignore the middle 60% for cleaner signal).
        """
        q_top = returns.quantile(1 - self.top_pct)
        q_bot = returns.quantile(self.bot_pct)

        if mode == 'top':
            return (returns >= q_top).astype(int)
        else:
            return (returns <= q_bot).astype(int)

    def _build_model(self, C: float = 1.0):
        """Build and return the ML classifier."""
        if self.model_type == 'logistic':
            return LogisticRegression(
                C=C,
                penalty='l2',
                solver='lbfgs',
                max_iter=500,
                class_weight='balanced'
            )
        elif self.model_type == 'mlp':
            from sklearn.neural_network import MLPClassifier
            return MLPClassifier(
                hidden_layer_sizes=(64, 32, 16),
                activation='relu',
                alpha=0.001,  # L2 regularization
                learning_rate_init=0.001,
                max_iter=200,
                early_stopping=True,
                validation_fraction=0.1,
                random_state=42
            )

    def walk_forward_predict(
        self,
        X: pd.DataFrame,       # MultiIndex: (date, asset)
        y: pd.Series,          # forward returns
        dates: pd.DatetimeIndex
    ) -> pd.DataFrame:
        """
        Full walk-forward backtest with purge gap.

        Returns: DataFrame with columns [date, asset, prediction, true_return]
        """
        results = []
        dates = sorted(dates.unique())

        train_size = self.train_years * 252
        test_size = self.test_years * 252

        step = 0
        while True:
            t_start = step
            t_end = t_start + train_size
            t_purge = t_end + self.purge_days
            t_test = t_purge
            t_test_e = t_test + test_size

            if t_test_e > len(dates):
                break
            train_dates = dates[t_start:t_end]
            test_dates = dates[t_test:t_test_e]

            # Extract train / test data
            X_train = X.loc[X.index.get_level_values(0).isin(train_dates)]
            y_train = y.loc[y.index.get_level_values(0).isin(train_dates)]
            X_test = X.loc[X.index.get_level_values(0).isin(test_dates)]
            y_test = y.loc[y.index.get_level_values(0).isin(test_dates)]

            if len(X_train) < self.min_samples:
                step += test_size
                continue

            # Scale features (fit on train only!)
            scaler = StandardScaler()
            Xtr_sc = scaler.fit_transform(X_train.fillna(0))
            Xte_sc = scaler.transform(X_test.fillna(0))

            # Create quintile labels for training
            lbl_train = self._create_labels(y_train, mode='top')

            # Train model
            model = self._build_model()
            model.fit(Xtr_sc, lbl_train)

            # Predict probabilities
            proba = model.predict_proba(Xte_sc)[:, 1]

            # Store results
            fold_df = pd.DataFrame({
                'pred_score': proba,
                'true_return': y_test.values,
            }, index=y_test.index)
            results.append(fold_df)

            print(f"[Fold {step // test_size + 1}] "
                  f"Train: {train_dates[0].date()} - {train_dates[-1].date()}, "
                  f"Test: {test_dates[0].date()} - {test_dates[-1].date()}, "
                  f"AUC: {roc_auc_score(lbl_train[:len(Xte_sc)], proba):.4f}")

            step += test_size
        return pd.concat(results)

    def compute_ic_series(self, results: pd.DataFrame) -> pd.Series:
        """
        Compute daily IC (Spearman) between predicted score and realized return.
        """
        dates = results.index.get_level_values(0).unique()
        ic_series = {}
        for date in dates:
            subset = results.loc[date]
            if len(subset) >= 20:
                rho, _ = spearmanr(subset['pred_score'], subset['true_return'])
                ic_series[date] = rho
        return pd.Series(ic_series, name='IC')

    def compute_quintile_returns(self, results: pd.DataFrame) -> pd.Series:
        """
        Group stocks into quintiles by predicted score, compute avg realized returns.
        This is the key diagnostic for an alpha model.
        """
        dates = results.index.get_level_values(0).unique()
        quintile_rets = {q: [] for q in range(1, 6)}

        for date in dates:
            subset = results.loc[date].copy()
            if len(subset) < 20:
                continue
            subset['quintile'] = pd.qcut(
                subset['pred_score'], 5, labels=[1, 2, 3, 4, 5]
            )
            for q in range(1, 6):
                qrets = subset.loc[subset['quintile'] == q, 'true_return']
                quintile_rets[q].append(qrets.mean())

        return pd.DataFrame(quintile_rets).mean().rename('Avg Return')

# QUINTILE ANALYSIS FUNCTION
def analyze_classification_signal(results: pd.DataFrame) -> None:
    """
    Full diagnostic analysis of a classification alpha signal.
    """
    model = ClassificationAlphaModel()

    # 1. IC statistics
    ic = model.compute_ic_series(results)
    print(f"\n=== IC Statistics ===")
    print(f"Mean IC: {ic.mean():.4f}")
    print(f"Std IC: {ic.std():.4f}")
    print(f"IR: {ic.mean()/ic.std():.4f}")
    print(f"t-stat: {ic.mean()/ic.std() * np.sqrt(len(ic)):.3f}")
    print(f"IC > 0: {(ic > 0).mean() * 100:.1f}%")

    # 2. Quintile spreads
    qrets = model.compute_quintile_returns(results)
    print(f"\n=== Quintile Returns (avg) ===")
    for q, r in qrets.items():
        print(f"Q{q}: {r * 100:.3f}%")
    print(f"Q5-Q1 Spread: {(qrets[5] - qrets[1]) * 100:.3f}%")

