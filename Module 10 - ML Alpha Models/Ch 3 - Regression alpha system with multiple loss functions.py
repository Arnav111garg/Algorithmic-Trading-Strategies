import numpy as np
import pandas as pd
from sklearn.linear_model import RidgeCV, LassoCV, ElasticNetCV, HuberRegressor
from sklearn.linear_model import QuantileRegressor
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import TimeSeriesSplit
from scipy.stats import spearmanr
import warnings
warnings.filterwarnings('ignore')

class RegressionAlphaSystem:
    """
    Comprehensive regression system for alpha forecasting.
    Includes Ridge, Lasso, Elastic Net, Quantile, and Huber regression.
    """

    def __init__(
        self,
        models: list = ['ridge', 'lasso', 'elastic_net', 'huber'],
        cv_folds: int = 5,
        decay_lambda: float = 0.97,  # exponential time decay
    ):
        self.models = models
        self.cv_folds = cv_folds
        self.decay_lambda = decay_lambda

    def exponential_sample_weights(self, n: int) -> np.ndarray:
        """
        Exponentially decaying sample weights
        Most recent observations get weight 1.0, oldest get lambda^n.
        """
        weights = self.decay_lambda ** np.arange(n - 1, -1, -1)
        return weights / weights.sum() * n  # rescale to preserve scale

    def build_models(self, X_train: np.ndarray, y_train: np.ndarray):
        """
        Train a suite of regression models, return dict of {name: model}.
        """
        n = len(X_train)
        sample_weights = self.exponential_sample_weights(n)
        tscv = TimeSeriesSplit(n_splits=self.cv_folds)
        trained = {}

        if 'ridge' in self.models:
            alphas = np.logspace(-4, 4, 50)
            model = RidgeCV(
                alphas=alphas,
                cv=tscv,
                scoring='neg_mean_squared_error',
                fit_intercept=True
            )
            model.fit(X_train, y_train, sample_weight=sample_weights)
            trained['ridge'] = model
            print(f"Ridge: alpha={model.alpha_:.4f}")

        if 'lasso' in self.models:
            model = LassoCV(
                cv=tscv,
                n_alphas=50,
                fit_intercept=True,
                max_iter=2000
            )
            model.fit(X_train, y_train, sample_weight=sample_weights)
            trained['lasso'] = model
            n_nonzero = np.sum(np.abs(model.coef_) > 1e-6)
            print(f"Lasso: alpha={model.alpha_:.4f}, nonzero={n_nonzero}/{X_train.shape[1]}")

        if 'elastic_net' in self.models:
            model = ElasticNetCV(
                l1_ratio=[0.1, 0.3, 0.5, 0.7, 0.9, 0.95],
                n_alphas=50,
                cv=tscv,
                fit_intercept=True,
                max_iter=2000
            )
            model.fit(X_train, y_train, sample_weight=sample_weights)
            trained['elastic_net'] = model
            print(f"ElasticNet: alpha={model.alpha_:.4f}, l1_ratio={model.l1_ratio_:.2f}")

        if 'huber' in self.models:
            model = HuberRegressor(
                epsilon=1.35,  # standard robust regression setting
                max_iter=200,
                alpha=0.001    # L2 penalty
            )
            model.fit(X_train, y_train)
            trained['huber'] = model

        if 'quantile_90' in self.models:
            model = QuantileRegressor(
                quantile=0.90,
                alpha=0.001,
                solver='highs'
            )
            model.fit(X_train, y_train)
            trained['quantile_90'] = model

        return trained

    def predict_ensemble(
        self,
        trained_models: dict,
        X_test: np.ndarray
    ) -> np.ndarray:
        """
        Average predictions across all models (equal-weight ensemble).
        """
        preds = np.column_stack([
            m.predict(X_test) for m in trained_models.values()
        ])
        return preds.mean(axis=1)

    def evaluate_regression_model(
        self,
        y_true: np.ndarray,
        y_pred: np.ndarray,
        verbose: bool = True
    ) -> dict:
        """
        Compute comprehensive regression performance metrics.
        """
        residuals = y_true - y_pred
        ss_res = np.sum(residuals ** 2)
        ss_tot = np.sum((y_true - y_true.mean()) ** 2)
        r2 = 1 - ss_res / ss_tot

        ic, pval = spearmanr(y_pred, y_true)
        mse = np.mean(residuals ** 2)
        mae = np.mean(np.abs(residuals))

        # Directional accuracy (sign prediction)
        hit_rate = np.mean(np.sign(y_pred) == np.sign(y_true))

        # Quintile spread
        n = len(y_true)
        q_size = n // 5
        sorted_idx = np.argsort(y_pred)
        q1_ret = y_true[sorted_idx[:q_size]].mean()
        q5_ret = y_true[sorted_idx[-q_size:]].mean()

        metrics = {
            'R2': r2,
            'IC': ic,
            'IC_pval': pval,
            'MSE': mse,
            'MAE': mae,
            'Hit_Rate': hit_rate,
            'Q5_minus_Q1': q5_ret - q1_ret,
        }

        if verbose:
            print("\n=== Regression Alpha Metrics ===")
            for k, v in metrics.items():
                print(f" {k:15s}: {v:.4f}")

        return metrics

    def walk_forward_regression(
        self,
        X: pd.DataFrame,
        y: pd.Series,
        train_window: int = 252 * 3,  # 3 years
        test_window: int = 63,        # 1 quarter
        purge_window: int = 21        # 1 month purge
    ) -> pd.Series:
        """
        Rolling walk-forward regression with purge window.
        Returns series of out-of-sample predicted alpha scores.
        """
        all_preds = {}
        n = len(X)

        for start in range(0, n - train_window - purge_window - test_window, test_window):
            end_train = start + train_window
            start_test = end_train + purge_window
            end_test = start_test + test_window

            if end_test > n:
                break

            Xtr = X.iloc[start:end_train].values
            ytr = y.iloc[start:end_train].values
            Xte = X.iloc[start_test:end_test].values
            yte = y.iloc[start_test:end_test].values

            # Scale (fit on train only)
            scaler = StandardScaler()
            Xtr_s = scaler.fit_transform(np.nan_to_num(Xtr))
            Xte_s = scaler.transform(np.nan_to_num(Xte))

            # Train
            trained = self.build_models(Xtr_s, ytr)

            # Predict
            pred = self.predict_ensemble(trained, Xte_s)

            # Store
            test_index = y.index[start_test:end_test]
            for idx, p in zip(test_index, pred):
                all_preds[idx] = p

        return pd.Series(all_preds, name='predicted_alpha')

