import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor, ExtraTreesRegressor
from sklearn.model_selection import cross_val_score, TimeSeriesSplit
from sklearn.inspection import permutation_importance
import matplotlib.pyplot as plt
from scipy.stats import spearmanr

class TreeAlphaModel:
    """
    Tree-based alpha models: Random Forest and Extra-Trees.
    Optimized for financial ML with proper temporal validation.
    """

    def __init__(
        self,
        model_type: str = 'random_forest',  # or 'extra_trees'
        n_estimators: int = 500,
        max_depth: int = 5,                 # shallow trees for finance
        min_samples_leaf: int = 50,         # enough samples per leaf
        max_features: float = 0.3,          # feature subsampling
        n_jobs: int = -1,
        random_state: int = 42
    ):
        self.model_type = model_type
        self.params = {
            'n_estimators': n_estimators,
            'max_depth': max_depth,
            'min_samples_leaf': min_samples_leaf,
            'max_features': max_features,
            'n_jobs': n_jobs,
            'random_state': random_state
        }

    def build(self):
        if self.model_type == 'random_forest':
            return RandomForestRegressor(**self.params)
        elif self.model_type == 'extra_trees':
            return ExtraTreesRegressor(**self.params)

    def hyperparameter_search(
        self,
        X: np.ndarray,
        y: np.ndarray
    ) -> dict:
        """
        Grid search with TimeSeriesSplit CV to find optimal tree parameters.
        Reports IC (Spearman) as the metric.
        """
        from sklearn.model_selection import GridSearchCV

        def ic_scorer(estimator, X, y):
            pred = estimator.predict(X)
            ic, _ = spearmanr(pred, y)
            return ic

        param_grid = {
            'n_estimators': [200, 500],
            'max_depth': [3, 5, 7],
            'min_samples_leaf': [30, 50, 100],
            'max_features': [0.2, 0.3, 0.5],
        }

        tscv = TimeSeriesSplit(n_splits=5)
        ModelClass = (
            RandomForestRegressor
            if self.model_type == 'random_forest'
            else ExtraTreesRegressor
        )

        gs = GridSearchCV(
            ModelClass(random_state=42, n_jobs=-1),
            param_grid,
            scoring=ic_scorer,
            cv=tscv,
            n_jobs=-1,
            verbose=1
        )
        gs.fit(X, y)

        print(f"\nBest IC: {gs.best_score_:.4f}")
        print(f"Best params: {gs.best_params_}")
        return gs.best_params_

    def analyze_tree_structure(self, model, feature_names: list) -> pd.DataFrame:
        """
        Analyze the tree structure: depth distribution,
        feature usage at different depths.
        """
        depths = []
        feature_depth = {f: [] for f in feature_names}

        for tree in model.estimators_:
            tree_ = tree.tree_
            depths.append(tree_.max_depth)

            # Feature usage by depth
            def traverse(node, depth):
                if tree_.feature[node] >= 0:  # not leaf
                    feat = feature_names[tree_.feature[node]]
                    feature_depth[feat].append(depth)
                    traverse(tree_.children_left[node], depth + 1)
                    traverse(tree_.children_right[node], depth + 1)

            traverse(0, 0)

        # Features used at depth 0 = most discriminating split
        top_features_depth0 = sorted(
            [(f, len([d for d in ds if d == 0])) for f, ds in feature_depth.items()],
            key=lambda x: -x[1]
        )

        print("\nTop features used at root split:")
        for feat, count in top_features_depth0[:10]:
            print(f" {feat:30s}: {count}")

        return pd.DataFrame({
            'feature': feature_names,
            'mean_depth_used': [
                np.mean(feature_depth[f]) if feature_depth[f] else np.nan
                for f in feature_names
            ],
            'usage_count': [len(feature_depth[f]) for f in feature_names]
        }).sort_values('usage_count', ascending=False)

    def out_of_bag_evaluation(self, X: np.ndarray, y: np.ndarray) -> dict:
        """
        OOB evaluation: free internal cross-validation for Random Forests.
        Only works for RandomForest (not ExtraTrees without modification).
        """
        model = RandomForestRegressor(
            **{**self.params, 'oob_score': True}
        )
        model.fit(X, y)
        oob_preds = model.oob_prediction_
        ic, _ = spearmanr(oob_preds, y)
        r2 = model.oob_score_

        print(f"\n=== OOB Evaluation ===")
        print(f" OOB R2: {r2:.4f}")
        print(f" OOB IC: {ic:.4f}")

        return {'oob_r2': r2, 'oob_ic': ic, 'model': model}

