import numpy as np
import pandas as pd
import xgboost as xgb
import lightgbm as lgb
from sklearn.model_selection import TimeSeriesSplit
from sklearn.preprocessing import StandardScaler
from scipy.stats import spearmanr
import optuna
optuna.logging.set_verbosity(optuna.logging.WARNING)

# CUSTOM FINANCIAL LOSS: RANK IC MAXIMIZATION
def rank_ic_objective(y_pred: np.ndarray, dtrain: xgb.DMatrix):
    """
    Custom XGBoost objective that directly maximizes rank IC (Spearman correlation).
    Uses differentiable surrogate via MSE on ranks.
    """
    y_true = dtrain.get_label()
    n = len(y_true)

    # Compute ranks
    true_ranks = np.argsort(np.argsort(y_true)).astype(float)
    pred_ranks = np.argsort(np.argsort(y_pred)).astype(float)

    # Normalize ranks to [-1, 1]
    true_ranks = (true_ranks - n / 2) / (n / 2)
    pred_ranks = (pred_ranks - n / 2) / (n / 2)

    # MSE on ranks (smooth approximation of -IC)
    grad = 2 * (pred_ranks - true_ranks)  # d/d(pred_rank) of rank MSE
    hess = np.ones(n) * 2  # constant hessian
    return grad, hess

def rank_ic_eval(y_pred: np.ndarray, dtrain: xgb.DMatrix):
    """Custom XGBoost evaluation metric: Spearman IC."""
    y_true = dtrain.get_label()
    ic, _ = spearmanr(y_pred, y_true)
    return 'IC', ic  # (name, value) higher is better

class GradientBoostingAlpha:
    """
    Production gradient boosting system for equity alpha.
    Includes XGBoost, LightGBM, and Optuna hyperparameter optimization.
    """

    def __init__(
        self,
        framework: str = 'lightgbm',  # 'xgboost', 'lightgbm', 'catboost'
        n_optuna_trials: int = 50,
        cv_folds: int = 5,
        early_stopping_rounds: int = 50,
        random_state: int = 42
    ):
        self.framework = framework
        self.n_trials = n_optuna_trials
        self.cv_folds = cv_folds
        self.es_rounds = early_stopping_rounds
        self.random_state = random_state
        self.best_params = None

    # DEFAULT FINANCIAL HYPERPARAMETERS
    def get_xgb_defaults(self) -> dict:
        """
        Carefully tuned XGBoost defaults for cross-sectional equity data.
        These are starting points based on empirical experience.
        """
        return {
            'n_estimators': 1000,
            'learning_rate': 0.02,  # low LR + more trees
            'max_depth': 4,  # shallow trees for finance
            'subsample': 0.7,  # row subsampling
            'colsample_bytree': 0.6,  # col subsampling per tree
            'colsample_bylevel': 0.6,  # col subsampling per level
            'min_child_weight': 20,  # min samples in leaf
            'gamma': 0.1,  # min split gain
            'reg_alpha': 0.1,  # L1 regularization
            'reg_lambda': 5.0,  # L2 regularization
            'tree_method': 'hist',  # fast histogram method
            'random_state': self.random_state,
            'n_jobs': -1,
        }

    def get_lgb_defaults(self) -> dict:
        """
        LightGBM defaults for equity alpha.
        Leaf-wise growth requires careful min_child_samples.
        """
        return {
            'n_estimators': 2000,
            'learning_rate': 0.01,
            'num_leaves': 31,  # key LightGBM param
            'max_depth': 6,
            'min_child_samples': 50,  # prevent overfit
            'feature_fraction': 0.7,
            'bagging_fraction': 0.7,  # row subsampling
            'bagging_freq': 5,  # frequency of bagging
            'reg_alpha': 0.1,
            'reg_lambda': 5.0,
            'random_state': self.random_state,
            'n_jobs': -1,
            'verbose': -1,
        }

    # OPTUNA HYPERPARAMETER OPTIMIZATION
    def optimize_hyperparameters(
        self,
        X_train: np.ndarray,
        y_train: np.ndarray
    ) -> dict:
        """
        Bayesian hyperparameter optimization using Optuna.
        Objective: maximize OOS IC via TimeSeriesSplit CV.
        """
        tscv = TimeSeriesSplit(n_splits=self.cv_folds)

        def objective(trial):
            if self.framework == 'xgboost':
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 100, 2000),
                    'learning_rate': trial.suggest_float('lr', 0.005, 0.1, log=True),
                    'max_depth': trial.suggest_int('max_depth', 3, 8),
                    'subsample': trial.suggest_float('subsample', 0.5, 1.0),
                    'colsample_bytree': trial.suggest_float('colsample', 0.3, 1.0),
                    'min_child_weight': trial.suggest_int('min_child_wt', 5, 100),
                    'gamma': trial.suggest_float('gamma', 0.0, 2.0),
                    'reg_alpha': trial.suggest_float('alpha', 1e-4, 10, log=True),
                    'reg_lambda': trial.suggest_float('lambda', 1e-4, 10, log=True),
                    'tree_method': 'hist',
                    'random_state': self.random_state,
                    'n_jobs': -1,
                }
                Model = xgb.XGBRegressor
            elif self.framework == 'lightgbm':
                params = {
                    'n_estimators': trial.suggest_int('n_estimators', 100, 3000),
                    'learning_rate': trial.suggest_float('lr', 0.005, 0.1, log=True),
                    'num_leaves': trial.suggest_int('num_leaves', 16, 128),
                    'max_depth': trial.suggest_int('max_depth', 3, 8),
                    'min_child_samples': trial.suggest_int('min_child', 20, 200),
                    'feature_fraction': trial.suggest_float('ff', 0.3, 1.0),
                    'bagging_fraction': trial.suggest_float('bf', 0.5, 1.0),
                    'bagging_freq': trial.suggest_int('bfreq', 1, 10),
                    'reg_alpha': trial.suggest_float('alpha', 1e-4, 10, log=True),
                    'reg_lambda': trial.suggest_float('lambda', 1e-4, 10, log=True),
                    'random_state': self.random_state,
                    'n_jobs': -1, 'verbose': -1,
                }
                Model = lgb.LGBMRegressor

            # Cross-validate with IC as metric
            ic_scores = []
            for tr_idx, te_idx in tscv.split(X_train):
                Xtr, ytr = X_train[tr_idx], y_train[tr_idx]
                Xte, yte = X_train[te_idx], y_train[te_idx]

                scaler = StandardScaler()
                Xtr_s = scaler.fit_transform(Xtr)
                Xte_s = scaler.transform(Xte)

                model = Model(**params)
                model.fit(Xtr_s, ytr)
                pred = model.predict(Xte_s)
                ic, _ = spearmanr(pred, yte)
                ic_scores.append(ic if not np.isnan(ic) else 0.0)

            return np.mean(ic_scores)

        study = optuna.create_study(
            direction='maximize',
            sampler=optuna.samplers.TPESampler(seed=self.random_state)
        )
        study.optimize(objective, n_trials=self.n_trials, show_progress_bar=True)

        self.best_params = study.best_params
        print(f"\nBest IC: {study.best_value:.4f}")
        print(f"Best params: {study.best_params}")
        return study.best_params

    # TRAINING WITH EARLY STOPPING
    def train_with_early_stopping(
        self,
        X_train: np.ndarray,
        y_train: np.ndarray,
        X_valid: np.ndarray,
        y_valid: np.ndarray,
    ):
        """
        Train with validation-based early stopping to prevent overfit.
        """
        params = self.best_params if self.best_params else self.get_lgb_defaults()

        if self.framework == 'lightgbm':
            dtrain = lgb.Dataset(X_train, label=y_train)
            dvalid = lgb.Dataset(X_valid, label=y_valid, reference=dtrain)

            # Custom IC metric for LightGBM
            def lgb_ic_metric(y_pred, dtrain):
                y_true = dtrain.get_label()
                ic, _ = spearmanr(y_pred, y_true)
                return 'IC', ic, True  # (name, value, is_higher_better)

            callbacks = [
                lgb.early_stopping(self.es_rounds, verbose=False),
                lgb.log_evaluation(100)
            ]

            model = lgb.train(
                {k: v for k, v in params.items() if k not in ['n_estimators']},
                dtrain,
                num_boost_round=params.get('n_estimators', 2000),
                valid_sets=[dvalid],
                feval=lgb_ic_metric,
                callbacks=callbacks,
            )

            print(f"\nBest iteration: {model.best_iteration}")
            print(f"Best valid IC: {model.best_score['valid_0']['IC']:.4f}")
            return model

        elif self.framework == 'xgboost':
            dtrain = xgb.DMatrix(X_train, label=y_train)
            dvalid = xgb.DMatrix(X_valid, label=y_valid)

            params_xgb = {k: v for k, v in params.items() if k not in ['n_estimators']}

            model = xgb.train(
                params_xgb,
                dtrain,
                num_boost_round=params.get('n_estimators', 1000),
                evals=[(dtrain, 'train'), (dvalid, 'valid')],
                obj=rank_ic_objective,
                custom_metric=rank_ic_eval,
                early_stopping_rounds=self.es_rounds,
                verbose_eval=100
            )
            return model

# CATBOOST ALPHA MODEL
def train_catboost_alpha(
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_valid: np.ndarray,
    y_valid: np.ndarray,
    cat_features: list = None
) -> object:
    """
    CatBoost with ordered boosting for alpha signals.
    Native support for categorical features (sectors, exchanges).
    """
    from catboost import CatBoostRegressor, Pool

    train_pool = Pool(X_train, label=y_train, cat_features=cat_features or [])
    valid_pool = Pool(X_valid, label=y_valid, cat_features=cat_features or [])

    model = CatBoostRegressor(
        iterations=2000,
        learning_rate=0.02,
        depth=5,
        l2_leaf_reg=5.0,
        bagging_temperature=0.5,
        random_strength=0.5,
        border_count=64,
        loss_function='RMSE',
        eval_metric='R2',
        od_type='Iter',
        od_wait=50,
        use_best_model=True,
        random_seed=42,
        verbose=200,
        boosting_type='Ordered'
    )

    model.fit(
        train_pool,
        eval_set=valid_pool,
        plot=False
    )

    pred = model.predict(X_valid)
    ic, _ = spearmanr(pred, y_valid)
    print(f"\nCatBoost Valid IC: {ic:.4f}")
    print(f"Best iteration: {model.best_iteration_}")
    return model

