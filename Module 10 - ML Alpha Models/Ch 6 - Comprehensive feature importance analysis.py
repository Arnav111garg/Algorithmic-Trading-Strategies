import numpy as np
import pandas as pd
import shap
import lightgbm as lgb
from sklearn.inspection import permutation_importance
from sklearn.ensemble import RandomForestRegressor
from scipy.stats import spearmanr
import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec

class FeatureImportanceAnalyzer:
    """
    Comprehensive feature importance analysis for ML alpha models.
    Computes MDI, Permutation Importance, and SHAP values.
    Produces full diagnostic suite for quant research.
    """

    def __init__(self, feature_names: list):
        self.feature_names = feature_names
        self.K = len(feature_names)

    def mdi_importance(self, model) -> pd.Series:
        """Mean Decrease Impurity from tree model."""
        if hasattr(model, 'feature_importances_'):
            imp = model.feature_importances_
        elif hasattr(model, 'feature_importance'):  # LightGBM
            imp = model.feature_importance(importance_type='gain')
        else:
            raise ValueError("Model doesn't support MDI")

        return pd.Series(
            imp, index=self.feature_names, name='MDI'
        ).sort_values(ascending=False)

    def permutation_importance_ic(
        self,
        model,
        X_test: np.ndarray,
        y_test: np.ndarray,
        n_repeats: int = 20,
        random_state: int = 42
    ) -> pd.DataFrame:
        """
        Permutation importance using IC (Spearman) as metric.
        This is more appropriate than R2 for financial alpha.
        """
        # Baseline IC
        if hasattr(model, 'predict'):
            pred_base = model.predict(X_test)
        else:
            import xgboost as xgb
            pred_base = model.predict(xgb.DMatrix(X_test))

        ic_base, _ = spearmanr(pred_base, y_test)

        importances = np.zeros((self.K, n_repeats))
        rng = np.random.default_rng(random_state)

        for j in range(self.K):
            for r in range(n_repeats):
                X_perm = X_test.copy()
                X_perm[:, j] = rng.permutation(X_perm[:, j])

                if hasattr(model, 'predict'):
                    pred_perm = model.predict(X_perm)
                else:
                    import xgboost as xgb
                    pred_perm = model.predict(xgb.DMatrix(X_perm))

                ic_perm, _ = spearmanr(pred_perm, y_test)
                importances[j, r] = ic_base - ic_perm  # IC decrease

        result = pd.DataFrame({
            'feature': self.feature_names,
            'PI_mean': importances.mean(axis=1),
            'PI_std': importances.std(axis=1),
            'PI_tstat': importances.mean(axis=1) / (importances.std(axis=1) + 1e-9)
        }).sort_values('PI_mean', ascending=False).reset_index(drop=True)

        return result

    def shap_analysis(
        self,
        model,
        X_background: np.ndarray,  # Background dataset (train subset)
        X_explain: np.ndarray,     # Dataset to explain (test)
        n_background: int = 500
    ) -> np.ndarray:
        """
        Compute SHAP values using TreeExplainer.
        Returns shap_values: (n_samples, n_features)
        """
        # Subsample background for efficiency
        idx = np.random.choice(
            len(X_background), min(n_background, len(X_background)), replace=False
        )
        background = X_background[idx]

        print("Computing SHAP values (TreeExplainer)...")
        explainer = shap.TreeExplainer(model, background)
        shap_values = explainer.shap_values(X_explain)

        if isinstance(shap_values, list):  # multi-class output
            shap_values = shap_values[1]

        return shap_values

    def shap_feature_importance(self, shap_values: np.ndarray) -> pd.Series:
        """Global feature importance = mean(|SHAP|) across samples."""
        return pd.Series(
            np.abs(shap_values).mean(axis=0),
            index=self.feature_names,
            name='SHAP_importance'
        ).sort_values(ascending=False)

    def shap_interaction_matrix(
        self,
        model,
        X: np.ndarray,
        n_samples: int = 200
    ) -> pd.DataFrame:
        """
        Compute SHAP interaction values: measures pairwise feature interactions.
        SHAP_interaction [i,j] = interaction effect of features i and j.
        """
        idx = np.random.choice(len(X), min(n_samples, len(X)), replace=False)
        X_sub = X[idx]

        explainer = shap.TreeExplainer(model)
        shap_interactions = explainer.shap_interaction_values(X_sub)

        interaction_matrix = np.abs(shap_interactions).mean(axis=0)
        return pd.DataFrame(
            interaction_matrix,
            index=self.feature_names,
            columns=self.feature_names
        )

    def feature_stability_analysis(
        self,
        models_by_period: dict,  # {date : model}
        X_by_period: dict        # {date : X_test}
    ) -> pd.DataFrame:
        """
        Analyze how feature importance changes over time.
        High instability = feature may be spurious or regime-dependent.
        """
        imp_history = {}
        for period, model in models_by_period.items():
            X = X_by_period.get(period)
            if X is None:
                continue
            explainer = shap.TreeExplainer(model)
            sv = explainer.shap_values(X)
            if isinstance(sv, list):
                sv = sv[1]
            imp_history[period] = np.abs(sv).mean(axis=0)

        imp_df = pd.DataFrame(imp_history, index=self.feature_names).T

        stability = pd.DataFrame({
            'mean_importance': imp_df.mean(),
            'std_importance': imp_df.std(),
            'cv_importance': imp_df.std() / (imp_df.mean() + 1e-9),
            'rank_stability': imp_df.rank(axis=1, ascending=False).std()
        }).sort_values('mean_importance', ascending=False)

        print("\n=== Feature Stability (lower CV = more stable) ===")
        print(stability.head(20).to_string())
        return stability

    def full_importance_report(
        self,
        model,
        X_train: np.ndarray,
        X_test: np.ndarray,
        y_test: np.ndarray
    ) -> pd.DataFrame:
        """
        Unified importance report combining all methods.
        """
        print("Computing MDI importance...")
        mdi = self.mdi_importance(model)

        print("Computing permutation importance (IC-based)...")
        pi = self.permutation_importance_ic(model, X_test, y_test)
        pi = pi.set_index('feature')

        print("Computing SHAP importance...")
        shap_vals = self.shap_analysis(model, X_train, X_test)
        shap_imp = self.shap_feature_importance(shap_vals)

        # Merge all methods
        report = pd.DataFrame({
            'MDI_rank': mdi.rank(ascending=False),
            'PI_IC_mean': pi['PI_mean'],
            'PI_rank': pi['PI_mean'].rank(ascending=False),
            'SHAP_mean_abs': shap_imp,
            'SHAP_rank': shap_imp.rank(ascending=False),
        })

        # Consensus rank (lower = more important)
        report['consensus_rank'] = report[
            ['MDI_rank', 'PI_rank', 'SHAP_rank']
        ].mean(axis=1)

        report = report.sort_values('consensus_rank')

        print("\n=== Top 20 Features by Consensus Rank ===")
        print(report.head(20).round(3).to_string())
        return report

