import numpy as np
import pandas as pd
from sklearn.linear_model import ElasticNetCV, Ridge
from sklearn.ensemble import RandomForestRegressor, ExtraTreesRegressor
import lightgbm as lgb
import xgboost as xgb
from sklearn.neural_network import MLPRegressor
from scipy.optimize import minimize
from scipy.stats import spearmanr
from sklearn.model_selection import TimeSeriesSplit

class EnsembleAlphaSystem:
    """
    Multi-model ensemble for robust alpha signal generation.

    Base models: Linear (ElasticNet), Trees (RF, ET),
    Boosting (LGB, XGB), Neural Network (MLP)
    Meta-model: Ridge regression on OOF predictions
    Weights: Dynamic IC-weighted combination
    """

    def __init__(
        self,
        use_models: list = ['elastic_net', 'random_forest', 'extra_trees', 'lightgbm', 'xgboost'],
        n_cv_folds: int = 5,
        meta_model: str = 'ridge',  # 'ridge', 'equal', 'ic_weighted'
        ic_decay: float = 0.95,     # decay for dynamic weighting
        purge_days: int = 21
    ):
        self.use_models = use_models
        self.n_folds = n_cv_folds
        self.meta_model = meta_model
        self.ic_decay = ic_decay
        self.purge_days = purge_days
        self.base_models = {}
        self.meta = None
        self.model_ic_history = {m: [] for m in use_models}

    def _get_base_models(self) -> dict:
        """Initialize base models with financially appropriate defaults."""
        models = {}

        if 'elastic_net' in self.use_models:
            models['elastic_net'] = ElasticNetCV(
                l1_ratio=[0.1, 0.5, 0.9], cv=5, max_iter=2000
            )

        if 'random_forest' in self.use_models:
            models['random_forest'] = RandomForestRegressor(
                n_estimators=300, max_depth=5,
                min_samples_leaf=50, max_features=0.3,
                n_jobs=-1, random_state=42
            )

        if 'extra_trees' in self.use_models:
            models['extra_trees'] = ExtraTreesRegressor(
                n_estimators=300, max_depth=6,
                min_samples_leaf=40, max_features=0.3,
                n_jobs=-1, random_state=42
            )

        if 'lightgbm' in self.use_models:
            models['lightgbm'] = lgb.LGBMRegressor(
                n_estimators=500, learning_rate=0.02,
                num_leaves=31, min_child_samples=50,
                feature_fraction=0.5, bagging_fraction=0.7,
                bagging_freq=5, reg_lambda=5.0,
                random_state=42, verbose=-1, n_jobs=-1
            )

        if 'xgboost' in self.use_models:
            models['xgboost'] = xgb.XGBRegressor(
                n_estimators=500, learning_rate=0.02,
                max_depth=4, subsample=0.7,
                colsample_bytree=0.6, min_child_weight=20,
                reg_lambda=5.0, tree_method='hist',
                random_state=42, n_jobs=-1, verbosity=0
            )

        if 'mlp' in self.use_models:
            models['mlp'] = MLPRegressor(
                hidden_layer_sizes=(128, 64, 32),
                activation='relu', alpha=0.01,
                learning_rate_init=0.001, max_iter=300,
                early_stopping=True, validation_fraction=0.1,
                random_state=42
            )

        return models

    def generate_oof_predictions(
        self,
        X: np.ndarray,
        y: np.ndarray,
        dates: np.ndarray  # dates for each sample (for proper split)
    ) -> pd.DataFrame:
        """
        Generate out-of-fold predictions for all base models.
        Uses forward-only splits (no look-ahead).
        """
        n = len(X)
        oof_preds = pd.DataFrame(
            np.nan,
            index=range(n),
            columns=self.use_models
        )

        # Time-based splits: each fold predicts the next period
        fold_size = n // (self.n_folds + 1)

        for fold in range(self.n_folds):
            train_end = (fold + 1) * fold_size
            test_start = train_end + self.purge_days
            test_end = test_start + fold_size

            if test_end > n:
                break

            X_tr, y_tr = X[:train_end], y[:train_end]
            X_te, y_te = X[test_start:test_end], y[test_start:test_end]

            from sklearn.preprocessing import StandardScaler
            sc = StandardScaler()
            X_tr_s = sc.fit_transform(np.nan_to_num(X_tr))
            X_te_s = sc.transform(np.nan_to_num(X_te))

            models = self._get_base_models()

            for name, model in models.items():
                try:
                    model.fit(X_tr_s, y_tr)
                    pred = model.predict(X_te_s)
                    oof_preds.loc[test_start:test_end - 1, name] = pred

                    # Track IC by fold
                    ic, _ = spearmanr(pred, y_te)
                    self.model_ic_history[name].append(ic)
                    print(f"Fold {fold + 1}, {name}: IC={ic:.4f}")

                    # Save the last fold model for final predictions
                    if fold == self.n_folds - 1:
                        self.base_models[name] = (model, sc)

                except Exception as e:
                    print(f"Warning: {name} failed on fold {fold + 1}: {e}")

        return oof_preds

    def fit_meta_model(
        self,
        oof_preds: pd.DataFrame,
        y: np.ndarray
    ) -> None:
        """
        Train meta-model on OOF predictions.
        """
        valid_mask = oof_preds.notna().all(axis=1)
        X_meta = oof_preds[valid_mask].values
        y_meta = y[valid_mask]

        if self.meta_model == 'ridge':
            self.meta = Ridge(alpha=1.0, fit_intercept=False)
            self.meta.fit(X_meta, y_meta)
            weights = self.meta.coef_
            # Normalize to sum to 1
            weights = np.abs(weights) / np.abs(weights).sum()
            print("\n=== Meta-Model Weights (Ridge) ===")
            for name, w in zip(self.use_models, weights):
                print(f" {name:20s}: {w:.3f}")

        elif self.meta_model == 'equal':
            weights = np.ones(len(self.use_models)) / len(self.use_models)

        elif self.meta_model == 'ic_weighted':
            # Weight by recent IC performance
            weights = np.array([
                np.mean(self.model_ic_history[m]) for m in self.use_models
            ])
            weights = np.clip(weights, 0, None)  # no negative weights
            weights = weights / (weights.sum() + 1e-9)
            print("\n=== Meta-Model Weights (IC-Weighted) ===")
            for name, w in zip(self.use_models, weights):
                print(f" {name:20s}: {w:.3f}")

        self.ensemble_weights = weights

    def predict(self, X: np.ndarray) -> np.ndarray:
        """
        Ensemble prediction: weighted average of base model predictions.
        """
        preds = []
        for name in self.use_models:
            if name in self.base_models:
                model, scaler = self.base_models[name]
                X_s = scaler.transform(np.nan_to_num(X))
                preds.append(model.predict(X_s))

        pred_matrix = np.column_stack(preds)  # (n, M)
        return pred_matrix @ self.ensemble_weights

    def dynamic_weights(
        self,
        recent_ics: dict,
        temperature: float = 5.0
    ) -> np.ndarray:
        """
        Softmax dynamic weighting based on recent IC performance.
        Temperature controls sharpness: low T = more equal weights.
        """
        ic_arr = np.array([recent_ics.get(m, 0.0) for m in self.use_models])
        exp_ic = np.exp(temperature * ic_arr)
        return exp_ic / exp_ic.sum()

    def ensemble_ic_decomposition(
        self,
        X_test: np.ndarray,
        y_test: np.ndarray
    ) -> pd.DataFrame:
        """
        Decompose ensemble IC into per-model contributions.
        Useful for attribution and understanding which model drives performance.
        """
        results = {}
        for name in self.use_models:
            if name in self.base_models:
                model, scaler = self.base_models[name]
                X_s = scaler.transform(np.nan_to_num(X_test))
                pred = model.predict(X_s)
                ic, pval = spearmanr(pred, y_test)
                results[name] = {
                    'IC': ic,
                    'pval': pval,
                    'weight': self.ensemble_weights[
                        list(self.use_models).index(name)
                    ]
                }

        # Ensemble IC
        ens_pred = self.predict(X_test)
        ens_ic, ens_pval = spearmanr(ens_pred, y_test)
        results['ENSEMBLE'] = {'IC': ens_ic, 'pval': ens_pval, 'weight': 1.0}

        df = pd.DataFrame(results).T
        print("\n=== Ensemble IC Decomposition ===")
        print(df.round(4).to_string())
        return df

