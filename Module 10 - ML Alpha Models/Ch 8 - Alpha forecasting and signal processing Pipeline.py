import numpy as np
import pandas as pd
from scipy import stats
from scipy.optimize import minimize
import warnings
warnings.filterwarnings('ignore')

class AlphaForecastPipeline:
    """
    Complete alpha signal processing pipeline.
    Converts raw ML predictions to tradeable, portfolio-ready alpha scores.
    """

    def __init__(
        self,
        shrinkage_method: str = 'james_stein', # 'james_stein', 'identity'
        horizons: list = [5, 21, 63],          # trading days
        max_alpha_zscores: float = 3.0         # winsorize final alphas
    ):
        self.shrinkage_method = shrinkage_method
        self.horizons = horizons
        self.max_z = max_alpha_zscores

    def rank_normalize(self, scores: pd.Series) -> pd.Series:
        """Convert raw scores to normalized ranks in [0, 1]."""
        n = scores.dropna().shape[0]
        ranks = scores.rank(method='average')
        return (ranks - 0.5) / n

    def cross_sectional_zscore(self, scores: pd.Series) -> pd.Series:
        """Convert to z-scores using robust statistics (MAD-based)."""
        med = scores.median()
        mad = (scores - med).abs().median() * 1.4826
        return (scores - med) / (mad + 1e-9)

    def bayesian_shrinkage(
        self,
        alphas: pd.DataFrame,  # (T, N) alpha scores
        ic_history: pd.Series  # historical ICs for estimating signal power
    ) -> pd.DataFrame:
        """
        James-Stein type Bayesian shrinkage.
        Shrinks alpha toward cross-sectional mean based on signal power.
        """
        # Estimate signal-to-noise ratio from IC history
        ic_mean = ic_history.mean()

        # Signal variance = fraction of alpha variance explained by signal
        # Under the factor model: R2 ~ IC^2
        signal_fraction = ic_mean ** 2
        signal_fraction = np.clip(signal_fraction, 0, 1)

        B = 1 - signal_fraction  # shrinkage coefficient

        cross_sec_mean = alphas.mean(axis=1)
        shrunk = (1 - B) * alphas + B * cross_sec_mean.values[:, None]

        print(f"Alpha shrinkage: B={B:.3f} (signal fraction={signal_fraction:.3f})")
        return shrunk

    def compute_alpha_decay(
        self,
        alpha_series: pd.DataFrame,  # (T, N) alpha scores
        max_lag: int = 63
    ) -> pd.Series:
        """
        Compute autocorrelation structure of alpha signals.
        Used to determine optimal rebalancing frequency.
        """
        # Average cross-sectional autocorrelation by lag
        autocorrs = {}
        for lag in range(1, max_lag + 1):
            lagged = alpha_series.shift(lag)
            corrs = []
            for date in alpha_series.index[lag:]:
                a1 = alpha_series.loc[date].dropna()
                a2 = lagged.loc[date].dropna()
                common = a1.index.intersection(a2.index)
                if len(common) >= 20:
                    r, _ = stats.spearmanr(a1[common], a2[common])
                    corrs.append(r)
            autocorrs[lag] = np.nanmean(corrs)

        ac_series = pd.Series(autocorrs, name='alpha_autocorr')

        # Compute half-life
        # Find lag where AC first crosses 0.5
        try:
            half_life = next(
                lag for lag, ac in autocorrs.items() if ac < 0.5
            )
        except StopIteration:
            half_life = max_lag

        print(f"\nAlpha half-life: ~{half_life} days")
        print(f"Lag-1 autocorr: {autocorrs.get(1, np.nan):.3f}")
        print(f"Lag-5 autocorr: {autocorrs.get(5, np.nan):.3f}")
        print(f"Lag-21 autocorr: {autocorrs.get(21, np.nan):.3f}")

        return ac_series

    def multi_horizon_combination(
        self,
        alpha_by_horizon: dict,   # {horizon: pd.DataFrame(T, N)}
        ic_by_horizon: dict,      # {horizon: float}
        min_ic_threshold: float = 0.02,
        turnover_penalty: float = 0.5  # penalize shorter horizons
    ) -> pd.DataFrame:
        """
        Optimally combine alphas from multiple horizons.
        Balances IC contribution against turnover cost.
        """
        valid_horizons = [
            h for h, ic in ic_by_horizon.items()
            if ic >= min_ic_threshold
        ]

        if not valid_horizons:
            print("WARNING: No horizon exceeds IC threshold!")
            valid_horizons = list(alpha_by_horizon.keys())

        H = len(valid_horizons)

        def objective(w):
            """Negative IC (to minimize) + turnover penalty."""
            combined = sum(
                w[i] * alpha_by_horizon[h]
                for i, h in enumerate(valid_horizons)
            )
            ic = ic_by_horizon.get(valid_horizons[0], 0) * w[0]  # simplified
            turnover_cost = sum(
                w[i] * turnover_penalty / h
                for i, h in enumerate(valid_horizons)
            )
            return -ic + turnover_cost

        constraints = [{'type': 'eq', 'fun': lambda w: w.sum() - 1}]
        bounds = [(0, 1)] * H

        result = minimize(
            objective,
            x0=np.ones(H) / H,
            method='SLSQP',
            bounds=bounds,
            constraints=constraints
        )

        weights = result.x
        print("\n=== Multi-Horizon Combination Weights ===")
        for h, w in zip(valid_horizons, weights):
            print(f" {h:3d}d: {w:.3f} (IC={ic_by_horizon.get(h, 0):.3f})")

        combined = sum(
            weights[i] * alpha_by_horizon[h]
            for i, h in enumerate(valid_horizons)
        )
        return combined

    def process_alpha(
        self,
        raw_predictions: pd.DataFrame,  # (T, N): ML model output
        ic_history: pd.Series = None
    ) -> pd.DataFrame:
        """
        Full alpha processing pipeline.
        """
        # Step 1: Cross-sectional rank normalize
        print("Step 1: Rank normalizing...")
        ranked = raw_predictions.apply(self.rank_normalize, axis=1)

        # Step 2: Z-score
        print("Step 2: Z-scoring...")
        zscored = ranked.apply(self.cross_sectional_zscore, axis=1)

        # Step 3: Winsorize
        print("Step 3: Winsorizing...")
        winsorized = zscored.clip(-self.max_z, self.max_z)

        # Step 4: Bayesian shrinkage
        if ic_history is not None:
            print("Step 4: Shrinking...")
            final = self.bayesian_shrinkage(winsorized, ic_history)
        else:
            final = winsorized

        print(f"\nAlpha stats:")
        print(f" Mean: {final.mean().mean():.4f}")
        print(f" Std: {final.std().mean():.4f}")
        print(f" Coverage: {final.notna().mean().mean() * 100:.1f}%")
        return final

    def alpha_to_portfolio_weights(
        self,
        alpha: pd.Series,             # cross-section at one date
        risk_model: pd.DataFrame,     # (N, N) covariance matrix
        n_longs: int = 100,
        n_shorts: int = 100,
        target_volatility: float = 0.10  # annual target vol
    ) -> pd.Series:
        """
        Convert alpha scores to dollar-neutral long/short weights.
        Simple approach: rank-weighted with volatility scaling.
        """
        alpha = alpha.dropna().sort_values(ascending=False)
        n = len(alpha)

        # Long top N, short bottom N
        longs = alpha.iloc[:n_longs]
        shorts = alpha.iloc[-n_shorts:]

        # Equal dollar within long/short legs
        long_weights = pd.Series(1 / n_longs, index=longs.index)
        short_weights = -pd.Series(1 / n_shorts, index=shorts.index)

        weights = pd.concat([long_weights, short_weights])

        # Scale to target volatility
        if risk_model is not None:
            subset = risk_model.loc[weights.index, weights.index]
            w = weights.values
            port_var = w @ subset.values @ w
            port_vol = np.sqrt(port_var * 252)  # annualized
            scale = target_volatility / (port_vol + 1e-9)
            weights *= scale
        return weights

