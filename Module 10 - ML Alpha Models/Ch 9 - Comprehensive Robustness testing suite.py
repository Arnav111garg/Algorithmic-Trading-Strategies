import numpy as np
import pandas as pd
from scipy import stats
from itertools import combinations
from sklearn.model_selection import KFold
import warnings
warnings.filterwarnings('ignore')

class RobustnessTestSuite:
    """
    Complete robustness testing suite for ML alpha models.
    Tests: permutation, regime stability, haircut SR, CPCV.
    """

    def __init__(
        self,
        n_permutations: int = 1000,
        n_bootstrap: int = 1000,
        embargo_days: int = 21,
        confidence_level: float = 0.95
    ):
        self.n_perms = n_permutations
        self.n_boot = n_bootstrap
        self.embargo = embargo_days
        self.alpha_level = 1 - confidence_level

    # 1. PERMUTATION TEST
    def permutation_test_ic(
        self,
        predicted: np.ndarray,
        actual: np.ndarray
    ) -> dict:
        """
        Test H0: IC = 0 via label permutation.
        If p-value > 0.05: you have no signal, just noise.
        """
        observed_ic, _ = stats.spearmanr(predicted, actual)

        perm_ics = np.zeros(self.n_perms)
        rng = np.random.default_rng(42)
        for i in range(self.n_perms):
            shuffled = rng.permutation(actual)
            perm_ics[i], _ = stats.spearmanr(predicted, shuffled)

        p_value = (np.abs(perm_ics) >= np.abs(observed_ic)).mean()

        print("\n=== Permutation Test ===")
        print(f" Observed IC: {observed_ic:.4f}")
        print(f" Null IC (mean): {perm_ics.mean():.4f}")
        print(f" Null IC (std): {perm_ics.std():.4f}")
        print(f" Z-score: {(observed_ic - perm_ics.mean()) / perm_ics.std():.2f}")
        print(f" p-value: {p_value:.4f}")
        print(f" Significant: {'YES' if p_value < self.alpha_level else 'NO'}")

        return {
            'observed_ic': observed_ic,
            'p_value': p_value,
            'null_mean': perm_ics.mean(),
            'null_std': perm_ics.std(),
            'null_distribution': perm_ics
        }

    # 2. DEFLATED SHARPE RATIO
    def deflated_sharpe_ratio(
        self,
        sr_observed: float,
        n_trials: int,
        sr_std: float = 0.5,  # std of trial SRs
        n_obs: int = 252       # number of observations
    ) -> dict:
        """
        Bailey et al (2014) Deflated Sharpe Ratio.
        Corrects for multiple testing bias.
        """
        from scipy.special import erf

        # Expected maximum SR under multiple testing
        euler_gamma = 0.5772156649
        # Approximation for expected max of n_trials normal (0, sr_std)
        z = stats.norm.ppf(1 - 1 / n_trials)
        z_adj = stats.norm.ppf(1 - 1 / (n_trials * np.e))
        expected_max_sr = sr_std * (
            (1 - euler_gamma) * z + euler_gamma * z_adj
        )

        # Prob that observed SR is greater than expected maximum
        sigma_sr = np.sqrt(1 / n_obs)  # simplified SR std
        dsr = (sr_observed - expected_max_sr) / sigma_sr
        prob = stats.norm.cdf(dsr)

        print("\n=== Deflated Sharpe Ratio ===")
        print(f" Observed SR: {sr_observed:.3f}")
        print(f" Trials tested: {n_trials}")
        print(f" Expected max SR: {expected_max_sr:.3f}")
        print(f" Deflated SR: {dsr:.3f}")
        print(f" P(significant): {prob:.4f}")
        print(f" Min SR to be 95% sig: {expected_max_sr + 1.645 * sigma_sr:.3f}")

        return {'dsr': dsr, 'prob': prob, 'expected_max_sr': expected_max_sr}

    # 3. REGIME STABILITY ANALYSIS
    def regime_ic_stability(
        self,
        ic_series: pd.Series,
        regime_labels: pd.Series  # must match ic_series index
    ) -> pd.DataFrame:
        """
        Analyze IC stability across different market regimes.
        """
        common = ic_series.index.intersection(regime_labels.index)
        ic = ic_series.loc[common]
        regimes = regime_labels.loc[common]

        results = {}
        for regime in regimes.unique():
            mask = regimes == regime
            regime_ic = ic[mask]
            if len(regime_ic) < 10:
                continue
            t_stat = regime_ic.mean() / (regime_ic.std() + 1e-9) * np.sqrt(len(regime_ic))

            results[regime] = {
                'n_periods': len(regime_ic),
                'mean_IC': regime_ic.mean(),
                'std_IC': regime_ic.std(),
                'IR': regime_ic.mean() / (regime_ic.std() + 1e-9),
                't_stat': t_stat,
                'pct_positive': (regime_ic > 0).mean()
            }

        df = pd.DataFrame(results).T
        print("\n=== Regime IC Stability ===")
        print(df.round(3).to_string())
        return df

    # 4. BOOTSTRAP IC CONFIDENCE INTERVALS
    def bootstrap_ic_confidence(
        self,
        ic_series: pd.Series,
        block_size: int = 21  # for block bootstrap (accounts for autocorrelation)
    ) -> dict:
        """
        Block bootstrap to get confidence intervals for mean IC.
        Block bootstrap preserves time-series autocorrelation structure.
        """
        n = len(ic_series)
        n_blocks = n // block_size
        ic_arr = ic_series.values

        boot_means = np.zeros(self.n_boot)
        rng = np.random.default_rng(42)

        for b in range(self.n_boot):
            # Sample blocks with replacement
            block_starts = rng.integers(0, n - block_size, size=n_blocks)
            indices = np.concatenate([
                np.arange(s, s + block_size) for s in block_starts
            ])[:n]
            boot_sample = ic_arr[indices % n]
            boot_means[b] = boot_sample.mean()

        ci_low = np.percentile(boot_means, 2.5)
        ci_high = np.percentile(boot_means, 97.5)

        print("\n=== Bootstrap IC Statistics (Block Bootstrap) ===")
        print(f" Mean IC: {ic_arr.mean():.4f}")
        print(f" 95% CI: [{ci_low:.4f}, {ci_high:.4f}]")
        print(f" CI excludes zero: {'YES' if ci_low > 0 else 'NO'}")
        print(f" IR: {ic_arr.mean() / ic_arr.std():.3f}")

        return {'mean': ic_arr.mean(), 'ci_low': ci_low, 'ci_high': ci_high, 'bootstrap_distribution': boot_means}

    # 5. FEATURE SHUFFLE TEST
    def feature_contribution_test(
        self,
        model,
        X_test: np.ndarray,
        y_test: np.ndarray,
        feature_names: list,
        n_repeats: int = 50
    ) -> pd.DataFrame:
        """
        Test which features contribute statistically significant IC.
        Features with p-value > 0.05 after FDR correction may be spurious.
        """
        from statsmodels.stats.multitest import fdrcorrection

        pred_full = model.predict(X_test)
        ic_full, _ = stats.spearmanr(pred_full, y_test)

        p_values = []
        ic_drops = []

        rng = np.random.default_rng(42)
        for j, feat in enumerate(feature_names):
            drops = []
            for _ in range(n_repeats):
                X_perm = X_test.copy()
                X_perm[:, j] = rng.permutation(X_perm[:, j])
                pred_perm = model.predict(X_perm)
                ic_perm, _ = stats.spearmanr(pred_perm, y_test)
                drops.append(ic_full - ic_perm)

            drop_mean = np.mean(drops)
            drop_std = np.std(drops) + 1e-9
            t = drop_mean / drop_std * np.sqrt(n_repeats)
            p = 1 - stats.norm.cdf(t)  # one-sided: IC drop > 0
            ic_drops.append(drop_mean)
            p_values.append(p)

        # FDR correction (Benjamini-Hochberg)
        reject, p_adjusted = fdrcorrection(p_values, alpha=0.05)

        result = pd.DataFrame({
            'feature': feature_names,
            'IC_drop': ic_drops,
            'p_raw': p_values,
            'p_fdr': p_adjusted,
            'significant': reject
        }).sort_values('IC_drop', ascending=False)

        n_sig = reject.sum()
        print(f"\n=== Feature Significance (FDR corrected) ===")
        print(f" Significant features: {n_sig}/{len(feature_names)}")
        print(result[result.significant].head(20).round(4).to_string())
        return result

    # 6. FULL ROBUSTNESS REPORT
    def full_report(
        self,
        ic_series: pd.Series,
        predicted: np.ndarray,
        actual: np.ndarray,
        n_models_tested: int = 1,
        regime_labels: pd.Series = None
    ) -> dict:
        """Run the full robustness test suite and summarize results."""
        print("=" * 60)
        print(" ROBUSTNESS TEST SUITE ML ALPHA MODEL ")
        print("=" * 60)

        results = {}
        # 1. Permutation test
        results['permutation'] = self.permutation_test_ic(predicted, actual)

        # 2. Bootstrap CI
        results['bootstrap'] = self.bootstrap_ic_confidence(ic_series)

        # 3. Deflated SR
        sharpe = ic_series.mean() / ic_series.std() * np.sqrt(252)
        results['dsr'] = self.deflated_sharpe_ratio(
            sharpe, n_models_tested, n_obs=len(ic_series)
        )

        # 4. Regime analysis
        if regime_labels is not None:
            results['regime'] = self.regime_ic_stability(
                ic_series, regime_labels
            )

        # Summary
        print("\n" + "=" * 60)
        print(" ROBUSTNESS SUMMARY ")
        print("=" * 60)
        passes = 0
        tests = 0

        tests += 1
        perm_pass = results['permutation']['p_value'] < self.alpha_level
        print(f"[{'PASS' if perm_pass else 'FAIL'}] Permutation test (p={results['permutation']['p_value']:.4f})")
        passes += int(perm_pass)

        tests += 1
        boot_pass = results['bootstrap']['ci_low'] > 0
        print(f"[{'PASS' if boot_pass else 'FAIL'}] Bootstrap CI ([{results['bootstrap']['ci_low']:.4f}, {results['bootstrap']['ci_high']:.4f}])")
        passes += int(boot_pass)

        tests += 1
        dsr_pass = results['dsr']['prob'] > 0.95
        print(f"[{'PASS' if dsr_pass else 'FAIL'}] Deflated SR (p={results['dsr']['prob']:.4f})")
        passes += int(dsr_pass)

        print(f"\nOverall: {passes}/{tests} tests passed")
        verdict = "STRONG ALPHA" if passes == tests else \
                  "WEAK ALPHA" if passes > 0 else "NO ALPHA"
        print(f" Verdict: {verdict}")

        return results

