import numpy as np
import pandas as pd
from scipy import stats
from sklearn.linear_model import Ridge
from sklearn.covariance import LedoitWolf

class AlphaAggregator:
    """
    Production-grade alpha aggregation engine.
    Combines multiple alpha signals using IC-weighting,
    cross-signal correlation adjustments, and optional
    non-linear stacking.
    """

    def __init__(self, method='ic_weighted', lookback=252):
        self.method = method
        self.lookback = lookback
        self.weights_ = None
        self.signal_corr_ = None

    def _compute_ic(self, signals: pd.DataFrame, returns: pd.Series) -> pd.DataFrame:
        """
        Compute rolling Information Coefficient for each signal.
        IC = rank correlation of signal with next-period return.
        Uses Spearman rank correlation (robust to outliers).
        """
        ics = {}
        for col in signals.columns:
            # Cross-sectional IC at each date
            daily_ics = signals[col].groupby(level='date').apply(
                lambda s: stats.spearmanr(
                    s.values,
                    returns.loc[s.index].values,
                    nan_policy='omit'
                ).correlation
                if len(s.dropna()) > 10 else np.nan
            )
            ics[col] = daily_ics
        return pd.DataFrame(ics)

    def _compute_signal_correlation(self, signals: pd.DataFrame) -> np.ndarray:
        """
        Estimate cross-signal correlation matrix with Ledoit-Wolf shrinkage.
        Signals must be cross-sectionally z-scored first. Treat different dates
        and assets as independent observation samples.
        """
        # Clean and align data
        clean_data = signals.dropna()
        lw = LedoitWolf()
        lw.fit(clean_data.values)
        # Extract correlation from covariance matrix
        cov = lw.covariance_
        std = np.sqrt(np.diag(cov))
        corr = cov / np.outer(std, std)
        return corr

    def fit(self, signals: pd.DataFrame, returns: pd.Series):
        """
        Fit aggregation weights from historical data.

        Parameters
        ----------
        signals : pd.DataFrame
            MultiIndex (date, asset) x (signal_name)
            Each signal must be cross-sectionally z-scored.
        returns : pd.Series
            MultiIndex (date, asset) next-period returns.
        """
        ic_df = self._compute_ic(signals, returns)

        # Rolling mean IC over lookback window
        mean_ic = ic_df.tail(self.lookback).mean()
        ic_se = ic_df.tail(self.lookback).std() / np.sqrt(self.lookback)
        t_stats = mean_ic / ic_se  # t-stat for signal significance

        # Filter: only use signals with |t-stat| > 2.0
        significant = t_stats[t_stats.abs() > 2.0].index
        mean_ic = mean_ic[significant]

        if self.method == 'equal':
            self.weights_ = pd.Series(
                1.0 / len(significant), index=significant
            )

        elif self.method == 'ic_weighted':
            # Weight by absolute IC, preserve sign
            w = mean_ic.abs()
            self.weights_ = (mean_ic.sign() * w) / w.sum()

        elif self.method == 'ic_ir_adjusted':
            # Account for cross-signal correlation via Markowitz on signal space
            self.signal_corr_ = self._compute_signal_correlation(
                signals[significant]
            )
            ic_vec = mean_ic.values
            Psi_inv = np.linalg.inv(self.signal_corr_)
            raw_w = Psi_inv @ ic_vec
            self.weights_ = pd.Series(
                raw_w / np.abs(raw_w).sum(),
                index=significant
            )

        elif self.method == 'ridge_stack':
            # Linear stacking via Ridge regression (regularized to prevent overfitting)
            X = signals[significant].unstack('asset').values
            y = returns.unstack('asset').values
            # Vectorize across dates
            X_flat = X.reshape(-1, len(significant))
            y_flat = y.reshape(-1)
            mask = ~np.isnan(X_flat).any(axis=1) & ~np.isnan(y_flat)
            ridge = Ridge(alpha=1.0, fit_intercept=False)
            ridge.fit(X_flat[mask], y_flat[mask])
            raw_w = ridge.coef_
            self.weights_ = pd.Series(
                raw_w / np.abs(raw_w).sum(),
                index=significant
            )

        print(f"Fitted {self.method} aggregator:")
        print(f" Signals used: {list(self.weights_.index)}")
        print(f" Weights: {self.weights_.round(4).to_dict()}")
        print(f" Estimated IR gain vs best signal: {np.sqrt((self.weights_.values ** 2).sum() * self.lookback):.3f}")
        return self

    def predict(self, signals: pd.DataFrame) -> pd.Series:
        """
        Combine signals into aggregated alpha using fitted weights.

        Returns
        -------
        pd.Series : MultiIndex (date, asset) combined alpha, z-scored.
        """
        if self.weights_ is None:
            raise RuntimeError("Call fit() first.")

        avail = [c for c in self.weights_.index if c in signals.columns]
        combined = (signals[avail] * self.weights_[avail]).sum(axis=1)

        # Re-standardize cross-sectionally (critical!)
        combined = combined.groupby(level='date').transform(
            lambda x: (x - x.mean()) / (x.std() + 1e-8)
        )
        return combined

