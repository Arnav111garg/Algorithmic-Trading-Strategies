if __name__ == '__main__':
    np.random.seed(42)
    dates = pd.date_range('2018-01-01', periods=500, freq='B')
    assets = [f'Asset_{i:03d}' for i in range(100)]
    idx = pd.MultiIndex.from_product([dates, assets], names=['date', 'asset'])

    # Simulate signals and returns
    signals = pd.DataFrame(
        np.random.randn(len(idx), 3),
        index=idx,
        columns=['Momentum', 'Value', 'Quality']
    )
    # Make signals slightly predictive
    true_weights = np.array([0.5, 0.3, 0.2])
    noise = np.random.randn(len(idx)) * 0.9
    returns = pd.Series(
        signals.values @ true_weights + noise, index=idx,
        name='return'
    )

    agg = AlphaAggregator(method='ic_ir_adjusted', lookback=250)
    agg.fit(signals, returns)
    combined_alpha = agg.predict(signals)
    print(f"\nCombined alpha stats:")
    print(f" Mean: {combined_alpha.mean():.4f}")
    print(f" Std: {combined_alpha.std():.4f}")

