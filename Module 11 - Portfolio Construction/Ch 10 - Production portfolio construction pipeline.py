import numpy as np
import pandas as pd
import cvxpy as cp
from dataclasses import dataclass, field
from typing import List, Dict, Optional
import warnings

@dataclass
class FundMandate:
    """Complete specification of a quant fund's portfolio mandate."""
    # Fund type
    fund_type: str = 'equity_long_short'  # or 'long_only', 'market_neutral'

    # Capital
    aum: float = 1e9  # Assets under management ($)

    # Leverage
    gross_exposure_max: float = 2.0  # x AUM
    net_exposure_max: float = 0.10   # fraction of AUM

    # Risk
    annual_vol_target: float = 0.10   # 10% annual vol
    max_drawdown_limit: float = -0.15 # Hard stop at -15%
    var_95_daily_limit: float = 0.015  # 1.5% daily VaR

    # Positions
    max_single_position: float = 0.04  # 4% of AUM
    min_position_size: float = 0.0005

    # Factor limits
    beta_limit: float = 0.05
    sector_limit: float = 0.06
    factor_limits: Dict[str, float] = field(
        default_factory=lambda: {
            'market': 0.05,
            'value': 0.10,
            'momentum': 0.10,
            'quality': 0.10,
            'size': 0.12,
            'volatility': 0.08,
        }
    )

    # Liquidity
    adv_participation: float = 0.15   # Max 15% of ADV

    # Turnover
    max_one_way_turnover: float = 0.40  # Per rebalance cycle


class InstitutionalPortfolioManager:
    """
    Complete institutional portfolio management system.
    Integrates all modules: alpha aggregation, risk budgeting,
    constrained optimization, turnover control.
    """

    def __init__(self, mandate: FundMandate):
        self.mandate = mandate
        self.portfolio_history: List[pd.Series] = []
        self.current_weights = None
        self.risk_history: List[dict] = []

    def run_full_pipeline(
        self,
        alpha_signals: pd.DataFrame,    # [N x K] cross-sectional signals
        returns_history: pd.DataFrame,  # [T x N] historical returns
        sector_dummy: np.ndarray,       # [N x S] sector membership
        factor_loadings: np.ndarray,    # [N x F] factor betas
        factor_names: list,
        market_betas: np.ndarray,       # [N] market betas
        adv: np.ndarray,                # [N] avg daily volume ($)
        date: pd.Timestamp,
        signal_weights: np.ndarray = None,
    ) -> dict:
        """
        End-to-end portfolio construction for one rebalance date.
        """
        m = self.mandate
        N = len(alpha_signals)
        K = alpha_signals.shape[1]

        print(f"\n{'='*60}")
        print(f" Portfolio Construction : {date.strftime('%Y-%m-%d')}")
        print(f"{'='*60}")

        # Step 1: Covariance Estimation
        from sklearn.covariance import LedoitWolf
        lw = LedoitWolf().fit(returns_history.values)
        cov = lw.covariance_
        daily_vols = np.sqrt(np.diag(cov))
        annual_vols = daily_vols * np.sqrt(252)

        # Step 2: Alpha Aggregation
        if signal_weights is None:
            signal_weights = np.ones(K) / K  # Equal weight fallback

        # Cross-sectional z-score each signal first
        alpha_zscored = alpha_signals.apply(
            lambda col: (col - col.mean()) / (col.std() + 1e-8)
        ).values

        # Combine
        combined_alpha = alpha_zscored @ signal_weights

        # Re-z-score
        combined_alpha = (combined_alpha - combined_alpha.mean()) / (combined_alpha.std() + 1e-8)

        print(f" Step 1-2: Alpha range: [{combined_alpha.min():.3f}, {combined_alpha.max():.3f}]")

        # Step 3: Volatility Targeting
        port_vol_naive = np.sqrt(combined_alpha @ cov @ combined_alpha / N**2) * np.sqrt(252)
        leverage = min(m.annual_vol_target / (port_vol_naive + 1e-8), m.gross_exposure_max)
        print(f" Step 3: Naive port vol = {port_vol_naive:.2%}, Leverage = {leverage:.2f}x")

        # Step 4: Constrained Optimization
        w = cp.Variable(N)

        # Expected return (alpha-based)
        exp_ret = combined_alpha * 0.15 / annual_vols  # Scale to return

        # Risk aversion scaled by vol target
        lam = 2.0 / (m.annual_vol_target ** 2)

        # Transaction costs
        to_penalty = 0.0010  # 10 bps
        w0 = (self.current_weights.values if self.current_weights is not None else np.zeros(N))

        objective = cp.Minimize(
            lam * cp.quad_form(w, cov)
            - exp_ret @ w
            + to_penalty * cp.norm1(w - w0)
        )

        constraints = [
            cp.sum(w) == 0.0,                        # dollar neutral
            cp.norm1(w) <= m.gross_exposure_max,     # gross
            cp.abs(cp.sum(w)) <= m.net_exposure_max, # net
            w <= m.max_single_position,              # max long
            w >= -m.max_single_position,             # max short
        ]

        # Sector limits
        for s in range(sector_dummy.shape[1]):
            constraints.append(cp.abs(sector_dummy[:, s] @ w) <= m.sector_limit)

        # Market beta limit
        constraints.append(cp.abs(market_betas @ w) <= m.beta_limit)

        # Factor limits
        for f, fname in enumerate(factor_names):
            limit = m.factor_limits.get(fname, 0.10)
            constraints.append(cp.abs(factor_loadings[:, f] @ w) <= limit)

        # Liquidity
        adv_limit = m.adv_participation * adv / m.aum
        constraints.append(cp.abs(w) <= adv_limit)

        # Turnover
        if self.current_weights is not None:
            constraints.append(cp.norm1(w - w0) <= m.max_one_way_turnover)

        prob = cp.Problem(objective, constraints)
        prob.solve(solver=cp.OSQP, max_iter=10000, eps_abs=1e-7, verbose=False)

        if prob.status not in ['optimal', 'optimal_inaccurate']:
            print(f" WARNING: Optimization {prob.status}. Returning previous weights.")
            return {'weights': self.current_weights, 'status': prob.status}

        w_opt = w.value

        # Step 5: Risk Decomposition
        port_vol = np.sqrt(w_opt @ cov @ w_opt) * np.sqrt(252)
        var_95 = port_vol * 1.645 / np.sqrt(252)
        gross_exp = np.abs(w_opt).sum()
        net_exp = w_opt.sum()
        beta_exp = market_betas @ w_opt
        turnover = np.abs(w_opt - w0).sum() / 2

        risk_report = {
            'date': date,
            'port_annual_vol': port_vol,
            'var_95_daily': var_95,
            'gross_exposure': gross_exp,
            'net_exposure': net_exp,
            'market_beta': beta_exp,
            'one_way_turnover': turnover,
            'n_longs': (w_opt > 0.0005).sum(),
            'n_shorts': (w_opt < -0.0005).sum(),
            'max_position': np.abs(w_opt).max(),
        }
        self.risk_history.append(risk_report)

        # Step 6: Risk Limit Check
        alerts = []
        if var_95 > m.var_95_daily_limit:
            alerts.append(f"VaR {var_95:.2%} > limit {m.var_95_daily_limit:.2%}")
        if abs(beta_exp) > m.beta_limit * 1.5:
            alerts.append(f"Beta {beta_exp:.3f} near limit")
        if alerts:
            print(f" RISK ALERTS: {alerts}")

        # Step 7: Update State
        self.current_weights = pd.Series(w_opt, index=alpha_signals.index)

        print(f"\nPortfolio Summary:")
        print(f" Annual Vol: {port_vol:.2%} (target: {m.annual_vol_target:.2%})")
        print(f" Daily VaR 95%: {var_95:.2%}")
        print(f" Gross Exposure : {gross_exp:.2f}x")
        print(f" Net Exposure : {net_exp:.3f}")
        print(f" Market Beta : {beta_exp:.4f}")
        print(f" One-Way TO: {turnover:.3f}")
        print(f" Longs/Shorts : {risk_report['n_longs']}/{risk_report['n_shorts']}")

        return {
            'weights': self.current_weights,
            'risk_report': risk_report,
            'status': prob.status,
            'alerts': alerts,
        }

    def compute_performance(
        self,
        weights_history: pd.DataFrame,
        returns: pd.DataFrame
    ) -> pd.DataFrame:
        """Compute portfolio P&L and performance metrics."""
        # Align dates (weights from t apply to returns at t+1)
        w_lag = weights_history.shift(1).dropna()
        common_dates = w_lag.index.intersection(returns.index)
        port_ret = (w_lag.loc[common_dates] * returns.loc[common_dates]).sum(axis=1)

        cum_ret = (1 + port_ret).cumprod()
        ann_ret = port_ret.mean() * 252
        ann_vol = port_ret.std() * np.sqrt(252)
        sharpe = ann_ret / (ann_vol + 1e-8)
        drawdown = cum_ret / cum_ret.cummax() - 1
        max_dd = drawdown.min()
        calmar = ann_ret / abs(max_dd + 1e-8)

        print(f"\nPerformance Attribution:")
        print(f" Annualized Return : {ann_ret:.2%}")
        print(f" Annualized Vol: {ann_vol:.2%}")
        print(f" Sharpe Ratio : {sharpe:.3f}")
        print(f" Max Drawdown : {max_dd:.2%}")
        print(f" Calmar Ratio : {calmar:.3f}")

        return pd.DataFrame({
            'portfolio_return': port_ret,
            'cumulative_return': cum_ret,
            'drawdown': drawdown,
        })

