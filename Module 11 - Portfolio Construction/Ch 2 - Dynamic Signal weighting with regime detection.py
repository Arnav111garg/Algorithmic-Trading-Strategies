import numpy as np
import pandas as pd
from hmmlearn import hmm
from scipy.special import softmax

class DynamicSignalWeighter:
    """
    Dynamic signal weighting using:
    1. EWMA IC estimates with ridge shrinkage
    2. HMM-based regime detection
    3. Regime-conditional signal weights
    """

    def __init__(
        self,
        n_regimes=3,
        ewma_halflife=63,
        shrinkage_lambda=0.5,
        min_t_stat=1.5
    ):
        self.n_regimes = n_regimes
        self.ewma_halflife = ewma_halflife
        self.shrinkage_lambda = shrinkage_lambda
        self.min_t_stat = min_t_stat
        self.hmm_model_ = None
        self.regime_weights_ = None # shape: (n_regimes, n_signals)

    def _fit_hmm(self, market_returns: np.ndarray):
        """Fit Hidden Markov Model to market returns for regime detection."""
        # Use (return, abs(return)) as 2D observation
        obs = np.column_stack([
            market_returns,
            np.abs(market_returns)
        ])
        model = hmm.GaussianHMM(
            n_components=self.n_regimes,
            covariance_type='full',
            n_iter=200,
            random_state=42
        )
        model.fit(obs.reshape(-1, 2))
        self.hmm_model_ = model
        return model

    def _compute_ewma_ic(self, ic_series: pd.Series) -> tuple:
        """
        Compute EWMA IC with ridge shrinkage.
        """
        alpha = 1 - 2 ** (-1 / self.ewma_halflife)
        ewma_ic = ic_series.ewm(halflife=self.ewma_halflife).mean().iloc[-1]
        # Ridge shrinkage toward zero
        n = len(ic_series.dropna())
        shrunk_ic = ewma_ic / (1 + self.shrinkage_lambda / max(n, 1))

        # IC standard error (analytical for rank correlation)
        ic_se = np.sqrt((1 - ewma_ic ** 2) / max(n - 2, 1))
        t_stat = shrunk_ic / (ic_se + 1e-8)
        return shrunk_ic, t_stat

    def fit(self, ic_panel: pd.DataFrame, market_returns: pd.Series):
        """
        Fit regime model and estimate regime-conditional weights.

        Parameters
        ----------
        ic_panel : pd.DataFrame [dates x signals] daily IC values
        market_returns : pd.Series market index daily returns
        """
        # 1. Fit HMM on market returns
        mkt = market_returns.reindex(ic_panel.index).dropna().values
        self._fit_hmm(mkt)

        # 2. Get regime assignments
        obs = np.column_stack([mkt, np.abs(mkt)])
        hidden_states = self.hmm_model_.predict(obs)

        # 3. Compute IC per signal per regime
        self.regime_weights_ = np.zeros((self.n_regimes, ic_panel.shape[1]))

        for regime in range(self.n_regimes):
            mask = hidden_states == regime
            if mask.sum() < 20: # insufficient data
                continue
            regime_ics = ic_panel.iloc[mask]
            for j, col in enumerate(ic_panel.columns):
                ic_in_regime = regime_ics[col].dropna()
                mean_ic = ic_in_regime.mean()
                se_ic = ic_in_regime.std() / np.sqrt(len(ic_in_regime))
                t_stat = mean_ic / (se_ic + 1e-8)
                # Only use significant signals per regime
                if abs(t_stat) >= self.min_t_stat:
                    self.regime_weights_[regime, j] = mean_ic
                else:
                    self.regime_weights_[regime, j] = 0.0

            # Normalize (sum to 1 within regime)
            row = self.regime_weights_[regime]
            pos_sum = np.abs(row).sum()
            if pos_sum > 0:
                self.regime_weights_[regime] = row / pos_sum

        # Print regime summary
        print("Regime IC Summary:")
        for r in range(self.n_regimes):
            state_mask = hidden_states == r
            regime_vol = np.std(mkt[state_mask]) * np.sqrt(252)
            regime_ret = np.mean(mkt[state_mask]) * 252
            print(f"Regime {r}: {state_mask.sum()} days | Ann.Ret={regime_ret:.2%} | Ann.Vol={regime_vol:.2%}")
            print(f"  Weights: " + " | ".join([
                f"{col}={self.regime_weights_[r, j]:.3f}"
                for j, col in enumerate(ic_panel.columns)
            ]))

    def predict_weights(self, market_returns: np.ndarray) -> np.ndarray:
        """
        Predict signal weights given recent market returns.
        Returns soft-blended weights from HMM regime posteriors.
        """
        obs = np.column_stack([market_returns, np.abs(market_returns)])
        # Get posterior regime probabilities
        log_posteriors = self.hmm_model_.predict_proba(obs)
        posterior = log_posteriors[-1] # Most recent period

        # Blend regime weights by posterior probability
        blended = posterior @ self.regime_weights_
        # Re-normalize
        total = np.abs(blended).sum()
        return blended / max(total, 1e-8)

