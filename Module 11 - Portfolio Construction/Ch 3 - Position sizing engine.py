import numpy as np
import pandas as pd
from arch import arch_model
from dataclasses import dataclass
from typing import Optional

@dataclass
class PositionSizerConfig:
    kelly_fraction: float = 0.33          # Fraction of full Kelly
    max_position_pct: float = 0.05        # Max single position (% of AUM)
    min_position_pct: float = 0.0005      # Min position below which we skip
    notrade_halfwidth: float = 0.25       # Half-width of no-trade zone (bps)
    vol_target: float = 0.15              # Annual vol target for portfolio
    use_garch: bool = True                 # Use GARCH (1,1) vol forecast
    garch_p: int = 1
    garch_q: int = 1

class PositionSizer:
    """
    Full pipeline: alpha signal -> sized positions.
    Handles volatility scaling, Kelly fraction, no-trade zones.
    """

    def __init__(self, config: PositionSizerConfig = None):
        self.config = config or PositionSizerConfig()
        self.garch_models_ = {}
        self.vol_forecasts_ = {}

    def fit_garch(self, returns: pd.DataFrame):
        """Fit GARCH (1,1) on each asset's return history."""
        for asset in returns.columns:
            ret = returns[asset].dropna() * 100  # percent for GARCH
            if len(ret) < 60:
                continue
            try:
                am = arch_model(
                    ret,
                    vol='Garch',
                    p=self.config.garch_p,
                    q=self.config.garch_q,
                    dist='normal'
                )
                res = am.fit(disp='off', show_warning=False)
                # 1-step ahead forecast
                fc = res.forecast(horizon=1)
                # Convert back to decimal
                self.vol_forecasts_[asset] = np.sqrt(
                    fc.variance.values[-1, 0]
                ) / 100 * np.sqrt(252)
                self.garch_models_[asset] = res
            except Exception:
                # Fallback to realized vol
                self.vol_forecasts_[asset] = ret.std() / 100 * np.sqrt(252)

    def compute_positions(
        self,
        alpha: pd.Series,               # alpha (z-scored)
        current_positions: pd.Series,   # current dollar positions
        aum: float,                     # total AUM in dollars
        returns_history: Optional[pd.DataFrame] = None,
    ) -> pd.Series:
        """
        Compute target positions from alpha signals.

        Parameters
        ----------
        alpha : pd.Series [ asset -> alpha z-score ]
        current_positions : pd.Series [ asset -> current $ position ]
        aum : float Assets under management
        returns_history : pd.DataFrame [ dates x assets ] for GARCH

        Returns
        -------
        pd.Series [ asset -> target $ position ]
        """
        assets = alpha.index
        positions = pd.Series(0.0, index=assets)

        # Step 1: Get volatility forecast
        if self.config.use_garch and returns_history is not None:
            if not self.vol_forecasts_:
                self.fit_garch(returns_history)
            vols = pd.Series({
                a: self.vol_forecasts_.get(
                    a,
                    returns_history[a].std() * np.sqrt(252) if a in returns_history else 0.20
                )
                for a in assets
            })
        else:
            # Fallback: use realized vol
            if returns_history is not None:
                vols = returns_history[assets].std() * np.sqrt(252)
            else:
                vols = pd.Series(0.20, index=assets)

        vols = vols.clip(lower=0.05)  # Floor at 5% annual vol

        # Step 2: Volatility-scaled alpha
        scaled_alpha = alpha / vols

        # Step 3: Scale to vol target
        # Equal-vol portfolio: each asset gets target_vol / N
        N = len(assets)
        per_asset_vol_target = self.config.vol_target / np.sqrt(N)

        # Dollar position: target_vol_$ = position * vol
        target_dollar = (
            scaled_alpha * per_asset_vol_target * aum / (scaled_alpha.std() + 1e-8)
        )

        # Step 4: Apply Kelly fraction
        target_dollar *= self.config.kelly_fraction

        # Step 5: Apply position limits
        max_pos = self.config.max_position_pct * aum
        min_pos = self.config.min_position_pct * aum
        target_dollar = target_dollar.clip(-max_pos, max_pos)

        # Step 6: No-trade zone filter
        curr = current_positions.reindex(assets).fillna(0)
        halfwidth = self.config.notrade_halfwidth * aum

        for asset in assets:
            target = target_dollar[asset]
            current = curr[asset]
            diff = target - current
            if abs(diff) < halfwidth:
                positions[asset] = current  # hold
            else:
                positions[asset] = target   # trade to target

        # Step 7: Zero out tiny positions
        positions[positions.abs() < min_pos * aum] = 0.0

        return positions

    def position_summary(self, positions: pd.Series, aum: float):
        """Print position statistics."""
        gross = positions.abs().sum()
        net = positions.sum()
        n_long = (positions > 0).sum()
        n_short = (positions < 0).sum()
        top5 = positions.abs().nlargest(5)
        print(f"\nPosition Summary (AUM = ${aum:,.0f}):")
        print(f" Gross Exposure: ${gross:,.0f} ({gross / aum:.1%} of AUM)")
        print(f" Net Exposure: ${net:,.0f} ({net / aum:.1%} of AUM)")
        print(f" Longs: {n_long} | Shorts: {n_short}")
        print(f" Top 5 by size: {top5.to_dict()}")

