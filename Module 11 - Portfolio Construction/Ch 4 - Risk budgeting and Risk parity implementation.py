import numpy as np
import pandas as pd
from scipy.optimize import minimize
import warnings

class RiskBudgetingOptimizer:
    """
    Implements risk budgeting (risk parity as special case).
    Supports both CCD and convex optimization approaches.
    """

    def __init__(self, method='ccd', max_iter=1000, tol=1e-8):
        self.method = method
        self.max_iter = max_iter
        self.tol = tol

    def risk_contributions(self, weights: np.ndarray, cov: np.ndarray) -> np.ndarray:
        """Compute marginal risk contributions (% of total variance)."""
        w = np.array(weights)
        port_var = w @ cov @ w
        port_vol = np.sqrt(port_var)
        mrc = cov @ w                    # Marginal risk
        rc = w * mrc / port_vol          # Risk contribution (absolute)
        prc = rc / port_vol              # Percentage risk contribution
        return prc

    def portfolio_risk(self, weights: np.ndarray, cov: np.ndarray) -> float:
        return np.sqrt(weights @ cov @ weights)

    def fit_ccd(self, cov: np.ndarray, budgets: np.ndarray) -> np.ndarray:
        """
        Cyclical Coordinate Descent for risk budgeting.
        Fast and reliable for most cases.
        """
        N = len(budgets)
        budgets = budgets / budgets.sum()  # Normalize
        w = np.ones(N) / N

        for iteration in range(self.max_iter):
            prc = self.risk_contributions(w, cov)
            # Check convergence
            if np.max(np.abs(prc - budgets)) < self.tol:
                break
            # Update each weight
            for i in range(N):
                # Bisection on each weight
                w_new = w.copy()
                alpha = budgets[i] / (prc[i] + 1e-10)
                w_new[i] *= np.clip(alpha, 0.5, 2.0)  # Damped update
                w = w_new / w_new.sum()  # Keep sum = 1

        return w

    def fit_convex(self, cov: np.ndarray, budgets: np.ndarray) -> np.ndarray:
        """
        Convex optimization approach (slower but more flexible).
        Minimizes sum of squared deviations from target RC.
        """
        N = len(budgets)
        budgets = budgets / budgets.sum()

        def objective(w):
            prc = self.risk_contributions(w, cov)
            return np.sum((prc - budgets) ** 2)

        def grad_objective(w):
            # Numerical gradient (use autodiff in production)
            eps = 1e-6
            grad = np.zeros(N)
            f0 = objective(w)
            for i in range(N):
                w_plus = w.copy()
                w_plus[i] += eps
                grad[i] = (objective(w_plus) - f0) / eps
            return grad

        constraints = [{'type': 'eq', 'fun': lambda w: np.sum(w) - 1}]
        bounds = [(1e-6, 1.0)] * N
        w0 = np.ones(N) / N

        result = minimize(
            objective,
            w0,
            method='SLSQP',
            jac=grad_objective,
            bounds=bounds,
            constraints=constraints,
            options={'maxiter': self.max_iter, 'ftol': self.tol}
        )
        return result.x

    def fit(self, cov: np.ndarray, budgets: np.ndarray = None) -> np.ndarray:
        """
        Main interface. budgets = None gives risk parity (equal budgets).
        """
        N = cov.shape[0]
        if budgets is None:
            budgets = np.ones(N) / N  # Risk parity

        if self.method == 'ccd':
            weights = self.fit_ccd(cov, budgets)
        else:
            weights = self.fit_convex(cov, budgets)

        return weights

    def report(self, weights: np.ndarray, cov: np.ndarray, asset_names: list = None, budgets: np.ndarray = None):
        """Print risk decomposition report."""
        N = len(weights)
        if asset_names is None:
            asset_names = [f'Asset_{i}' for i in range(N)]
        prc = self.risk_contributions(weights, cov)
        port_vol = self.portfolio_risk(weights, cov) * np.sqrt(252)

        print(f"\nRisk Budgeting Report")
        print(f"Portfolio Annual Vol: {port_vol:.2%}")
        print(f"{'Asset': <12} {'Weight': >8} {'% RC': >8} {'Target': >8} {'Deviation': >10}")
        print("-" * 52)
        tgt = budgets if budgets is not None else np.ones(N) / N

        for i, name in enumerate(asset_names):
            dev = prc[i] - tgt[i]
            print(f"{name: <12} {weights[i]: >8.4f} {prc[i]: >8.2%} {tgt[i]: >8.2%} {dev: >+10.4f}")
        print(f"{'TOTAL': <12} {weights.sum(): >8.4f} {prc.sum(): >8.2%}")


class FactorRiskDecomposer:
    """
    Decompose portfolio risk into factor and idiosyncratic components.
    Uses a pre-fitted factor model (e.g., Barra-style).
    """

    def __init__(self, factor_names: list):
        self.factor_names = factor_names

    def decompose(self, weights: np.ndarray, B: np.ndarray, F_cov: np.ndarray, D: np.ndarray) -> dict:
        """
        Decompose portfolio risk.

        Returns dict with:
        total_var, factor_var, idio_var,
        factor_rc (per factor), idio_rc (per asset)
        """
        w = np.array(weights)
        factor_exposure = B.T @ w  # [F]
        factor_var = factor_exposure @ F_cov @ factor_exposure
        idio_var = w @ (D * w)     # w^T diag(D) w
        total_var = factor_var + idio_var

        # Per-factor risk contribution
        factor_rc = {}
        for f, fname in enumerate(self.factor_names):
            fc_row = F_cov[f] @ factor_exposure
            factor_rc[fname] = factor_exposure[f] * fc_row / np.sqrt(total_var)

        result = {
            'total_vol': np.sqrt(total_var) * np.sqrt(252),
            'factor_vol': np.sqrt(factor_var) * np.sqrt(252),
            'idio_vol': np.sqrt(idio_var) * np.sqrt(252),
            'factor_pct': factor_var / total_var,
            'idio_pct': idio_var / total_var,
            'factor_rc': factor_rc,
        }
        return result


