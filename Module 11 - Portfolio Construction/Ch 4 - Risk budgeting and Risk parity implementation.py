    cov = np.outer(vols, vols) * corr

    # Risk parity
    rbo = RiskBudgetingOptimizer(method='ccd')
    w_rp = rbo.fit(cov)
    rbo.report(w_rp, cov, [f'Stock_{i}' for i in range(N)])

    # Custom budgets: over-weight low-vol assets
    budgets = 1.0 / vols
    budgets /= budgets.sum()
    w_rb = rbo.fit(cov, budgets)
    print("\nCustom Risk Budget:")
    rbo.report(w_rb, cov, [f'Stock_{i}' for i in range(N)], budgets)

