import numpy as np
import pandas as pd
from arch import arch_model
from scipy import stats

class VolatilityTargeter:
    """
    Complete volatility targeting engine with multiple estimators.
    Supports EWMA, GARCH(1,1), RV, and HAR models.
    """

    def __init__(
        self,
        target_vol: float = 0.10,      # Annual vol target (10%)
        max_leverage: float = 2.0,     # Hard leverage cap
        min_leverage: float = 0.0,     # Minimum leverage (0 = go to cash)
        estimator: str = 'garch',      # 'ewma', 'garch', 'rv', 'har'
        halflife_days: int = 21,       # For EWMA / RV window
        floor_vol: float = 0.05        # Minimum vol estimate (floor)
    ):
        self.target_vol = target_vol
        self.max_lev = max_leverage
        self.min_lev = min_leverage
        self.estimator = estimator
        self.halflife = halflife_days
        self.floor_vol = floor_vol

    def estimate_vol_ewma(self, returns: pd.Series) -> pd.Series:
        """EWMA volatility forecast (RiskMetrics style)."""
        alpha = 1 - np.exp(-np.log(2) / self.halflife)
        ewma_var = returns.ewm(alpha=alpha, adjust=False).var()
        return np.sqrt(ewma_var * 252)

    def estimate_vol_rv(self, returns: pd.Series) -> pd.Series:
        """Realized volatility using rolling window."""
        return returns.rolling(self.halflife).std() * np.sqrt(252)

    def estimate_vol_garch(self, returns: pd.Series) -> pd.Series:
        """GARCH(1,1) 1-step-ahead volatility forecast."""
        pct_rets = returns * 100  # GARCH likes percent returns
        am = arch_model(pct_rets.dropna(), vol='Garch', p=1, q=1, dist='t')
        res = am.fit(disp='off', show_warning=False)

        # Extract conditional volatility
        cond_vol = res.conditional_volatility / 100  # back to decimal
        cond_vol_ann = cond_vol * np.sqrt(252)

        # Align with original index
        vol_series = pd.Series(np.nan, index=returns.index)
        vol_series.loc[cond_vol.index] = cond_vol_ann.values
        return vol_series

    def estimate_vol_har(self, returns: pd.Series) -> pd.Series:
        """
        HAR (Heterogeneous Autoregressive) model.
        Combines daily, weekly, monthly realized variance.
        """
        rv_1d = returns ** 2 * 252            # Daily RV
        rv_5d = rv_1d.rolling(5).mean()      # Weekly RV
        rv_22d = rv_1d.rolling(22).mean()    # Monthly RV

        # Align and construct feature matrix
        X = pd.DataFrame({
            'rv_1d': rv_1d.shift(1),
            'rv_5d': rv_5d.shift(1),
            'rv_22d': rv_22d.shift(1),
        }).dropna()
        y = rv_1d.reindex(X.index)

        # OLS regression (log-HAR for stability)
        log_X = np.log(X.clip(lower=1e-8) + 1)
        log_y = np.log(y.clip(lower=1e-8) + 1)
        from sklearn.linear_model import LinearRegression
        lr = LinearRegression()
        lr.fit(log_X, log_y)

        # Out-of-sample prediction
        log_pred = pd.Series(lr.predict(log_X), index=X.index)
        rv_pred = np.exp(log_pred) - 1
        vol_pred = np.sqrt(rv_pred.clip(lower=0))

        vol_series = pd.Series(np.nan, index=returns.index)
        vol_series.loc[vol_pred.index] = vol_pred
        return vol_series

    def estimate_vol(self, returns: pd.Series) -> pd.Series:
        """Dispatch to appropriate estimator."""
        if self.estimator == 'ewma':
            vol = self.estimate_vol_ewma(returns)
        elif self.estimator == 'rv':
            vol = self.estimate_vol_rv(returns)
        elif self.estimator == 'garch':
            try:
                vol = self.estimate_vol_garch(returns)
            except Exception as e:
                print(f"GARCH failed ({e}), falling back to EWMA")
                vol = self.estimate_vol_ewma(returns)
        elif self.estimator == 'har':
            vol = self.estimate_vol_har(returns)
        else:
            raise ValueError(f"Unknown estimator: {self.estimator}")
        return vol.clip(lower=self.floor_vol)

    def compute_leverage(self, returns: pd.Series) -> pd.Series:
        """
        Compute daily leverage multiplier.
        Returns leverage to apply to portfolio weights.
        """
        vol = self.estimate_vol(returns)
        lev = self.target_vol / vol
        lev = lev.clip(self.min_lev, self.max_lev)
        return lev

    def apply(self, portfolio_returns: pd.Series) -> pd.DataFrame:
        """
        Apply volatility targeting to a portfolio return stream.
        Returns DataFrame with original and VT-adjusted metrics.
        """
        lev = self.compute_leverage(portfolio_returns)
        # Leverage is determined from yesterday's vol estimate
        lev_lagged = lev.shift(1).fillna(method='bfill')

        vt_returns = portfolio_returns * lev_lagged

        result = pd.DataFrame({
            'raw_return': portfolio_returns,
            'vt_return': vt_returns,
            'leverage': lev_lagged,
            'vol_estimate': self.estimate_vol(portfolio_returns),
        })

        # Performance stats
        ann = 252
        for col, ret in [('Raw', portfolio_returns), ('Vol-Targeted', vt_returns)]:
            mu = ret.mean() * ann
            sigma = ret.std() * np.sqrt(ann)
            sr = mu / (sigma + 1e-8)
            dd = (1 + ret).cumprod()
            mdd = (dd / dd.cummax() - 1).min()
            print(f"\n{col} Portfolio:")
            print(f" Ann. Return: {mu:.2%}")
            print(f" Ann. Vol: {sigma:.2%}")
            print(f" Sharpe: {sr:.3f}")
            print(f" Max DD: {mdd:.2%}")
            skew = stats.skew(ret.dropna())
            kurt = stats.kurtosis(ret.dropna())
            print(f" Skewness: {skew:.3f}")
            print(f" Excess Kurt: {kurt:.3f}")

        return result

