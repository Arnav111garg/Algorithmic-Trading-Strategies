import numpy as np
import pandas as pd
from sklearn.covariance import LedoitWolf, OAS
from scipy.linalg import eigh

class CovarianceEstimator:
    """
    Advanced covariance estimation:
    - Sample covariance
    - Ledoit-Wolf shrinkage
    - Factor model (PCA)
    - RMT eigenvalue cleaning
    - DCC correlation dynamics (simplified)
    """

    def __init__(self, method='ledoit_wolf', n_factors=10, min_obs_ratio=2.0):
        self.method = method
        self.n_factors = n_factors
        self.min_obs_ratio = min_obs_ratio

    def sample_cov(self, returns: pd.DataFrame) -> np.ndarray:
        """Standard sample covariance."""
        return returns.cov().values

    def ledoit_wolf_cov(self, returns: pd.DataFrame) -> np.ndarray:
        """Ledoit-Wolf shrinkage estimator."""
        lw = LedoitWolf()
        lw.fit(returns.values)
        return lw.covariance_

    def pca_factor_cov(self, returns: pd.DataFrame) -> np.ndarray:
        """Factor model covariance via PCA."""
        X = returns.values
        T, N = X.shape
        X = X - X.mean(axis=0)  # Demean

        # SVD
        U, s, Vt = np.linalg.svd(X / np.sqrt(T - 1), full_matrices=False)
        F = self.n_factors

        # Factor loadings (N x F)
        B = Vt[:F].T * s[:F]
        # Factor covariance (from data)
        factors = X @ Vt[:F].T / s[:F]  # (T x F)
        F_cov = np.cov(factors.T)

        # Idiosyncratic variances
        reconstructed = factors @ B.T
        residuals = X - reconstructed
        D = np.diag(np.var(residuals, axis=0))

        return B @ F_cov @ B.T + D

    def rmt_clean(self, returns: pd.DataFrame) -> np.ndarray:
        """
        Random Matrix Theory eigenvalue cleaning.
        Replaces noisy eigenvalues with bulk average.
        """
        X = returns.values
        T, N = X.shape
        cov = np.cov(X.T)

        # Theoretical noise bounds (Marchenko-Pastur)
        gamma = N / T
        sigma2 = 1.0  # normalized
        lam_plus = sigma2 * (1 + np.sqrt(gamma)) ** 2
        lam_minus = sigma2 * (1 - np.sqrt(gamma)) ** 2

        # Eigendecomposition
        eigenvalues, eigenvectors = eigh(cov)

        # Identify signal vs noise
        signal_mask = eigenvalues > lam_plus
        noise_eigs = eigenvalues[~signal_mask]

        # Replace noise eigenvalues with their mean
        cleaned_eigs = eigenvalues.copy()
        if noise_eigs.size > 0:
            bulk_avg = noise_eigs.mean()
            cleaned_eigs[~signal_mask] = bulk_avg

        # Reconstruct covariance
        cov_clean = eigenvectors @ np.diag(cleaned_eigs) @ eigenvectors.T

        n_signal = signal_mask.sum()
        print(f"RMT: {n_signal} signal eigenvalues, {N - n_signal} noise eigenvalues cleaned")
        print(f"Noise band: [{lam_minus:.3f}, {lam_plus:.3f}]")
        print(f"Largest signal eigenvalue: {eigenvalues[-1]:.3f}")

        return cov_clean

    def estimate(self, returns: pd.DataFrame) -> np.ndarray:
        """Main interface."""
        T, N = returns.shape
        if T < self.min_obs_ratio * N:
            print(f"Warning: T={T} < {self.min_obs_ratio}*N={N}. Using Ledoit-Wolf.")
            return self.ledoit_wolf_cov(returns)

        if self.method == 'sample':
            return self.sample_cov(returns)
        elif self.method == 'ledoit_wolf':
            return self.ledoit_wolf_cov(returns)
        elif self.method == 'pca_factor':
            return self.pca_factor_cov(returns)
        elif self.method == 'rmt':
            return self.rmt_clean(returns)
        else:
            raise ValueError(f"Unknown method: {self.method}")

    def correlation_stress_test(
        self,
        weights: np.ndarray,
        base_cov: np.ndarray,
        stress_corr: float = 0.85,
    ) -> dict:
        """
        Test portfolio risk under correlation stress.
        All pairwise correlations set to stress_corr.
        """
        N = base_cov.shape[0]
        vols = np.sqrt(np.diag(base_cov))

        # Stressed correlation matrix
        corr_stress = stress_corr * np.ones((N, N))
        np.fill_diagonal(corr_stress, 1.0)
        cov_stress = np.outer(vols, vols) * corr_stress

        base_vol = np.sqrt(weights @ base_cov @ weights) * np.sqrt(252)
        stress_vol = np.sqrt(weights @ cov_stress @ weights) * np.sqrt(252)

        return {
            'base_vol': base_vol,
            'stress_vol': stress_vol,
            'vol_increase': (stress_vol - base_vol) / base_vol,
            'stress_corr': stress_corr,
        }

