import numpy as np
import pandas as pd
import cvxpy as cp
from dataclasses import dataclass, field
from typing import Dict, List, Optional

@dataclass
class PortfolioConstraints:
    """Container for all portfolio constraints."""
    # Capital constraints
    gross_exposure_max: float = 2.0  # max |w|_1
    net_exposure_max: float = 0.10   # max |sum w|
    # Position limits
    max_position: float = 0.05       # max |w_i|
    min_position: float = 0.0        # min position to hold
    # Sector constraints
    sector_exposure_max: float = 0.05  # max sector net exposure
    # Factor constraints
    beta_max: float = 0.05           # max market beta exposure
    factor_exposure_max: Dict[str, float] = field(
        default_factory=lambda: {
            'momentum': 0.10, 'value': 0.10,
            'size': 0.15, 'quality': 0.10
        }
    )
    # Liquidity
    adv_pct_max: float = 0.20        # max % of ADV
    # Turnover
    turnover_max: Optional[float] = 0.30  # one-way turnover per rebalance
    # Long-only flag
    long_only: bool = False

class ConstrainedPortfolioOptimizer:
    """
    Full-featured constrained portfolio optimizer using CVXPY.
    Supports equity long-short, long-only, and market-neutral mandates.
    """

    def __init__(self, constraints: PortfolioConstraints = None):
        self.constraints = constraints or PortfolioConstraints()
        self.result_ = None

    def optimize(
        self,
        alpha: np.ndarray,              # Expected returns / alpha scores
        cov: np.ndarray,                # Covariance matrix
        risk_aversion: float = 2.0,     # Lambda in mean-variance
        current_weights: np.ndarray = None,  # For turnover constraint
        sector_matrix: np.ndarray = None,    # [N x S] sector dummies
        factor_matrix: np.ndarray = None,    # [N x F] factor loadings
        factor_names: list = None,
        betas: np.ndarray = None,       # Market betas [N]
        adv: np.ndarray = None,         # Average daily volume [N]
        aum: float = 1e8,
        verbose: bool = False,
    ) -> np.ndarray:
        """
        Solve the constrained mean-variance optimization.
        Returns: Optimal portfolio weights.
        """
        N = len(alpha)
        C = self.constraints
        w = cp.Variable(N)

        # Objective: Mean-variance with L1 transaction cost penalty
        portfolio_return = alpha @ w
        portfolio_risk = cp.quad_form(w, cov)
        objective_terms = [risk_aversion * portfolio_risk - portfolio_return]

        # Transaction cost penalty (if current weights provided)
        if current_weights is not None:
            tc_penalty = 0.001 * cp.norm1(w - current_weights)
            objective_terms.append(tc_penalty)

        objective = cp.Minimize(sum(objective_terms))

        # Constraints
        constraints_list = []

        # 1. Sum of weights
        if C.long_only:
            constraints_list.append(cp.sum(w) == 1.0)
            constraints_list.append(w >= 0)
        else:
            constraints_list.append(cp.sum(w) == 0.0)  # dollar-neutral

        # 2. Gross exposure
        constraints_list.append(cp.norm1(w) <= C.gross_exposure_max)

        # 3. Net exposure
        constraints_list.append(cp.abs(cp.sum(w)) <= C.net_exposure_max)

        # 4. Individual position limits
        constraints_list.append(w <= C.max_position)
        constraints_list.append(w >= -C.max_position)

        # 5. Sector neutrality / limits
        if sector_matrix is not None:
            for s in range(sector_matrix.shape[1]):
                sector_exp = sector_matrix[:, s] @ w
                constraints_list.append(cp.abs(sector_exp) <= C.sector_exposure_max)

        # 6. Market beta neutrality
        if betas is not None:
            constraints_list.append(cp.abs(betas @ w) <= C.beta_max)

        # 7. Factor exposure limits
        if factor_matrix is not None and factor_names is not None:
            for f, fname in enumerate(factor_names):
                limit = C.factor_exposure_max.get(fname, 0.15)
                factor_exp = factor_matrix[:, f] @ w
                constraints_list.append(cp.abs(factor_exp) <= limit)

        # 8. Liquidity constraint
        if adv is not None:
            adv_limit = C.adv_pct_max * adv / aum
            constraints_list.append(cp.abs(w) <= adv_limit)

        # 9. Turnover constraint
        if current_weights is not None and C.turnover_max is not None:
            constraints_list.append(cp.norm1(w - current_weights) <= C.turnover_max)

        # Solve
        problem = cp.Problem(objective, constraints_list)
        try:
            problem.solve(solver=cp.OSQP, verbose=verbose, max_iter=10000, eps_abs=1e-7, eps_rel=1e-6)
        except Exception:
            problem.solve(solver=cp.SCS, verbose=verbose)

        if problem.status in ['optimal', 'optimal_inaccurate']:
            self.result_ = {
                'weights': w.value,
                'status': problem.status,
                'objective': problem.value,
                'active_constraints': self._check_active(w.value, constraints_list),
            }
            return w.value
        else:
            print(f"Optimization failed: {problem.status}")
            # Fallback: return vol-scaled alpha
            scaled = alpha / np.sqrt(np.diag(cov))
            return scaled / np.abs(scaled).sum() * C.gross_exposure_max

    def _check_active(self, w, constraints):
        """Report which constraints are binding."""
        active = []
        if w is None:
            return active
        tol = 1e-4
        if abs(np.sum(np.abs(w)) - 2.0) < tol:
            active.append('gross_exposure_binding')
        if np.max(np.abs(w)) > 0.048:
            active.append('position_limit_near_binding')
        return active

    def efficient_frontier(self, alpha, cov, n_points=20, **kwargs) -> pd.DataFrame:
        """Trace the constrained efficient frontier."""
        lambdas = np.logspace(-2, 2, n_points)
        frontier = []
        for lam in lambdas:
            w = self.optimize(alpha, cov, risk_aversion=lam, **kwargs)
            if w is not None:
                ret = alpha @ w
                vol = np.sqrt(w @ cov @ w) * np.sqrt(252)
                frontier.append({
                    'lambda': lam,
                    'return': ret,
                    'vol': vol,
                    'sharpe': ret / (vol + 1e-8)
                })
        return pd.DataFrame(frontier)

