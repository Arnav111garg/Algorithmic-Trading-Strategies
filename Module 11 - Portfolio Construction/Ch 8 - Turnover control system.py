import numpy as np
import pandas as pd
import cvxpy as cp
from typing import Optional

class TurnoverController:
    """
    Implements multiple turnover control mechanisms:
    1. Signal smoothing (EWMA)
    2. No-trade zone (dead-band filter)
    3. Turnover-penalized optimization
    4. Portfolio buffer management
    """

    def __init__(
        self,
        max_one_way_turnover: float = 0.5,      # per rebalance
        no_trade_threshold: float = 0.005,      # min trade to execute
        signal_ewma_halflife: int = 5,          # days
        cost_per_unit: float = 0.001            # 10 bps round-trip
    ):
        self.max_turnover = max_one_way_turnover
        self.no_trade_thresh = no_trade_threshold
        self.ewma_hl = signal_ewma_halflife
        self.tc = cost_per_unit
        self._alpha_ewma = None                 # EWMAed alpha state

    def smooth_signal(self, alpha_raw: np.ndarray) -> np.ndarray:
        """Apply EWMA smoothing to raw alpha signal."""
        decay = np.exp(-np.log(2) / self.ewma_hl)
        if self._alpha_ewma is None:
            self._alpha_ewma = alpha_raw.copy()
        else:
            self._alpha_ewma = (1 - decay) * alpha_raw + decay * self._alpha_ewma
        return self._alpha_ewma.copy()

    def no_trade_filter(
        self,
        target_weights: np.ndarray,
        current_weights: np.ndarray,
        alpha: np.ndarray,
        risk_aversion: float = 2.0,
        per_asset_costs: np.ndarray = None,
    ) -> np.ndarray:
        """
        Apply dead-band no-trade filter.
        Returns adjusted target (no change if deviation < threshold).
        """
        N = len(target_weights)
        if per_asset_costs is None:
            per_asset_costs = np.full(N, self.tc)

        adjusted = target_weights.copy()
        for i in range(N):
            deviation = abs(target_weights[i] - current_weights[i])
            # Theoretical optimal threshold: 2 * TC / risk_aversion
            threshold = max(
                self.no_trade_thresh,
                2 * per_asset_costs[i] / risk_aversion
            )
            if deviation < threshold:
                adjusted[i] = current_weights[i]  # Hold

        return adjusted

    def turnover_penalized_optimize(
        self,
        alpha: np.ndarray,
        cov: np.ndarray,
        current_weights: np.ndarray,
        risk_aversion: float = 2.0,
        tc_vector: np.ndarray = None,
    ) -> np.ndarray:
        """
        Mean-variance optimization with explicit L1 turnover penalty.
        min (lambda / 2) * w'Sw - mu'w + c'|w - w0|
        """
        N = len(alpha)
        if tc_vector is None:
            tc_vector = np.full(N, self.tc)

        w = cp.Variable(N)
        # Turnover = |w - w0| (use absolute value via auxiliary variable delta)
        delta = cp.Variable(N)

        objective = cp.Minimize(
            risk_aversion * cp.quad_form(w, cov)
            - alpha @ w
            + tc_vector @ delta
        )

        constraints = [
            cp.sum(w) == 0,                          # dollar-neutral
            cp.norm1(w) <= 2.0,                      # gross exposure
            w <= 0.05, w >= -0.05,                   # position limits
            cp.norm1(w - current_weights) <= self.max_turnover,
            delta >= w - current_weights,
            delta >= -(w - current_weights),
            delta >= 0,
        ]

        prob = cp.Problem(objective, constraints)
        prob.solve(solver=cp.OSQP, eps_abs=1e-7, eps_rel=1e-6)

        if prob.status in ['optimal', 'optimal_inaccurate']:
            actual_to = np.abs(w.value - current_weights).sum()
            print(f"Actual turnover: {actual_to:.4f} (limit: {self.max_turnover:.4f})")
            return w.value
        else:
            print(f"Optimization failed: {prob.status}")
            return current_weights

    def portfolio_buffer_check(
        self,
        current: np.ndarray,
        target: np.ndarray,
        buffer_threshold: float = 0.10,
    ) -> tuple:
        """
        Check if portfolio has drifted outside buffer.
        Returns (should_rebalance, drift_measure).
        """
        drift = np.abs(current - target).sum()
        should_rebalance = drift > buffer_threshold
        return should_rebalance, drift

    def backtest_turnover(
        self,
        weights_history: pd.DataFrame,
    ) -> pd.DataFrame:
        """Compute turnover statistics from a history of portfolio weights."""
        diffs = weights_history.diff().abs()
        to_daily = diffs.sum(axis=1) / 2  # One-way
        result = pd.DataFrame({
            'daily_turnover': to_daily,
            'rolling_ann_to': to_daily.rolling(252).sum(),
        })
        print(f"\nTurnover Summary:")
        print(f"Mean Daily One-Way Turnover: {to_daily.mean():.4f}")
        print(f"Annual Turnover (x): {to_daily.sum():.2f}")
        print(f"Est. Annual TC (bps): {to_daily.sum() * self.tc * 10000:.1f}")
        return result

