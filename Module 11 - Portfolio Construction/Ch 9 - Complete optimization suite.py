import numpy as np
import pandas as pd
import cvxpy as cp
from scipy.optimize import minimize
from sklearn.covariance import LedoitWolf

class PortfolioOptimizationSuite:
    """
    Comprehensive portfolio optimization with multiple methods:
    - Mean-Variance (MVO)
    - Robust MVO
    - Black-Litterman MVO
    - Risk Parity
    - 1/N benchmark
    """

    def __init__(self, risk_aversion: float = 2.0):
        self.risk_aversion = risk_aversion

    # 1. Classical MVO
    def mvo(self, mu: np.ndarray, cov: np.ndarray, constraints: dict = None) -> np.ndarray:
        """Standard mean-variance optimization."""
        N = len(mu)
        w = cp.Variable(N)
        obj = cp.Minimize(
            self.risk_aversion * cp.quad_form(w, cov) - mu @ w
        )
        cons = [
            cp.sum(w) == 0,
            cp.norm1(w) <= 2.0,
            w <= 0.05,
            w >= -0.05
        ]
        prob = cp.Problem(obj, cons)
        prob.solve(solver=cp.OSQP)
        return w.value

    # 2. Robust MVO
    def robust_mvo(self, mu: np.ndarray, cov: np.ndarray, kappa: float = 1.0) -> np.ndarray:
        """
        Minimax robust MVO with ellipsoidal uncertainty in mu.
        Penalizes estimation uncertainty proportional to kappa.
        """
        N = len(mu)
        w = cp.Variable(N)
        # Uncertainty penalty: kappa * ||w||_{Sigma}
        uncertainty = kappa * cp.quad_form(w, cov) ** 0.5

        obj = cp.Minimize(
            self.risk_aversion * cp.quad_form(w, cov) - mu @ w + uncertainty
        )
        cons = [
            cp.sum(w) == 0,
            cp.norm1(w) <= 2.0,
            w <= 0.05,
            w >= -0.05
        ]
        prob = cp.Problem(obj, cons)
        prob.solve(solver=cp.OSQP)
        return w.value

    # 3. Black-Litterman MVO
    def black_litterman_mvo(
        self,
        cov: np.ndarray,
        w_mkt: np.ndarray,  # Market cap weights
        P: np.ndarray,       # View matrix [K x N]
        Q: np.ndarray,       # View returns [K]
        tau: float = 0.05,
        risk_aversion: float = 2.5,
    ) -> np.ndarray:
        """Black-Litterman expected returns, then MVO."""
        N = len(w_mkt)
        # CAPM equilibrium returns
        Pi = risk_aversion * cov @ w_mkt

        # View confidence (proportional approach)
        Omega = np.diag([tau * (P[k] @ cov @ P[k]) for k in range(len(Q))])

        # BL posterior mean
        inv_term = np.linalg.inv(tau * cov) + P.T @ np.linalg.inv(Omega) @ P
        right_term = np.linalg.inv(tau * cov) @ Pi + P.T @ np.linalg.inv(Omega) @ Q
        mu_bl = np.linalg.solve(inv_term, right_term)

        # Optimize with BL mu
        return self.mvo(mu_bl, cov)

    # 4. Risk Parity
    def risk_parity(self, cov: np.ndarray) -> np.ndarray:
        """Equal risk contribution portfolio (long-only)."""
        N = cov.shape[0]
        def neg_log_risk(w):
            port_var = w @ cov @ w
            return -np.sum(np.log(np.maximum(w * (cov @ w) / port_var, 1e-10)))

        constraints = [{'type': 'eq', 'fun': lambda w: np.sum(w) - 1}]
        bounds = [(1e-6, 1)] * N
        w0 = np.ones(N) / N
        res = minimize(
            neg_log_risk,
            w0,
            method='SLSQP',
            bounds=bounds,
            constraints=constraints,
            options={'maxiter': 1000, 'ftol': 1e-10}
        )
        return res.x

    # 5. Equal Weight
    def equal_weight(self, N: int) -> np.ndarray:
        """The famous 1/N benchmark."""
        return np.ones(N) / N

    # Comparison
    def compare_methods(
        self,
        mu: np.ndarray,
        cov: np.ndarray,
        w_mkt: np.ndarray = None,
        P: np.ndarray = None,
        Q: np.ndarray = None,
    ) -> pd.DataFrame:
        """Compare all methods on key portfolio metrics."""
        N = len(mu)
        methods = {}
        methods['MVO'] = self.mvo(mu, cov)
        methods['Robust MVO'] = self.robust_mvo(mu, cov, kappa=2.0)
        methods['Risk Parity'] = self.risk_parity(cov)

        # Long-short 1/N: top half long, bottom half short
        top_half = mu > np.median(mu)
        ls_ew = np.where(top_half, 1 / top_half.sum(), -1 / (~top_half).sum())
        methods['LS Equal Weight'] = ls_ew

        if w_mkt is not None and P is not None:
            methods['Black-Litterman'] = self.black_litterman_mvo(cov, w_mkt, P, Q)

        results = []
        for name, w in methods.items():
            if w is None:
                continue
            ret = mu @ w
            vol = np.sqrt(w @ cov @ w) * np.sqrt(252)
            sr = ret / (vol + 1e-8)
            gross = np.abs(w).sum()
            net = w.sum()
            max_w = np.abs(w).max()
            results.append({
                'Method': name,
                'Return': f"{ret:.4f}",
                'Ann. Vol': f"{vol:.2%}",
                'Sharpe': f"{sr:.3f}",
                'Gross Exp': f"{gross:.2f}",
                'Net Exp': f"{net:.3f}",
                'Max |w|': f"{max_w:.4f}",
            })

        df = pd.DataFrame(results).set_index('Method')
        print("\nOptimization Method Comparison:")
        print(df.to_string())
        return df

