import numpy as np
import pandas as pd
from scipy import stats
from scipy.optimize import minimize
import matplotlib.pyplot as plt
from typing import Optional, Tuple, Dict

class MarketRiskCalculator:
    """
    Production-grade VaR and ES calculator supporting
    Historical Simulation, Parametric, and Monte Carlo methods.
    """

    def __init__(self, returns: pd.Series, confidence: float = 0.99, horizon: int = 1):
        """
        Parameters
        ----------
        returns : pd.Series of daily portfolio returns (not losses)
        confidence : VaR confidence level (e.g. 0.99 for 99% VaR)
        horizon : holding period in days
        """
        self.returns = returns
        self.alpha = confidence
        self.h = horizon
        self.losses = -returns # convert to loss convention

    # 1. Historical Simulation
    def var_historical(self) -> float:
        """Historical simulation VaR."""
        return np.quantile(self.losses, self.alpha)

    def es_historical(self) -> float:
        """Historical simulation Expected Shortfall."""
        var = self.var_historical()
        tail_losses = self.losses[self.losses > var]
        return tail_losses.mean() if len(tail_losses) > 0 else var

    # 2. Parametric (Normal)
    def var_parametric(self) -> float:
        """Parametric VaR assuming normal returns."""
        mu = self.returns.mean() * self.h
        sigma = self.returns.std() * np.sqrt(self.h)
        return -mu + stats.norm.ppf(self.alpha) * sigma

    def es_parametric(self) -> float:
        """Parametric ES (Conditional VaR) under normality."""
        mu = self.returns.mean() * self.h
        sigma = self.returns.std() * np.sqrt(self.h)
        z = stats.norm.ppf(self.alpha)
        es_factor = stats.norm.pdf(z) / (1 - self.alpha)
        return -mu + sigma * es_factor

    # 3. Parametric Student-t
    def var_student_t(self) -> Tuple[float, float]:
        """
        Fit Student-t distribution and compute VaR.
        Returns (VaR, degrees_of_freedom).
        """
        nu, loc, scale = stats.t.fit(self.losses, floc=self.losses.mean())
        var = stats.t.ppf(self.alpha, df=nu, loc=loc, scale=scale)
        return var, nu

    def es_student_t(self) -> float:
        """ES under Student-t distribution."""
        nu, loc, scale = stats.t.fit(self.losses, floc=self.losses.mean())
        z = stats.t.ppf(self.alpha, df=nu)
        # Closed-form ES for Student-t
        es_factor = (stats.t.pdf(z, df=nu) * (nu + z**2)) / ((1 - self.alpha) * (nu - 1))
        return loc + scale * es_factor

    # 4. Monte Carlo VaR
    def var_monte_carlo(self, n_sims: int = 100000, model: str = 'normal') -> float:
        """
        Monte Carlo VaR. Supports 'normal' and 'student_t' simulations.
        """
        mu = self.returns.mean()
        sigma = self.returns.std()

        if model == 'normal':
            sim_losses = -np.random.normal(mu * self.h, sigma * np.sqrt(self.h), n_sims)
        elif model == 'student_t':
            nu, _, scale = stats.t.fit(self.losses)
            sim_returns = stats.t.rvs(df=nu, loc=mu * self.h, scale=scale * np.sqrt(self.h), size=n_sims)
            sim_losses = -sim_returns

        return np.quantile(sim_losses, self.alpha)

    # 5. GARCH-based VaR
    def var_garch_filtered(self, window: int = 252) -> pd.Series:
        """
        Filtered Historical Simulation using GARCH(1,1) volatility.
        Standardizes returns by conditional vol before applying HS.
        """
        from arch import arch_model  # pip install arch

        model = arch_model(self.returns * 100, vol='GARCH', p=1, q=1, dist='Normal', rescale=False)
        res = model.fit(disp='off', last_obs=len(self.returns))
        cond_vol = res.conditional_volatility / 100

        # Standardized residuals
        std_resids = self.returns / cond_vol

        # Forecast next-period conditional vol
        forecast = res.forecast(horizon=1)
        next_vol = np.sqrt(forecast.variance.values[-1, 0]) / 100

        # Apply HS VaR to standardized residuals, scale by forecast vol
        var_std = np.quantile(-std_resids, self.alpha)
        return var_std * next_vol

    # 6. Full Report
    def full_report(self) -> Dict[str, float]:
        """Generate complete risk report."""
        t_var, nu = self.var_student_t()
        report = {
            'VaR_HS_99': self.var_historical(),
            'ES_HS_99': self.es_historical(),
            'VaR_Param_99': self.var_parametric(),
            'ES_Param_99': self.es_parametric(),
            'VaR_StudentT_99': t_var,
            'ES_StudentT_99': self.es_student_t(),
            'StudentT_DoF': nu,
            'VaR_MC_99': self.var_monte_carlo(),
        }
        print("\n" + "=" * 50)
        print(f" MARKET RISK REPORT | Confidence : {self.alpha * 100:.0f}%")
        print("=" * 50)
        for k, v in report.items():
            print(f" {k : <22}: {v : >10.4f}")
        print("=" * 50)
        return report

