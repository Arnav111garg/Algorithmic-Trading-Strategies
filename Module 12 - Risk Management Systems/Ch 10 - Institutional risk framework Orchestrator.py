import numpy as np
import pandas as pd
from datetime import datetime, timedelta
from dataclasses import dataclass, field
from typing import Dict, List, Optional

@dataclass
class RiskBudget:
    """Hierarchical risk budget allocation."""
    total_var_limit: float  # firm-level variance budget
    desk_allocations: Dict[str, float] = field(default_factory=dict)
    headroom_pct: float = 0.20

    def allocate_risk_parity(self, desks: List[str], corr_matrix: np.ndarray) -> dict:
        """
        Allocate risk budget via Equal Risk Contribution (Risk Parity).
        Each desk contributes equally to total portfolio variance.
        """
        n = len(desks)
        target_per_desk = self.total_var_limit * (1 - self.headroom_pct) / n

        # Solve for weights under equal risk contribution
        # (Simplified: assume independent desks first)
        allocations = {desk: np.sqrt(target_per_desk) for desk in desks}

        self.desk_allocations = allocations
        print(f"Risk Parity Allocation (Total Budget: {self.total_var_limit:.4f}):")
        for desk, alloc in allocations.items():
            print(f"  {desk:<20}: vol_limit={alloc:.4f} var_limit={alloc**2:.6f}")
        return allocations

class InstitutionalRiskFramework:
    """
    Enterprise-grade institutional risk management framework.
    Integrates market risk, stress testing, monitoring, attribution.
    """

    def __init__(self, firm_name: str, nav: float, risk_budget: RiskBudget):
        self.firm = firm_name
        self.nav = nav
        self.budget = risk_budget
        self.desk_risk: Dict[str, dict] = {}
        self.daily_reports: List[dict] = []

    def register_desk(
        self,
        desk_name: str,
        desk_nav: float,
        strategy_type: str,
        pm_name: str
    ) -> None:
        """Register a trading desk in the framework."""
        vol_limit = self.budget.desk_allocations.get(
            desk_name, self.nav * 0.005  # default 0.5% vol
        )
        self.desk_risk[desk_name] = {
            'nav': desk_nav,
            'strategy_type': strategy_type,
            'pm': pm_name,
            'vol_limit': vol_limit,
            'var_limit': vol_limit ** 2,
            'current_var': 0.0,
            'current_dd': 0.0,
            'status': 'NORMAL'
        }
        print(f"Registered desk: {desk_name} ({strategy_type}, PM: {pm_name})")

    def daily_risk_cycle(self, date: datetime, market_data: dict, positions: dict) -> dict:
        """
        Run the complete daily risk management cycle:
        1. Compute risk metrics
        2. Run stress tests
        3. Check limits
        4. Generate report
        """
        report = {
            'date': date,
            'firm': self.firm,
            'nav': self.nav,
            'desks': {},
            'breaches': [],
            'actions': []
        }

        print(f"\n{'='*70}")
        print(f"DAILY RISK REPORT | {self.firm} | {date.date()}")
        print(f"{'='*70}")

        # Process each desk
        for desk_name, desk_info in self.desk_risk.items():
            desk_positions = positions.get(desk_name, {})

            # Simulate risk metrics (in production: real calculations)
            daily_pnl_pct = market_data.get(f'{desk_name}_pnl', 0)
            current_var_pct = market_data.get(f'{desk_name}_var', 0.01)
            current_vol = np.sqrt(current_var_pct * 252)

            # Limit utilization
            var_utilization = current_var_pct / desk_info['var_limit']

            status = 'NORMAL'
            if var_utilization > 1.0:
                status = 'BREACH'
                report['breaches'].append(f"{desk_name}: VaR limit breached")
                report['actions'].append(f"Notify {desk_info['pm']}: reduce exposure")
            elif var_utilization > 0.8:
                status = 'WARNING'

            desk_report = {
                'pm': desk_info['pm'],
                'nav': desk_info['nav'],
                'daily_pnl_pct': daily_pnl_pct,
                'var_pct': current_var_pct,
                'vol_ann': current_vol,
                'var_limit': desk_info['var_limit'],
                'utilization': var_utilization,
                'status': status
            }
            report['desks'][desk_name] = desk_report

            status_color = {'NORMAL': 'OK', 'WARNING': 'WARN', 'BREACH': 'BREACH'}[status]
            print(f"[{status_color}] {desk_name:<20} | "
                  f"P&L: {daily_pnl_pct:>+.2%} | "
                  f"VaR: {current_var_pct:.4f} | "
                  f"Util: {var_utilization:.0%}")

        print(f"\nBreaches: {len(report['breaches'])}")
        for b in report['breaches']:
            print(f" >>> {b}")
        print(f"{'='*70}")

        self.daily_reports.append(report)
        return report

