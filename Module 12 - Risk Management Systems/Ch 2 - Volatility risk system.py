import numpy as np
import pandas as pd
from arch import arch_model
from scipy.stats import norm
import warnings
warnings.filterwarnings('ignore')

class VolatilityRiskSystem:
    """
    Comprehensive volatility risk measurement and forecasting system.
    Includes GARCH forecasting, realized vol estimation, and Vega risk.
    """
    def __init__(self, returns: pd.Series):
        self.returns = returns
        self.model_fit = None

    def fit_garch(self, p: int = 1, q: int = 1, dist: str = 'skewt') -> dict:
        """
        Fit GJR-GARCH with skewed-t innovations (industry standard).
        """
        model = arch_model(
            self.returns * 100,
            vol='GARCH',
            p=p,
            o=1,
            q=q,
            dist=dist,
            rescale=False
        )
        self.model_fit = model.fit(disp='off')
        params = self.model_fit.params

        print(f" GARCH ({p},1,{q}) Fit Summary :")
        print(f" omega = {params['omega']:.4f}")
        print(f" alpha = {params.get('alpha[1]', 0):.4f}")
        print(f" gamma = {params.get('gamma[1]', 0):.4f} (leverage)")
        print(f" beta = {params.get('beta[1]', 0):.4f}")

        alpha = params.get('alpha[1]', 0)
        beta = params.get('beta[1]', 0)
        persistence = alpha + 0.5 * params.get('gamma[1]', 0) + beta
        half_life = -np.log(2) / np.log(persistence) if persistence < 1 else np.inf
        print(f" Persistence = {persistence:.4f}")
        print(f" Half-life = {half_life:.1f} days ")

        return {
            'params': params,
            'persistence': persistence,
            'half_life': half_life
        }

    def forecast_vol(self, horizon: int = 5) -> np.ndarray:
        """Multi-step ahead volatility forecast."""
        if self.model_fit is None:
            self.fit_garch()
        fc = self.model_fit.forecast(horizon=horizon)
        annualized = np.sqrt(fc.variance.values[-1] * 252) / 100
        print(f"\nVol Forecast (annualized):")
        for h, v in enumerate(annualized, 1):
            print(f" Day +{h}: {v:.4f} ({v * 100:.2f}%) ")
        return annualized

    def realized_vol(self, intraday_returns: pd.Series = None, window: int = 21) -> pd.Series:
        """
        Compute realized volatility. If intraday_returns provided,
        uses 5-min RV. Otherwise uses daily close-to-close.
        """
        if intraday_returns is not None:
            # Sum of squared 5-min returns, annualized
            rv_daily = intraday_returns.groupby(intraday_returns.index.date).apply(lambda x: np.sum(x ** 2))
            return np.sqrt(rv_daily * 252)
        else:
            # Rolling window realized vol from daily returns
            return self.returns.rolling(window).std() * np.sqrt(252)

    def vol_risk_premium(self, implied_vol: pd.Series, window: int = 21) -> pd.Series:
        """
        Variance Risk Premium = Implied Vol ^2 - Realized Vol ^2.
        Positive VRP => implied vol > realized vol (options expensive).
        """
        rv = self.realized_vol(window=window)
        vrp = implied_vol ** 2 - rv ** 2

        print(f" Average VRP: {vrp.mean():.4f} (ann. variance units)")
        print(f" Positive VRP days: {(vrp > 0).mean() * 100:.1f}%")
        return vrp

    def compute_vega_risk(
        self,
        S: float,
        K: float,
        T: float,
        r: float,
        sigma: float,
        position: float,
        vol_shock: float = 0.01
    ) -> dict:
        """
        Compute Vega, Volga, and stress P&L from vol shocks.
        """
        def bs_price(sig):
            d1 = (np.log(S / K) + (r + 0.5 * sig ** 2) * T) / (sig * np.sqrt(T))
            d2 = d1 - sig * np.sqrt(T)
            return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)

        price_0 = bs_price(sigma)
        price_up = bs_price(sigma + vol_shock)
        price_down = bs_price(sigma - vol_shock)

        vega = (price_up - price_down) / (2 * vol_shock)
        volga = (price_up - 2 * price_0 + price_down) / (vol_shock ** 2)

        return {
            'price': price_0,
            'vega': position * vega,
            'volga': position * volga,
            'pnl_+1 vol': position * vega * vol_shock,
            'pnl_+5 vol': position * (vega * 5 * vol_shock + 0.5 * volga * (5 * vol_shock) ** 2),
            'pnl_-5 vol': position * (vega * (-5 * vol_shock) + 0.5 * volga * (5 * vol_shock) ** 2),
        }

