import numpy as np
import pandas as pd
from scipy.optimize import minimize
import matplotlib.pyplot as plt

class LiquidityRiskSystem:
    """
    Comprehensive liquidity risk system:
    - LVaR computation (BDSS model)
    - Market impact estimation
    - Optimal liquidation scheduling
    - Liquidity-adjusted position sizing
    """
    def __init__(self, adv: float, price: float, sigma: float, spread_bps: float):
        """
        Parameters
        ----------
        adv : Average Daily Volume (shares)
        price : Current market price
        sigma : Daily return volatility
        spread_bps : Bid-ask spread in basis points
        """
        self.adv = adv
        self.price = price
        self.sigma = sigma
        self.spread = spread_bps / 10000.0 # convert to decimal

    def days_to_liquidate(self, position: float, pov: float = 0.10) -> float:
        """
        Estimate days to liquidate based on Participation-of-Volume.
        pov = fraction of daily volume we can trade without major impact.
        """
        return position / (self.adv * pov)

    def square_root_impact(self, trade_size: float) -> float:
        """
        Price impact using square-root model.
        Returns impact as fraction of price.
        """
        eta = 0.1 # empirical constant
        return eta * self.sigma * np.sqrt(trade_size / self.adv)

    def lvar(self, position: float, var_1d: float, confidence: float = 0.99, spread_vol: float = None) -> dict:
        """
        Compute Liquidity-Adjusted VaR using BDSS model.

        Parameters
        ----------
        position : position size in shares
        var_1d : 1-day VaR of the position (in $)
        confidence : confidence for spread adjustment
        spread_vol : spread volatility (if None, assumes 0.5 * spread)
        """
        if spread_vol is None:
            spread_vol = self.spread * 0.5

        # Days to liquidate at 10% POV
        D = self.days_to_liquidate(position)

        # Scale VaR to liquidation horizon
        var_D = var_1d * np.sqrt(D)

        # Spread cost (BDSS)
        from scipy.stats import norm
        k = norm.ppf(confidence)
        spread_adj = 0.5 * (self.spread + k * spread_vol)
        spread_cost = position * self.price * spread_adj

        # Market impact cost
        impact = self.square_root_impact(position)
        impact_cost = impact * position * self.price

        lvar_total = var_D + spread_cost + impact_cost

        return {
            'VaR_1day': var_1d,
            'liquidation_days': D,
            'VaR_D_day': var_D,
            'spread_cost': spread_cost,
            'impact_cost': impact_cost,
            'LVaR': lvar_total,
            'LVaR_premium': (lvar_total / (var_1d + 1e-8) - 1.0) * 100.0
        }

    def optimal_liquidation(self, X0: float, T: int, lam: float = 1e-4, eta: float = 0.01) -> np.ndarray:
        """
        Almgren-Chriss optimal liquidation schedule.

        Parameters
        ----------
        X0 : initial position (shares)
        T : liquidation horizon (days)
        lam : permanent impact parameter
        eta : temporary impact parameter
        """
        kappa = np.sqrt(lam / eta)
        t = np.arange(T + 1)
        schedule = X0 * np.sinh(kappa * (T - t)) / np.sinh(kappa * T)
        trades = -np.diff(schedule) # shares traded each day

        print(f"Optimal Liquidation Schedule (X0={X0:.0f}, T={T} days)")
        print(f"Urgency kappa = {kappa:.4f}")
        for day, trade in enumerate(trades[:5], 1):
            print(f" Day {day}: Sell {trade:.1f} shares")
        if T > 5:
            print(f" ... ({T - 5} more days) ...")

        return trades

    def position_size_liquidity_limit(self, max_pov: float = 0.10, max_days: float = 5.0) -> float:
        """
        Maximum position size given liquidity constraints.
        """
        max_size = self.adv * max_pov * max_days
        print(f"Max position (given {max_pov * 100:.0f}% POV, {max_days} days): "
              f"{max_size:,.0f} shares = ${max_size * self.price:,.0f}")
        return max_size

