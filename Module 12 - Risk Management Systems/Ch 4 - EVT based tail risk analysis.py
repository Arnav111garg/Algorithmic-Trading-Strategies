import numpy as np
import pandas as pd
from scipy.stats import genpareto, genextreme
from scipy.optimize import minimize
import matplotlib.pyplot as plt

class TailRiskAnalyzer:
    """
    Extreme Value Theory-based tail risk analysis.
    Implements POT method with GPD fitting.
    """
    def __init__(self, losses: pd.Series):
        """losses: series of portfolio losses (positive = loss)."""
        self.losses = losses
        self.gpd_params = None
        self.threshold = None

    def select_threshold(self, quantile_range: tuple = (0.85, 0.98), n_thresholds: int = 30) -> float:
        """
        Mean Excess Plot for threshold selection.
        Threshold should be where mean excess plot is approximately linear.
        """
        quantiles = np.linspace(quantile_range[0], quantile_range[1], n_thresholds)
        thresholds = np.quantile(self.losses, quantiles)
        mean_excess = [
            self.losses[self.losses > u].mean() - u
            for u in thresholds
        ]

        # Find approximately linear region (simple heuristic: use 90th percentile)
        optimal_threshold = np.quantile(self.losses, 0.90)
        self.threshold = optimal_threshold

        print(f"Selected threshold u = {optimal_threshold:.4f}")
        print(f"Exceedances: {(self.losses > optimal_threshold).sum()}")
        return optimal_threshold

    def fit_gpd(self, threshold: float = None) -> dict:
        """
        Fit Generalized Pareto Distribution to threshold exceedances.
        """
        if threshold is not None:
            self.threshold = threshold
        elif self.threshold is None:
            self.select_threshold()

        exceedances = self.losses[self.losses > self.threshold] - self.threshold
        xi, loc, beta = genpareto.fit(exceedances, floc=0)

        self.gpd_params = {'xi': xi, 'beta': beta, 'loc': loc}
        self.n_u = len(exceedances)
        self.n = len(self.losses)

        print(f"\nGPD Fit Results:")
        print(f"Shape (xi) = {xi:.4f} ({'heavy' if xi > 0 else 'light'} tail)")
        print(f"Scale (beta) = {beta:.4f}")
        print(f"Threshold u = {self.threshold:.4f}")
        print(f"N_u / N = {self.n_u} / {self.n} = {self.n_u / self.n:.3f}")

        return self.gpd_params

    def gpd_var(self, alpha: float) -> float:
        """EVT-based VaR using GPD fit."""
        if self.gpd_params is None:
            self.fit_gpd()
        xi = self.gpd_params['xi']
        beta = self.gpd_params['beta']
        u = self.threshold

        # Equation (15.18)
        var = u + (beta / xi) * (((self.n / self.n_u) * (1 - alpha))**(-xi) - 1)
        return var

    def gpd_es(self, alpha: float) -> float:
        """EVT-based Expected Shortfall using GPD fit."""
        if self.gpd_params is None:
            self.fit_gpd()
        xi = self.gpd_params['xi']
        beta = self.gpd_params['beta']
        u = self.threshold

        var = self.gpd_var(alpha)
        # Equation (15.19)
        es = var / (1 - xi) + (beta - xi * u) / (1 - xi)
        return es

    def tail_dependence(self, X: pd.Series, Y: pd.Series, u: float = 0.95) -> dict:
        """
        Estimate lower and upper tail dependence coefficients.
        """
        rank_X = X.rank(pct=True)
        rank_Y = Y.rank(pct=True)

        # Lower tail dependence
        joint_lower = ((rank_X <= 1 - u) & (rank_Y <= 1 - u)).mean()
        lambda_L = joint_lower / (1 - u)

        # Upper tail dependence
        joint_upper = ((rank_X >= u) & (rank_Y >= u)).mean()
        lambda_U = joint_upper / (1 - u)

        print(f"Tail Dependence at u={u:.2f}:")
        print(f"Lower (lambda_L) = {lambda_L:.4f}")
        print(f"Upper (lambda_U) = {lambda_U:.4f}")

        return {'lambda_L': lambda_L, 'lambda_U': lambda_U}

    def full_tail_report(self, confidence_levels: list = [0.95, 0.99, 0.999]):
        """Generate complete tail risk report."""
        if self.gpd_params is None:
            self.fit_gpd()

        print("\n" + "=" * 55)
        print("TAIL RISK REPORT (Extreme Value Theory)")
        print("=" * 55)
        print(f"{'Confidence': >12} | {'HS VaR': >10} | {'GPD VaR': >10} | {'GPD ES': >10}")
        print("-" * 55)
        for alpha in confidence_levels:
            hs_var = np.quantile(self.losses, alpha)
            gpd_var = self.gpd_var(alpha)
            gpd_es = self.gpd_es(alpha)
            print(f"{alpha * 100: >11.1f}% | {hs_var: >10.4f} | {gpd_var: >10.4f} | {gpd_es: >10.4f}")
        print("=" * 55)

