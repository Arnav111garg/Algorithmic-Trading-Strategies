import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from typing import List, Tuple

class DrawdownManager:
    """
    Complete drawdown analysis and management system.
    """
    def __init__(self, nav: pd.Series):
        """
        Parameters
        ----------
        nav : Net Asset Value time series (price or index level)
        """
        self.nav = nav
        self.returns = nav.pct_change().dropna()
        self._compute_drawdown()

    def _compute_drawdown(self):
        """Compute drawdown series."""
        self.running_max = self.nav.cummax()
        self.drawdown = (self.nav - self.running_max) / self.running_max

    def max_drawdown(self) -> float:
        return self.drawdown.min()

    def drawdown_periods(self) -> pd.DataFrame:
        """
        Identify all distinct drawdown periods (start, trough, end, MDD).
        """
        dd = self.drawdown
        is_drawdown = dd < 0

        periods = []
        in_dd = False
        start, trough_date, trough_val = None, None, 0.0

        for date, val in dd.items():
            if val < 0 and not in_dd:
                in_dd = True
                start = date
                trough_date = date
                trough_val = val
            elif val < 0 and in_dd:
                if val < trough_val:
                    trough_val = val
                    trough_date = date
            elif val >= 0 and in_dd:
                recovery_date = date
                duration = (recovery_date - start).days
                recovery_time = (recovery_date - trough_date).days
                periods.append({
                    'start': start,
                    'trough': trough_date,
                    'end': recovery_date,
                    'max_dd': trough_val,
                    'total_days': duration,
                    'recovery_days': recovery_time
                })
                in_dd = False

        # Handle ongoing drawdown
        if in_dd:
            periods.append({
                'start': start,
                'trough': trough_date,
                'end': None,
                'max_dd': trough_val,
                'total_days': None,
                'recovery_days': None
            })

        return pd.DataFrame(periods).sort_values('max_dd')

    def performance_ratios(self, rf: float = 0.02) -> dict:
        """Compute all drawdown-adjusted performance ratios."""
        rets = self.returns
        ann_ret = (1 + rets.mean()) ** 252 - 1
        ann_vol = rets.std() * np.sqrt(252)
        mdd = abs(self.max_drawdown())

        # Ulcer Index (RMS drawdown)
        ulcer = np.sqrt((self.drawdown ** 2).mean()) + 1e-8

        # Burke Ratio denominator
        dd_periods_df = self.drawdown_periods()
        dd_periods = dd_periods_df['max_dd'].values if not dd_periods_df.empty else np.array([])
        burke_denom = np.sqrt(np.sum(dd_periods ** 2)) if len(dd_periods) > 0 else mdd
        burke_denom = abs(burke_denom) + 1e-8

        ratios = {
            'CAGR': ann_ret,
            'Ann_Vol': ann_vol,
            'Sharpe': (ann_ret - rf) / (ann_vol + 1e-8),
            'Max_Drawdown': -mdd,
            'Calmar': ann_ret / (mdd + 1e-8),
            'Ulcer_Index': ulcer,
            'Pain_Ratio': ann_ret / ulcer,
            'Burke_Ratio': (ann_ret - rf) / burke_denom
        }

        print("\nPerformance Ratios:")
        for k, v in ratios.items():
            print(f"  {k:<18}: {v:>8.4f}")
        return ratios

    def drawdown_control(self, thresholds: List[float] = [-0.03, -0.05, -0.08, -0.12], actions: List[str] = None) -> pd.DataFrame:
        """
        Check current drawdown against hierarchical control thresholds.
        Returns action recommendations.
        """
        if actions is None:
            actions = [
                'Review positions, tighten sizing',
                'Reduce gross exposure 25%, notify PM',
                'Reduce exposure 50%, risk committee review',
                'Full liquidation, strategy review required'
            ]

        current_dd = self.drawdown.iloc[-1]

        print(f"\nCurrent Drawdown: {current_dd:.2%}")
        print("=" * 50)

        active_levels = []
        for level, (thresh, action) in enumerate(zip(thresholds, actions), 1):
            triggered = current_dd <= thresh
            status = ">>> TRIGGERED <<<" if triggered else "clear"
            print(f"  Level {level} ({thresh:.0%}): {status}")
            if triggered:
                print(f"  ACTION: {action}")
                active_levels.append(level)

        print("=" * 50)

        result = pd.DataFrame({
            'threshold': thresholds,
            'action': actions,
            'triggered': [current_dd <= t for t in thresholds]
        })
        return result

    def kelly_sizing(self, target_dd_limit: float = 0.15, horizon_days: int = 252) -> float:
        """
        Compute Kelly fraction consistent with a drawdown limit.
        Uses approximation: E[MDD] ~ sigma * sqrt(T) / (2*f/f*)
        """
        mu = self.returns.mean() * 252
        sigma = self.returns.std() * np.sqrt(252)

        if sigma == 0 or mu <= 0:
            return 0.0

        f_kelly = mu / (sigma ** 2)

        # Approximate expected MDD at fraction f of Kelly
        k = 0.5 # empirical constant

        # Solve: target_dd = k * sigma * sqrt(T) / (f_fraction * f_kelly * sigma)
        denom = target_dd_limit * f_kelly
        f_fraction = (k * np.sqrt(horizon_days / 252.0)) / denom if denom > 0 else 0.0
        f_fraction = min(f_fraction, 1.0) # cap at full Kelly

        print(f"\nKelly Sizing Analysis:")
        print(f"  Full Kelly fraction : {f_kelly:.4f}")
        print(f"  Recommended fraction : {f_fraction:.4f}")
        print(f"  (= {f_fraction * 100:.1f}% of Kelly)")
        print(f"  Target MDD limit     : {target_dd_limit:.0%}")

        return f_fraction

