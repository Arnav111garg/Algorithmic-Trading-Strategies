import numpy as np
import pandas as pd
from dataclasses import dataclass
from typing import Dict, List, Optional

@dataclass
class StressScenario:
    name: str
    factor_shocks: Dict[str, float]  # factor -> shock size
    description: str
    source: str  # 'historical' or 'hypothetical'

class StressTestEngine:
    """
    Production stress testing system for algorithmic trading portfolios.
    Supports historical, hypothetical, and reverse stress tests.
    """

    # Predefined Historical Scenarios
    HISTORICAL_SCENARIOS = {
        'GFC_2008': StressScenario(
            name='Global Financial Crisis 2008 (Oct Peak)',
            factor_shocks={
                'equity': -0.50, 'credit_spread': +0.04,
                'volatility': +0.50, 'fx_usd': +0.15,
                'rates_10y': -0.015, 'commodities': -0.30,
                'liquidity': -0.40  # bid-ask spread widening
            },
            description='Peak crisis week Oct 2008: correlation spike, liquidity freeze',
            source='historical'
        ),
        'COVID_2020': StressScenario(
            name='COVID-19 Market Crash (Feb - Mar 2020)',
            factor_shocks={
                'equity': -0.34, 'credit_spread': +0.02,
                'volatility': +0.65, 'fx_usd': +0.05,
                'rates_10y': -0.012, 'commodities': -0.35,
                'liquidity': -0.50
            },
            description='Fastest 30%+ crash in history; VIX reached 85',
            source='historical'
        ),
        'VOL_SPIKE_2018': StressScenario(
            name='VIX Spike February 2018 (Volmageddon)',
            factor_shocks={
                'equity': -0.10, 'credit_spread': +0.005,
                'volatility': +0.40, 'fx_usd': -0.01,
                'rates_10y': +0.001, 'commodities': -0.05,
                'liquidity': -0.20
            },
            description='Implosion of short-vol products (XIV, SVXY)',
            source='historical'
        ),
        'RATE_SHOCK': StressScenario(
            name='Hypothetical: 200 bp Rate Shock',
            factor_shocks={
                'equity': -0.15, 'credit_spread': +0.01,
                'volatility': +0.15, 'fx_usd': +0.08,
                'rates_10y': +0.020, 'commodities': +0.05,
                'liquidity': -0.10
            },
            description='Fed emergency rate hike 200 bps; equity de-rating',
            source='hypothetical'
        ),
    }

    def __init__(
        self,
        portfolio_exposures: Dict[str, float],
        portfolio_value: float,
        covariance_matrix: Optional[np.ndarray] = None,
        factor_names: Optional[List[str]] = None
    ):
        """
        Parameters
        ----------
        portfolio_exposures : dict of {factor: dollar_exposure}
            e.g., {'equity': 1e6, 'rates_10y': -5e5}
        portfolio_value : total portfolio NAV
        covariance_matrix : factor covariance matrix (for reverse stress)
        factor_names : ordered list of factor names matching cov matrix
        """
        self.exposures = portfolio_exposures
        self.nav = portfolio_value
        self.cov = covariance_matrix
        self.factors = factor_names or list(portfolio_exposures.keys())

    def run_scenario(self, scenario: StressScenario, include_second_order: bool = False) -> dict:
        """
        Apply a stress scenario to the portfolio.
        Returns P&L breakdown by factor.
        """
        pnl_by_factor = {}
        total_pnl = 0

        for factor, shock in scenario.factor_shocks.items():
            exposure = self.exposures.get(factor, 0)
            pnl = exposure * shock
            pnl_by_factor[factor] = pnl
            total_pnl += pnl

        result = {
            'scenario': scenario.name,
            'total_pnl': total_pnl,
            'pnl_pct_nav': total_pnl / self.nav,
            'pnl_by_factor': pnl_by_factor,
            'source': scenario.source
        }
        return result

    def run_all_scenarios(self, additional: Dict[str, StressScenario] = None) -> pd.DataFrame:
        """Run all predefined + additional scenarios."""
        scenarios = dict(self.HISTORICAL_SCENARIOS)
        if additional:
            scenarios.update(additional)

        results = []
        print(f"\n{'='*65}")
        print(f" STRESS TEST RESULTS | Portfolio NAV: ${self.nav:,.0f}")
        print(f"{'='*65}")
        print(f" {'Scenario':<35} | {'P&L ($)':>10} | {'P&L (%)':>8}")
        print(f" {'-'*35} -+- {'-'*10} -+- {'-'*8}")

        for key, scenario in scenarios.items():
            res = self.run_scenario(scenario)
            results.append(res)
            print(f" {scenario.name[:35]:<35} | {res['total_pnl']:>10,.0f} | {res['pnl_pct_nav']:>8.2%}")

        print(f"{'='*65}")
        return pd.DataFrame(results)

    def reverse_stress_test(self, loss_threshold: float) -> dict:
        """
        Find minimum-likelihood scenario causing loss >= threshold.
        Uses equation (15.25): delta_f* = L* * Sigma * b / (b' * Sigma * b)

        Parameters
        ----------
        loss_threshold : target loss in dollar terms (positive = loss)
        """
        if self.cov is None:
            raise ValueError("Covariance matrix required for reverse stress test")

        b = np.array([self.exposures.get(f, 0) for f in self.factors])
        Sigma = self.cov

        # Minimum-likelihood scenario
        Sigma_b = Sigma @ b
        b_Sigma_b = b @ Sigma_b

        delta_f_star = loss_threshold * Sigma_b / b_Sigma_b

        mahalanobis = np.sqrt(delta_f_star @ np.linalg.solve(Sigma, delta_f_star))

        scenario_dict = {f: d for f, d in zip(self.factors, delta_f_star)}

        print(f"\nReverse Stress Test: Find scenario causing ${loss_threshold:,.0f} loss")
        print(f" Mahalanobis distance: {mahalanobis:.2f} (in sigma units)")
        print(f" Factor shocks required:")
        for f, d in scenario_dict.items():
            if abs(d) > 1e-6:
                print(f"   {f:<20}: {d:>+.4f}")

        return {
            'loss_threshold': loss_threshold,
            'factor_shocks': scenario_dict,
            'mahalanobis': mahalanobis,
            'implied_probability': np.exp(-0.5 * mahalanobis ** 2)
        }

