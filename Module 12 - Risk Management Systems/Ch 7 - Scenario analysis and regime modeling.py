import numpy as np
import pandas as pd
from sklearn.mixture import GaussianMixture
from scipy.stats import norm
from typing import List, Dict, Tuple

class ScenarioAnalysisEngine:
    """
    Comprehensive scenario analysis system.
    Includes regime detection, scenario probability assignment,
    and portfolio positioning under different scenarios.
    """

    # Macroeconomic scenarios (4 quadrant model)
    MACRO_SCENARIOS = {
        'Goldilocks': {
            'probability': 0.35,
            'equity': 0.15, 'bonds': 0.05, 'tips': 0.03,
            'commodities': 0.05, 'gold': 0.00, 'credit': 0.10,
            'vol_regime': 'low'
        },
        'Overheating': {
            'probability': 0.25,
            'equity': 0.10, 'bonds': -0.10, 'tips': 0.05,
            'commodities': 0.20, 'gold': 0.08, 'credit': 0.05,
            'vol_regime': 'medium'
        },
        'Deflation': {
            'probability': 0.20,
            'equity': -0.20, 'bonds': 0.20, 'tips': 0.08,
            'commodities': -0.25, 'gold': 0.05, 'credit': -0.30,
            'vol_regime': 'high'
        },
        'Stagflation': {
            'probability': 0.20,
            'equity': -0.10, 'bonds': -0.05, 'tips': 0.10,
            'commodities': 0.15, 'gold': 0.15, 'credit': -0.15,
            'vol_regime': 'high'
        }
    }

    def __init__(self, portfolio_weights: Dict[str, float], portfolio_value: float):
        """
        portfolio_weights : { asset_class : weight }
        """
        self.weights = portfolio_weights
        self.nav = portfolio_value

    def scenario_pnl(self, scenario_name: str) -> dict:
        """Compute portfolio P&L under a specific macro scenario."""
        if scenario_name not in self.MACRO_SCENARIOS:
            raise KeyError(f"Unknown scenario: {scenario_name}")

        scenario = self.MACRO_SCENARIOS[scenario_name]
        total_return = sum(
            self.weights.get(asset, 0) * ret
            for asset, ret in scenario.items()
            if isinstance(ret, float) and asset != 'probability'
        )

        return {
            'scenario': scenario_name,
            'probability': scenario['probability'],
            'portfolio_ret': total_return,
            'pnl_dollar': total_return * self.nav,
            'vol_regime': scenario.get('vol_regime', 'medium')
        }

    def full_scenario_analysis(self) -> pd.DataFrame:
        """Run all scenarios and compute probability-weighted statistics."""
        results = []
        print(f"\n{'='*70}")
        print(f" SCENARIO ANALYSIS | Portfolio NAV: ${self.nav:,.0f}")
        print(f"{'='*70}")
        print(f" {'Scenario':<15} | {'Prob':>5} | {'Return':>8} | {'P&L ($)':>12} | {'Regime':>8}")
        print(f" {'-'*15} -+- {'-'*5} -+- {'-'*8} -+- {'-'*12} -+- {'-'*8}")

        for name in self.MACRO_SCENARIOS:
            res = self.scenario_pnl(name)
            results.append(res)
            print(f" {name:<15} | {res['probability']:>5.0%} | {res['portfolio_ret']:>8.2%} | {res['pnl_dollar']:>12,.0f} | {res['vol_regime']:>8}")

        df = pd.DataFrame(results)

        # Expected value and variance
        ev = (df['portfolio_ret'] * df['probability']).sum()
        ev2 = ((df['portfolio_ret']**2) * df['probability']).sum()
        vol = np.sqrt(ev2 - ev**2)

        print(f"\n Expected Return : {ev:.2%}")
        print(f" Scenario Vol: {vol:.2%}")
        print(f" Sharpe (scen): {ev/vol:.2f}")
        print(f"{'='*70}")

        return df

    def fit_regime_model(self, returns: pd.Series, n_regimes: int = 2) -> dict:
        """
        Fit Gaussian Mixture Model to identify market regimes.
        Uses EM algorithm to estimate regime parameters.
        """
        X = returns.values.reshape(-1, 1)

        gmm = GaussianMixture(
            n_components=n_regimes,
            covariance_type='full',
            n_init=10,
            random_state=42
        )
        gmm.fit(X)

        # Sort regimes by mean (low return = crisis, high = bull)
        order = np.argsort(gmm.means_.ravel())
        means = gmm.means_.ravel()[order]
        vols = np.sqrt(gmm.covariances_.ravel()[order])
        priors = gmm.weights_[order]

        print(f"\nRegime Detection ({n_regimes} regimes):")

        regime_names = ['Bear / Crisis', 'Bull / Normal'] if n_regimes == 2 else [f'Regime {i+1}' for i in range(n_regimes)]

        for i, (name, mu, sig, pi) in enumerate(zip(regime_names, means, vols, priors)):
            print(f" {name:<15}: mu ={mu:.4f} sigma ={sig:.4f} prior ={pi:.3f}")
            print(f" Ann. Return ={mu * 252:.1%} Ann. Vol ={sig * np.sqrt(252):.1%}")

        # Current regime probabilities
        regime_probs = gmm.predict_proba(returns.values[-1:].reshape(-1, 1))
        current_regime = np.argmax(regime_probs[0])
        print(f"\n Current regime : {regime_names[current_regime]} (prob ={regime_probs[0, current_regime]:.3f})")

        return {
            'means': means, 'vols': vols, 'priors': priors,
            'model': gmm, 'current_regime': current_regime,
            'current_probs': regime_probs[0]
        }

    def conditional_scenario_var(self, current_regime: str, confidence: float = 0.99) -> float:
        """
        Regime-conditional VaR: weight scenarios by current regime probability.
        """
        # Simplified: map regime to scenario weights
        if current_regime == 'bear':
            weights = {'Goldilocks': 0.05, 'Overheating': 0.10, 'Deflation': 0.55, 'Stagflation': 0.30}
        else:
            weights = {k: v['probability'] for k, v in self.MACRO_SCENARIOS.items()}

        weighted_returns = np.array([
            self.scenario_pnl(s)['portfolio_ret'] for s in weights
        ])
        weighted_probs = np.array(list(weights.values()))

        # Weighted quantile
        sorted_idx = np.argsort(weighted_returns)
        cum_probs = np.cumsum(weighted_probs[sorted_idx])

        var_idx = np.searchsorted(cum_probs, 1 - confidence)
        return -weighted_returns[sorted_idx[var_idx]]

