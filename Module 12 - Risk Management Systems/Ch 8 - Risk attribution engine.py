import numpy as np
import pandas as pd
from scipy.linalg import cholesky

class RiskAttributionEngine:
    """
    Production risk attribution system.
    Decomposes portfolio risk into factor and idiosyncratic components.
    """

    def __init__(
        self,
        weights: np.ndarray,
        B: np.ndarray,
        F: np.ndarray,
        D: np.ndarray,
        asset_names: list,
        factor_names: list
    ):
        """
        Parameters
        ----------
        weights : (n,) portfolio weight vector
        B : (n, k) factor loading matrix
        F : (k, k) factor covariance matrix
        D : (n,) diagonal idiosyncratic variance vector
        asset_names : list of n asset names
        factor_names : list of k factor names
        """
        self.w = weights
        self.B = B
        self.F = F
        self.D = np.diag(D) if D.ndim == 1 else D
        self.assets = asset_names
        self.factors = factor_names
        self.n = len(weights)
        self.k = len(factor_names)

        # Full covariance matrix
        self.Sigma = B @ F @ B.T + self.D

        # Portfolio variance
        self.port_var = float(weights @ self.Sigma @ weights)
        self.port_vol = np.sqrt(self.port_var)

    def component_risk_contributions(self) -> pd.DataFrame:
        """
        Compute component risk contributions (sum to 100%).
        Implements equations (15.32) and (15.33).
        """
        # Marginal risk contribution (gradient of variance)
        mrc = 2 * (self.Sigma @ self.w)

        # Component risk contribution
        crc = self.w * (self.Sigma @ self.w)  # dollar contribution
        crc_pct = crc / self.port_var  # percentage contribution

        # Risk contribution to sigma (not sigma^2)
        crc_vol = crc / self.port_vol

        df = pd.DataFrame({
            'weight': self.w,
            'MRC_var': mrc / 2,  # marginal to variance
            'CRC_var': crc,  # component var contribution
            'CRC_pct': crc_pct * 100,  # % of total variance
            'CRC_vol': crc_vol,  # component vol contribution
        }, index=self.assets)

        print(f"\nPortfolio Vol: {self.port_vol:.4f} Var: {self.port_var:.6f}")
        print(f"\nComponent Risk Contributions:")
        print(df.to_string(float_format='{:.4f}'.format))

        return df

    def factor_attribution(self) -> dict:
        """
        Decompose portfolio risk into systematic and idiosyncratic.
        Factor-level contributions using Cholesky decomposition.
        """
        beta_p = self.B.T @ self.w  # (k,) portfolio factor exposures

        sys_var = float(beta_p @ self.F @ beta_p)  # Eq 15.36
        idio_var = float(self.w @ self.D @ self.w)
        total_var = sys_var + idio_var

        # Orthogonal factor contributions via Cholesky
        L = cholesky(self.F, lower=True)  # F = L L'
        z = L.T @ beta_p  # Eq 15.37
        factor_var_contribs = z**2 / total_var

        # Cross-factor contributions (from full F matrix)
        factor_contribs_full = {}
        for j, fname in enumerate(self.factors):
            # Contribution of factor j to systematic variance
            # = beta_p[j] * (F @ beta_p)[j] (one row of the decomposition)
            contrib = beta_p[j] * (self.F @ beta_p)[j]
            factor_contribs_full[fname] = contrib / total_var

        result = {
            'systematic_var': sys_var,
            'idiosymmetric_var': idio_var,
            'total_var': total_var,
            'systematic_pct': sys_var / total_var * 100,
            'idiosymmetric_pct': idio_var / total_var * 100,
            'R_squared': sys_var / total_var,
            'factor_exposures': dict(zip(self.factors, beta_p)),
            'factor_risk_pct': factor_contribs_full
        }

        print(f"\nFactor Risk Attribution:")
        print(f" Systematic  : {result['systematic_pct']:.1f}% (vol: {np.sqrt(sys_var):.4f})")
        print(f" Idiosyncratic: {result['idiosymmetric_pct']:.1f}% (vol: {np.sqrt(idio_var):.4f})")
        print(f" R-squared   : {result['R_squared']:.4f}")

        print(f"\n Factor Exposures and Risk %:")
        for f, beta in zip(self.factors, beta_p):
            pct = factor_contribs_full[f] * 100
            print(f"  {f:<20}: beta ={beta:>+.4f} risk %={pct:>6.2f}%")

        return result

    def pnl_attribution(self, factor_returns: pd.Series, asset_returns: pd.Series) -> dict:
        """
        Ex-post P&L attribution.
        Decomposes daily return into factor and stock selection.
        """
        # Factor P&L
        beta_p = self.B.T @ self.w
        factor_pnl = {
            fname: float(beta_p[j]) * float(factor_returns[fname])
            for j, fname in enumerate(self.factors)
            if fname in factor_returns.index
        }

        # Total return
        total_pnl = float(self.w @ asset_returns.values)

        # Systematic P&L
        sys_pnl = sum(factor_pnl.values())

        # Stock selection (residual)
        selection_pnl = total_pnl - sys_pnl

        print(f"\nP&L Attribution:")
        print(f" Total P&L: {total_pnl:>+.4f}")
        print(f" Systematic: {sys_pnl:>+.4f}")
        for fname, pnl in factor_pnl.items():
            print(f"  {fname:<20}: {pnl:>+.4f}")
        print(f" Stock Selection: {selection_pnl:>+.4f}")

        return {
            'total': total_pnl,
            'systematic': sys_pnl,
            'factor_pnl': factor_pnl,
            'selection': selection_pnl
        }

