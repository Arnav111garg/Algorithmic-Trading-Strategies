import numpy as np
import pandas as pd
from datetime import datetime
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Optional
from enum import Enum
import threading
import time

class AlertLevel(Enum):
    INFO = 1
    WARNING = 2
    ERROR = 3
    CRITICAL = 4

@dataclass
class Alert:
    timestamp: datetime
    level: AlertLevel
    metric: str
    value: float
    threshold: float
    message: str
    action_taken: str = ""

@dataclass
class RiskLimits:
    """Configurable risk limits hierarchy."""
    max_var_pct: float = 0.05  # VaR as % of NAV
    max_drawdown_l1: float = 0.03  # Level 1 DD threshold
    max_drawdown_l2: float = 0.05  # Level 2 DD threshold
    max_drawdown_l3: float = 0.08  # Level 3 DD threshold
    max_drawdown_l4: float = 0.12  # Level 4 DD threshold (liquidate)
    max_gross_exposure: float = 2.0  # Multiple of NAV
    max_net_exposure: float = 0.5  # Fraction of NAV
    max_position_pct: float = 0.05  # Single position as % NAV
    daily_loss_limit: float = 0.02  # Daily P&L stop
    max_beta: float = 1.0  # Absolute portfolio beta
    max_vega_per_vol_pt: float = 200000  # Vega limit in $

class RealTimeRiskMonitor:
    """
    Production real-time risk monitoring system.
    Designed for 1-second to 1-minute update frequency.
    """

    def __init__(
        self,
        nav: float,
        limits: RiskLimits = None,
        alert_callbacks: List[Callable] = None
    ):
        """
        Parameters
        ----------
        nav : Current portfolio NAV
        limits : Risk limits configuration
        alert_callbacks : Functions to call when alert fires
                          (e.g., send_slack, send_email, auto_reduce)
        """
        self.nav = nav
        self.limits = limits or RiskLimits()
        self.callbacks = alert_callbacks or []
        self.alerts_log: List[Alert] = []
        self.nav_peak = nav
        self.start_nav = nav

        # CUSUM state
        self.cusum_pos = 0.0
        self.cusum_neg = 0.0
        self.baseline_daily_pnl = 0.0  # to be estimated from history

    def update(
        self,
        current_nav: float,
        gross_exposure: float,
        net_exposure: float,
        var_1d: float,
        beta: float,
        vega: float,
        positions: Dict[str, float] = None,
        timestamp: datetime = None
    ) -> List[Alert]:
        """
        Main update function. Call this on every risk compute cycle.
        Returns list of newly triggered alerts.
        """
        if timestamp is None:
            timestamp = datetime.now()
        new_alerts = []
        self.nav = current_nav

        # Update peak for drawdown
        self.nav_peak = max(self.nav_peak, current_nav)
        drawdown = (self.nav_peak - current_nav) / self.nav_peak

        # Daily P&L
        daily_pnl_pct = (current_nav - self.start_nav) / self.start_nav

        # Check each limit
        checks = [
            # (metric_name, value, threshold, alert_level, action)
            ('Daily_PnL_Loss', -daily_pnl_pct, self.limits.daily_loss_limit, AlertLevel.ERROR, 'Review positions'),
            ('VaR_vs_NAV', var_1d / current_nav, self.limits.max_var_pct, AlertLevel.WARNING, 'Consider reducing exposure'),
            ('Gross_Exposure', gross_exposure / current_nav, self.limits.max_gross_exposure, AlertLevel.ERROR, 'Reduce gross exposure immediately'),
            ('Net_Exposure', abs(net_exposure) / current_nav, self.limits.max_net_exposure, AlertLevel.WARNING, 'Reduce net directional exposure'),
            ('Beta', abs(beta), self.limits.max_beta, AlertLevel.WARNING, 'Hedge market beta'),
            ('Vega_$', abs(vega), self.limits.max_vega_per_vol_pt, AlertLevel.WARNING, 'Reduce vega exposure')
        ]

        # Drawdown hierarchy
        dd_levels = [
            (drawdown, self.limits.max_drawdown_l1, AlertLevel.INFO, 'Review positions, tighten sizing'),
            (drawdown, self.limits.max_drawdown_l2, AlertLevel.WARNING, 'Reduce gross exposure 25%, notify PM'),
            (drawdown, self.limits.max_drawdown_l3, AlertLevel.ERROR, 'Reduce exposure 50%, risk committee review'),
            (drawdown, self.limits.max_drawdown_l4, AlertLevel.CRITICAL, 'FULL LIQUIDATION REQUIRED')
        ]

        for val, thresh, level, action in dd_levels:
            if val >= thresh:
                checks.append((
                    f'Drawdown_L{dd_levels.index((val, thresh, level, action)) + 1}',
                    val, thresh, level, action
                ))

        # Position concentration
        if positions:
            for asset, notional in positions.items():
                pct = abs(notional) / current_nav
                if pct > self.limits.max_position_pct:
                    checks.append((
                        f'Position_{asset}',
                        pct, self.limits.max_position_pct,
                        AlertLevel.WARNING,
                        f'Reduce {asset} position'
                    ))

        # Fire alerts for breached limits
        for metric, value, threshold, level, action in checks:
            if value > threshold:
                alert = Alert(
                    timestamp=timestamp,
                    level=level,
                    metric=metric,
                    value=value,
                    threshold=threshold,
                    message=f"{metric}: {value:.4f} exceeds limit {threshold:.4f}",
                    action_taken=action
                )
                self.alerts_log.append(alert)
                new_alerts.append(alert)

                # Fire callbacks
                for cb in self.callbacks:
                    cb(alert)

        return new_alerts

    def cusum_pnl_monitor(
        self,
        daily_pnl: float,
        sigma_pnl: float,
        k_factor: float = 0.5,
        h_factor: float = 4.0
    ) -> dict:
        """
        CUSUM control chart for detecting regime changes in P&L.
        Implements equations (15.42) - (15.44).
        """
        k = k_factor * sigma_pnl  # reference value
        h = h_factor * sigma_pnl  # control limit

        deviation = daily_pnl - self.baseline_daily_pnl

        self.cusum_pos = max(0.0, self.cusum_pos + deviation - k)
        self.cusum_neg = max(0.0, self.cusum_neg - deviation - k)

        alert_up = self.cusum_pos > h
        alert_dn = self.cusum_neg > h

        if alert_up or alert_dn:
            direction = 'UPWARD' if alert_up else 'DOWNWARD'
            print(f"CUSUM ALERT: {direction} shift detected in P&L!")
            if alert_up:
                self.cusum_pos = 0  # reset after alert
            else:
                self.cusum_neg = 0

        return {
            'cusum_positive': self.cusum_pos,
            'cusum_negative': self.cusum_neg,
            'alert_up': alert_up,
            'alert_down': alert_dn,
            'control_limit': h
        }

    def summary_report(self) -> pd.DataFrame:
        """Generate alert summary report."""
        if not self.alerts_log:
            print("No alerts recorded.")
            return pd.DataFrame()

        df = pd.DataFrame([{
            'timestamp': a.timestamp,
            'level': a.level.name,
            'metric': a.metric,
            'value': a.value,
            'threshold': a.threshold,
            'action': a.action_taken
        } for a in self.alerts_log])

        print(f"\nRisk Alerts Summary ({len(df)} alerts):")
        print(df.to_string(index=False))
        return df

