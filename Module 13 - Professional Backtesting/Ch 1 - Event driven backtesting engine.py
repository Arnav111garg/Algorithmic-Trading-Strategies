import heapq
from dataclasses import dataclass, field
from enum import Enum, auto
from typing import Optional, List, Deque
from collections import deque
import numpy as np
import pandas as pd

# Event Types
class EventType(Enum):
    MARKET = auto()
    SIGNAL = auto()
    ORDER = auto()
    FILL = auto()

class OrderType(Enum):
    MARKET = auto()
    LIMIT = auto()
    STOP = auto()

class Direction(Enum):
    LONG = 1
    SHORT = -1
    EXIT = 0

@dataclass
class MarketEvent:
    timestamp: pd.Timestamp
    symbol: str
    open: float
    high: float
    low: float
    close: float
    volume: float
    type: EventType = field(default=EventType.MARKET, init=False)

@dataclass
class SignalEvent:
    timestamp: pd.Timestamp
    symbol: str
    direction: Direction
    strength: float = 1.0  # 0-1 conviction
    type: EventType = field(default=EventType.SIGNAL, init=False)

@dataclass
class OrderEvent:
    timestamp: pd.Timestamp
    symbol: str
    order_type: OrderType
    quantity: float
    direction: Direction
    limit_price: Optional[float] = None
    type: EventType = field(default=EventType.ORDER, init=False)

@dataclass
class FillEvent:
    timestamp: pd.Timestamp
    symbol: str
    exchange: str
    quantity: float
    direction: Direction
    fill_price: float
    commission: float
    slippage: float
    type: EventType = field(default=EventType.FILL, init=False)

# Portfolio
class Portfolio:
    """Tracks positions, cash, equity, and generates orders from signals."""

    def __init__(self, initial_capital: float = 1000000.0):
        self.initial_capital = initial_capital
        self.cash = initial_capital
        self.positions = {}  # symbol -> signed quantity
        self.market_prices = {}  # symbol -> last close
        self.equity_curve = []
        self.trade_log = []

    @property
    def equity(self) -> float:
        holdings_value = sum(
            self.positions.get(s, 0) * self.market_prices.get(s, 0)
            for s in self.positions
        )
        return self.cash + holdings_value

    def update_market(self, event: MarketEvent):
        self.market_prices[event.symbol] = event.close
        self.equity_curve.append({
            'timestamp': event.timestamp,
            'equity': self.equity,
            'cash': self.cash
        })

    def generate_order(self, signal: SignalEvent, fraction: float = 0.02) -> Optional[OrderEvent]:
        """Kelly-scaled position sizing: risk fraction * equity per trade."""
        target_value = self.equity * fraction * signal.strength
        price = self.market_prices.get(signal.symbol, 1.0)
        quantity = target_value / price if price > 0 else 0

        if signal.direction == Direction.EXIT:
            quantity = abs(self.positions.get(signal.symbol, 0))
            if quantity == 0:
                return None

        return OrderEvent(
            timestamp=signal.timestamp,
            symbol=signal.symbol,
            order_type=OrderType.MARKET,
            quantity=quantity,
            direction=signal.direction
        )

    def update_fill(self, fill: FillEvent):
        sign = fill.direction.value if fill.direction != Direction.EXIT else (
            -np.sign(self.positions.get(fill.symbol, 0))
        )
        self.positions[fill.symbol] = (
            self.positions.get(fill.symbol, 0) + sign * fill.quantity
        )
        self.cash -= sign * fill.quantity * fill.fill_price + fill.commission
        self.trade_log.append({
            'timestamp': fill.timestamp,
            'symbol': fill.symbol,
            'direction': fill.direction.name,
            'quantity': fill.quantity,
            'fill_price': fill.fill_price,
            'commission': fill.commission,
            'slippage': fill.slippage,
        })

# Execution Handler
class SimulatedExecutionHandler:
    """
    Realistic order execution simulator.
    Models: commission, slippage, partial fills.
    """

    def __init__(
        self,
        commission_rate: float = 0.001,  # 10 bps per side
        slippage_pct: float = 0.0005,    # 5 bps
        partial_fill_prob: float = 0.0
    ):
        self.commission_rate = commission_rate
        self.slippage_pct = slippage_pct
        self.partial_fill_prob = partial_fill_prob

    def execute_order(self, order: OrderEvent, market: MarketEvent) -> FillEvent:
        # Slippage: buys fill higher, sells fill lower
        direction_sign = 1 if order.direction == Direction.LONG else -1
        slippage_adj = direction_sign * self.slippage_pct
        fill_price = market.close * (1 + slippage_adj)

        # Commission: flat bps on notional
        commission = order.quantity * fill_price * self.commission_rate

        return FillEvent(
            timestamp=order.timestamp,
            symbol=order.symbol,
            exchange='SIMULATED',
            quantity=order.quantity,
            direction=order.direction,
            fill_price=fill_price,
            commission=commission,
            slippage=order.quantity * market.close * abs(slippage_adj)
        )

# Main Backtest Engine
class EventDrivenBacktester:
    """
    Production-grade event-driven backtesting engine
    Usage:
        engine = EventDrivenBacktester(strategy, data, initial_capital=1e6)
        results = engine.run()
    """

    def __init__(self, strategy, data: dict, initial_capital: float = 1000000):
        self.strategy = strategy
        self.data = data  # { symbol: pd.DataFrame with OHLCV }
        self.portfolio = Portfolio(initial_capital)
        self.executor = SimulatedExecutionHandler()
        self.events: Deque = deque()
        self._build_event_stream()

    def _build_event_stream(self):
        """Merge all symbols' data into chronological MarketData events."""
        all_events = []
        for symbol, df in self.data.items():
            for ts, row in df.iterrows():
                all_events.append(MarketEvent(
                    timestamp=ts,
                    symbol=symbol,
                    open=row['open'],
                    high=row['high'],
                    low=row['low'],
                    close=row['close'],
                    volume=row['volume']
                ))
        # Sort chronologically
        all_events.sort(key=lambda e: e.timestamp)
        self.events.extend(all_events)

    def run(self) -> dict:
        """Main simulation loop."""
        current_market = {}  # symbol -> latest MarketEvent

        while self.events:
            event = self.events.popleft()

            if event.type == EventType.MARKET:
                current_market[event.symbol] = event
                self.portfolio.update_market(event)

                # Strategy generates signals from market data
                signals = self.strategy.on_market(event, self.portfolio)
                for sig in (signals or []):
                    self.events.append(sig)

            elif event.type == EventType.SIGNAL:
                order = self.portfolio.generate_order(event)
                if order:
                    self.events.append(order)

            elif event.type == EventType.ORDER:
                if event.symbol in current_market:
                    mkt = current_market[event.symbol]
                    fill = self.executor.execute_order(event, mkt)
                    self.events.append(fill)

            elif event.type == EventType.FILL:
                self.portfolio.update_fill(event)

        return self._compute_results()

    def _compute_results(self) -> dict:
        eq = pd.DataFrame(self.portfolio.equity_curve).set_index('timestamp')
        returns = eq['equity'].pct_change().dropna()

        total_return = (eq['equity'].iloc[-1] / self.portfolio.initial_capital) - 1
        ann_factor = 252
        ann_return = (1 + total_return) ** (ann_factor / len(returns)) - 1
        ann_vol = returns.std() * np.sqrt(ann_factor)
        sharpe = ann_return / ann_vol if ann_vol > 0 else 0

        rolling_max = eq['equity'].cummax()
        drawdown = (eq['equity'] - rolling_max) / rolling_max
        max_drawdown = drawdown.min()

        return {
            'equity_curve': eq,
            'returns': returns,
            'total_return': total_return,
            'ann_return': ann_return,
            'ann_vol': ann_vol,
            'sharpe_ratio': sharpe,
            'max_drawdown': max_drawdown,
            'calmar_ratio': -ann_return / max_drawdown if max_drawdown < 0 else np.nan,
            'trade_log': pd.DataFrame(self.portfolio.trade_log)
        }

