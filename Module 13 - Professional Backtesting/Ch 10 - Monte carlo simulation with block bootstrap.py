import numpy as np
import pandas as pd
from scipy.stats import t as t_dist

def block_bootstrap_returns(returns: np.ndarray, n_simulations: int = 10_000, block_length: int = None) -> np.ndarray:
    """
    Stationary block bootstrap for return series.
    Returns shape: (n_simulations, T)
    """
    T = len(returns)
    if block_length is None:
        block_length = max(1, int(T ** (1/3)))  # Optimal block length

    simulated = np.zeros((n_simulations, T))

    for sim in range(n_simulations):
        resampled = []
        while len(resampled) < T:
            # Geometric block length
            L = np.random.geometric(1 / block_length)
            L = min(L, T - len(resampled))
            # Random starting point (circular)
            start = np.random.randint(0, T)
            block = [returns[(start + i) % T] for i in range(L)]
            resampled.extend(block)
        simulated[sim] = resampled[:T]

    return simulated

def monte_carlo_performance(returns: pd.Series, n_simulations: int = 10_000, block_length: int = None) -> dict:
    """
    Full Monte Carlo analysis of strategy performance.
    Computes confidence intervals for all key metrics.
    """
    r = returns.values
    sims = block_bootstrap_returns(r, n_simulations, block_length)

    # Compute metrics for each simulation
    ann = 252
    metrics = {
        'sharpe': [],
        'ann_return': [],
        'max_dd': [],
        'calmar': [],
        'hit_rate': []
    }

    for sim_r in sims:
        mu = sim_r.mean() * ann
        sigma = sim_r.std() * np.sqrt(ann)
        sr = mu / sigma if sigma > 0 else 0

        # Max drawdown
        equity = np.cumprod(1 + sim_r)
        roll_mx = np.maximum.accumulate(equity)
        dd = (equity - roll_mx) / roll_mx
        max_dd = dd.min()

        metrics['sharpe'].append(sr)
        metrics['ann_return'].append(mu)
        metrics['max_dd'].append(max_dd)
        metrics['calmar'].append(-mu / max_dd if max_dd < 0 else np.nan)
        metrics['hit_rate'].append((sim_r > 0).mean())

    results = {}
    for name, vals in metrics.items():
        v = np.array(vals)
        v = v[~np.isnan(v)]

        if name == 'ann_return':
            observed_val = returns.mean() * ann
        elif name == 'sharpe':
            observed_val = (returns.mean() / returns.std() * np.sqrt(ann)) if returns.std() > 0 else 0.0
        else:
            observed_val = np.nan

        results[name] = {
            'observed': observed_val,
            'mean': np.mean(v) if len(v) > 0 else np.nan,
            'std': np.std(v) if len(v) > 0 else np.nan,
            'p5': np.percentile(v, 5) if len(v) > 0 else np.nan,
            'p25': np.percentile(v, 25) if len(v) > 0 else np.nan,
            'p50': np.percentile(v, 50) if len(v) > 0 else np.nan,
            'p75': np.percentile(v, 75) if len(v) > 0 else np.nan,
            'p95': np.percentile(v, 95) if len(v) > 0 else np.nan,
            'p_positive': (v > 0).mean() if len(v) > 0 else np.nan
        }

    return results

def permutation_test(returns: pd.Series, signals: pd.Series, n_perm: int = 10_000, metric: str = 'sharpe') -> dict:
    """
    Permutation test: is observed performance distinguishable from noise?
    H0: signal is independent of returns (no alpha)
    H1: signal has predictive power
    """
    # Observed metric
    aligned = pd.DataFrame({'ret': returns, 'sig': signals.shift(1)}).dropna()
    obs_pnl = aligned['sig'] * aligned['ret']
    obs_sr = (obs_pnl.mean() / obs_pnl.std() * np.sqrt(252)) if obs_pnl.std() > 0 else 0.0

    null_distribution = []
    sig_vals = aligned['sig'].values
    ret_vals = aligned['ret'].values

    for _ in range(n_perm):
        shuffled = np.random.permutation(sig_vals)
        pnl_null = shuffled * ret_vals
        null_sr = (pnl_null.mean() / pnl_null.std() * np.sqrt(252)) if pnl_null.std() > 0 else 0.0
        null_distribution.append(null_sr)

    null_arr = np.array(null_distribution)
    p_value = (null_arr >= obs_sr).mean()
    std_null = null_arr.std()
    z_score = (obs_sr - null_arr.mean()) / std_null if std_null > 0 else 0.0

    return {
        'observed_sharpe': obs_sr,
        'null_mean_sharpe': null_arr.mean(),
        'null_std_sharpe': std_null,
        'p_value': p_value,
        'is_significant': p_value < 0.05,
        'z_score': z_score,
        'null_distribution': null_arr
    }

