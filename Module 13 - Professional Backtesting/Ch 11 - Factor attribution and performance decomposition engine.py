import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import StandardScaler

class FactorAttributionEngine:
    """
    Multi-factor return attribution.
    Supports: Fama-French 5-factor, Barra-style, custom factor models.
    """

    FAMA_FRENCH_FACTORS = ['Mkt-RF', 'SMB', 'HML', 'RMW', 'CMA']

    def __init__(self, factor_names: list = None):
        self.factor_names = factor_names or self.FAMA_FRENCH_FACTORS
        self.model = LinearRegression()
        self.fitted = False

    def fit(self, portfolio_returns: pd.Series, factor_returns: pd.DataFrame, risk_free_rate: pd.Series = None) -> dict:
        """
        Regress portfolio excess returns on factor returns.
        Returns attribution dict.
        """
        if risk_free_rate is not None:
            excess_returns = portfolio_returns - risk_free_rate
        else:
            excess_returns = portfolio_returns

        # Align data
        common_idx = excess_returns.index.intersection(factor_returns.index)
        y = excess_returns[common_idx].values
        X = factor_returns.loc[common_idx, self.factor_names].values

        self.model.fit(X, y)
        y_hat = self.model.predict(X)
        residual = y - y_hat

        # Attribution
        factor_contrib = {}
        for j, name in enumerate(self.factor_names):
            factor_contrib[name] = {
                'beta': self.model.coef_[j],
                'factor_mean': factor_returns[name][common_idx].mean(),
                'contribution_daily': self.model.coef_[j] * factor_returns[name][common_idx].mean(),
                'contribution_annual': self.model.coef_[j] * factor_returns[name][common_idx].mean() * 252
            }

        alpha_daily = self.model.intercept_
        r_squared = self.model.score(X, y)

        # Information Ratio of residual (true alpha)
        alpha_ir = (residual.mean() / residual.std() * np.sqrt(252)) if residual.std() > 0 else 0.0

        # t-statistics
        T = len(y)
        residual_std = residual.std()
        se_alpha = residual_std / np.sqrt(T) if T > 0 else 1e-9
        t_alpha = alpha_daily / se_alpha

        # Factor contribution to total return
        total_factor_contrib = sum(
            v['contribution_annual'] for v in factor_contrib.values()
        )

        self.fitted = True
        self.results = {
            'alpha_daily': alpha_daily,
            'alpha_annual': alpha_daily * 252,
            'alpha_t_stat': t_alpha,
            'alpha_ir': alpha_ir,
            'r_squared': r_squared,
            'factor_contributions': factor_contrib,
            'total_factor_return': total_factor_contrib,
            'total_portfolio_return': y.mean() * 252 if len(y) > 0 else 0.0,
            'residual_vol_annual': residual.std() * np.sqrt(252),
            'factor_names': self.factor_names
        }
        return self.results

    def attribution_table(self) -> pd.DataFrame:
        """Display formatted attribution breakdown."""
        if not self.fitted:
            raise RuntimeError("Must call fit() first")

        rows = []
        for factor, vals in self.results['factor_contributions'].items():
            rows.append({
                'Source': factor,
                'Beta': f"{vals['beta']:.3f}",
                'Factor Return (Ann)': f"{vals['factor_mean'] * 252 * 100:.2f}%",
                'Contribution (Ann)': f"{vals['contribution_annual'] * 100:.2f}%"
            })
        rows.append({
            'Source': 'Alpha (Jensen)',
            'Beta': '',
            'Factor Return (Ann)': '',
            'Contribution (Ann)': f"{self.results['alpha_annual'] * 100:.2f}% (t={self.results['alpha_t_stat']:.2f})"
        })
        return pd.DataFrame(rows)

# Drawdown Attribution
def drawdown_attribution(portfolio_returns: pd.Series, component_returns: pd.DataFrame) -> pd.DataFrame:
    """
    Attribute each drawdown period to component strategies or factors.
    Answers: during the worst drawdown, what drove the losses?
    """
    equity = (1 + portfolio_returns).cumprod()
    roll_max = equity.cummax()
    drawdown = (equity - roll_max) / roll_max

    # Identify drawdown periods
    in_drawdown = drawdown < -0.01  # > 1% drawdown
    dd_periods = []

    start = None
    for t, is_dd in in_drawdown.items():
        if is_dd and start is None:
            start = t
        elif not is_dd and start is not None:
            dd_periods.append((start, t))
            start = None

    attributions = []
    for (dd_start, dd_end) in dd_periods:
        period_port = portfolio_returns[dd_start:dd_end]
        port_total = period_port.sum()

        comp_attr = {}
        for col in component_returns.columns:
            comp_ret = component_returns[col][dd_start:dd_end].sum()
            comp_attr[col] = comp_ret

        attributions.append({
            'drawdown_start': dd_start,
            'drawdown_end': dd_end,
            'duration_days': (dd_end - dd_start).days,
            'portfolio_return': port_total,
            'max_dd': drawdown[dd_start:dd_end].min(),
            **comp_attr
        })

    return pd.DataFrame(attributions)

# P&L Attribution by Time Period
def pnl_calendar_attribution(returns: pd.Series) -> pd.DataFrame:
    """
    Attribute P&L by year, quarter, month.
    Standard institutional reporting format.
    """
    df = pd.DataFrame({'return': returns})
    df['year'] = df.index.year
    df['quarter'] = df.index.quarter
    df['month'] = df.index.month

    monthly = df.groupby(['year', 'month'])['return'].apply(
        lambda x: (1 + x).prod() - 1
    ).unstack(level='month')

    return monthly

