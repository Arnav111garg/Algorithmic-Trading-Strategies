import pandas as pd
from scipy.stats import spearmanr

def decay_analysis(signal: pd.Series, returns: pd.Series, max_lag: int = 60) -> pd.Series:
    """
    Compute forward IC at each lag 1..max_lag.
    Plots alpha decay profile critical for determining holding period.
    """
    decay = {}
    s_ranked = signal.rank(pct=True)
    for lag in range(1, max_lag + 1):
        r_lagged = returns.shift(-lag)  # returns tau bars ahead
        valid = s_ranked.dropna().index.intersection(r_lagged.dropna().index)
        if len(valid) > 30:
            decay[lag] = spearmanr(s_ranked[valid], r_lagged[valid])[0]
    return pd.Series(decay)

