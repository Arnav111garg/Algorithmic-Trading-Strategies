class PurgedKFoldCV:
    """
    Purged K-Fold with embargo for financial time series.
    Reference: Lopez de Prado (2018), Chapter 7.
    """

    def __init__(self, n_splits: int = 5, purge_pct: float = 0.01, embargo_pct: float = 0.01):
        self.n_splits = n_splits
        self.purge_pct = purge_pct
        self.embargo_pct = embargo_pct

    def split(self, X: pd.DataFrame, y=None):
        n = len(X)
        indices = np.arange(n)
        test_size = n // self.n_splits
        purge = int(n * self.purge_pct)
        embargo = int(n * self.embargo_pct)

        for fold in range(self.n_splits):
            test_start = fold * test_size
            test_end = test_start + test_size

            # Purge: exclude [test_start - purge, test_end + embargo]
            excl_start = max(0, test_start - purge)
            excl_end = min(n, test_end + embargo)

            test_idx = indices[test_start:test_end]
            train_idx = np.concatenate([
                indices[:excl_start],
                indices[excl_end:]
            ])
            yield train_idx, test_idx

