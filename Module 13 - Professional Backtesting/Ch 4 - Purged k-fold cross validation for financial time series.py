from itertools import product
from typing import Callable, Dict, Any, Tuple, List
import warnings
import numpy as np
import pandas as pd

class WalkForwardOptimiser:
    """
    Production WFO with:
    - Anchored & rolling window modes
    - Parameter grid search
    - Stability analysis across folds
    - Combinatorial Purged Cross-Validation (CPCV) integration
    """

    def __init__(
        self,
        strategy_factory: Callable,  # factory(params) -> strategy
        backtest_fn: Callable,       # fn(data, strategy) -> metrics dict
        param_grid: Dict[str, list],
        train_length: int = 252,     # trading days
        test_length: int = 63,       # ~1 quarter
        mode: str = 'rolling',
        objective: str = 'sharpe_ratio'
    ):
        self.strategy_factory = strategy_factory
        self.backtest_fn = backtest_fn
        self.param_grid = param_grid
        self.train_length = train_length
        self.test_length = test_length
        self.mode = mode
        self.objective = objective
        self._param_combos = self._expand_grid()

    def _expand_grid(self) -> list:
        keys = list(self.param_grid.keys())
        values = list(self.param_grid.values())
        return [dict(zip(keys, combo)) for combo in product(*values)]

    def _get_windows(self, data: pd.DataFrame) -> List[Tuple]:
        """Generate (train_slice, test_slice) index pairs."""
        n = len(data)
        windows = []
        t = self.train_length
        while t + self.test_length <= n:
            if self.mode == 'rolling':
                train_start = t - self.train_length
            else:  # anchored
                train_start = 0
            windows.append((
                slice(train_start, t),
                slice(t, t + self.test_length)
            ))
            t += self.test_length
        return windows

    def run(self, data: pd.DataFrame) -> Dict:
        windows = self._get_windows(data)
        fold_results = []

        for fold_idx, (train_sl, test_sl) in enumerate(windows):
            train_data = data.iloc[train_sl]
            test_data = data.iloc[test_sl]

            # In-sample optimisation
            best_obj = -np.inf
            best_params = None
            is_results = []

            for params in self._param_combos:
                strategy = self.strategy_factory(params)
                try:
                    metrics = self.backtest_fn(train_data, strategy)
                    obj_val = metrics.get(self.objective, -np.inf)
                    is_results.append({'params': params, 'obj': obj_val, **metrics})
                    if obj_val > best_obj:
                        best_obj = obj_val
                        best_params = params
                except Exception as e:
                    warnings.warn(f"Fold {fold_idx}, params {params}: {e}")

            # Out-of-sample evaluation
            if best_params is not None:
                strategy = self.strategy_factory(best_params)
                oos_metrics = self.backtest_fn(test_data, strategy)

                fold_results.append({
                    'fold': fold_idx + 1,
                    'train_start': data.index[train_sl.start],
                    'train_end': data.index[train_sl.stop - 1],
                    'test_start': data.index[test_sl.start],
                    'test_end': data.index[test_sl.stop - 1],
                    'best_params': best_params,
                    'is_sharpe': best_obj,
                    'oos_sharpe': oos_metrics.get('sharpe_ratio', np.nan),
                    'oos_return': oos_metrics.get('ann_return', np.nan),
                    'oos_drawdown': oos_metrics.get('max_drawdown', np.nan)
                })

        df_folds = pd.DataFrame(fold_results)
        return self._aggregate_results(df_folds)

    def _aggregate_results(self, df: pd.DataFrame) -> Dict:
        wfe = df['oos_sharpe'].mean() / df['is_sharpe'].mean()

        # Parameter stability: most frequent optimal parameter
        param_stability = {}
        for key in self.param_grid.keys():
            vals = df['best_params'].apply(lambda d: d[key])
            param_stability[key] = {
                'mode': vals.mode()[0] if len(vals) > 0 else None,
                'std': vals.std(),
                'range': (vals.min(), vals.max())
            }

        return {
            'fold_results': df,
            'oos_sharpe_mean': df['oos_sharpe'].mean(),
            'oos_sharpe_std': df['oos_sharpe'].std(),
            'oos_return_mean': df['oos_return'].mean(),
            'max_drawdown_mean': df['oos_drawdown'].mean(),
            'walk_forward_eff': wfe,
            'param_stability': param_stability,
            'n_folds': len(df)
        }

