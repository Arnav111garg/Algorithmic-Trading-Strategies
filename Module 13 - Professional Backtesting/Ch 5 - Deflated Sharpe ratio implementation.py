import numpy as np
from scipy.stats import norm
from scipy.special import gamma as gamma_fn

def deflated_sharpe_ratio(
    returns: np.ndarray,
    n_trials: int,
    benchmark_sr: float = 0.0
) -> dict:
    """
    Compute Deflated Sharpe Ratio.

    Parameters
    ----------
    returns : array of strategy returns (daily)
    n_trials : number of independent parameter combinations tested
    benchmark_sr : benchmark Sharpe (annualised, default 0)

    Returns
    -------
    dict with : sharpe, dsr, p_value, expected_max_sr_under_null
    """
    T = len(returns)
    mu = returns.mean()
    sigma = returns.std(ddof=1)

    if sigma == 0:
        return {'sharpe': 0, 'dsr': 0, 'p_value': 1.0}

    sr_raw = mu / sigma * np.sqrt(252) # annualised
    skew = _skewness(returns)
    kurt = _excess_kurtosis(returns)

    # Standard error of Sharpe
    sr_se = np.sqrt((1 + 0.5 * sr_raw**2 - skew * sr_raw + (kurt / 4) * sr_raw**2) / (T - 1))

    # Expected max SR under null (Extreme Value Theory approximation)
    euler_gamma = 0.5772156649
    sr_null = sr_se * (
        (1 - euler_gamma) * norm.ppf(1 - 1 / n_trials) +
        euler_gamma * norm.ppf(1 - 1 / (n_trials * np.e))
    )

    # DSR: probability that observed SR is genuine after multiple testing
    dsr_stat = (sr_raw - sr_null) / sr_se
    dsr = norm.cdf(dsr_stat)

    return {
        'annualised_sharpe': sr_raw,
        'standard_error_sr': sr_se,
        'expected_null_max_sr': sr_null,
        'dsr_statistic': dsr_stat,
        'dsr': dsr,
        'p_value': 1 - dsr,
        'n_trials': n_trials,
        'skewness': skew,
        'excess_kurtosis': kurt,
        'interpretation': (
            'Likely genuine alpha' if dsr > 0.95 else
            'Marginal' if dsr > 0.75 else
            'Likely spurious'
        )
    }

def _skewness(x: np.ndarray) -> float:
    n = len(x)
    mu = x.mean()
    s = x.std(ddof=0)
    return (n / ((n - 1) * (n - 2))) * np.sum(((x - mu) / s) ** 3) if s > 0 else 0

def _excess_kurtosis(x: np.ndarray) -> float:
    n = len(x)
    mu = x.mean()
    s = x.std(ddof=0)
    if s == 0:
        return 0
    k4 = (n * (n + 1) / ((n - 1) * (n - 2) * (n - 3))) * np.sum(((x - mu) / s) ** 4)
    return k4 - 3 * (n - 1)**2 / ((n - 2) * (n - 3))

# Minimum Track Record Length
def min_track_record_length(
    target_sr: float = 1.0,
    observed_sr: float = 1.5,
    skew: float = 0.0,
    kurt: float = 3.0,
    alpha: float = 0.05
) -> float:
    """
    Minimum number of observations needed to achieve statistical significance.
    Formula: T* = 1 + (1 - skew * SR + (kurt - 1) / 4 * SR^2) / (SR - SR_0)^2 * z_alpha^2
    """
    z_alpha = norm.ppf(1 - alpha)
    numer = (1 - skew * observed_sr + (kurt - 1) / 4 * observed_sr**2)
    denom = (observed_sr - target_sr) **2
    return 1 + numer / denom * z_alpha**2

