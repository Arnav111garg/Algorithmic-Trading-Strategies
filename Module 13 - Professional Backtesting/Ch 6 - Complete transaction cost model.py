import numpy as np
import pandas as pd
from dataclasses import dataclass

@dataclass
class CostModel:
    """Full transaction cost model for equity strategies."""
    commission_bps: float = 1.0     # per side, bps
    spread_bps: float = 5.0         # half-spread, bps (full round-trip = 2x)
    impact_bps: float = 10.0        # market impact, bps
    slippage_bps: float = 2.0       # timing / implementation shortfall, bps

    @property
    def total_one_way_bps(self) -> float:
        return self.commission_bps + self.spread_bps + self.impact_bps + self.slippage_bps

    @property
    def total_round_trip_bps(self) -> float:
        return 2 * self.total_one_way_bps

    def apply_to_returns(
        self,
        returns: pd.Series,
        weights: pd.DataFrame,
        prices: pd.DataFrame = None
    ) -> pd.Series:
        """
        Apply full cost model to strategy returns.
        Returns cost-adjusted net returns.
        """
        # Turnover: sum of absolute weight changes across all assets
        weight_change = weights.diff().abs().sum(axis=1)

        # Cost per unit of turnover (round-trip)
        cost_rate = self.total_round_trip_bps / 10000
        costs = weight_change * cost_rate
        return returns - costs

    def break_even_annual_turnover(self, gross_alpha_annual: float) -> float:
        """Max allowable annual turnover to remain profitable."""
        cost_per_rt = self.total_round_trip_bps / 10000
        return gross_alpha_annual / cost_per_rt

    def min_holding_days(self, gross_alpha_annual: float) -> float:
        """Minimum average holding period (trading days) to break even."""
        beto = self.break_even_annual_turnover(gross_alpha_annual)
        return 252 / beto if beto > 0 else np.inf

def cost_sensitivity_analysis(
    returns: pd.Series,
    weights: pd.DataFrame,
    cost_grid_bps: np.ndarray = None
) -> pd.DataFrame:
    """
    Stress-test strategy performance across a range of cost assumptions.
    Essential for institutional presentations to show IR decay vs costs.
    """
    if cost_grid_bps is None:
        cost_grid_bps = np.arange(0, 50, 2)  # 0 to 50 bps

    turnover_daily = weights.diff().abs().sum(axis=1).mean()
    ann_turnover = turnover_daily * 252
    gross_sr = returns.mean() / returns.std() * np.sqrt(252) if returns.std() > 0 else 0
    gross_ret = returns.mean() * 252

    results = []
    for c_bps in cost_grid_bps:
        cost_rate = c_bps / 10000
        daily_cost = turnover_daily * cost_rate / 2  # one-way daily turnover
        net_ret_d = returns - daily_cost

        std_net = net_ret_d.std()
        net_sr = net_ret_d.mean() / std_net * np.sqrt(252) if std_net > 0 else 0
        net_ret_a = net_ret_d.mean() * 252

        results.append({
            'cost_bps': c_bps,
            'net_sharpe': net_sr,
            'net_annual_ret': net_ret_a,
            'sr_degradation': gross_sr - net_sr,
        })

    df = pd.DataFrame(results)
    negative_returns = df[df['net_annual_ret'] <= 0]['cost_bps']
    breakeven = negative_returns.min() if not negative_returns.empty else np.nan
    df['breakeven_cost_bps'] = breakeven
    return df

