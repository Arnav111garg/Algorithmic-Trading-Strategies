import numpy as np
import pandas as pd
from typing import Optional

class SlippageModel:
    """Base class for slippage models."""
    def compute(self, price: float, quantity: float, direction: int, **kwargs) -> float:
        raise NotImplementedError

class FixedBpsSlippage(SlippageModel):
    """Fixed slippage: alpha bps per trade."""
    def __init__(self, bps: float = 5.0):
        self.bps = bps

    def compute(self, price: float, quantity: float, direction: int, **kwargs) -> float:
        return direction * price * self.bps / 10000

class VolatilityScaledSlippage(SlippageModel):
    """
    Volatility-scaled slippage.
    Slippage = kappa * sigma_intraday * price
    """
    def __init__(self, kappa: float = 0.25):
        self.kappa = kappa

    def compute(
        self,
        price: float,
        quantity: float,
        direction: int,
        high: Optional[float] = None,
        low: Optional[float] = None,
        **kwargs
    ) -> float:
        if high is not None and low is not None and price > 0:
            # Parkinson intraday vol estimator
            sigma_intraday = (high - low) / (4 * np.log(2) * price)
        else:
            sigma_intraday = 0.01  # default 1% fallback
        return direction * self.kappa * sigma_intraday * price

class SquareRootSlippage(SlippageModel):
    """
    Square-root market impact model.
    Slippage = sigma * sqrt(Q / ADV) * price
    """
    def __init__(self, impact_coeff: float = 1.0):
        self.impact_coeff = impact_coeff

    def compute(
        self,
        price: float,
        quantity: float,
        direction: int,
        sigma: float = 0.02,
        adv: Optional[float] = None,
        **kwargs
    ) -> float:
        if adv is None or adv <= 0:
            adv = quantity * 10  # fallback: order is 10% of ADV
        participation = quantity / adv
        impact = self.impact_coeff * sigma * np.sqrt(participation) * price
        return direction * impact

class OrderBookSlippage(SlippageModel):
    """
    Limit Order Book slippage: walks the book.
    book_levels: [(price, volume), ...] sorted by price from best
    """
    def compute(
        self,
        price: float,
        quantity: float,
        direction: int,
        book_levels: list = None,
        **kwargs
    ) -> float:
        if not book_levels:
            return FixedBpsSlippage(5.0).compute(price, quantity, direction)

        remaining = abs(quantity)
        total_cost = 0.0
        total_filled = 0.0

        for level_price, level_vol in book_levels:
            fill_size = min(remaining, level_vol)
            total_cost += fill_size * level_price
            total_filled += fill_size
            remaining -= fill_size
            if remaining <= 0:
                break

        if total_filled == 0:
            return 0.0

        vwap_fill = total_cost / total_filled
        return direction * (vwap_fill - price) * abs(quantity)

class HybridSlippageModel(SlippageModel):
    """
    Production-grade hybrid model combining:
    - Fixed bid-ask spread component
    - Volatility-scaled uncertainty
    - Square-root impact for large orders
    """
    def __init__(
        self,
        spread_bps: float = 5.0,
        vol_kappa: float = 0.15,
        impact_coeff: float = 0.5,
        large_order_pct: float = 0.01
    ):
        self.spread = FixedBpsSlippage(spread_bps)
        self.vol_model = VolatilityScaledSlippage(vol_kappa)
        self.sqrt_model = SquareRootSlippage(impact_coeff)
        self.large_pct = large_order_pct

    def compute(self, price: float, quantity: float, direction: int, **kwargs) -> float:
        adv = kwargs.get('adv', quantity * 100)
        participation = abs(quantity) / adv if adv > 0 else 0

        # Always pay the spread
        spread_cost = self.spread.compute(price, quantity, direction)

        # Vol component for timing uncertainty
        vol_cost = self.vol_model.compute(price, quantity, direction, **kwargs)

        # Square-root impact only if large order
        impact_cost = 0.0
        if participation > self.large_pct:
            impact_cost = self.sqrt_model.compute(price, quantity, direction, **kwargs)

        return spread_cost + vol_cost * 0.5 + impact_cost

# Backtester Integration
def apply_slippage_to_backtest(
    prices: pd.DataFrame,
    signals: pd.DataFrame,
    model: SlippageModel,
    adv: Optional[pd.DataFrame] = None
) -> pd.DataFrame:
    """
    Apply slippage model to backtest signal changes.
    Returns DataFrame of slippage costs per asset per day.
    """
    position_changes = signals.diff()  # Change in position (generates trades)
    slippage_costs = pd.DataFrame(0.0, index=prices.index, columns=prices.columns)

    for date in prices.index:
        for sym in prices.columns:
            delta = position_changes.loc[date, sym]
            if pd.isna(delta) or abs(delta) < 1e-10:
                continue

            p = prices.loc[date, sym]
            direction = int(np.sign(delta))
            q = abs(delta)

            kwargs = {}
            if adv is not None and sym in adv.columns:
                kwargs['adv'] = adv.loc[date, sym]

            slip = model.compute(p, q, direction, **kwargs)
            slippage_costs.loc[date, sym] = abs(slip)

    return slippage_costs

