import numpy as np
import pandas as pd
from scipy.optimize import minimize_scalar
import matplotlib.pyplot as plt

class AlmgrenChrissModel:
    """
    Almgren-Chriss (2001) optimal execution model.

    Parameters
    ----------
    sigma : daily volatility (fraction)
    eta : permanent impact coefficient ($/share per share/day)
    theta : temporary impact coefficient ($/share per share/day)
    """

    def __init__(self, sigma: float = 0.02, eta: float = 2.5e-7, theta: float = 5.0e-7):
        self.sigma = sigma
        self.eta = eta
        self.theta = theta

    def optimal_trajectory(
        self,
        X: float,
        T: float,
        lam: float = 1e-6,
        n_steps: int = 100
    ) -> pd.DataFrame:
        """
        Compute optimal liquidation trajectory.

        Parameters
        ----------
        X : initial position (shares)
        T : time horizon (trading days)
        lam : risk aversion parameter
        n_steps : number of time steps
        """
        kappa = np.sqrt(lam * self.sigma**2 / self.theta)
        times = np.linspace(0, T, n_steps + 1)

        # Optimal remaining position
        if kappa * T < 1e-8:  # near-TWAP limit
            x_t = X * (1 - times / T)
        else:
            x_t = X * np.sinh(kappa * (T - times)) / np.sinh(kappa * T)

        # Trading rate (shares per day)
        v_t = -np.gradient(x_t, times[1] - times[0])
        v_t = np.maximum(v_t, 0)  # only selling

        # Price impact trajectory
        perm_impact = self.eta * (X - x_t)
        temp_impact = self.theta * v_t

        return pd.DataFrame({
            'time': times,
            'shares_held': x_t,
            'trading_rate': v_t,
            'perm_impact': perm_impact,
            'temp_impact': temp_impact,
            'total_impact': perm_impact + temp_impact
        })

    def expected_cost(self, X: float, T: float, lam: float = 1e-6) -> dict:
        """Compute E[IS] and Var[IS] for optimal trajectory."""
        kappa = np.sqrt(lam * self.sigma**2 / self.theta)

        if kappa * T < 1e-8:
            # TWAP limit
            E_cost = self.eta * X**2 / 2 + self.theta * X**2 / T
            V_cost = self.sigma**2 * X**2 * T / 3
        else:
            tnh = np.tanh(kappa * T / 2)
            E_cost = (self.eta * X**2 / 2 + self.theta * kappa * X**2 / (2 * np.tanh(kappa * T)))
            V_cost = (self.sigma**2 * X**2 / (2 * kappa) * (np.tanh(kappa * T / 2))**(-1) * (kappa * T / np.sinh(kappa * T))**2)

        return {
            'expected_cost': E_cost,
            'variance_cost': V_cost,
            'kappa': kappa
        }

    def capacity_analysis(
        self,
        gross_alpha_bps: float,
        sigma: float,
        turnover_pct: float,
        adv_millions: float,
        sr_threshold: float = 0.5
    ) -> dict:
        """
        Determine strategy capacity.
        Finds max AUM where net Sharpe >= sr_threshold.
        """
        # Gross return per unit AUM
        gross_ret = gross_alpha_bps / 10000
        gross_sr = gross_ret * np.sqrt(252) / sigma

        def net_sr(aum_millions):
            # Trade size per rebalance
            trade_value = aum_millions * 1e6 * turnover_pct
            adv_value = adv_millions * 1e6
            pct_adv = trade_value / adv_value

            # Square-root impact (bps)
            # 50 is calibration constant
            impact_bps = 50 * sigma * np.sqrt(pct_adv)
            impact_ret = impact_bps / 10000 * turnover_pct * 252

            net_return = gross_ret - impact_ret
            net_sr_val = net_return * np.sqrt(252) / sigma
            return net_sr_val

        # Binary search for capacity
        aum_grid = np.logspace(1, 5, 200)  # $10M to $100B
        sr_vals = [net_sr(a) for a in aum_grid]

        capacity = aum_grid[0]  # default
        for aum, sr in zip(aum_grid, sr_vals):
            if sr >= sr_threshold:
                capacity = aum

        return {
            'strategy_capacity_millions': capacity,
            'gross_sharpe': gross_sr,
            'aum_grid': aum_grid,
            'net_sr_curve': sr_vals,
        }

# Power-Law Impact
def power_law_impact(
    quantity: float,
    adv: float,
    sigma: float,
    gamma: float = 0.5,
    delta: float = 0.5
) -> float:
    """
    Power-law market impact.
    impact_frac = gamma * sigma * (Q/ADV)^delta
    Returns impact as fraction of price.
    """
    pct_adv = abs(quantity) / adv if adv > 0 else 0
    return np.sign(quantity) * gamma * sigma * pct_adv**delta

