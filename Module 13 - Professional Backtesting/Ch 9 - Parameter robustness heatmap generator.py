import numpy as np
import pandas as pd
from itertools import product
import warnings

def parameter_robustness_analysis(
    backtest_fn,  # fn(data, param1, param2) -> {'sharpe_ratio': float, ...}
    data: pd.DataFrame,
    param1_range: np.ndarray,
    param2_range: np.ndarray,
    param1_name: str = 'param1',
    param2_name: str = 'param2',
    metric: str = 'sharpe_ratio',
    threshold: float = 0.5
) -> dict:
    """
    2D parameter sensitivity analysis.
    Generates robustness heatmap for two key parameters.
    """
    results = np.full((len(param1_range), len(param2_range)), np.nan)

    for i, p1 in enumerate(param1_range):
        for j, p2 in enumerate(param2_range):
            try:
                r = backtest_fn(data, p1, p2)
                results[i, j] = r.get(metric, np.nan)
            except Exception as e:
                warnings.warn(f"p1={p1}, p2={p2}: {e}")

    # Robustness metrics
    valid_mask = ~np.isnan(results)
    above_threshold = (results >= threshold) & valid_mask
    robustness_ratio = above_threshold.sum() / valid_mask.sum() if valid_mask.sum() > 0 else 0.0

    # Find optimal and neighbouring performance
    if valid_mask.any():
        flat_idx = np.nanargmax(results)
        opt_i, opt_j = np.unravel_index(flat_idx, results.shape)
        opt_p1 = param1_range[opt_i]
        opt_p2 = param2_range[opt_j]
        opt_metric = results[opt_i, opt_j]
    else:
        opt_p1, opt_p2, opt_metric = np.nan, np.nan, np.nan

    # Gradient magnitude measures peakiness (high = fragile)
    grad_x, grad_y = np.gradient(np.nan_to_num(results))
    grad_magnitude = np.sqrt(grad_x**2 + grad_y**2)
    avg_gradient = grad_magnitude[valid_mask].mean() if valid_mask.sum() > 0 else 0.0

    return {
        'heatmap': pd.DataFrame(
            results,
            index=param1_range,
            columns=param2_range
        ),
        'robustness_ratio': robustness_ratio,
        'optimal_params': {param1_name: opt_p1, param2_name: opt_p2},
        'optimal_metric': opt_metric,
        'mean_metric': np.nanmean(results) if valid_mask.any() else np.nan,
        'gradient_peakiness': avg_gradient,  # low = robust; high = fragile
        'pct_above_threshold': (above_threshold.sum() / valid_mask.sum() * 100) if valid_mask.sum() > 0 else 0.0
    }

