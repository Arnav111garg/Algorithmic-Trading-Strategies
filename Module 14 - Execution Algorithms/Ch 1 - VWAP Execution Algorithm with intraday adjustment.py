import numpy as np
import pandas as pd
from typing import List, Optional

class VWAPExecutionAlgorithm:
    """
    VWAP execution algorithm with adaptive volume forecast.

    Parameters
    ----------
    parent_size : int
        Total shares to execute (positive=buy, negative=sell)
    start_time : int
        Start interval index
    end_time : int
        End interval index
    hist_vol_profile : np.ndarray
        Historical average volume fractions (sums to 1)
    max_participation : float
        Maximum participation rate (default 0.25)
    min_participation : float
        Minimum participation rate (default 0.01)
    """

    def __init__(
        self,
        parent_size: int,
        start_time: int,
        end_time: int,
        hist_vol_profile: np.ndarray,
        max_participation: float = 0.25,
        min_participation: float = 0.01
    ):
        self.parent_size = parent_size
        self.direction = np.sign(parent_size)
        self.abs_size = abs(parent_size)
        self.start = start_time
        self.end = end_time
        self.N = end_time - start_time

        # Extract and normalize relevant portion of volume profile
        self.base_profile = hist_vol_profile[start_time:end_time].copy()
        self.base_profile /= self.base_profile.sum()  # normalize

        self.max_pov = max_participation
        self.min_pov = min_participation

        # State tracking
        self.filled = 0
        self.current_interval = start_time
        self.actual_volumes = []
        self.adjusted_profile = self.base_profile.copy()

        # Pre-compute initial schedule
        self.schedule = self._compute_schedule(self.base_profile)

    def _compute_schedule(self, profile: np.ndarray) -> np.ndarray:
        """Compute child order schedule from volume profile."""
        remaining = self.abs_size - self.filled
        schedule = profile * remaining
        return np.round(schedule).astype(int)

    def update_volume_observation(self, interval_idx: int, observed_volume: int) -> int:
        """
        Observe actual market volume for current interval.
        Returns the child order size for this interval.

        Parameters
        ----------
        interval_idx : int
            Current interval index (absolute)
        observed_volume : int
            Actual market volume observed in this interval
        """
        k = interval_idx - self.start  # relative index
        self.actual_volumes.append(observed_volume)

        # Update adjusted profile using intraday adjustment
        if k < self.N - 1:
            observed_frac = observed_volume / max(
                sum(self.actual_volumes) +
                self.base_profile[k+1:].sum() *
                (observed_volume / max(self.base_profile[k], 1e-10)),
                1
            )
            self._update_profile(k, observed_frac)

        # Compute child order with participation constraint
        child_order = self._get_child_order(k, observed_volume)
        self.filled += child_order
        self.current_interval = interval_idx + 1
        return child_order

    def _update_profile(self, completed_k: int, actual_frac: float) -> None:
        """Update remaining profile (intraday adjustment)."""
        # Rescale remaining intervals
        remaining_profile = self.base_profile[completed_k+1:].copy()
        remaining_base_sum = remaining_profile.sum()

        if remaining_base_sum > 1e-10:
            # Adjust remaining schedule for completion constraint
            remaining_needed = self.abs_size - self.filled
            total_remaining_volume_estimate = (
                remaining_profile.sum() *
                (sum(self.actual_volumes) /
                 self.base_profile[:completed_k+1].sum())
            )
            # Re-normalized adjustment
            self.adjusted_profile[completed_k+1:] = (                remaining_profile / remaining_base_sum
            )

    def _get_child_order(self, k: int, market_volume: int) -> int:
        """
        Compute child order with participation constraints.
        Apply min/max POV and ensure completion.
        """
        # Ideal VWAP share
        ideal = self.adjusted_profile[k] * (self.abs_size - self.filled)

        # Apply participation constraints
        min_qty = int(self.min_pov * market_volume)
        max_qty = int(self.max_pov * market_volume)

        # Must complete : accelerate if running behind
        intervals_left = self.N - k - 1
        remaining = self.abs_size - self.filled

        if intervals_left == 0:
            # Last interval : execute all remaining
            child = remaining
        else:
            # Clip to participation bounds
            child = int(np.clip(ideal, min_qty, max_qty))

        # Urgency adjustment: if behind schedule
        expected_remaining_vol = (
            self.adjusted_profile[k+1:].sum() *
            market_volume / max(self.adjusted_profile[k], 1e-10)
        )
        max_feasible_remaining = self.max_pov * expected_remaining_vol

        if remaining - child > max_feasible_remaining:
            # Accelerate: take more now
            child = min(remaining, max_qty)

        return min(child, remaining)  # Don't overfill

    def get_vwap_slippage(
        self,
        execution_prices: List[float],
        execution_qtys: List[int],
        market_vwap: float
    ) -> float:
        """
        Compute VWAP slippage in basis points.

        Returns
        -------
        float
            Slippage in bps (negative = favorable for buy)
        """
        if sum(execution_qtys) == 0:
            return 0.0

        exec_vwap = (
            sum(p * q for p, q in zip(execution_prices, execution_qtys)) /
            sum(execution_qtys)
        )
        # Slippage: buy order pays above market VWAP = positive slippage (bad)
        slippage_bps = (
            (exec_vwap - market_vwap) / market_vwap * 10000 *
            self.direction
        )
        return slippage_bps


