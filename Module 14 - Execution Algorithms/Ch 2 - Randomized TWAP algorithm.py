if __name__ == "__main__":
    algo = RandomizedTWAP(
        parent_size=30000,  # Buy 30 ,000 shares
        n_intervals=13,
        size_randomization=0.20
    )

    print("Scheduled sizes:", algo.scheduled_sizes)
    print(f"Sum check: {algo.scheduled_sizes.sum()} (target: {abs(algo.parent_size)})")

    # Simulate fills
    mid = 100.0
    sigma_per_interval = 0.002
    spread = 0.05

    fills = []
    midprices = []

    for k in range(algo.N):
        mid += sigma_per_interval * np.random.randn()
        midprices.append(mid)

        qty, otype, lim = algo.get_slice(k, spread, mid)

        # Simulate fill ( market order always fills ; limit sometimes misses )
        if otype == 'market':
            fill_price = mid + 0.5 * spread * np.sign(qty)
            fills.append((fill_price, qty))
        elif otype == 'marketable_limit' and lim is not None:
            fill_price = lim
            fills.append((fill_price, qty))

        print(f"Interval {k:2d}: Qty={qty:5d}, Type={otype:20s}, Mid={mid:.3f}, Fill={fill_price:.3f}")

    fill_prices = np.array([f[0] for f in fills])
    fill_sizes = np.array([f[1] for f in fills])

    stats = algo.compute_twap_slippage(
        fill_prices, fill_sizes, np.array(midprices)
    )
    print("\n--- TWAP Performance ---")
    for k, v in stats.items():
        print(f"  {k}: {v:.4f}" if isinstance(v, float) else f"  {k}: {v}")

