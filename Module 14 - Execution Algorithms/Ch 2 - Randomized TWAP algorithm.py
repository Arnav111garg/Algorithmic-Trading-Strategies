import numpy as np
from dataclasses import dataclass
from typing import Tuple, Optional

@dataclass
class TWAPOrder:
    """ Represents a TWAP child order with execution metadata ."""
    interval: int
    target_size: int
    actual_size: int
    scheduled_time: float
    price: float

class RandomizedTWAP:
    """
    Randomized TWAP execution algorithm .

    Reduces predictability through :
    1. Random sizing around equal slice target
    2. Random timing within each interval
    3. Random order type selection ( limit vs market )
    """

    def __init__(
        self,
        parent_size: int,
        n_intervals: int,
        interval_duration: float = 30.0,  # minutes
        size_randomization: float = 0.15,  # 15% std of slice
        use_limit_orders: bool = True,
        limit_order_aggression: float = 0.5  # 0= passive , 1= aggressive
    ):
        self.parent_size = parent_size
        self.N = n_intervals
        self.dt = interval_duration
        self.size_rand = size_randomization
        self.use_limits = use_limit_orders
        self.aggression = limit_order_aggression

        self.base_slice = abs(parent_size) / n_intervals
        self.direction = np.sign(parent_size)

        self._generate_schedule()

    def _generate_schedule(self) -> None:
        """Pre - generate randomized schedule ensuring sum = parent_size ."""
        np.random.seed(None)  # Don't fix seed in production !

        # Random sizes around equal slice
        noise = np.random.normal(0, self.size_rand * self.base_slice, self.N)
        sizes = self.base_slice + noise

        # Scale to ensure sum = total
        sizes = sizes * abs(self.parent_size) / sizes.sum()
        sizes = np.round(sizes).astype(int)

        # Fix rounding errors in last slice
        sizes[-1] = abs(self.parent_size) - sizes[:-1].sum()
        self.scheduled_sizes = sizes

        # Random timing within each interval ( uniformly distributed )
        self.scheduled_offsets = np.random.uniform(
            0.1 * self.dt, 0.9 * self.dt, self.N
        )

        print("TWAP Schedule Generated:")
        print(f"  Total: {abs(self.parent_size):,} shares over {self.N} intervals")
        print(f"  Avg slice: {self.base_slice:.0f} ± {self.size_rand * self.base_slice:.0f} shares\n")

    def get_slice(
        self,
        interval_idx: int,
        current_spread: float,
        current_mid: float
    ) -> Tuple[int, str, Optional[float]]:
        """
        Get child order for current interval .

        Returns
        -------
        Tuple [ quantity , order_type , limit_price ]
        quantity : shares to trade
        order_type : 'market' or 'limit'
        limit_price : limit price ( None for market orders )
        """
        qty = self.scheduled_sizes[interval_idx] * self.direction

        if not self.use_limits:
            return qty, 'market', None

        # Choose order type based on urgency and spread
        # Aggression =0: rest at midpoint ; Aggression =1: cross spread
        half_spread = current_spread / 2

        if self.direction > 0:  # Buy
            limit_price = (current_mid - half_spread + self.aggression * current_spread)
        else:  # Sell
            limit_price = (current_mid + half_spread - self.aggression * current_spread)

        order_type = 'marketable_limit'
        return qty, order_type, round(limit_price, 2)

    def compute_twap_slippage(
        self,
        fill_prices: np.ndarray,
        fill_sizes: np.ndarray,
        interval_midprices: np.ndarray
    ) -> dict:
        """
        Compute TWAP performance metrics .

        Returns
        -------
        dict with slippage statistics
        """
        # Our TWAP
        total_qty = np.abs(fill_sizes).sum()
        if total_qty == 0:
            exec_twap = 0.0
        else:
            exec_twap = np.sum(fill_prices * np.abs(fill_sizes)) / total_qty

        # Market TWAP ( simple average of interval midprices )
        market_twap = np.mean(interval_midprices)

        # Slippage in bps
        slippage_bps = ((exec_twap - market_twap) / market_twap * 10000 * self.direction)

        return {
            'exec_twap': exec_twap,
            'market_twap': market_twap,
            'slippage_bps': slippage_bps,
            'total_filled': total_qty,
            'completion_rate': total_qty / abs(self.parent_size)
        }


