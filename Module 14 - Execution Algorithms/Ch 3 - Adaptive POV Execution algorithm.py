import numpy as np
from typing import Optional

class POVAlgorithm:
    """
    Percentage-of-Volume (POV) execution algorithm.
    Adaptively adjusts participation rate based on urgency.

    Features:
    - Bounded participation rate [rho_min, rho_max]
    - Urgency acceleration near deadline
    - Spread-sensitive order aggression
    - Completion guarantee
    """

    def __init__(
        self,
        parent_size: int,
        target_rho: float = 0.15,
        rho_min: float = 0.05,
        rho_max: float = 0.30,
        total_intervals: int = 13,
        urgency_alpha: float = 1.0,
        liquidity_beta: float = 0.2,
        deadline_buffer: int = 2
    ):
        self.X = abs(parent_size)
        self.direction = np.sign(parent_size)
        self.rho_target = target_rho
        self.rho_min = rho_min
        self.rho_max = rho_max
        self.N = total_intervals
        self.alpha = urgency_alpha
        self.beta = liquidity_beta
        self.deadline_buffer = deadline_buffer

        # State
        self.filled = 0
        self.interval = 0
        self.avg_spread = None
        self.history = []

    def _update_avg_spread(self, current_spread: float) -> None:
        """Maintain EMA of spread for normalization."""
        if self.avg_spread is None:
            self.avg_spread = current_spread
        else:
            self.avg_spread = 0.9 * self.avg_spread + 0.1 * current_spread

    def _compute_urgency(self) -> float:
        """
        Urgency factor: 1.0 when on track, >1.0 when behind.
        Returns value in [1.0, 3.0]
        """
        if self.interval >= self.N - 1:
            return 3.0  # Max urgency in last interval

        remaining_shares = self.X - self.filled
        remaining_intervals = self.N - self.interval

        # Fraction remaining vs time remaining
        completion_fraction = self.filled / self.X
        time_fraction = self.interval / self.N

        if time_fraction < 1e-10:
            return 1.0

        # If completion_fraction < time_fraction, we're behind
        shortfall = time_fraction - completion_fraction
        urgency = 1.0 + self.alpha * max(0.0, shortfall / max(1.0 - time_fraction, 0.01))
        return min(urgency, 3.0)

    def _compute_adaptive_rho(self, current_spread: float) -> float:
        """Compute adaptive participation rate."""
        urgency = self._compute_urgency()

        # Liquidity adjustment
        spread_ratio = current_spread / max(self.avg_spread, 1e-6)
        liquidity_factor = 1.0 - self.beta * (spread_ratio - 1.0)
        liquidity_factor = max(0.5, min(1.5, liquidity_factor))

        rho = self.rho_target * urgency * liquidity_factor

        # Hard clamp
        return float(np.clip(rho, self.rho_min, self.rho_max))

    def on_volume_update(
        self,
        interval_idx: int,
        market_volume: int,
        current_spread: float
    ) -> dict:
        """
        Process market volume update and compute child order.

        Parameters
        ----------
        interval_idx : int
        market_volume : int
            Observed market volume in this interval
        current_spread : float
            Current bid-ask spread

        Returns
        -------
        dict with child order details
        """
        self.interval = interval_idx
        self._update_avg_spread(current_spread)

        remaining = self.X - self.filled
        if remaining <= 0:
            return {'qty': 0, 'rho': 0.0, 'status': 'complete'}

        # Compute adaptive rho
        rho = self._compute_adaptive_rho(current_spread)

        # Base POV quantity
        qty = rho * market_volume

        # Deadline constraint: must complete
        remaining_intervals = self.N - interval_idx - 1
        max_future = self.rho_max * market_volume * remaining_intervals

        if remaining - qty > max_future:
            # Accelerate: take more than rho would suggest
            qty = max(qty, remaining - max_future)
            qty = min(qty, self.rho_max * market_volume)

        # Final clamp to remaining
        qty = int(min(qty, remaining))
        qty = max(qty, 0)

        self.filled += qty

        result = {
            'qty': qty * self.direction,
            'abs_qty': qty,
            'rho_actual': qty / max(market_volume, 1),
            'rho_target': self.rho_target,
            'rho_adaptive': rho,
            'urgency': self._compute_urgency(),
            'completion_pct': self.filled / self.X * 100,
            'status': 'complete' if self.filled >= self.X else 'active',
        }

        self.history.append(result)
        return result

    def get_completion_stats(self) -> dict:
        """Summary statistics after completion."""
        rhos = [h['rho_actual'] for h in self.history]
        return {
            'total_intervals': len(self.history),
            'total_filled': self.filled,
            'avg_participation': np.mean(rhos),
            'std_participation': np.std(rhos),
            'min_participation': np.min(rhos),
            'max_participation': np.max(rhos),
            'completion_pct': self.filled / self.X * 100,
        }


