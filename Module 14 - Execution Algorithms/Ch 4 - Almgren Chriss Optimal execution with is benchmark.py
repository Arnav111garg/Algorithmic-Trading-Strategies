import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from scipy.optimize import minimize_scalar
import warnings
warnings.filterwarnings('ignore')

class AlmgrenChrissExecutor:
    """
    Almgren-Chriss (2001) optimal execution algorithm.
    Minimizes E[IS] + lambda * Var[IS].

    References
    ----------
    Almgren, R. & Chriss, N. (2001), "Optimal execution of portfolio transactions",
    Journal of Risk, 3(2), 5-39.
    """

    def __init__(
        self,
        parent_size: int,
        arrival_price: float,
        total_time: float,  # hours
        n_intervals: int,
        sigma: float,        # daily volatility (fraction)
        gamma: float,        # permanent impact coeff
        eta: float,          # temporary impact coeff
        adv: float,          # average daily volume (shares)
        risk_aversion: float = 1e-6
    ):
        self.X = abs(parent_size)
        self.direction = int(np.sign(parent_size))
        self.S0 = arrival_price
        self.T = total_time
        self.N = n_intervals
        self.dt = total_time / n_intervals

        # Convert sigma from daily to per-interval
        trading_hours_per_day = 6.5
        self.sigma = sigma * np.sqrt(self.dt / trading_hours_per_day)

        self.gamma = gamma
        self.eta = eta
        self.adv = adv
        self.lam = risk_aversion

        # Compute urgency parameter kappa
        self.kappa = np.sqrt(risk_aversion * (sigma ** 2) * adv / eta)

        # Precompute optimal trajectory
        self.trajectory = self._compute_trajectory()
        self.schedule = np.diff(-self.trajectory, prepend=self.X)

    def _compute_trajectory(self) -> np.ndarray:
        """
        Compute optimal inventory trajectory x_k^* using AC formula (Eq 17.8).
        Returns array of length N+1 (including initial position X).
        """
        times = np.linspace(0, self.T, self.N + 1)

        # AC optimal trajectory
        traj = self.X * np.sinh(self.kappa * (self.T - times)) / np.sinh(self.kappa * self.T)

        # Edge case: kappa -> 0 (TWAP)
        if self.kappa < 1e-6:
            traj = self.X * (1 - times / self.T)

        return np.round(np.maximum(traj, 0)).astype(int)

    def get_child_order(self, interval_idx: int) -> int:
        """Get optimal child order for interval k."""
        if interval_idx >= self.N:
            return 0
        return int(self.schedule[interval_idx + 1]) * self.direction

    def compute_is_realized(
        self,
        fill_prices: np.ndarray,
        fill_sizes: np.ndarray,
        final_midprice: float
    ) -> dict:
        """
        Compute realized Implementation Shortfall.
        IS = sum(n_k * (P_k - S_0)) + (X - sum(n_k)) * (S_T - S_0)
        """
        total_filled = np.sum(np.abs(fill_sizes))
        unfilled = self.X - total_filled

        # Explicit cost (market impact)
        explicit_cost = np.sum(fill_sizes * (fill_prices - self.S0) * self.direction)

        # Opportunity cost (unfilled shares * price appreciation)
        opportunity_cost = unfilled * (final_midprice - self.S0) * self.direction

        total_is = explicit_cost + opportunity_cost

        # In basis points
        is_bps = total_is / (self.X * self.S0) * 10000

        # Decompose
        impact_bps = explicit_cost / (self.X * self.S0) * 10000
        opp_bps = opportunity_cost / (self.X * self.S0) * 10000

        return {
            'IS_dollars': total_is,
            'IS_bps': is_bps,
            'explicit_cost_bps': impact_bps,
            'opportunity_cost_bps': opp_bps,
            'total_filled': total_filled,
            'completion_rate': total_filled / self.X,
        }

    def plot_trajectory(self) -> None:
        """Visualize optimal trajectory and compare with TWAP."""
        fig, axes = plt.subplots(1, 2, figsize=(13, 4))

        times = np.linspace(0, self.T, self.N + 1)

        # Trajectory
        ax1 = axes[0]
        ax1.plot(
            times,
            self.trajectory / self.X,
            color='#1a2864',
            lw=2,
            label=fr'AC Optimal ($\kappa$ ={self.kappa:.3f})'
        )
        ax1.plot(times, 1 - times / self.T, color='gray', lw=1.5, ls='--', label='TWAP')
        ax1.set_xlabel('Time (hours)')
        ax1.set_ylabel('Fraction of Position Remaining')
        ax1.set_title('Optimal Execution Trajectory')
        ax1.legend()
        ax1.grid(True, alpha=0.3)

        # Trading schedule
        ax2 = axes[1]
        bars = np.diff(-self.trajectory, prepend=self.X)[1:]
        ax2.bar(
            range(len(bars)),
            bars / self.X * 100,
            color='#1a2864',
            alpha=0.7,
            label='AC Schedule'
        )
        uniform = np.ones(self.N) * (100 / self.N)
        ax2.plot(range(self.N), uniform, color='gray', ls='--', lw=2, label='TWAP')
        ax2.set_xlabel('Interval')
        ax2.set_ylabel('% of Total Order')
        ax2.set_title('Child Order Schedule')
        ax2.legend()
        ax2.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig('ac_trajectory.png', dpi=120, bbox_inches='tight')
        plt.close()

    @classmethod
    def calibrate_kappa(
        cls,
        historical_IS: np.ndarray,
        historical_variance: np.ndarray,
        target_percentile: float = 0.5
    ) -> float:
        """
        Calibrate risk aversion lambda from historical IS distribution.
        Chooses lambda such that expected IS is at target_percentile.
        """
        target_IS = np.percentile(historical_IS, target_percentile * 100)

        def objective(log_lam):
            lam = np.exp(log_lam)
            # Simplified: kappa proportional to sqrt(lambda)
            kappa = np.sqrt(lam)
            # Expected IS ~ eta * kappa * coth(kappa * T) [simplified]
            expected_IS = kappa * np.cosh(kappa) / np.sinh(kappa)
            return (expected_IS - target_IS) ** 2

        result = minimize_scalar(objective, bounds=(-20, 5), method='bounded')
        return np.exp(result.x)


# ---- Run Example ----
if __name__ == "__main__":
    print("=== Almgren-Chriss Optimal Execution ===\n")
    executor = AlmgrenChrissExecutor(
        parent_size=100000,    # Buy 100K shares
        arrival_price=50.00,
        total_time=6.5,         # Full trading day (hours)
        n_intervals=13,
        sigma=0.015,            # 1.5% daily vol
        gamma=2e-7,             # Permanent impact
        eta=5e-7,              # Temporary impact
        adv=2000000,            # 2M ADV
        risk_aversion=1e-6
    )

    print(f"Urgency kappa = {executor.kappa:.6f}")
    print(f"Trajectory (first 5 of {executor.N+1} points):")
    print(f"  {executor.trajectory[:6]}")
    print(f"\nChild order schedule (shares per interval):")
    # The first element in executor.schedule is a placeholder for prepend; actual trading sizes are indices 1 to N
    trading_schedule = executor.schedule[1:]
    print(f"  {trading_schedule}")
    print(f"  Total: {trading_schedule.sum():,}")

    # Simulate execution with random price path
    np.random.seed(42)
    prices = [50.0]
    for _ in range(executor.N):
        prices.append(prices[-1] + executor.sigma * 50 * np.random.randn())
    prices = np.array(prices[1:])

    fill_prices = prices * (1 + 5e-5 * trading_schedule / 1000)

    is_results = executor.compute_is_realized(
        fill_prices=fill_prices,
        fill_sizes=trading_schedule,
        final_midprice=prices[-1]
    )

    print("\n--- IS Results ---")
    for k, v in is_results.items():
        if isinstance(v, float):
            print(f"  {k}: {v:.4f}")
        else:
            print(f"  {k}: {v:,}")

    executor.plot_trajectory()
    print("\nTrajectory plot saved to ac_trajectory.png")

