import numpy as np
from dataclasses import dataclass
from typing import List, Dict, Optional
from enum import Enum

class VenueType(Enum):
    LIT_EXCHANGE = "lit"
    DARK_POOL = "dark"
    ATS = "ats"
    INTERNALIZER = "internal"

@dataclass
class VenueQuote:
    venue_id: str
    venue_type: VenueType
    bid: float
    ask: float
    bid_size: int
    ask_size: int
    taker_fee: float  # per share (negative = rebate)
    maker_rebate: float  # per share
    latency_us: float  # microseconds
    fill_prob_dark: float = 1.0  # Only for dark pools

class SmartOrderRouter:
    """
    Smart Order Router (SOR) for multi-venue equity routing.

    Features:
    - Greedy NBBO-first routing (Reg NMS compliant)
    - Maker-taker fee optimization
    - Dark pool integration with fill probability model
    - Latency-adjusted effective prices
    - Information leakage scoring
    """

    def __init__(
        self,
        venues: List[VenueQuote],
        info_leakage_penalty: float = 0.002,  # 0.2 bps per dark unit
        latency_drift_alpha: float = 1e-5
    ):
        self.venues = venues
        self.info_penalty = info_leakage_penalty
        self.lat_alpha = latency_drift_alpha

        # Separate lit and dark venues
        self.lit_venues = [v for v in venues if v.venue_type != VenueType.DARK_POOL]
        self.dark_venues = [v for v in venues if v.venue_type == VenueType.DARK_POOL]

        # Compute NBBO
        self.nbbo_bid = max(v.bid for v in self.lit_venues)
        self.nbbo_ask = min(v.ask for v in self.lit_venues)
        self.nbbo_mid = (self.nbbo_bid + self.nbbo_ask) / 2

    def _effective_ask(self, venue: VenueQuote, price_drift_est: float = 0.0) -> float:
        """Effective ask price including fees and latency impact."""
        base = venue.ask if venue.venue_type != VenueType.DARK_POOL else self.nbbo_mid
        fee = venue.taker_fee
        latency_adj = self.lat_alpha * venue.latency_us * price_drift_est
        return base + fee + latency_adj

    def _dark_fill_prob(self, venue: VenueQuote, size: int) -> float:
        """Model dark pool fill probability."""
        # Exponential model: larger orders have lower fill prob
        base_fill = venue.fill_prob_dark
        size_penalty = np.exp(-size / 5000)  # Scale factor
        return base_fill * size_penalty

    def route(
        self,
        side: str,  # 'buy' or 'sell'
        total_size: int,
        price_drift_estimate: float = 0.0,
        prefer_dark: bool = True,
        dark_size_limit: float = 0.3
    ) -> Dict:
        """
        Execute SOR routing logic.

        Parameters
        ----------
        side : str
            'buy' or 'sell'
        total_size : int
            Total shares to route
        price_drift_estimate : float
            Short-term price drift (shares/sec) for latency adjustment
        prefer_dark : bool
            Try dark pools first before lit venues
        dark_size_limit : float
            Max fraction of order to send to dark pools

        Returns
        -------
        dict with routing decisions
        """
        routes = {}
        remaining = total_size
        total_cost = 0.0

        # Step 1: Dark pool routing (if preferred)
        dark_allocated = 0
        max_dark = int(total_size * dark_size_limit)

        if prefer_dark and side == 'buy':
            for dv in sorted(self.dark_venues, key=lambda v: v.taker_fee):
                if remaining <= 0 or dark_allocated >= max_dark:
                    break

                dark_qty = min(remaining, max_dark - dark_allocated, dv.bid_size)
                fill_p = self._dark_fill_prob(dv, dark_qty)

                # Expected cost: fill_prob * (mid + fee) + (1 - fill_p) * lit_backup
                lit_backup_cost = self.nbbo_ask + 0.003  # avg lit taker
                dark_cost = (fill_p * (self.nbbo_mid + dv.taker_fee) + (1 - fill_p) * lit_backup_cost)

                # Check if dark is cheaper than best lit
                best_lit_venue = min(self.lit_venues, key=lambda v: self._effective_ask(v, price_drift_estimate))
                best_lit_cost = self._effective_ask(best_lit_venue, price_drift_estimate)

                # Info leakage cost
                info_cost = self.info_penalty * dark_qty / total_size

                if dark_cost + info_cost < best_lit_cost:
                    routes[dv.venue_id] = {
                        'qty': dark_qty,
                        'type': 'dark_IOC',
                        'expected_price': self.nbbo_mid + dv.taker_fee,
                        'fill_prob': fill_p,
                        'expected_cost_bps': (dark_cost - self.nbbo_mid) / self.nbbo_mid * 10000,
                    }
                    dark_allocated += dark_qty
                    # Note: dark IOC - don't subtract remaining until confirmed
                    # (handled by fill confirmation callback)

        # Step 2: Lit venue routing (Reg NMS compliant)
        # Sort lit venues by effective ask price
        if side == 'buy':
            sorted_venues = sorted(
                self.lit_venues,
                key=lambda v: self._effective_ask(v, price_drift_estimate)
            )
        else:
            sorted_venues = sorted(
                self.lit_venues,
                key=lambda v: -(v.bid - v.taker_fee - self.lat_alpha * v.latency_us * price_drift_estimate)
            )

        lit_remaining = remaining - dark_allocated  # Conservative: assume dark misses

        for venue in sorted_venues:
            if lit_remaining <= 0:
                break

            # Reg NMS: must protect NBBO
            if side == 'buy' and venue.ask > self.nbbo_ask + 0.001:
                continue  # Trade-through violation if we took here

            avail = venue.ask_size if side == 'buy' else venue.bid_size
            qty = min(lit_remaining, avail)

            if qty > 0:
                eff_price = self._effective_ask(venue, price_drift_estimate)
                routes[venue.venue_id] = {
                    'qty': qty,
                    'type': 'limit_IOC',
                    'expected_price': eff_price,
                    'fill_prob': 1.0,  # lit markets: immediate fill
                    'expected_cost_bps': (eff_price - self.nbbo_mid) / self.nbbo_mid * 10000,
                }
                total_cost += qty * eff_price
                lit_remaining -= qty

        # Summary
        routed_qty = sum(r['qty'] for r in routes.values())
        if routed_qty > 0:
            avg_fill = sum(r['qty'] * r['expected_price'] for r in routes.values()) / routed_qty
        else:
            avg_fill = self.nbbo_ask if side == 'buy' else self.nbbo_bid

        return {
            'routes': routes,
            'total_routed': routed_qty,
            'unfilled': total_size - min(routed_qty, total_size),
            'expected_avg_price': avg_fill,
            'expected_slippage_bps': (avg_fill - self.nbbo_mid) / self.nbbo_mid * 10000,
            'nbbo_bid': self.nbbo_bid,
            'nbbo_ask': self.nbbo_ask,
            'nbbo_mid': self.nbbo_mid,
        }

