import numpy as np
import pandas as pd
from scipy import stats
from typing import List, Optional
from dataclasses import dataclass

@dataclass
class ExecutionRecord:
    """Single trade execution record."""
    trade_id: str
    symbol: str
    side: int  # +1 buy, -1 sell
    parent_size: int
    filled_size: int
    avg_fill_price: float
    arrival_price: float  # midprice at decision time
    market_vwap: float  # market VWAP over exec window
    market_twap: float  # market TWAP over exec window
    close_price: float
    spread_at_arrival: float  # bid-ask spread at t0
    volatility: float  # realized vol during execution
    adv: float  # ADV (shares)
    exec_duration: float  # hours
    algo_type: str  # VWAP, TWAP, IS, etc.
    pre_trade_estimate: float  # pre-trade cost estimate (bps)

class TCAEngine:
    """
    Comprehensive Transaction Cost Analysis Engine.

    Computes:
    - Multiple benchmark comparisons
    - IS decomposition
    - Execution quality scoring
    - Statistical significance testing
    - Cross-sectional analysis
    """

    def __init__(self):
        self.records: List[ExecutionRecord] = []

    def add_execution(self, record: ExecutionRecord) -> None:
        self.records.append(record)

    def compute_single_tca(self, r: ExecutionRecord) -> dict:
        """Full TCA for a single execution record."""

        direction = r.side  # +1 buy, -1 sell

        # Execution quality vs benchmarks (in bps)
        # Convention: positive = bad (paid more than benchmark for buy)
        def to_bps(diff):
            return diff / r.arrival_price * 10000

        # 1. Arrival Price (IS) benchmark
        is_bps = to_bps(direction * (r.avg_fill_price - r.arrival_price))

        # 2. VWAP benchmark
        vwap_slippage_bps = to_bps(direction * (r.avg_fill_price - r.market_vwap))

        # 3. TWAP benchmark
        twap_slippage_bps = to_bps(direction * (r.avg_fill_price - r.market_twap))

        # 4. Close benchmark
        close_slippage_bps = to_bps(direction * (r.avg_fill_price - r.close_price))

        # IS Decomposition
        # Spread cost: half spread at arrival
        spread_cost_bps = to_bps(r.spread_at_arrival / 2)

        # Timing cost: midprice movement during execution
        timing_cost_bps = to_bps(direction * (r.market_vwap - r.arrival_price))

        # Market impact: our slippage vs market VWAP
        impact_cost_bps = to_bps(direction * (r.avg_fill_price - r.market_vwap))

        # Opportunity cost: from unfilled shares (simplified)
        unfilled_frac = (r.parent_size - r.filled_size) / r.parent_size
        opp_cost_bps = to_bps(direction * (r.close_price - r.arrival_price)) * unfilled_frac

        # Total IS check
        is_check = spread_cost_bps + timing_cost_bps + impact_cost_bps + opp_cost_bps

        # Participation rate
        participation = r.filled_size / (r.adv * r.exec_duration / 6.5)

        # Normalized order size
        normalized_size = r.parent_size / r.adv

        # Execution quality score (0-100, higher = better)
        # Based on IS vs pre-trade estimate
        if r.pre_trade_estimate > 0:
            efficiency = max(0, min(100, (1 - is_bps / r.pre_trade_estimate) * 100))
        else:
            efficiency = 50.0

        return {
            'trade_id': r.trade_id,
            'symbol': r.symbol,
            'algo': r.algo_type,
            'parent_size': r.parent_size,
            'filled_size': r.filled_size,
            'completion_rate': r.filled_size / r.parent_size,
            'participation_rate': participation,
            'normalized_size': normalized_size,
            # Benchmark comparisons (bps)
            'is_bps': is_bps,
            'vwap_slippage_bps': vwap_slippage_bps,
            'twap_slippage_bps': twap_slippage_bps,
            'close_slippage_bps': close_slippage_bps,
            # IS Decomposition (bps)
            'spread_cost_bps': spread_cost_bps,
            'timing_cost_bps': timing_cost_bps,
            'impact_cost_bps': impact_cost_bps,
            'opp_cost_bps': opp_cost_bps,
            'is_check_bps': is_check,
            # Model diagnostics
            'pre_trade_estimate_bps': r.pre_trade_estimate,
            'prediction_error_bps': is_bps - r.pre_trade_estimate,
            'execution_efficiency': efficiency,
        }

    def run_portfolio_tca(self) -> pd.DataFrame:
        """Run TCA on all recorded executions."""
        results = [self.compute_single_tca(r) for r in self.records]
        df = pd.DataFrame(results)
        return df

    def generate_tca_report(self, df: pd.DataFrame) -> str:
        """Generate summary TCA report."""
        report = []
        report.append("=" * 60)
        report.append(" TRANSACTION COST ANALYSIS REPORT ")
        report.append("=" * 60)
        report.append(f"\nTotal Trades Analyzed : {len(df)}")
        report.append(f"Total Volume : {df['parent_size'].sum():,.0f} shares")

        report.append("\n--- Benchmark Performance (avg bps) ---")
        for col, label in [
            ('is_bps', 'Implementation Shortfall'),
            ('vwap_slippage_bps', 'VWAP Slippage'),
            ('twap_slippage_bps', 'TWAP Slippage'),
        ]:
            mean = df[col].mean()
            sem = df[col].sem()
            t_stat, p_val = stats.ttest_1samp(df[col].dropna(), 0)
            sig = "***" if p_val < 0.01 else "**" if p_val < 0.05 else "*" if p_val < 0.10 else ""
            report.append(f"  {label:<30s}: {mean:+7.2f} bps ({sem:.2f}, p={p_val:.3f} {sig})")

        report.append("\n--- IS Decomposition ---")
        for col, label in [
            ('spread_cost_bps', 'Spread Cost'),
            ('timing_cost_bps', 'Timing Cost'),
            ('impact_cost_bps', 'Market Impact'),
            ('opp_cost_bps', 'Opportunity Cost'),
        ]:
            report.append(f"  {label:<25s}: {df[col].mean():+7.2f} bps")

        report.append("\n--- Model Calibration ---")
        r_corr = df['is_bps'].corr(df['pre_trade_estimate_bps'])
        report.append(f"  Prediction IC (corr): {r_corr:.4f}")
        report.append(f"  Avg Prediction Error : {df['prediction_error_bps'].mean():+.2f} bps")
        report.append(f"  Std Prediction Error : {df['prediction_error_bps'].std():.2f} bps")

        report.append("\n--- Algo Performance ---")
        for algo in df['algo'].unique():
            sub = df[df['algo'] == algo]
            report.append(f"  {algo:<12s}: IS={sub['is_bps'].mean():+6.2f} bps (n={len(sub)}, eff={sub['execution_efficiency'].mean():.1f}%)")

        return "\n".join(report)

    def analyze_cross_sectional(self, df: pd.DataFrame) -> dict:
        """
        Regression analysis: what drives IS?
        IS ~ beta * sqrt(Q/ADV) * sigma
        """
        X = df['normalized_size'].apply(np.sqrt) * df.get('volatility', 1.0)
        y = df['is_bps']
        mask = ~(X.isna() | y.isna())

        if mask.sum() > 5:
            slope, intercept, r, p, se = stats.linregress(X[mask], y[mask])
            return {
                'intercept': intercept,
                'kappa_estimated': slope,
                'r_squared': r ** 2,
                'p_value': p,
                'n_obs': mask.sum(),
            }
        return {}

