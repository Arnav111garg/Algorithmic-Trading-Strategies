import numpy as np
import pandas as pd
from collections import deque
from dataclasses import dataclass, field
from typing import Deque, Dict, List, Callable
from enum import Enum
import time

class OrderStatus(Enum):
    NEW = "NEW"
    PENDING = "PENDING"
    PARTIAL = "PARTIAL"
    FILLED = "FILLED"
    CANCELLED = "CANCELLED"
    REJECTED = "REJECTED"

@dataclass
class Order:
    order_id: str
    symbol: str
    side: int  # +1 buy, -1 sell
    parent_qty: int
    filled_qty: int = 0
    avg_fill_price: float = 0.0
    status: OrderStatus = OrderStatus.NEW
    arrival_price: float = 0.0
    fills: List = field(default_factory=list)
    schedule: np.ndarray = field(default_factory=lambda: np.array([]))
    schedule_idx: int = 0
    interval_start_time: float = 0.0

    @property
    def remaining(self) -> int:
        return self.parent_qty - self.filled_qty

    @property
    def is_complete(self) -> bool:
        return self.remaining <= 0

class ExecutionMonitor:
    """
    Real-time execution monitoring and microstructure analysis.

    Monitors:
    - Order progress vs schedule
    - OFI and VPIN
    - Pace alerts
    - Real-time slippage attribution
    """

    def __init__(self, symbol: str, ofi_window: int = 100, vpin_bucket_size: float = 0.01):
        self.symbol = symbol
        self.ofi_window = ofi_window
        self.vpin_bucket_size = vpin_bucket_size

        # Real-time state
        self.orders: Dict[str, Order] = {}
        self.market_vwap_num = 0.0
        self.market_vwap_den = 0.0

        # OFI state
        self.lob_history: Deque = deque(maxlen=ofi_window)
        self.ofi_values: Deque = deque(maxlen=100)

        # VPIN state
        self.current_bucket_buy = 0.0
        self.current_bucket_sell = 0.0
        self.bucket_threshold = 0.0  # Set when ADV is known
        self.vpin_values: Deque = deque(maxlen=50)

        # Alerts
        self.alerts: List[dict] = []
        self.alert_callbacks: List[Callable] = []

    def register_order(self, order: Order, algo_schedule: np.ndarray):
        """Register a new parent order with its algorithm schedule."""
        self.orders[order.order_id] = order
        order.schedule = algo_schedule
        order.schedule_idx = 0
        order.interval_start_time = time.time()

    def on_lob_update(self, bid: float, ask: float, bid_size: int, ask_size: int, timestamp: float) -> dict:
        """
        Process a LOB update.
        Compute OFI and update VWAP.

        Returns current microstructure state.
        """
        if len(self.lob_history) > 0:
            prev = self.lob_history[-1]

            # OFI computation (Cont, Kukanov, Stoikov 2014)
            ofi = 0

            # Bid side
            if bid > prev['bid']:
                ofi += bid_size
            elif bid == prev['bid']:
                ofi += (bid_size - prev['bid_size'])

            # Ask side
            if ask < prev['ask']:
                ofi += ask_size
            elif ask == prev['ask']:
                ofi -= (ask_size - prev['ask_size'])

            self.ofi_values.append(ofi)

        self.lob_history.append({
            'bid': bid,
            'ask': ask,
            'bid_size': bid_size,
            'ask_size': ask_size,
            'mid': (bid + ask) / 2,
            'spread': ask - bid,
            'ts': timestamp,
        })
        mid = (bid + ask) / 2
        ofi_ma = np.mean(list(self.ofi_values)) if self.ofi_values else 0

        return {
            'mid': mid,
            'spread': ask - bid,
            'ofi': ofi_ma,
            'ofi_signal': 'bullish' if ofi_ma > 50 else 'bearish' if ofi_ma < -50 else 'neutral',
        }

    def on_trade(self, price: float, volume: int, is_buy_initiated: bool, timestamp: float):
        """Process a market trade."""
        # Update market VWAP
        self.market_vwap_num += price * volume
        self.market_vwap_den += volume

        # VPIN bucket update
        if is_buy_initiated:
            self.current_bucket_buy += volume
        else:
            self.current_bucket_sell += volume

        # Check bucket completion
        if (self.current_bucket_buy + self.current_bucket_sell >= self.bucket_threshold and self.bucket_threshold > 0):
            total = self.current_bucket_buy + self.current_bucket_sell
            vpin = abs(self.current_bucket_buy - self.current_bucket_sell) / total
            self.vpin_values.append(vpin)

            # Reset bucket
            self.current_bucket_buy = 0
            self.current_bucket_sell = 0

            # Alert on high VPIN
            if vpin > 0.6:
                self._raise_alert('HIGH_VPIN', f'VPIN={vpin:.3f} high probability of informed trading')

    def on_fill(self, order_id: str, fill_price: float, fill_qty: int, timestamp: float):
        """Record an execution fill."""
        if order_id not in self.orders:
            return

        order = self.orders[order_id]
        order.fills.append({'price': fill_price, 'qty': fill_qty, 'ts': timestamp})

        # Update average fill price
        total_value = (order.avg_fill_price * order.filled_qty + fill_price * fill_qty)
        order.filled_qty += fill_qty
        order.avg_fill_price = total_value / order.filled_qty if order.filled_qty > 0 else 0

        # Update status
        if order.is_complete:
            order.status = OrderStatus.FILLED
        elif order.filled_qty > 0:
            order.status = OrderStatus.PARTIAL

        # Compute real-time IS
        is_bps = (order.side * (order.avg_fill_price - order.arrival_price) / order.arrival_price * 10000)

        return {
            'order_id': order_id,
            'filled_pct': order.filled_qty / order.parent_qty * 100,
            'is_bps': is_bps,
            'market_vwap': (self.market_vwap_num / self.market_vwap_den if self.market_vwap_den > 0 else fill_price),
        }

    def check_pace(self, order_id: str, elapsed_fraction: float) -> dict:
        """
        Check if order is on pace with its schedule.

        Parameters
        ----------
        elapsed_fraction : float
            Fraction of total time elapsed [0, 1]
        """
        if order_id not in self.orders:
            return {}

        order = self.orders[order_id]
        filled_frac = order.filled_qty / order.parent_qty

        # Expected completion based on schedule
        if hasattr(order, 'schedule') and len(order.schedule) > 0:
            schedule_cumsum = np.cumsum(order.schedule) / order.parent_qty
            expected_frac = np.interp(
                elapsed_fraction,
                np.linspace(0, 1, len(order.schedule) + 1),
                np.concatenate([[0], schedule_cumsum])
            )
        else:
            expected_frac = elapsed_fraction  # TWAP baseline

        pace_ratio = filled_frac / max(expected_frac, 0.01)

        # Alert conditions
        if pace_ratio < 0.5 and elapsed_fraction > 0.3:
            self._raise_alert(
                'BEHIND_PACE',
                f'Order {order_id}: {pace_ratio:.1%} of expected pace. Risk of incomplete execution.'
            )

        return {
            'filled_pct': filled_frac * 100,
            'expected_pct': expected_frac * 100,
            'pace_ratio': pace_ratio,
            'pace_status': ('ON_PACE' if 0.8 <= pace_ratio <= 1.2 else 'AHEAD' if pace_ratio > 1.2 else 'BEHIND'),
            'time_remaining_frac': 1 - elapsed_fraction,
            'shares_remaining': order.remaining,
        }

    def _raise_alert(self, alert_type: str, message: str):
        """Record and broadcast an alert."""
        alert = {
            'type': alert_type,
            'message': message,
            'timestamp': time.time(),
        }
        self.alerts.append(alert)
        for cb in self.alert_callbacks:
            cb(alert)
        print(f"[ALERT] {alert_type}: {message}")

    def get_snapshot(self, order_id: str) -> dict:
        """Full execution snapshot for monitoring dashboard."""
        order = self.orders.get(order_id, None)
        if not order:
            return {}

        market_vwap = (self.market_vwap_num / self.market_vwap_den if self.market_vwap_den > 0 else 0)
        lob = self.lob_history[-1] if self.lob_history else {}
        vpin_avg = np.mean(list(self.vpin_values)) if self.vpin_values else 0
        ofi_avg = np.mean(list(self.ofi_values)) if self.ofi_values else 0

        return {
            'order_id': order_id,
            'status': order.status.value,
            'filled_qty': order.filled_qty,
            'remaining_qty': order.remaining,
            'avg_fill': order.avg_fill_price,
            'arrival_price': order.arrival_price,
            'is_bps': (order.side * (order.avg_fill_price - order.arrival_price) / order.arrival_price * 10000) if order.filled_qty > 0 else 0,
            'vwap_slippage_bps': (order.side * (order.avg_fill_price - market_vwap) / order.arrival_price * 10000) if market_vwap > 0 else 0,
            'current_mid': lob.get('mid', 0),
            'current_spread': lob.get('spread', 0),
            'ofi': ofi_avg,
            'vpin': vpin_avg,
            'market_vwap': market_vwap,
            'n_alerts': len(self.alerts),
        }

