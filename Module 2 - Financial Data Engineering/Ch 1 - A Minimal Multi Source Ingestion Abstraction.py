from abc import ABC, abstractmethod
from dataclasses import dataclass
from datetime import datetime
import pandas as pd

@dataclass
class Bar:
    symbol: str
    t_event: datetime  # when the bar's period ended (economic time)
    t_know: datetime   # when this bar became available to us (knowledge time)
    open: float
    high: float
    low: float
    close: float
    volume: float
    source: str

class DataSourceAdapter(ABC):
    """Every vendor adapter must normalize into the Bar schema.
    This is the seam that lets us swap Polygon-> Algoseek-> internal
    feed without touching a single downstream model."""

    @abstractmethod
    def fetch_bars(self, symbol: str, start: datetime, end: datetime, freq: str = "1min") -> list[Bar]:
        ...

class PolygonAdapter(DataSourceAdapter):
    def __init__(self, client):
        self.client = client

    def fetch_bars(self, symbol: str, start: datetime, end: datetime, freq: str = "1min") -> list[Bar]:
        raw = self.client.get_aggs(symbol, 1, "minute", start, end)
        bars = []
        for r in raw:
            t_event = datetime.fromtimestamp(r.timestamp / 1000)
            bars.append(Bar(
                symbol=symbol,
                t_event=t_event,
                # Polygon delivers with ~minimal delay on paid tiers;
                # ALWAYS verify vendor's stated latency in your knowledge-time model
                t_know=t_event,
                open=r.open,
                high=r.high,
                low=r.low,
                close=r.close,
                volume=r.volume,
                source="polygon"
            ))
        return bars

def to_dataframe(bars: list[Bar]) -> pd.DataFrame:
    df = pd.DataFrame([b.__dict__ for b in bars])
    df = df.sort_values("t_event").reset_index(drop=True)
    return df

