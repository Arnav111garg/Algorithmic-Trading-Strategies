import numpy as np
import pandas as pd

def mad_filter(prices: pd.Series, window: int = 50, k: float = 5.0) -> pd.Series:
    """
    Flag outliers using a rolling median + MAD filter (Brownlees-Gallo style).
    Returns a boolean mask: True = flagged as bad tick.
    """
    rolling_med = prices.rolling(window, center=True, min_periods=10).median()
    abs_dev = (prices - rolling_med).abs()
    rolling_mad = abs_dev.rolling(window, center=True, min_periods=10).median()
    # 1.4826 scales MAD to be a consistent estimator of sigma under normality
    robust_sigma = 1.4826 * rolling_mad
    flagged = abs_dev > k * robust_sigma
    return flagged.fillna(False)

def clean_tick_series(df: pd.DataFrame, price_col: str = "price") -> pd.DataFrame:
    log = {"input_rows": len(df)}

    # 1. Drop exact duplicates (same timestamp, price, size, venue)
    before = len(df)
    df = df.drop_duplicates(subset=["timestamp", price_col, "size", "venue"])
    log["duplicates_removed"] = before - len(df)

    # 2. Enforce monotonic timestamps (resolve out-of-sequence capture)
    df = df.sort_values("timestamp", kind="stable").reset_index(drop=True)

    # 3. Flag and remove fat-finger outliers
    flagged = mad_filter(df[price_col])
    log["outliers_flagged"] = int(flagged.sum())
    df["is_outlier"] = flagged  # KEEP the flag--never silently delete
    df_clean = df.loc[~flagged].copy()

    # 4. Sanity bound: no crossed market persisting > 1 print
    if {"bid", "ask"}.issubset(df.columns):
        crossed = df_clean["bid"] > df_clean["ask"]
        log["crossed_quotes"] = int(crossed.sum())
        df_clean = df_clean.loc[~crossed]

    log["output_rows"] = len(df_clean)
    df_clean.attrs["cleaning_log"] = log # audit trail travels with the data

    return df_clean

