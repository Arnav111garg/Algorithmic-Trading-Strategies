import pandas as pd

def point_in_time_universe(membership: pd.DataFrame, as_of: pd.Timestamp) -> set:
    """
    membership columns required:
    permno / identifier, start_date, end_date (NaT if still active)
    Returns the set of identifiers that were ACTUALLY tradable members
    of the universe (e.g., index, or 'liquid stock universe') on as_of.
    """
    mask = (membership["start_date"] <= as_of) & (
        membership["end_date"].isna() | (membership["end_date"] >= as_of)
    )
    return set(membership.loc[mask, "permno"])

def backtest_universe_for_each_date(membership: pd.DataFrame, dates: pd.DatetimeIndex) -> dict:
    """Pre-compute the point-in-time universe for every rebalance date.
    This is the correct pattern-- compute ONCE up front, never derive
    the universe inside the simulation loop from 'current' static lists."""
    return {d: point_in_time_universe(membership, d) for d in dates}

def apply_delisting_return(returns: pd.DataFrame, delistings: pd.DataFrame) -> pd.DataFrame:
    """
    delistings columns: permno, delist_date, delist_return (may be NaN),
    delist_code (used to impute if delist_return is NaN)
    Shumway (1997) style imputation for missing delisting returns.
    """
    impute_map = {
        "bankruptcy_nyse_amex": -0.30,
        "bankruptcy_nasdaq": -0.55,
    }
    out = returns.copy()
    for _, row in delistings.iterrows():
        ret = row["delist_return"]
        if pd.isna(ret):
            ret = impute_map.get(row["delist_code"], -0.30)  # conservative default
        out.loc[(out["permno"] == row["permno"]) & (out["date"] == row["delist_date"]), "return"] = ret
    return out

