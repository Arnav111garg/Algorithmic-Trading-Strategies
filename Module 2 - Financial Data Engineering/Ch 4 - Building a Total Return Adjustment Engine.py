import pandas as pd

def build_adjustment_factors(corp_actions: pd.DataFrame, cum_div_close: pd.Series) -> pd.Series:
    """
    corp_actions: DataFrame indexed by ex_date with columns
    ['split_ratio' (e.g. 2.0 for 2-for-1, 1.0 if none),
    'dividend' (cash amount, 0 if none)]
    cum_div_close: close price ON the ex_date, cum-dividend (i.e. before
    the price drop is reflected)-- this is the price the vendor
    reports just prior to applying the corporate action.
    Returns: a Series of cumulative adjustment factors, same index as
    corp_actions, to be applied to ALL prices strictly before each ex_date.
    """
    factors = pd.Series(index=corp_actions.index, dtype=float)
    cum_factor = 1.0
    # iterate from MOST RECENT action backward to oldest
    for ex_date in sorted(corp_actions.index, reverse=True):
        row = corp_actions.loc[ex_date]
        price = cum_div_close.loc[ex_date]
        div_factor = price / (price - row["dividend"]) if row["dividend"] > 0 else 1.0
        split_factor = row["split_ratio"] if row["split_ratio"] > 0 else 1.0
        cum_factor *= div_factor * split_factor
        factors.loc[ex_date] = cum_factor
    return factors.sort_index()

def apply_adjustments(raw_prices: pd.Series, factors: pd.Series) -> pd.Series:
    """Apply the appropriate cumulative factor to every price BEFORE
    each ex_date. Prices on/after the most recent action are untouched."""
    adjusted = raw_prices.copy()
    sorted_dates = sorted(factors.index)
    for i, ex_date in enumerate(sorted_dates):
        f = factors.loc[ex_date]
        mask = adjusted.index < ex_date
        if i > 0:
            mask &= adjusted.index >= sorted_dates[i - 1]
        adjusted.loc[mask] = raw_prices.loc[mask] / f
    return adjusted

