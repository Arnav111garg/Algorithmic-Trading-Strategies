import pandas as pd
import numpy as np

def missingness_report(panel: pd.DataFrame, value_col: str) -> pd.DataFrame:
    """
    Cross-sectional missingness rate per date-- a sudden spike often
    signals a vendor outage, not genuine economic missingness.
    """
    report = panel.groupby("date")[value_col].apply(
        lambda s: s.isna().mean()
    ).rename("missing_rate")
    return report.to_frame()

def asof_join_fundamentals(prices: pd.DataFrame, fundamentals: pd.DataFrame, by: str = "permno") -> pd.DataFrame:
    """
    prices: columns [permno, date, close, ...]
    fundamentals: columns [permno, know_date, eps, book_value, ...]
    know_date = the date the figure became PUBLICLY available
    (e.g., 8-K/10-Q filing date), NOT the fiscal period end date.
    Uses pandas merge_asof: for each price row, attaches the most recent
    fundamentals row whose know_date <= price date. This guarantees
    no look-ahead bias.
    """
    prices_sorted = prices.sort_values("date")
    fund_sorted = fundamentals.sort_values("know_date").rename(
        columns={"know_date": "date"}
    )
    merged = pd.merge_asof(
        prices_sorted, fund_sorted,
        on="date", by=by, direction="backward"
    )
    return merged

def flag_trading_halts(volume: pd.Series, price_change: pd.Series) -> pd.Series:
    """
    Crude halt detector: zero volume + the day before/after shows a
    large jump suggests a halt rather than genuine illiquidity.
    """
    zero_vol = volume == 0
    big_move_around = price_change.abs().rolling(2).max() > 0.10
    return zero_vol & big_move_around

