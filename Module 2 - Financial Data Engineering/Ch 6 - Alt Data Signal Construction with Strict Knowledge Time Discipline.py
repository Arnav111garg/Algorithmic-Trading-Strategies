import pandas as pd
import numpy as np

def build_altdata_feature(raw_panel: pd.DataFrame, publication_lag_days: int, value_col: str = "foot_traffic_index") -> pd.DataFrame:
    """
    raw_panel: columns [entity_id, period_end_date, value_col]
    publication_lag_days: REAL-WORLD lag between period_end_date and when
    the vendor actually published/delivered this data point to clients.
    This must be sourced from the vendor’s documented SLA or, better,
    from your own ingestion timestamps logged historically-- never
    assumed to be zero.
    """
    out = raw_panel.copy()
    out["t_know"] = out["period_end_date"] + pd.Timedelta(days=publication_lag_days)
    out = out.rename(columns={value_col: "raw_value"})
    return out[["entity_id", "period_end_date", "t_know", "raw_value"]]

def cross_sectional_zscore(panel: pd.DataFrame, value_col: str) -> pd.Series:
    """Standardize within each t_know cross-section-- standard
    normalization before feeding into a cross-sectional ranking model."""
    return panel.groupby("t_know")[value_col].transform(
        lambda s: (s - s.mean()) / s.std(ddof=0)
    )

def decay_adjusted_ic(signal: pd.Series, fwd_return: pd.Series, horizon_days: list) -> pd.Series:
    """Estimate IC at multiple forward horizons to empirically map out
    the alpha decay curve described in Proposition 3.6.1."""
    results = {}
    for h in horizon_days:
        shifted_ret = fwd_return.shift(-h)
        valid = signal.notna() & shifted_ret.notna()
        results[h] = signal[valid].corr(shifted_ret[valid], method="spearman")
    return pd.Series(results)

