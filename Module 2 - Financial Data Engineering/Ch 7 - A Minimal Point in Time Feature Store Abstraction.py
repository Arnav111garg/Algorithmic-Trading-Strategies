import pandas as pd
from dataclasses import dataclass, field

@dataclass
class FeatureDefinition:
    name: str
    version: str
    compute_fn: callable
    input_cols: list

class FeatureStore:
    def __init__(self):
        self._registry: dict[tuple[str, str], FeatureDefinition] = {}
        self._materialized: dict[tuple[str, str], pd.DataFrame] = {}

    def register(self, fd: FeatureDefinition):
        key = (fd.name, fd.version)
        self._registry[key] = fd

    def materialize(self, name: str, version: str, raw: pd.DataFrame,
                    entity_col: str = "symbol", time_col: str = "date"):
        """Computes and stores feature values, tagging each with the
        knowledge time it became valid--immutable once written."""
        fd = self._registry[(name, version)]
        result = raw.groupby(entity_col).apply(
            lambda g: fd.compute_fn(g[fd.input_cols[0]])
        ).reset_index()
        result["t_know"] = raw[time_col]
        result["feature_name"] = name
        result["feature_version"] = version
        key = (name, version)
        # append-only: never overwrite prior materializations
        if key in self._materialized:
            self._materialized[key] = pd.concat(
                [self._materialized[key], result]).drop_duplicates(
                subset=[entity_col, "t_know"], keep="last")
        else:
            self._materialized[key] = result

    def get_point_in_time(self, name: str, version: str, entity: str,
                          as_of: pd.Timestamp):
        df = self._materialized[(name, version)]
        sub = df[(df["symbol"] == entity) & (df["t_know"] <= as_of)]
        if sub.empty:
            return None
        return sub.sort_values("t_know").iloc[-1]

