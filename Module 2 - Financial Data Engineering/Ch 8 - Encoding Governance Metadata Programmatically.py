from dataclasses import dataclass
from enum import Enum

class UsageTier(Enum):
    RESEARCH_ONLY = "research_only"
    PRODUCTION_APPROVED = "production_approved"

@dataclass
class DatasetCatalogEntry:
    name: str
    vendor: str
    usage_tier: UsageTier
    license_expiry: str
    data_steward: str
    pii_flag: bool
    mnpi_risk_flag: bool

class GovernanceError(Exception):
    pass

def check_production_eligibility(entry: DatasetCatalogEntry):
    if entry.usage_tier != UsageTier.PRODUCTION_APPROVED:
        raise GovernanceError(
            f"Dataset '{entry.name}' is licensed as {entry.usage_tier.value} "
            f"and cannot be wired into a production pipeline. "
            f"Contact data steward {entry.data_steward} to upgrade the license."
        )
    if entry.mnpi_risk_flag:
        raise GovernanceError(
            f"Dataset '{entry.name}' is flagged for MNPI review; "
            f"compliance sign-off required before production use."
        )

