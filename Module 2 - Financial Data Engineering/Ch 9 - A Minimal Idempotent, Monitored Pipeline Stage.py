import pandas as pd
import logging
from datetime import datetime, timedelta

logger = logging.getLogger("pipeline.ingest_prices")

class PipelineFailure(Exception):
    """Raised to halt downstream consumption--never swallow this."""

def ingest_daily_prices(raw_feed: pd.DataFrame, expected_universe_size: int, tolerance: float = 0.05) -> pd.DataFrame:
    # 1. Volume sanity check--fail loudly, don’t silently propagate
    actual_size = raw_feed["symbol"].nunique()
    deviation = abs(actual_size - expected_universe_size) / expected_universe_size
    if deviation > tolerance:
        raise PipelineFailure(
            f"Universe size deviated by {deviation:.1%} "
            f"(expected ~{expected_universe_size}, got {actual_size}). "
            f"Halting downstream consumption--investigate upstream feed."
        )

    # 2. Schema check
    required_cols = {"symbol", "date", "close", "volume"}
    missing = required_cols - set(raw_feed.columns)
    if missing:
        raise PipelineFailure(f"Schema drift detected--missing columns: {missing}")

    # 3. Freshness check
    max_date = raw_feed["date"].max()
    if (datetime.now().date() - max_date.date()) > timedelta(days=1):
        raise PipelineFailure(f"Stale data: latest date in feed is {max_date}")

    logger.info(f"Ingest passed all gates: {actual_size} symbols, latest={max_date}")
    return raw_feed

def upsert_to_store(df: pd.DataFrame, store_conn, table: str):
    """Idempotent write: re-running with the same df produces the same
    end state, not duplicate rows (achieved via a composite primary key
    on (symbol, date) and an ON CONFLICT/MERGE clause)."""
    store_conn.execute(f"""
        MERGE INTO {table} AS target
        USING staged_df AS source
        ON target.symbol = source.symbol AND target.date = source.date
        WHEN MATCHED THEN UPDATE SET close = source.close, volume = source.volume
        WHEN NOT MATCHED THEN INSERT (symbol, date, close, volume)
        VALUES (source.symbol, source.date, source.close, source.volume)
    """)

