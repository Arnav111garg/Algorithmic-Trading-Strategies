# TSMOM Backtesting Engine
import numpy as np
import pandas as pd

class TSMOMBacktest:
    """
    Complete Time-Series Momentum backtesting engine
    with realistic transaction costs and performance analytics.
    """

    def __init__(
        self,
        prices: pd.DataFrame,
        signals: pd.DataFrame,
        rebal_freq: str = 'M',            # Monthly rebalancing
        transaction_cost: float = 0.001,  # 10 bps one-way
        initial_capital: float = 1e6,
        leverage: float = 1.0
    ):
        self.prices = prices
        self.signals = signals
        self.rebal_freq = rebal_freq
        self.tc = transaction_cost
        self.capital = initial_capital
        self.leverage = leverage

    def run(self) -> dict:
        """Execute backtest and return performance metrics."""
        log_ret = np.log(self.prices / self.prices.shift(1)).dropna()

        # Reindex signals to match returns
        signals_aligned = self.signals.reindex(
            log_ret.index, method='ffill'
        )

        # Normalise signal weights (sum of absolute weights = 1)
        weights = signals_aligned.div(
            signals_aligned.abs().sum(axis=1), axis=0
        ) * self.leverage

        # Raw portfolio returns
        port_ret = (weights.shift(1) * log_ret).sum(axis=1)

        # Transaction costs (proportional to turnover)
        turnover = weights.diff().abs().sum(axis=1)
        cost = turnover * self.tc

        net_ret = port_ret - cost

        # Compute performance metrics
        metrics = self._compute_metrics(net_ret, port_ret, cost)

        return {
            'returns': net_ret,
            'gross_returns': port_ret,
            'weights': weights,
            'metrics': metrics
        }

    def _compute_metrics(self, net_ret, gross_ret, cost):
        """Compute comprehensive performance statistics."""
        ann_factor = 252

        def sharpe(r):
            return (r.mean() / r.std()) * np.sqrt(ann_factor)

        def max_drawdown(r):
            cumulative = (1 + r).cumprod()
            rolling_max = cumulative.cummax()
            dd = (cumulative - rolling_max) / rolling_max
            return dd.min()

        def calmar(r):
            ann_ret = r.mean() * ann_factor
            mdd = abs(max_drawdown(r))
            return ann_ret / mdd if mdd > 0 else np.nan

        def sortino(r, mar=0):
            downside = r[r < mar]
            downside_std = np.sqrt((downside**2).mean()) * np.sqrt(ann_factor)
            ann_ret = r.mean() * ann_factor
            return ann_ret / downside_std if downside_std > 0 else np.nan

        def skewness(r):
            return r.skew()

        def kurtosis(r):
            return r.kurt()

        return {
            'ann_gross_return': gross_ret.mean() * ann_factor,
            'ann_net_return': net_ret.mean() * ann_factor,
            'ann_volatility': net_ret.std() * np.sqrt(ann_factor),
            'gross_sharpe': sharpe(gross_ret),
            'net_sharpe': sharpe(net_ret),
            'sortino': sortino(net_ret),
            'calmar': calmar(net_ret),
            'max_drawdown': max_drawdown(net_ret),
            'skewness': skewness(net_ret),
            'excess_kurtosis': kurtosis(net_ret),
            'ann_cost_drag': cost.mean() * ann_factor,
            'hit_rate': (net_ret > 0).mean()
        }

