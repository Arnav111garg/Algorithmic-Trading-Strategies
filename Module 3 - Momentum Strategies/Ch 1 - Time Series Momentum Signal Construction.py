import numpy as np
import pandas as pd

def compute_tsmom_signal(
    prices: pd.DataFrame,
    lookback: int = 252,       # trading days (~12 months)
    skip_last: int = 21,       # skip last month (21 trading days)
    vol_window: int = 63,      # 3-month vol estimate
    vol_target: float = 0.10,  # 10% annualised target vol
    lambda_ewma: float = 0.94  # RiskMetrics decay factor
) -> pd.DataFrame:
    """
    Computes volatility-scaled Time-Series Momentum signals.

    Parameters
    ----------
    prices : pd.DataFrame
        Daily adjusted close prices (columns = assets)
    lookback : int
        Formation period in trading days
    skip_last : int
        Number of days to skip at end (microstructure reversal)
    vol_window : int
        Lookback window for volatility estimation
    vol_target : float
        Target annualised portfolio volatility per asset
    lambda_ewma : float
        EWMA decay factor for volatility estimation

    Returns
    -------
    pd.DataFrame
        Volatility-scaled momentum signals
    """
    # Step 1: Compute log returns
    log_ret = np.log(prices / prices.shift(1))

    # Step 2: Compute EWMA volatility
    ewma_var = log_ret.ewm(
        alpha=(1 - lambda_ewma),
        min_periods=vol_window
    ).var()
    ewma_vol = np.sqrt(ewma_var * 252) # Annualise (252 trading days)

    # Step 3: Compute formation period return (skip last 'skip_last' days)
    formation_return = log_ret.shift(skip_last).rolling(
        lookback - skip_last
    ).sum()

    # Step 4: Directional signal (binary: +1 or -1)
    direction = np.sign(formation_return)

    # Step 5: Volatility-scaled position
    # Replace zero vol with NaN to avoid division errors
    ewma_vol_safe = ewma_vol.replace(0, np.nan)
    signals = (vol_target / ewma_vol_safe) * direction

    return signals

def multi_horizon_tsmom(
    prices: pd.DataFrame,
    horizons: list = [1, 3, 6, 12], # months
    days_per_month: int = 21
) -> pd.DataFrame:
    """
    Multi-horizon TSMOM signal (equal-weighted combination).
    """
    signals_list = []
    for h in horizons:
        lookback_days = h * days_per_month
        sig = compute_tsmom_signal(prices, lookback=lookback_days)
        signals_list.append(sig)
    # Equal-weight combination
    combined = pd.concat(signals_list, axis=0).groupby(level=0).mean()
    return combined

