import numpy as np
import pandas as pd
from scipy import stats

def cross_sectional_momentum(
    returns: pd.DataFrame,
    J: int = 12, # formation months
    skip: int = 1, # skip last month
    K: int = 1, # holding months
    weighting: str = 'rank', # 'rank', 'score', 'decile'
    n_deciles: int = 10,
    long_pct: float = 0.3,
    short_pct: float = 0.3
) -> pd.DataFrame:
    """
    Compute cross-sectional momentum weights.

    Parameters
    ----------
    returns : pd.DataFrame
        Monthly returns (rows = time, columns = assets)
    J : int
        Formation period (months)
    skip : int
        Number of months to skip
    K : int
        Holding period (months)
    weighting : str
        Portfolio weighting scheme
    n_deciles : int
        Number of deciles (for decile weighting)
    long_pct : float
        Fraction of assets to go long
    short_pct : float
        Fraction of assets to go short

    Returns
    -------
    pd.DataFrame
        Time series of portfolio weights
    """
    # Step 1: Compute formation period return
    # Skip last 'skip' months
    if skip > 0:
        formation = returns.shift(skip).rolling(J - skip).sum()
    else:
        formation = returns.rolling(J).sum()

    weights_list = []

    for date in returns.index[J:]:
        # Get scores for this date
        scores = formation.loc[date].dropna()
        n = len(scores)

        if n < 10:
            weights_list.append(pd.Series(0.0, index=returns.columns))
            continue

        if weighting == 'rank':
            # Rank-weighted: uniform dispersion
            ranks = scores.rank(pct=True) # [0, 1]
            raw_weights = ranks - 0.5 # [-0.5, +0.5]
        elif weighting == 'score':
            # Score-weighted: z-score
            raw_weights = (scores - scores.mean()) / scores.std()
        elif weighting == 'decile':
            # Decile-based: long top, short bottom
            deciles = pd.qcut(scores, n_deciles, labels=False) + 1
            raw_weights = pd.Series(0.0, index=scores.index)
            long_assets = scores[deciles >= n_deciles * (1 - long_pct) + 1].index
            short_assets = scores[deciles <= n_deciles * short_pct].index
            raw_weights[long_assets] = 1.0 / len(long_assets)
            raw_weights[short_assets] = -1.0 / len(short_assets)
        else:
            raise ValueError(f"Unknown weighting: {weighting}")

        # Normalise to sum to zero (market-neutral)
        if weighting != 'decile':
            # Dollar-neutral: long weight sum = short weight sum
            pos_mask = raw_weights > 0
            neg_mask = raw_weights < 0
            if pos_mask.sum() > 0:
                raw_weights[pos_mask] /= raw_weights[pos_mask].sum()
            if neg_mask.sum() > 0:
                raw_weights[neg_mask] /= (-raw_weights[neg_mask].sum())
            raw_weights /= 2 # Scale so total notional = 1 long + 1 short

        # Reindex to full universe
        full_weights = raw_weights.reindex(returns.columns).fillna(0)
        weights_list.append(full_weights)

    weights_df = pd.DataFrame(weights_list, index=returns.index[J:])

    # Apply holding period overlap (average K cohorts)
    if K > 1:
        weights_df = weights_df.rolling(K).mean()

    return weights_df

def compute_wml_factor(
    returns: pd.DataFrame,
    J: int = 12,
    K: int = 1,
    long_pct: float = 0.3,
    short_pct: float = 0.3
) -> pd.Series:
    """
    Compute the WML (Winner-Minus-Loser) factor return.
    """
    weights = cross_sectional_momentum(
        returns, J=J, K=K,
        weighting='decile',
        long_pct=long_pct,
        short_pct=short_pct
    )

    # Align and compute portfolio returns
    ret_aligned = returns.reindex(weights.index)
    wml = (weights * ret_aligned).sum(axis=1)
    return wml

# --- Fama-MacBeth Regression ---
def fama_macbeth(
    returns: pd.DataFrame,
    signals: pd.DataFrame,
    n_lags: int = 3 # Newey-West lags
) -> dict:
    """
    Fama-MacBeth (1973) two-pass cross-sectional regression.
    Tests whether momentum signal predicts next-month returns.
    """
    # Align signals to be predetermined
    X = signals.shift(1)
    Y = returns

    betas = []
    dates = X.index.intersection(Y.index)

    for date in dates:
        x = X.loc[date].dropna()
        y = Y.loc[date].reindex(x.index).dropna()
        common = x.index.intersection(y.index)

        if len(common) < 20:
            continue

        x_vals = x[common].values
        y_vals = y[common].values

        # Add constant
        X_mat = np.column_stack([np.ones(len(x_vals)), x_vals])

        # OLS
        beta_ols, _, _, _ = np.linalg.lstsq(X_mat, y_vals, rcond=None)
        betas.append(beta_ols)

    betas = np.array(betas)
    b_mean = betas.mean(axis=0)

    # Newey-West standard errors
    T = len(betas)
    e = betas - b_mean
    omega = e.T @ e / T # Initial variance
    for lag in range(1, n_lags + 1):
        weight = 1 - lag / (n_lags + 1)
        gamma = (e[lag:].T @ e[:-lag]) / T
        omega += weight * (gamma + gamma.T)
    se = np.sqrt(np.diag(omega) / T)
    t_stats = b_mean / se

    return {
        'alpha': b_mean[0], 'alpha_se': se[0], 'alpha_t': t_stats[0],
        'beta_mom': b_mean[1], 'beta_mom_se': se[1], 'beta_mom_t': t_stats[1]
    }

