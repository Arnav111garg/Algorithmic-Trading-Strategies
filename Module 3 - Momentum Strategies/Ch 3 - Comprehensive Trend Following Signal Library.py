import numpy as np
import pandas as pd
from typing import Dict, List, Tuple, Optional

class TrendFollowingSignals:
    """
    Comprehensive library of trend-following signals for systematic trading.
    All signals return values in [-1, +1] range for easy combination.
    """

    @staticmethod
    def ewmac(prices: pd.Series, fast: int, slow: int) -> pd.Series:
        """
        EWMA Crossover signal. Returns continuous signal proportional to
        the normalised difference between fast and slow EWMAs.

        Parameters
        ----------
        prices : pd.Series
            Daily close prices
        fast : int
            Fast EWMA span (in days). Typical: 8, 16, 32
        slow : int
            Slow EWMA span (in days). Typical: 24, 64, 256

        Returns
        -------
        pd.Series
            Signal in range ~[-1, +1]
        """
        fast_ewma = prices.ewm(span=fast, adjust=False).mean()
        slow_ewma = prices.ewm(span=slow, adjust=False).mean()

        # Raw crossover (price units)
        raw_signal = fast_ewma - slow_ewma

        # Normalise by rolling standard deviation of the raw signal
        # to put all signals on the same scale
        signal_std = raw_signal.ewm(span=slow * 4, adjust=False).std()
        normalised = raw_signal / signal_std.replace(0, np.nan)

        # Clip to [-1, +1] (optional use for blending)
        return normalised.clip(-1, 1)

    @staticmethod
    def breakout_signal(prices: pd.Series, window: int = 20) -> pd.Series:
        """
        Donchian Channel breakout signal.
        Long when price at n-day high, short when at n-day low.
        """
        roll_max = prices.rolling(window).max()
        roll_min = prices.rolling(window).min()
        roll_mid = (roll_max + roll_min) / 2

        # Continuous signal: normalise price position within channel
        channel_width = (roll_max - roll_min).replace(0, np.nan)
        signal = (prices - roll_mid) / (channel_width / 2)

        return signal.clip(-1, 1)

    @staticmethod
    def macd_signal(prices: pd.Series, fast: int = 12, slow: int = 26, signal_period: int = 9) -> pd.Series:
        """
        MACD crossover signal.
        """
        fast_ewma = prices.ewm(span=fast, adjust=False).mean()
        slow_ewma = prices.ewm(span=slow, adjust=False).mean()
        macd_line = fast_ewma - slow_ewma
        signal_line = macd_line.ewm(span=signal_period, adjust=False).mean()

        histogram = macd_line - signal_line

        # Normalise
        hist_std = histogram.rolling(252).std().replace(0, np.nan)
        return (histogram / hist_std).clip(-1, 1)

    @staticmethod
    def rsi_signal(prices: pd.Series, window: int = 14) -> pd.Series:
        """
        RSI-based trend signal (momentum oscillator).
        Note: RSI is primarily a mean-reversion indicator, but can be
        used as a trend confirmation signal at extreme readings.
        """
        delta = prices.diff()
        gain = delta.clip(lower=0)
        loss = (-delta).clip(lower=0)

        avg_gain = gain.ewm(span=window, adjust=False).mean()
        avg_loss = loss.ewm(span=window, adjust=False).mean()

        rs = avg_gain / avg_loss.replace(0, np.nan)
        rsi = 100 - (100 / (1 + rs))

        # Convert RSI [0,100] to signal [-1, +1]
        # Bullish if RSI > 50 (trend signal interpretation)
        signal = (rsi - 50) / 50
        return signal.clip(-1, 1)

    @staticmethod
    def kalman_trend(prices: pd.Series, q: float = 1e-4, r: float = 1e-2) -> pd.Series:
        """
        Kalman filter trend estimate.

        Parameters
        ----------
        prices : pd.Series
            Log prices (or returns)
        q : float
            State noise variance (trend volatility). Higher q = faster adaptation.
        r : float
            Observation noise variance (price noise). Higher r = smoother filter.

        Returns
        -------
        pd.Series
            Kalman-filtered trend signal
        """
        log_prices = np.log(prices)

        n = len(log_prices)
        mu_est = np.zeros(n)  # State estimate
        P_est = np.ones(n)   # Estimate variance
        K = np.zeros(n)       # Kalman gain

        # Initialise
        mu_est[0] = log_prices.iloc[0]
        P_est[0] = 1.0

        for t in range(1, n):
            # Predict
            mu_pred = mu_est[t-1]
            P_pred = P_est[t-1] + q

            # Update
            y = log_prices.iloc[t] - mu_pred  # Innovation
            S = P_pred + r                    # Innovation variance
            K[t] = P_pred / S                 # Kalman gain
            mu_est[t] = mu_pred + K[t] * y
            P_est[t] = (1 - K[t]) * P_pred

        trend_signal = pd.Series(mu_est, index=log_prices.index)

        # Return the rate of change of estimated trend as a signal
        trend_velocity = trend_signal.diff()
        vol = trend_velocity.rolling(63).std().replace(0, np.nan)
        return (trend_velocity / vol).clip(-1, 1)

class TrendFollowingPortfolio:
    """
    Multi-signal, multi-asset trend-following portfolio.
    Implements the AHL/Winton-style approach.
    """

    def __init__(
        self,
        prices: pd.DataFrame,
        signal_config: List[Dict],
        vol_target: float = 0.15,
        vol_window: int = 63,
        max_leverage: float = 3.0
    ):
        """
        Parameters
        ----------
        prices : pd.DataFrame
            Daily futures prices
        signal_config : list of dict
            Each dict has keys: 'type', 'params', 'weight'
            e.g., {'type': 'ewmac', 'params': {'fast': 8, 'slow': 32}, 'weight': 0.5}
        vol_target : float
            Annualised portfolio volatility target
        vol_window : int
            Lookback for volatility estimation
        max_leverage : float
            Maximum portfolio leverage
        """
        self.prices = prices
        self.signal_config = signal_config
        self.vol_target = vol_target
        self.vol_window = vol_window
        self.max_leverage = max_leverage
        self.signals = TrendFollowingSignals()

    def compute_signals(self) -> pd.DataFrame:
        """Compute combined multi-signal trend indicator for each asset."""
        all_signals = {}

        for asset in self.prices.columns:
            price_series = self.prices[asset].dropna()
            combined = pd.Series(0.0, index=price_series.index)
            total_weight = 0.0

            for cfg in self.signal_config:
                sig_type = cfg['type']
                params = cfg['params']
                weight = cfg['weight']

                if sig_type == 'ewmac':
                    sig = TrendFollowingSignals.ewmac(price_series, **params)
                elif sig_type == 'breakout':
                    sig = TrendFollowingSignals.breakout_signal(price_series, **params)
                elif sig_type == 'macd':
                    sig = TrendFollowingSignals.macd_signal(price_series, **params)
                elif sig_type == 'rsi':
                    sig = TrendFollowingSignals.rsi_signal(price_series, **params)
                elif sig_type == 'kalman':
                    sig = TrendFollowingSignals.kalman_trend(price_series, **params)
                else:
                    raise ValueError(f"Unknown signal type: {sig_type}")

                combined += weight * sig.reindex(combined.index).fillna(0)
                total_weight += weight

            combined /= total_weight  # Normalise to [-1, +1]
            all_signals[asset] = combined

        return pd.DataFrame(all_signals)

    def compute_positions(self, signals: pd.DataFrame) -> pd.DataFrame:
        """
        Convert signals to position sizes (number of contracts or fractional).
        Uses volatility targeting to size positions.
        """
        log_ret = np.log(self.prices / self.prices.shift(1))

        # EWMA volatility (annualised)
        ewma_vol = log_ret.ewm(
            span=self.vol_window, adjust=False
        ).std() * np.sqrt(252)

        ewma_vol_safe = ewma_vol.replace(0, np.nan)

        # Position = (vol_target / asset_vol) * signal
        positions = (self.vol_target / ewma_vol_safe) * signals

        # Apply maximum leverage constraint
        total_notional = positions.abs().sum(axis=1)
        scale = np.minimum(1.0, self.max_leverage / total_notional)
        positions = positions.multiply(scale, axis=0)

        return positions

    def backtest(self) -> dict:
        """Run the complete backtest."""
        signals = self.compute_signals()
        positions = self.compute_positions(signals)

        log_ret = np.log(self.prices / self.prices.shift(1)).dropna()
        pos_aligned = positions.reindex(log_ret.index).shift(1)  # Lag 1 day

        portfolio_ret = (pos_aligned * log_ret).sum(axis=1)

        # Statistics
        ann = 252
        stats = {
            'annual_return': portfolio_ret.mean() * ann,
            'annual_vol': portfolio_ret.std() * np.sqrt(ann),
            'sharpe': (portfolio_ret.mean() / portfolio_ret.std()) * np.sqrt(ann),
            'max_dd': ((1 + portfolio_ret).cumprod() / (1 + portfolio_ret).cumprod().cummax() - 1).min(),
            'skewness': portfolio_ret.skew(),
            'kurtosis': portfolio_ret.kurt(),
        }

        return {'returns': portfolio_ret, 'positions': positions, 'stats': stats}

