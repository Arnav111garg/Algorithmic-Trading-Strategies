import numpy as np
import pandas as pd

class BreakoutSystems:
    """
    Comprehensive breakout signal library.
    """

    @staticmethod
    def donchian_breakout(
        high: pd.Series,
        low: pd.Series,
        close: pd.Series,
        entry_window: int = 20,
        exit_window: int = 10,
        continuous: bool = True
    ) -> pd.Series:
        """
        Donchian Channel breakout (original Turtle Trading system).

        Parameters
        ----------
        continuous : bool
            If True, return continuous signal (price position in channel).
            If False, return binary entry signal.
        """
        upper_entry = high.rolling(entry_window).max()
        lower_entry = low.rolling(entry_window).min()

        if continuous:
            # Continuous signal: where is current price in the channel?
            channel_mid = (upper_entry + lower_entry) / 2
            channel_half_width = (upper_entry - lower_entry) / 2
            signal = (close - channel_mid) / channel_half_width.replace(0, np.nan)
            return signal.clip(-1, 1)
        else:
            # Binary breakout signal
            upper_lag = upper_entry.shift(1)
            lower_lag = lower_entry.shift(1)

            signal = pd.Series(0.0, index=close.index)
            signal[close > upper_lag] = 1.0 # Long breakout
            signal[close < lower_lag] = -1.0 # Short breakout
            return signal

    @staticmethod
    def atr_breakout(
        high: pd.Series,
        low: pd.Series,
        close: pd.Series,
        n: int = 20,
        k: float = 2.0
    ) -> pd.Series:
        """ATR-based breakout signal."""
        # True Range
        tr = pd.concat([
            high - low,
            (high - close.shift(1)).abs(),
            (low - close.shift(1)).abs()
        ], axis=1).max(axis=1)

        atr = tr.rolling(n).mean()

        # Upper and lower breakout levels
        upper = close.shift(n) + k * atr
        lower = close.shift(n) - k * atr

        signal = pd.Series(0.0, index=close.index)
        signal[close > upper] = 1.0
        signal[close < lower] = -1.0

        return signal

    @staticmethod
    def zscore_breakout(
        close: pd.Series,
        n: int = 20,
        threshold: float = 1.96
    ) -> pd.Series:
        """Statistical significance breakout signal."""
        sma = close.rolling(n).mean()
        std = close.rolling(n).std()

        # Z-score
        z = (close - sma) / std.replace(0, np.nan)

        signal = pd.Series(0.0, index=close.index)
        signal[z > threshold] = z[z > threshold]
        signal[z < -threshold] = z[z < -threshold]

        # Normalise to [-1, +1]
        max_z = signal.abs().rolling(252).quantile(0.99).replace(0, np.nan)
        return (signal / max_z).clip(-1, 1)

    @staticmethod
    def volatility_expansion_signal(
        high: pd.Series,
        low: pd.Series,
        close: pd.Series,
        nr_days: int = 7
    ) -> pd.Series:
        """
        NR7 (Narrowest Range in 7 days) volatility expansion signal.
        Returns +1/-1 on the first expansion bar after NR7.
        """
        tr = pd.concat([
            high - low,
            (high - close.shift(1)).abs(),
            (low - close.shift(1)).abs()
        ], axis=1).max(axis=1)

        # NR7: True range is the narrowest in the past 7 bars
        rolling_min_tr = tr.rolling(nr_days).min()
        nr7 = (tr == rolling_min_tr)

        # After NR7, go long if price exceeds NR7 high, short below NR7 low
        nr7_high = high.where(nr7).ffill()
        nr7_low = low.where(nr7).ffill()

        signal = pd.Series(0.0, index=close.index)
        signal[close > nr7_high] = 1.0
        signal[close < nr7_low] = -1.0

        return signal

    @staticmethod
    def turtle_position_size(
        close: pd.Series,
        atr: pd.Series,
        account_size: float,
        risk_pct: float = 0.01, # 1% of account per trade (Turtle: N=1%)
        contract_value: float = 1.0
    ) -> pd.Series:
        """
        Original Turtle Trading position sizing via ATR (N).

        Position = (Account * Risk%) / (N * Contract_value)
        The Turtles called ATR their 'N' value.
        1N = 1 ATR move = 1% of account (their standard risk unit).
        """
        dollar_volatility = atr * contract_value
        # Avoid division by zero
        dollar_volatility = dollar_volatility.replace(0, np.nan)
        position = (account_size * risk_pct) / dollar_volatility

        return position.round() # Round to whole contracts

