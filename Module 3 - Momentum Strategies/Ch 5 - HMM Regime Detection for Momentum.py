import numpy as np
import pandas as pd
from hmmlearn import hmm
from sklearn.preprocessing import StandardScaler

class MomentumRegimeDetector:
    """
    Hidden Markov Model for detecting momentum-favourable regimes.
    Uses the hmmlearn package (pip install hmmlearn).
    """

    def __init__(
        self,
        n_states: int = 2,
        n_iter: int = 1000,
        covariance_type: str = 'diag',
        random_state: int = 42
    ):
        self.n_states = n_states
        self.model = hmm.GaussianHMM(
            n_components=n_states,
            covariance_type=covariance_type,
            n_iter=n_iter,
            random_state=random_state
        )
        self.scaler = StandardScaler()
        self.fitted = False

    def fit(self, features: pd.DataFrame) -> 'MomentumRegimeDetector':
        """
        Fit the HMM to a feature matrix.

        Parameters
        ----------
        features : pd.DataFrame
            Feature matrix. Good choices: [returns, log_vol, skewness].
            Rows = time, columns = features.
        """
        X = self.scaler.fit_transform(features.values)
        self.model.fit(X)
        self.fitted = True

        # Label states by mean return (ascending)
        state_means = self.model.means_[:, 0]  # First feature assumed to be return
        self.state_order = np.argsort(state_means)

        return self

    def predict_regime(self, features: pd.DataFrame) -> pd.Series:
        """Predict the most likely regime at each time step (Viterbi)."""
        assert self.fitted, "Model must be fitted first"
        X = self.scaler.transform(features.values)
        raw_states = self.model.predict(X)

        # Relabel: 0 = Bear (lowest mean return), 1 = Bull (highest mean)
        relabelled = np.zeros_like(raw_states)
        for new_label, old_label in enumerate(self.state_order):
            relabelled[raw_states == old_label] = new_label

        return pd.Series(relabelled, index=features.index)

    def predict_proba(self, features: pd.DataFrame) -> pd.DataFrame:
        """Return smoothed regime probabilities (forward-backward)."""
        assert self.fitted, "Model must be fitted first"
        X = self.scaler.transform(features.values)
        _, posteriors = self.model.score_samples(X)

        # Reorder columns by state_order
        posteriors_reordered = posteriors[:, self.state_order]

        cols = [f'P(state={i})' for i in range(self.n_states)]
        return pd.DataFrame(posteriors_reordered, index=features.index, columns=cols)

    def regime_conditioned_momentum(
        self,
        momentum_signal: pd.Series,
        features: pd.DataFrame,
        prob_threshold: float = 0.70
    ) -> pd.Series:
        """
        Scale momentum signal by regime probability.
        Only trade when regime is clearly identified (P > threshold).
        """
        probabilities = self.predict_proba(features)

        # Bull regime probability (last column = highest mean return state)
        p_bull = probabilities.iloc[:, -1]
        p_bear = probabilities.iloc[:, 0]

        # Scale factor: +1 in clear bull, -1 in clear bear, reduced in uncertainty
        regime_scale = pd.Series(0.5, index=features.index)  # Default: half signal
        regime_scale[p_bull > prob_threshold] = 1.0          # Full momentum signal in bull
        regime_scale[p_bear > prob_threshold] = 0.25         # Reduce signal in bear (crash risk)

        return momentum_signal * regime_scale


def compute_hurst_exponent(ts: pd.Series, max_lag: int = 100) -> float:
    """
    Estimate Hurst exponent via R/S analysis.
    H > 0.5: trending, H < 0.5: mean-reverting, H = 0.5: random walk.
    """
    lags = range(2, max_lag)
    tau = []
    for lag in lags:
        # R/S statistic for each lag
        segments = len(ts) // lag
        rs_values = []
        for i in range(segments):
            segment = ts.iloc[i*lag:(i+1)*lag].values
            mean_seg = segment.mean()
            deviations = np.cumsum(segment - mean_seg)
            R = deviations.max() - deviations.min()
            S = segment.std()
            if S > 0:
                rs_values.append(R / S)
        if rs_values:
            tau.append(np.mean(rs_values))

    # Fit log(R/S) = H * log(lag) + const
    log_lags = np.log(list(lags)[:len(tau)])
    log_rs = np.log(tau)

    H, _ = np.polyfit(log_lags, log_rs, 1)
    return H

