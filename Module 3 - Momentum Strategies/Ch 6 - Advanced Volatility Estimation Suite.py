import numpy as np
import pandas as pd
from scipy.optimize import minimize

class VolatilityEstimators:
    """Suite of volatility estimators for momentum position sizing."""

    @staticmethod
    def ewma_vol(returns: pd.Series, lambd: float = 0.94, annualise: bool = True) -> pd.Series:
        """RiskMetrics EWMA volatility."""
        var = returns.ewm(alpha=1-lambd, adjust=False).var()
        ann_factor = 252 if annualise else 1
        return np.sqrt(var * ann_factor)

    @staticmethod
    def parkinson_vol(high: pd.Series, low: pd.Series, n: int = 21, annualise: bool = True) -> pd.Series:
        """Parkinson (1980) high-low volatility estimator."""
        log_hl = np.log(high / low)
        pk_var = (log_hl ** 2) / (4 * np.log(2))
        ann_factor = 252 if annualise else 1
        return np.sqrt(pk_var.rolling(n).mean() * ann_factor)

    @staticmethod
    def yang_zhang_vol(open_: pd.Series, high: pd.Series, low: pd.Series, close: pd.Series, n: int = 21, annualise: bool = True) -> pd.Series:
        """Yang-Zhang (2000) OHLC volatility estimator (most efficient)."""
        k = 0.34 / (1.34 + (n + 1) / (n - 1))

        # Overnight return variance
        log_co = np.log(open_ / close.shift(1))
        var_open = log_co.rolling(n).var()

        # Close-to-close variance
        log_cc = np.log(close / close.shift(1))
        var_close = log_cc.rolling(n).var()

        # Rogers-Satchell variance
        log_ho = np.log(high / open_)
        log_lo = np.log(low / open_)
        log_hc = np.log(high / close)
        log_lc = np.log(low / close)
        rs_var = (log_ho * (log_ho - log_co) + log_lo * (log_lo - log_co)).rolling(n).mean()

        yz_var = var_open + k * var_close + (1 - k) * rs_var
        ann_factor = 252 if annualise else 1
        return np.sqrt(np.maximum(yz_var, 0) * ann_factor)

    @staticmethod
    def garch11_vol(returns: pd.Series, n_burn: int = 252) -> pd.Series:
        """
        GARCH(1,1) volatility forecast.
        Estimates parameters via MLE, then filters conditional variance.
        """
        r = returns.dropna().values

        def garch_loglik(params, r):
            omega, alpha, beta = params
            if omega <= 0 or alpha < 0 or beta < 0 or alpha + beta >= 1:
                return np.inf

            T = len(r)
            sigma2 = np.zeros(T)
            sigma2[0] = np.var(r)

            for t in range(1, T):
                sigma2[t] = omega + alpha * r[t-1]**2 + beta * sigma2[t-1]
            loglik = -0.5 * np.sum(np.log(sigma2) + r**2 / sigma2)
            return -loglik # Minimise negative log-likelihood

        # Optimise
        result = minimize(
            garch_loglik,
            x0=[1e-6, 0.10, 0.85],
            args=(r,),
            method='L-BFGS-B',
            bounds=[(1e-8, None), (0, 0.5), (0, 0.99)]
        )

        omega, alpha, beta = result.x

        # Filter conditional variance
        T = len(r)
        sigma2 = np.zeros(T)
        sigma2[0] = np.var(r)
        for t in range(1, T):
            sigma2[t] = omega + alpha * r[t-1]**2 + beta * sigma2[t-1]

        vol_series = pd.Series(
            np.sqrt(sigma2 * 252), # Annualise
            index=returns.dropna().index
        )
        return vol_series.reindex(returns.index)

    @staticmethod
    def blend_vol_estimators(ewma_vol: pd.Series, parkinson_vol: pd.Series, weights: tuple = (0.5, 0.5)) -> pd.Series:
        """
        Blend multiple vol estimators for a more robust estimate.
        Default: 50% EWMA + 50% Parkinson.
        """
        w1, w2 = weights
        # Use squared vols for averaging, then sqrt (variance-weighted blend)
        blended_var = w1 * ewma_vol**2 + w2 * parkinson_vol**2
        return np.sqrt(blended_var)

