import numpy as np
import pandas as pd
from scipy.stats import norm
from typing import Tuple, Optional

class MomentumRiskManager:
    """
    Comprehensive risk management system for momentum strategies.
    Implements stop-losses, VaR monitoring, drawdown control,
    and crash protection.
    """

    def __init__(
        self,
        vol_target: float = 0.15,
        max_leverage: float = 3.0,
        max_drawdown_limit: float = 0.20,
        var_confidence: float = 0.99,
        atr_stop_multiplier: float = 2.0,
        crash_vix_threshold: float = 30.0
    ):
        self.vol_target = vol_target
        self.max_leverage = max_leverage
        self.max_dd_limit = max_drawdown_limit
        self.var_conf = var_confidence
        self.atr_mult = atr_stop_multiplier
        self.crash_vix = crash_vix_threshold

    def compute_var_es(
        self,
        returns: pd.Series,
        alpha: float = 0.01,
        method: str = 'historical'
    ) -> Tuple[float, float]:
        """
        Compute Value-at-Risk and Expected Shortfall.

        Parameters
        ----------
        returns : pd.Series
            Historical portfolio returns
        alpha : float
            Tail probability (e.g., 0.01 for 99% VaR)
        method : str
            'historical', 'parametric', or 'fhs' (filtered historical)

        Returns
        -------
        Tuple[float, float]
            (VaR, ES) as positive numbers (losses)
        """
        if method == 'historical':
            var = -np.quantile(returns, alpha)
            es = -returns[returns < -var].mean()
        elif method == 'parametric':
            mu = returns.mean()
            sigma = returns.std()
            z_alpha = norm.ppf(alpha)
            var = -(mu + z_alpha * sigma)
            es = -(mu - sigma * norm.pdf(z_alpha) / alpha)
        elif method == 'fhs':
            # Filtered Historical Simulation
            # Scale historical returns by current vol / historical vol
            current_vol = returns.ewm(span=21).std().iloc[-1]
            hist_vols = returns.ewm(span=21).std()
            scaled_returns = returns * (current_vol / hist_vols)
            var = -np.quantile(scaled_returns, alpha)
            es = -scaled_returns[scaled_returns < -var].mean()
        else:
            raise ValueError("Method must be 'historical', 'parametric', or 'fhs'")

        return var, es

    def compute_drawdown(self, nav: pd.Series) -> pd.Series:
        """Compute drawdown series from NAV."""
        rolling_max = nav.cummax()
        drawdown = (nav - rolling_max) / rolling_max
        return drawdown

    def atr_stop_signal(
        self,
        prices: pd.DataFrame,
        positions: pd.DataFrame,
        entry_prices: pd.DataFrame,
        n_atr: int = 14
    ) -> pd.DataFrame:
        """
        Compute ATR stop-loss signal. Returns a multiplier [0, 1]
        that reduces positions when stop-loss is triggered.
        """
        # True Range
        high = prices.add_prefix('H_') # Assume prices is close; use proxy
        low = prices.sub(prices.diff().abs()) # Approximate

        # Simplified: use absolute daily return * price
        tr = prices.diff().abs()
        atr = tr.ewm(span=n_atr, adjust=False).mean()

        # Check if current adverse move exceeds ATR stop
        adverse_move = (prices - entry_prices).abs()
        atr_units_moved = adverse_move / atr.replace(0, np.nan)

        # Stop-loss multiplier: 0 if stopped out, 1 otherwise
        stop_triggered = atr_units_moved > self.atr_mult
        stop_multiplier = (~stop_triggered).astype(float)
        return stop_multiplier

    def drawdown_control(
        self,
        nav: pd.Series,
        positions: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Scale down positions as drawdown increases.
        Uses a linear ramp from DD=10% (full size) to DD=25% (flat).
        """
        dd = self.compute_drawdown(nav)
        current_dd = dd.iloc[-1]

        if current_dd > -0.10:
            scale = 1.0
        elif current_dd > -self.max_dd_limit:
            # Linear ramp-down
            scale = 1.0 - (abs(current_dd) - 0.10) / (self.max_dd_limit - 0.10)
        else:
            scale = 0.0 # Flat book if max DD exceeded

        return positions * scale

    def crash_protection_overlay(
        self,
        positions: pd.DataFrame,
        vix: pd.Series,
        market_return_12m: pd.Series,
        crowding_index: Optional[pd.Series] = None
    ) -> Tuple[pd.DataFrame, pd.Series]:
        """
        Apply crash protection overlay based on regime indicators.

        Returns
        -------
        Tuple[pd.DataFrame, pd.Series]
            (Scaled positions, Regime scale factor)
        """
        # Initialise scale at 1.0
        regime_scale = pd.Series(1.0, index=positions.index)

        # VIX-based reduction
        vix_aligned = vix.reindex(positions.index, method='ffill')
        high_vol = vix_aligned > self.crash_vix
        regime_scale[high_vol] *= 0.50

        # Bear market reduction
        bear_market = market_return_12m.reindex(positions.index, method='ffill') < -0.20
        regime_scale[bear_market] *= 0.30

        # Crowding reduction (if available)
        if crowding_index is not None:
            crowd_aligned = crowding_index.reindex(positions.index, method='ffill')
            high_crowd = crowd_aligned > crowd_aligned.rolling(252).quantile(0.90)
            regime_scale[high_crowd] *= 0.70

        # Apply scale to positions
        scaled_positions = positions.multiply(regime_scale, axis=0)

        return scaled_positions, regime_scale

    def portfolio_risk_report(
        self,
        returns: pd.Series,
        positions: pd.DataFrame,
        asset_returns: pd.DataFrame,
        factor_returns: pd.DataFrame
    ) -> dict:
        """
        Generate a comprehensive portfolio risk report.
        """
        ann = 252

        # Basic metrics
        ann_ret = returns.mean() * ann
        ann_vol = returns.std() * np.sqrt(ann)
        sharpe = ann_ret / ann_vol

        # Drawdown analysis
        nav = (1 + returns).cumprod()
        dd = self.compute_drawdown(nav)
        max_dd = dd.min()

        # VaR and ES
        var_99, es_99 = self.compute_var_es(returns, 0.01, 'historical')
        var_95, es_95 = self.compute_var_es(returns, 0.05, 'historical')

        # Factor exposures (OLS regression)
        X = factor_returns.reindex(returns.index).dropna()
        y = returns.reindex(X.index)
        X_mat = np.column_stack([np.ones(len(X)), X.values])
        betas = np.linalg.lstsq(X_mat, y.values, rcond=None)[0]

        report = {
            'Annual Return': f'{ann_ret:.2%}',
            'Annual Volatility': f'{ann_vol:.2%}',
            'Sharpe Ratio': f'{sharpe:.3f}',
            'Max Drawdown': f'{max_dd:.2%}',
            'Calmar Ratio': f'{ann_ret/abs(max_dd):.3f}',
            'Skewness': f'{returns.skew():.3f}',
            'Excess Kurtosis': f'{returns.kurt():.3f}',
            '99% VaR (Daily)': f'{var_99:.2%}',
            '99% ES (Daily)': f'{es_99:.2%}',
            '95% VaR (Daily)': f'{var_95:.2%}',
            '95% ES (Daily)': f'{es_95:.2%}',
            'Factor Alpha (Monthly)': f'{betas[0]*ann:.2%}',
            'Market Beta': f'{betas[1]:.3f}' if len(betas) > 1 else 'N/A',
        }

        return report

    def compute_risk_contributions(
        self,
        weights: pd.Series,
        cov_matrix: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Compute marginal and component risk contributions for each asset.
        """
        Sigma_w = cov_matrix.values @ weights.values
        port_vol = np.sqrt(weights.values @ Sigma_w)

        # Marginal contribution to risk (MCTR)
        mctr = Sigma_w / port_vol

        # Component contribution to risk (CTR)
        ctr = weights.values * mctr

        # Percentage contribution
        pct_ctr = ctr / port_vol

        return pd.DataFrame({
            'Weight': weights.values,
            'MCTR': mctr,
            'CTR': ctr,
            'Pct_CTR': pct_ctr
        }, index=weights.index)

