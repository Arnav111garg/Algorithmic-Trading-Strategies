import numpy as np
import pandas as pd
from typing import Optional
from scipy.optimize import minimize
from scipy.linalg import pinv

class MomentumPortfolioOptimiser:
    """
    Institutional-grade momentum portfolio optimiser.
    Solves mean-variance optimisation with transaction costs,
    factor exposure constraints, and leverage limits.
    """

    def __init__(
        self,
        gamma: float = 2.0,            # Risk aversion
        max_leverage: float = 2.0,     # Max sum |w|
        min_weight: float = -0.05,     # Max short per asset
        max_weight: float = 0.05,      # Max long per asset
        tc_lambda: float = 0.001,      # Transaction cost rate (10 bps)
        shrinkage: float = 0.1,        # Ledoit-Wolf shrinkage intensity
    ):
        self.gamma = gamma
        self.max_leverage = max_leverage
        self.min_weight = min_weight
        self.max_weight = max_weight
        self.tc_lambda = tc_lambda
        self.shrinkage = shrinkage

    def ledoit_wolf_shrinkage(self, returns: pd.DataFrame) -> np.ndarray:
        """
        Apply Ledoit-Wolf analytical shrinkage to sample covariance.
        """
        T, N = returns.shape
        S = returns.cov().values * 252  # Annualised sample covariance

        # Constant correlation target
        corr = returns.corr().values
        avg_corr = (corr.sum() - N) / (N * (N - 1))
        std = np.sqrt(np.diag(S))
        F = avg_corr * np.outer(std, std)
        np.fill_diagonal(F, np.diag(S))

        # Ledoit-Wolf optimal alpha
        alpha = self.shrinkage  # Use fixed shrinkage (analytical is more complex)

        return (1 - alpha) * S + alpha * F

    def optimise(
        self,
        signals: pd.Series,
        returns: pd.DataFrame,
        current_weights: Optional[pd.Series] = None,
        factor_exposures: Optional[pd.DataFrame] = None,
        factor_limits: Optional[pd.Series] = None
    ) -> pd.Series:
        """
        Solve the momentum portfolio optimisation problem.

        Parameters
        ----------
        signals : pd.Series
            Expected return signals (e.g., momentum z-scores)
        returns : pd.DataFrame
            Historical returns for covariance estimation (T x N)
        current_weights : pd.Series, optional
            Current portfolio for TC calculation
        factor_exposures : pd.DataFrame, optional
            Factor loadings (N x K) for factor exposure constraints
        factor_limits : pd.Series, optional
            Max absolute factor exposure limits (K,)

        Returns
        -------
        pd.Series
            Optimal portfolio weights
        """
        N = len(signals)
        assets = signals.index

        # Estimate covariance matrix
        ret_aligned = returns[assets].dropna()
        Sigma = self.ledoit_wolf_shrinkage(ret_aligned)

        # Normalise signals to [-1, +1]
        sig_std = signals.std()
        if sig_std > 0:
            mu = signals.values / sig_std
        else:
            mu = np.zeros(N)

        # Current weights (for transaction cost calculation)
        w0 = np.zeros(N) if current_weights is None else current_weights.values

        def objective(w):
            # Expected return contribution
            ret_contrib = -w @ mu
            # Risk contribution
            risk_contrib = 0.5 * self.gamma * w @ Sigma @ w
            # Transaction cost
            tc = self.tc_lambda * np.sum(np.abs(w - w0))
            return ret_contrib + risk_contrib + tc

        def gradient(w):
            return -mu + self.gamma * (Sigma @ w) + self.tc_lambda * np.sign(w - w0)

        # Constraints
        constraints = [
            # Dollar-neutral constraint
            {'type': 'eq', 'fun': lambda w: np.sum(w)},
        ]

        # Factor exposure constraints
        if factor_exposures is not None and factor_limits is not None:
            B = factor_exposures[assets].values  # K x N
            for k in range(B.shape[0]):
                constraints.append({
                    'type': 'ineq',
                    'fun': lambda w, k=k: factor_limits.iloc[k] - np.abs(B[k] @ w)
                })

        # Bounds: position limits
        bounds = [(self.min_weight, self.max_weight)] * N

        # Leverage constraint (additional inequality)
        constraints.append({
            'type': 'ineq',
            'fun': lambda w: self.max_leverage - np.sum(np.abs(w))
        })

        # Solve
        result = minimize(
            objective,
            x0=w0,  # Warm start from current portfolio
            jac=gradient,
            method='SLSQP',
            bounds=bounds,
            constraints=constraints,
            options={'ftol': 1e-12, 'maxiter': 2000}
        )

        if not result.success:
            print(f"Warning: optimisation did not converge: {result.message}")

        return pd.Series(result.x, index=assets)

    def compute_ic(
        self,
        signals: pd.DataFrame,
        forward_returns: pd.DataFrame,
        n_periods: int = 1
    ) -> pd.Series:
        """
        Compute Information Coefficient (IC) for signal evaluation.
        IC = Spearman rank correlation between signal and subsequent return.
        """
        from scipy.stats import spearmanr

        ics = []
        forward = forward_returns.shift(-n_periods)

        for date in signals.index:
            if date not in forward.index:
                continue
            sig = signals.loc[date].dropna()
            fwd = forward.loc[date].reindex(sig.index).dropna()
            common = sig.index.intersection(fwd.index)
            if len(common) < 20:
                continue

            ic, _ = spearmanr(sig[common].values, fwd[common].values)
            ics.append({'date': date, 'IC': ic})

        if not ics:
            return pd.Series()

        ic_series = pd.DataFrame(ics).set_index('date')['IC']

        return pd.Series({
            'Mean IC': ic_series.mean(),
            'IC Std': ic_series.std(),
            'ICIR': ic_series.mean() / ic_series.std() if ic_series.std() > 0 else 0,
            'IC > 0 Pct': (ic_series > 0).mean(),
            'IC t-stat': ic_series.mean() / (ic_series.std() / np.sqrt(len(ic_series))) if ic_series.std() > 0 else 0
        })

    def hrp_weights(self, returns: pd.DataFrame) -> pd.Series:
        """
        Hierarchical Risk Parity weights (López de Prado, 2016).
        """
        from scipy.cluster.hierarchy import linkage, leaves_list
        from scipy.spatial.distance import squareform

        corr = returns.corr()
        dist = np.sqrt(0.5 * (1 - corr))

        # Hierarchical clustering
        link = linkage(squareform(dist.values), method='ward')
        leaf_order = leaves_list(link)

        # Recursive bisection
        assets = returns.columns[leaf_order].tolist()
        cov = returns.cov().values * 252
        vols = np.sqrt(np.diag(cov))

        def get_ivp_weights(assets_subset, all_assets):
            """Inverse-variance weights for a subset."""
            indices = [all_assets.index(a) for a in assets_subset]
            sub_vols = vols[indices]
            w = 1.0 / (sub_vols ** 2)
            return w / w.sum()

        weights_dict = {a: 1.0 for a in assets}

        def recursive_bisect(asset_list):
            if len(asset_list) == 1:
                return
            mid = len(asset_list) // 2
            left = asset_list[:mid]
            right = asset_list[mid:]

            # Sub-portfolio variances
            left_w = get_ivp_weights(left, assets)
            right_w = get_ivp_weights(right, assets)

            left_idx = [assets.index(a) for a in left]
            right_idx = [assets.index(a) for a in right]

            def sub_vol(subset_w, subset_idx):
                sub_cov = cov[np.ix_(subset_idx, subset_idx)]
                return subset_w @ sub_cov @ subset_w

            var_left = sub_vol(left_w, left_idx)
            var_right = sub_vol(right_w, right_idx)

            alpha = 1 - var_left / (var_left + var_right)

            for a in left:
                weights_dict[a] *= alpha
            for a in right:
                weights_dict[a] *= (1 - alpha)

            recursive_bisect(left)
            recursive_bisect(right)

        recursive_bisect(assets)

        w = pd.Series(weights_dict)
        return w / w.sum()

