@dataclass
class MomentumConfig:
    """Configuration for institutional momentum system."""
    # Universe
    n_assets: int = 500
    min_market_cap: float = 1e9 # $1B minimum

    # Signal
    formation_months: int = 12
    skip_months: int = 1
    signal_type: str = 'residual' # 'raw', 'residual', 'industry'

    # Volatility
    vol_target: float = 0.10
    vol_window: int = 63
    vol_estimator: str = 'ewma'

    # Portfolio
    gamma: float = 2.0
    max_leverage: float = 2.0
    max_position: float = 0.02
    rebal_freq: str = 'M'

    # Risk
    max_drawdown: float = 0.20
    var_limit_daily: float = 0.02
    crash_protection: bool = True

    # Transaction costs
    tc_rate: float = 0.001 # 10 bps
    market_impact_kappa: float = 0.5


class InstitutionalMomentumSystem:
    """
    Production-grade momentum system combining:
    - Multi-signal momentum alpha
    - GARCH volatility scaling
    - Regime-aware position sizing
    - MVO with transaction costs
    - Drawdown control
    - Real-time risk monitoring
    """

    def __init__(self, config: MomentumConfig):
        self.config = config
        self._universe = None
        self._signal_cache = {}
        self._risk_model = None

    def generate_alpha(
        self,
        prices: pd.DataFrame,
        financials: Optional[pd.DataFrame] = None,
        analyst_revisions: Optional[pd.DataFrame] = None
    ) -> pd.DataFrame:
        """
        Generate multi-factor momentum alpha signal.
        Returns combined signal with IC-weighted combination.
        """
        signals = {}
        ic_weights = {}

        # 1. Raw price momentum (12-1 month)
        raw_mom = self._raw_momentum(prices, self.config.formation_months)
        signals['raw_12_1'] = raw_mom
        ic_weights['raw_12_1'] = 0.04 # Historical IC estimate

        # 2. 6-month momentum
        raw_6m = self._raw_momentum(prices, 6)
        signals['raw_6_1'] = raw_6m
        ic_weights['raw_6_1'] = 0.03

        # 3. 52-week high ratio (George & Hwang, 2004)
        high_52w = prices.rolling(252).max()
        signals['high_52w'] = prices / high_52w.replace(0, np.nan) - 1
        ic_weights['high_52w'] = 0.04

        # 4. Earnings momentum (if available)
        if analyst_revisions is not None:
            sue = self._earnings_momentum(analyst_revisions)
            signals['earnings_mom'] = sue
            ic_weights['earnings_mom'] = 0.08

        # Combine with IC weights
        combined = pd.DataFrame()
        total_ic = sum(ic_weights.values())
        for name, sig in signals.items():
            # Standardise each signal
            sig_std = sig.sub(sig.mean(axis=1), axis=0).div(
                sig.std(axis=1), axis=0
            )
            weight = ic_weights[name] / total_ic
            combined = combined.add(sig_std * weight, fill_value=0)

        return combined

    def _raw_momentum(
        self,
        prices: pd.DataFrame,
        formation_months: int
    ) -> pd.DataFrame:
        """Compute raw momentum signal."""
        log_ret = np.log(prices / prices.shift(1))
        formation_days = formation_months * 21
        skip_days = self.config.skip_months * 21

        # Skip last 'skip_days'
        formation_ret = log_ret.shift(skip_days).rolling(
            formation_days - skip_days
        ).sum()

        return formation_ret

    def _earnings_momentum(
        self,
        analyst_revisions: pd.DataFrame
    ) -> pd.DataFrame:
        """
        Standardised Unexpected Earnings (SUE) signal.
        """
        # 3-month consensus EPS revision
        revision = analyst_revisions.pct_change(3)
        # Standardise by trailing vol of revision
        sue = revision / revision.rolling(12).std().replace(0, np.nan)
        return sue

    def run_full_pipeline(
        self,
        prices: pd.DataFrame,
        vix: pd.Series,
        market_cap: pd.DataFrame,
        dates: Optional[pd.DatetimeIndex] = None
    ) -> Dict:
        """
        Execute the full institutional momentum pipeline.

        Returns
        -------
        Dict with keys: 'weights', 'returns', 'metrics', 'risk_report'
        """
        logger.info("Starting institutional momentum pipeline")

        # Step 1: Universe selection
        logger.info("Step 1: Universe selection")
        universe = self._select_universe(prices, market_cap)

        # Step 2: Generate alpha signals
        logger.info("Step 2: Generating alpha signals")
        alpha = self.generate_alpha(prices[universe])

        # Step 3: Regime detection
        logger.info("Step 3: Regime detection")
        log_ret = np.log(prices[universe] / prices[universe].shift(1))
        regime_scale = self._detect_regime(log_ret, vix)

        # Step 4: Volatility estimation
        logger.info("Step 4: Volatility estimation")
        vol = log_ret.ewm(
            span=self.config.vol_window, adjust=False
        ).std() * np.sqrt(252)

        # Step 5: Covariance matrix (factor model)
        logger.info("Step 5: Computing covariance matrix")
        # Use 3-month rolling covariance (simplified; use Barra in production)
        cov = log_ret.rolling(63).cov().dropna()

        # Step 6: Portfolio optimisation (monthly)
        logger.info("Step 6: Portfolio optimisation")
        rebal_dates = pd.date_range(
            log_ret.index[252], log_ret.index[-1], freq='M'
        )

        all_weights = {}
        prev_weights = pd.Series(0.0, index=universe)

        for date in rebal_dates:
            if date not in alpha.index:
                continue

            sig = alpha.loc[date].dropna()

            # Get recent return history for covariance
            hist_end = date
            hist_start = hist_end - pd.DateOffset(months=12)
            hist_ret = log_ret.loc[hist_start:hist_end, sig.index].dropna(axis=1)
            if hist_ret.shape[0] < 60 or hist_ret.shape[1] < 10:
                continue

            # Apply regime scale
            scale = regime_scale.loc[date] if date in regime_scale.index else 1.0
            sig_scaled = sig * scale

            # Optimise
            try:
                optimiser = MomentumPortfolioOptimiser(
                    gamma=self.config.gamma,
                    max_leverage=self.config.max_leverage,
                    max_weight=self.config.max_position,
                    min_weight=-self.config.max_position,
                    tc_lambda=self.config.tc_rate
                )

                weights = optimiser.optimise(
                    signals=sig_scaled,
                    returns=hist_ret,
                    current_weights=prev_weights.reindex(sig.index).fillna(0)
                )

                all_weights[date] = weights
                prev_weights = weights

            except Exception as e:
                logger.warning(f"Optimisation failed for {date}: {e}")
                all_weights[date] = prev_weights

        # Step 7: Compute portfolio returns
        logger.info("Step 7: Computing portfolio returns")
        weights_df = pd.DataFrame(all_weights).T.reindex(log_ret.index).ffill()
        portfolio_ret = (weights_df.shift(1) * log_ret).sum(axis=1)

        # Step 8: Risk report
        logger.info("Step 8: Generating risk report")
        risk_mgr = MomentumRiskManager(
            vol_target=self.config.vol_target,
            max_drawdown_limit=self.config.max_drawdown
        )

        # Factor returns (market, value, momentum) for attribution
        mkt_ret = log_ret.mean(axis=1) # Equal-weighted market
        factor_ret = pd.DataFrame({'Market': mkt_ret})

        metrics = risk_mgr.portfolio_risk_report(
            returns=portfolio_ret,
            positions=weights_df,
            asset_returns=log_ret,
            factor_returns=factor_ret
        )

        logger.info("Pipeline complete")
        logger.info("=" * 50)
        for k, v in metrics.items():
            logger.info(f" {k:25s}: {v}")

        return {
            'weights': weights_df,
            'returns': portfolio_ret,
            'metrics': metrics,
            'regime_scale': regime_scale
        }

    def _select_universe(
        self,
        prices: pd.DataFrame,
        market_cap: pd.DataFrame
    ) -> List[str]:
        """Select liquid, investable universe."""
        # Filter by minimum market cap (latest available)
        latest_mcap = market_cap.iloc[-1].dropna()
        eligible = latest_mcap[
            latest_mcap >= self.config.min_market_cap
        ].index

        # Filter by sufficient price history
        min_history = 252 + self.config.formation_months * 21
        sufficient_history = prices[eligible].dropna(
            thresh=min_history, axis=0
        ).columns

        return sufficient_history.tolist()[:self.config.n_assets]

    def _detect_regime(
        self,
        returns: pd.DataFrame,
        vix: pd.Series
    ) -> pd.Series:
        """
        Simple VIX + market return based regime detection.
        Returns a scale factor [0.25, 1.0] indicating
        momentum-friendliness of current regime.
        """
        mkt_ret = returns.mean(axis=1)
        mkt_ret_12m = mkt_ret.rolling(252).sum()
        vix_aligned = vix.reindex(returns.index, method='ffill')

        scale = pd.Series(1.0, index=returns.index)
        # Bear market: reduce to 30%
        bear = (mkt_ret_12m < -0.20) & (vix_aligned > 30)
        scale[bear] = 0.30

        # High vol but not full bear: reduce to 50%
        high_vol = (vix_aligned > 25) & ~bear
        scale[high_vol] = 0.50

        return scale

