import numpy as np
import pandas as pd
from statsmodels.tsa.stattools import adfuller, kpss, coint
from statsmodels.tsa.vector_ar.vecm import coint_johansen
from hurst import compute_Hc
import warnings
warnings.filterwarnings('ignore')

class StatisticalFoundations:
    """
    Complete toolkit for mean-reversion statistical testing.
    Senior quant standard: always run battery of tests.
    """

    def __init__(self, series: pd.Series, name: str = "series"):
        self.series = series.dropna()
        self.name = name
        self.n = len(self.series)

    def adf_test(self, max_lags: int = None, regression: str = 'c') -> dict:
        """
        Augmented Dickey-Fuller test.
        regression: 'n' (none), 'c' (constant), 'ct' (constant + trend)
        """
        if max_lags is None:
            # Schwert (1989) rule of thumb
            max_lags = int(12 * (self.n / 100) ** 0.25)

        result = adfuller(self.series, maxlag=max_lags, regression=regression, autolag='AIC')
        return {
            'test_stat': result[0],
            'p_value': result[1],
            'n_lags': result[2],
            'n_obs': result[3],
            'critical_values': result[4],
            'stationary': result[1] < 0.05
        }

    def kpss_test(self, regression: str = 'c', nlags: str = 'auto') -> dict:
        """
        KPSS test: H0 = stationarity (opposite of ADF!).
        """
        stat, p_val, lags, crit = kpss(self.series, regression=regression, nlags=nlags)
        return {
            'test_stat': stat,
            'p_value': p_val,
            'n_lags': lags,
            'critical_values': crit,
            'stationary': p_val > 0.05  # KPSS: fail to reject H0 = stationary
        }

    def hurst_exponent(self) -> dict:
        """
        Compute Hurst exponent via R/S analysis.
        """
        H, c, data = compute_Hc(self.series.values, kind='price', simplified=True)
        interpretation = (
            'mean-reverting' if H < 0.45 else
            'random-walk' if H < 0.55 else
            'trending'
        )
        return {'H': H, 'c': c, 'interpretation': interpretation}

    def variance_ratio_test(self, k: int = 2) -> dict:
        """
        Lo-MacKinlay variance ratio test.
        VR(k) < 1 implies mean reversion.
        """
        rets = self.series.pct_change().dropna()
        T = len(rets)
        mu = rets.mean()

        # Single-period variance
        sigma2_1 = ((rets - mu) ** 2).sum() / (T - 1)

        # k-period variance
        rets_k = self.series.pct_change(k).dropna()
        m = k * (T - k + 1) * (1 - k / T)
        sigma2_k = ((rets_k - k * mu) ** 2).sum() / m

        vr = sigma2_k / (k * sigma2_1)
        return {'VR': vr, 'mean_reverting': vr < 1.0}

    def half_life_estimation(self) -> dict:
        """
        Estimate OU half-life via AR(1) regression.
        """
        y = self.series.values
        y_lag = y[:-1]
        y_curr = y[1:]

        # OLS: y_t = alpha + phi * y_{t-1} + eps
        X = np.column_stack([np.ones(len(y_lag)), y_lag])
        beta = np.linalg.lstsq(X, y_curr, rcond=None)[0]
        phi = beta[1]

        if phi >= 1.0 or phi <= 0:
            return {'half_life': np.inf, 'phi': phi, 'kappa': 0}

        kappa = -np.log(phi)  # daily speed of reversion
        half_life = np.log(2) / kappa
        residuals = y_curr - X @ beta
        sigma_eps = residuals.std()
        sigma_inf = sigma_eps / np.sqrt(1 - phi ** 2)  # stationary vol

        return {
            'phi': phi,
            'kappa': kappa,
            'half_life_days': half_life,
            'stationary_vol': sigma_inf,
            'long_run_mean': beta[0] / (1 - phi)
        }

    def full_battery_report(self) -> dict:
        """
        Run complete stationarity test battery.
        Gold standard for production deployment.
        """
        adf = self.adf_test()
        kpss_res = self.kpss_test()
        hurst = self.hurst_exponent()
        vr = self.variance_ratio_test()
        hl = self.half_life_estimation()

        print(f"\n{'='*60}")
        print(f" STATIONARITY BATTERY REPORT: {self.name}")
        print(f"{'='*60}")
        print(f"ADF Statistic: {adf['test_stat']:.4f} (p={adf['p_value']:.4f}) -> {'STATIONARY' if adf['stationary'] else 'NON-STATIONARY'}")
        print(f"KPSS Statistic: {kpss_res['test_stat']:.4f} (p={kpss_res['p_value']:.4f}) -> {'STATIONARY' if kpss_res['stationary'] else 'NON-STATIONARY'}")
        print(f"Hurst Exponent: {hurst['H']:.4f} -> {hurst['interpretation']}")
        print(f"Variance Ratio (2): {vr['VR']:.4f} -> {'mean-reverting' if vr['mean_reverting'] else 'momentum'}")
        print(f"Half-Life: {hl['half_life_days']:.2f} days")
        print(f"Stationary Volatility: {hl['stationary_vol']:.6f}")

        # Consensus
        signals = [adf['stationary'], kpss_res['stationary'], hurst['H'] < 0.5, vr['mean_reverting']]
        confidence = sum(signals) / len(signals)
        print(f"\nMEAN-REVERSION CONFIDENCE: {confidence * 100:.0f}%")
        if confidence >= 0.75:
            print("=> TRADEABLE mean-reverting signal detected")
        elif confidence >= 0.5:
            print("=> MARGINAL evidence; proceed with caution")
        else:
            print("=> INSUFFICIENT evidence; do not trade mean reversion")

        return hl

# Cointegration test for pairs trading outside the class
def test_cointegration(Y: pd.Series, Z: pd.Series, significance: float = 0.05) -> dict:
    """
    Engle-Granger cointegration test between two series.
    Returns hedge ratio, spread properties, and test result.
    """
    # Engle-Granger test
    score, pvalue, _ = coint(Y, Z)

    # Estimate hedge ratio via OLS
    X = np.column_stack([np.ones(len(Z)), Z.values])
    beta = np.linalg.lstsq(X, Y.values, rcond=None)[0]
    hedge_ratio = beta[1]
    alpha = beta[0]

    # Compute spread
    spread = Y - hedge_ratio * Z - alpha

    # Estimate OU parameters of spread
    sf = StatisticalFoundations(spread, name="Spread")
    hl_info = sf.half_life_estimation()

    return {
        'cointegrated': pvalue < significance,
        'p_value': pvalue,
        'coint_score': score,
        'hedge_ratio': hedge_ratio,
        'spread_mean': spread.mean(),
        'spread_std': spread.std(),
        'half_life_days': hl_info['half_life_days'],
        'spread': spread
    }

