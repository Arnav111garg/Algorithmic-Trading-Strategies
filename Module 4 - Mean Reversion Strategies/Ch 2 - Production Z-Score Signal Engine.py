import numpy as np
import pandas as pd
from scipy import stats

class ZScoreSignalEngine:
    """
    Production-grade z-score signal generator with multiple methods.
    """

    def __init__(self, spread: pd.Series):
        self.spread = spread

    def rolling_zscore(self, window: int) -> pd.Series:
        """Standard rolling z-score."""
        mu = self.spread.rolling(window, min_periods=window // 2).mean()
        sigma = self.spread.rolling(window, min_periods=window // 2).std()
        return (self.spread - mu) / sigma.replace(0, np.nan)

    def ewma_zscore(self, halflife: float) -> pd.Series:
        """Exponentially weighted z-score."""
        mu = self.spread.ewm(halflife=halflife).mean()
        sigma = self.spread.ewm(halflife=halflife).std()
        return (self.spread - mu) / sigma.replace(0, np.nan)

    def kalman_zscore(self, Q: float = 1e-5, R: float = 1e-3) -> pd.Series:
        """
        Kalman filter z-score.
        Q: process noise (how fast true mean changes)
        R: observation noise (measurement error of spread)
        """
        n = len(self.spread)
        values = self.spread.values

        # Initialize
        mu_hat = np.zeros(n)
        P = np.zeros(n)
        z_kf = np.zeros(n)

        mu_hat[0] = values[0]
        P[0] = 1.0

        for t in range(1, n):
            # Predict
            mu_pred = mu_hat[t - 1]
            P_pred = P[t - 1] + Q

            # Innovation
            innov = values[t] - mu_pred
            innov_var = P_pred + R

            # Kalman gain
            K = P_pred / innov_var

            # Update
            mu_hat[t] = mu_pred + K * innov
            P[t] = (1 - K) * P_pred

            # Z-score
            z_kf[t] = innov / np.sqrt(innov_var)

        return pd.Series(z_kf, index=self.spread.index, name='kalman_zscore')

    def generate_signals(
        self,
        z: pd.Series,
        entry_threshold: float = 2.0,
        exit_threshold: float = 0.5,
        stop_threshold: float = 3.5
    ) -> pd.DataFrame:
        """
        Convert z-score to trading signals.

        Returns DataFrame with:
        - signal: +1 (long), -1 (short), 0 (flat)
        - entry: +1 (buy entry), -1 (sell entry), 0 (no entry)
        """
        position = pd.Series(0.0, index=z.index)
        entry_signal = pd.Series(0.0, index=z.index)

        current_pos = 0

        for i, (idx, z_val) in enumerate(z.items()):
            if np.isnan(z_val):
                position.iloc[i] = 0
                continue

            if current_pos == 0:
                # Flat: look for entry
                if z_val < -entry_threshold:
                    current_pos = 1  # go long spread
                    entry_signal.iloc[i] = 1
                elif z_val > entry_threshold:
                    current_pos = -1  # go short spread
                    entry_signal.iloc[i] = -1

            elif current_pos == 1:
                # Long spread: exit if reverted or stop
                if z_val >= -exit_threshold:
                    current_pos = 0
                elif z_val < -stop_threshold:
                    current_pos = 0  # stop loss

            elif current_pos == -1:
                # Short spread: exit if reverted or stop
                if z_val <= exit_threshold:
                    current_pos = 0
                elif z_val > stop_threshold:
                    current_pos = 0  # stop loss

            position.iloc[i] = current_pos

        return pd.DataFrame({
            'zscore': z,
            'position': position,
            'entry_signal': entry_signal
        })

    def optimize_thresholds(
        self,
        z: pd.Series,
        spread_returns: pd.Series,
        entry_grid: list = None,
        exit_grid: list = None
    ) -> dict:
        """
        Walk-forward optimization of entry/exit thresholds.
        Uses Sharpe ratio as objective.
        """
        if entry_grid is None:
            entry_grid = [1.0, 1.5, 2.0, 2.5, 3.0]
        if exit_grid is None:
            exit_grid = [0.0, 0.25, 0.5, 0.75, 1.0]

        best_sharpe = -np.inf
        best_params = {}

        for entry in entry_grid:
            for exit_t in exit_grid:
                if exit_t >= entry:
                    continue

                signals_df = self.generate_signals(z, entry, exit_t)
                pos = signals_df['position'].shift(1)  # 1-period delay
                strat_rets = pos * spread_returns

                if strat_rets.std() == 0:
                    continue

                sharpe = strat_rets.mean() / strat_rets.std() * np.sqrt(252)

                if sharpe > best_sharpe:
                    best_sharpe = sharpe
                    best_params = {
                        'entry': entry,
                        'exit': exit_t,
                        'sharpe': sharpe
                    }

        return best_params

