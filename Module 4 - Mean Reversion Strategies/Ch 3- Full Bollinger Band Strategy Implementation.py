import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

class BollingerMeanReversionSystem:
    """
    Production Bollinger Band mean-reversion system.
    Includes squeeze detection, double bands, and band walk filter.
    """

    def __init__(self,
                 window: int = 20,
                 k1: float = 1.0,
                 k2: float = 2.0,
                 atr_window: int = 14):
        self.window = window
        self.k1 = k1
        self.k2 = k2
        self.atr_window = atr_window

    def compute_bollinger_bands(self, prices: pd.Series) -> pd.DataFrame:
        """Compute SMA, bands, %B, and bandwidth."""
        sma = prices.rolling(self.window).mean()
        std = prices.rolling(self.window).std()

        return pd.DataFrame({
            'sma': sma,
            'std': std,
            'upper_1': sma + self.k1 * std,
            'lower_1': sma - self.k1 * std,
            'upper_2': sma + self.k2 * std,
            'lower_2': sma - self.k2 * std,
            'pct_b': (prices - (sma - self.k2 * std)) / (4 * std),
            'bandwidth': 4 * std / sma,
            'zscore': (prices - sma) / std
        })

    def compute_atr(self, high: pd.Series, low: pd.Series, close: pd.Series) -> pd.Series:
        """Average True Range calculation."""
        hl = high - low
        hc = (high - close.shift(1)).abs()
        lc = (low - close.shift(1)).abs()
        tr = pd.concat([hl, hc, lc], axis=1).max(axis=1)
        return tr.ewm(span=self.atr_window, adjust=False).mean()

    def compute_keltner_channels(self, prices: pd.Series,
                                 high: pd.Series, low: pd.Series,
                                 close: pd.Series, kc_mult: float = 1.5) -> pd.DataFrame:
        """Keltner Channels for squeeze detection."""
        ema = prices.ewm(span=self.window, adjust=False).mean()
        atr = self.compute_atr(high, low, close)
        return pd.DataFrame({
            'kc_upper': ema + kc_mult * atr,
            'kc_lower': ema - kc_mult * atr
        })

    def detect_squeeze(self, bb: pd.DataFrame, kc: pd.DataFrame) -> pd.Series:
        """TTM Squeeze: BB inside KC."""
        return (
            (bb['upper_2'] < kc['kc_upper']) &
            (bb['lower_2'] > kc['kc_lower'])
        ).astype(int)

    def detect_band_walk(self, prices: pd.Series, bb: pd.DataFrame, lookback: int = 3) -> pd.Series:
        """
        Detect when price is walking along a band (trending).
        Returns: +1 (upper walk), -1 (lower walk), 0 (no walk)
        """
        upper_touch = (prices > bb['upper_1']).astype(int)
        lower_touch = (prices < bb['lower_1']).astype(int)

        upper_walk = upper_touch.rolling(lookback).sum() == lookback
        lower_walk = lower_touch.rolling(lookback).sum() == lookback

        walk = pd.Series(0, index=prices.index)
        walk[upper_walk] = 1
        walk[lower_walk] = -1
        return walk

    def generate_signals(self, prices: pd.Series,
                         high: pd.Series = None,
                         low: pd.Series = None) -> pd.DataFrame:
        """
        Generate complete mean-reversion signals with all filters.
        """
        bb = self.compute_bollinger_bands(prices)

        # Initialize signal columns
        signal = pd.Series(0.0, index=prices.index)
        position = pd.Series(0.0, index=prices.index)

        # Band walk filter (requires high/low if available)
        if high is not None and low is not None:
            kc = self.compute_keltner_channels(prices, high, low, prices)
            squeeze = self.detect_squeeze(bb, kc)
            band_walk = self.detect_band_walk(prices, bb)
        else:
            squeeze = pd.Series(0, index=prices.index)
            band_walk = pd.Series(0, index=prices.index)

        current_pos = 0
        for i in range(self.window, len(prices)):
            z = bb['zscore'].iloc[i]
            is_squeeze = squeeze.iloc[i]
            walk = band_walk.iloc[i]

            if np.isnan(z):
                continue

            # Trend filter: don't trade mean reversion during band walk
            if walk != 0:
                # Exit position if we're in a band walk
                current_pos = 0
                position.iloc[i] = 0
                continue

            if current_pos == 0:
                # Entry logic: prefer entries during / after a squeeze
                entry_mult = 1.2 if is_squeeze else 1.0

                if z < -(self.k2 * entry_mult * 0.9):
                    current_pos = 1
                    signal.iloc[i] = 1
                elif z > (self.k2 * entry_mult * 0.9):
                    current_pos = -1
                    signal.iloc[i] = -1

            elif current_pos == 1:
                # Exit long: price reverted to upper k1 band or beyond
                if z >= -0.5:
                    current_pos = 0
                elif z < -3.5:  # stop loss
                    current_pos = 0

            elif current_pos == -1:
                # Exit short: price reverted
                if z <= 0.5:
                    current_pos = 0
                elif z > 3.5:  # stop loss
                    current_pos = 0

            position.iloc[i] = current_pos

        result = bb.copy()
        result['price'] = prices
        result['signal'] = signal
        result['position'] = position
        result['squeeze'] = squeeze
        result['band_walk'] = band_walk

        return result

    def backtest(self, prices: pd.Series, transaction_cost: float = 0.001) -> pd.DataFrame:
        """
        Simple backtest with transaction costs.
        """
        df = self.generate_signals(prices)
        # Returns
        price_rets = prices.pct_change()
        pos_shifted = df['position'].shift(1)  # trade at next open

        # Transaction costs on trades
        trades = df['position'].diff().abs()
        tc = trades * transaction_cost

        strategy_rets = pos_shifted * price_rets - tc

        # Performance metrics
        total_ret = (1 + strategy_rets).prod() - 1
        ann_ret = (1 + strategy_rets.mean()) ** 252 - 1
        ann_vol = strategy_rets.std() * np.sqrt(252)
        sharpe = ann_ret / ann_vol if ann_vol > 0 else 0

        drawdown = (strategy_rets.cumsum() - strategy_rets.cumsum().expanding().max())
        max_dd = drawdown.min()

        n_trades = (trades > 0).sum() / 2

        print(f" Bollinger MR Backtest Results:")
        print(f" Total Return: {total_ret * 100:.2f}%")
        print(f" Annual Return: {ann_ret * 100:.2f}%")
        print(f" Annual Vol: {ann_vol * 100:.2f}%")
        print(f" Sharpe Ratio: {sharpe:.3f}")
        print(f" Max Drawdown: {max_dd * 100:.2f}%")
        print(f" Num Trades: {n_trades:.0f}")

        df['strategy_returns'] = strategy_rets
        df['cumulative_pnl'] = (1 + strategy_rets).cumprod() - 1

        return df

