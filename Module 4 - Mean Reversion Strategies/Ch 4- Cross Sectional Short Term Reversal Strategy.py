import numpy as np
import pandas as pd

class ShortTermReversionStrategy:
    """
    Cross-sectional short-term reversal strategy.
    Classic stat-arb: long losers, short winners.
    """
    def __init__(
        self,
        lookback: int = 5,       # holding / signal days
        holding: int = 5,
        top_pct: float = 0.2,    # top / bottom 20% decile
        min_price: float = 5.0,  # liquidity filter
        min_adv: float = 1e6     # min avg daily volume ($)
    ):
        self.lookback = lookback
        self.holding = holding
        self.top_pct = top_pct
        self.min_price = min_price
        self.min_adv = min_adv

    def compute_signals(
        self,
        returns: pd.DataFrame,
        prices: pd.DataFrame = None,
        volumes: pd.DataFrame = None
    ) -> pd.DataFrame:
        """
        Compute cross-sectional reversal weights.

        returns: DataFrame of shape (T, N) with stock returns
        """
        # Past-lookback returns (signal)
        past_returns = returns.rolling(self.lookback).sum()

        # Liquidity filter
        if prices is not None and volumes is not None:
            adv = (prices * volumes).rolling(20).mean()
            liquid = (prices > self.min_price) & (adv > self.min_adv)
        else:
            liquid = pd.DataFrame(True, index=returns.index, columns=returns.columns)

        # Cross-sectional ranking (universe-neutral signal)
        weights = pd.DataFrame(index=returns.index, columns=returns.columns, dtype=float)

        for date in returns.index:
            # Apply liquidity filter
            universe = liquid.loc[date]
            eligible = universe[universe].index

            if len(eligible) < 10:
                weights.loc[date] = 0.0
                continue

            r = past_returns.loc[date, eligible].dropna()
            n = len(r)

            if n < 10:
                weights.loc[date] = 0.0
                continue

            # Rank-based portfolio (more robust than raw returns)
            ranks = r.rank(pct=True)

            # Long bottom quintile, short top quintile
            w = pd.Series(0.0, index=r.index)
            top_mask = ranks > (1 - self.top_pct)
            bot_mask = ranks < self.top_pct

            n_long = bot_mask.sum()
            n_short = top_mask.sum()

            if n_long > 0 and n_short > 0:
                w[bot_mask] = 1.0 / n_long   # equal weight longs
                w[top_mask] = -1.0 / n_short # equal weight shorts

            # Dollar-neutral: ensure sum of weights near 0
            w = w - w.mean()

            # Unit gross exposure
            if w.abs().sum() > 0:
                w = w / w.abs().sum()

            weights.loc[date, eligible] = w

        return weights.fillna(0.0)

    def compute_performance(
        self,
        weights: pd.DataFrame,
        next_returns: pd.DataFrame,
        transaction_cost_bps: float = 5.0
    ) -> pd.DataFrame:
        """
        Compute strategy performance.
        transaction_cost_bps: cost per side in basis points
        """
        tc = transaction_cost_bps / 10000

        # Gross PnL
        gross_pnl = (weights.shift(1) * next_returns).sum(axis=1)

        # Transaction costs (turnover-based)
        turnover = weights.diff().abs().sum(axis=1)
        tc_drag = turnover * tc

        net_pnl = gross_pnl - tc_drag

        # Performance stats
        ann_factor = 252
        ann_ret = net_pnl.mean() * ann_factor
        ann_vol = net_pnl.std() * np.sqrt(ann_factor)
        sharpe = ann_ret / ann_vol if ann_vol > 0 else 0

        # Information Coefficient (IC)
        ic_series = weights.shift(1).corrwith(next_returns, axis=1)
        avg_ic = ic_series.mean()
        ic_ir = avg_ic / ic_series.std() if ic_series.std() > 0 else 0

        print("Short-Term Reversal Performance:")
        print(f"  Ann. Return (net): {ann_ret * 100:.2f}%")
        print(f"  Ann. Volatility : {ann_vol * 100:.2f}%")
        print(f"  Sharpe Ratio    : {sharpe:.3f}")
        print(f"  Avg IC          : {avg_ic:.4f}")
        print(f"  IC IR           : {ic_ir:.3f}")
        print(f"  Avg Daily Turnover: {turnover.mean() * 100:.1f}%")

        return pd.DataFrame({
            'gross_pnl': gross_pnl,
            'tc_drag': tc_drag,
            'net_pnl': net_pnl,
            'turnover': turnover,
            'ic': ic_series
        })

