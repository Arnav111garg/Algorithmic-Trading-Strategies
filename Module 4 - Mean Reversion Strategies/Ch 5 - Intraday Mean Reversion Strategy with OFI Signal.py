import numpy as np
import pandas as pd
from typing import Optional

class IntradayReversionStrategy:
    """
    Intraday mean reversion with Order Flow Imbalance and VWAP signals.
    Designed for minute-bar or tick data.
    """

    def __init__(self,
                 vwap_z_entry: float = 1.5,
                 vwap_z_exit: float = 0.3,
                 ofi_lookback: int = 10,
                 vol_window: int = 30,
                 stop_z: float = 3.0,
                 no_trade_first_min: int = 10,
                 no_trade_last_min: int = 15):
        self.vwap_z_entry = vwap_z_entry
        self.vwap_z_exit = vwap_z_exit
        self.ofi_lookback = ofi_lookback
        self.vol_window = vol_window
        self.stop_z = stop_z
        self.no_trade_first_min = no_trade_first_min
        self.no_trade_last_min = no_trade_last_min

    def compute_vwap(self, df: pd.DataFrame) -> pd.Series:
        """
        Compute running intraday VWAP.
        df must have columns: 'close', 'volume', 'date' (or DatetimeIndex)
        """
        df = df.copy()
        df['cum_vol'] = df.groupby(df.index.date)['volume'].cumsum()
        df['cum_pv'] = df.groupby(df.index.date).apply(
            lambda x: (x['close'] * x['volume']).cumsum()
        ).reset_index(level=0, drop=True)
        return df['cum_pv'] / df['cum_vol']

    def compute_ofi(self, bid: pd.Series, ask: pd.Series,
                    bid_vol: pd.Series, ask_vol: pd.Series) -> pd.Series:
        """
        Order Flow Imbalance:
        OFI = (bid_vol * I[bid >= prev_bid]) - (ask_vol * I[ask <= prev_ask])
        Approximation using bid/ask changes.
        """
        delta_bid = bid.diff()
        delta_ask = ask.diff()

        ofi = (bid_vol * (delta_bid >= 0).astype(int) -
               ask_vol * (delta_ask <= 0).astype(int))

        # Normalize by rolling window
        ofi_rolling = ofi.rolling(self.ofi_lookback).sum()
        ofi_vol_norm = ofi_rolling / (bid_vol + ask_vol).rolling(self.ofi_lookback).sum()

        return ofi_vol_norm

    def compute_intraday_vol(self, returns: pd.Series) -> pd.Series:
        """
        Rolling intraday volatility (parkinson or standard deviation).
        """
        return returns.rolling(self.vol_window).std()

    def generate_signals(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Generate intraday mean reversion signals.

        Expected df columns: close, volume, minute_of_day
        Optional: bid, ask, bid_vol, ask_vol
        """
        df = df.copy()

        # VWAP
        df['vwap'] = self.compute_vwap(df)

        # Intraday returns and vol
        df['ret'] = df['close'].pct_change()
        df['intraday_vol'] = self.compute_intraday_vol(df['ret'])

        # VWAP z-score
        df['vwap_dev'] = df['close'] - df['vwap']
        df['vwap_z'] = df['vwap_dev'] / (df['intraday_vol'] * df['close'] + 1e-10)

        # Time filters
        total_mins = df.index.hour * 60 + df.index.minute
        market_open_mins = 9 * 60 + 30
        market_close_mins = 16 * 60

        no_trade = (
            (total_mins < market_open_mins + self.no_trade_first_min) |
            (total_mins > market_close_mins - self.no_trade_last_min)
        )

        # Position logic
        position = pd.Series(0.0, index=df.index)
        current_pos = 0

        for i in range(self.vol_window, len(df)):
            z = df['vwap_z'].iloc[i]

            if np.isnan(z) or no_trade.iloc[i]:
                position.iloc[i] = 0
                current_pos = 0
                continue

            if current_pos == 0:
                if z > self.vwap_z_entry:
                    current_pos = -1  # short: price above VWAP
                elif z < -self.vwap_z_entry:
                    current_pos = 1  # long: price below VWAP

            elif current_pos == 1:
                if z >= -self.vwap_z_exit or z < -self.stop_z:
                    current_pos = 0

            elif current_pos == -1:
                if z <= self.vwap_z_exit or z > self.stop_z:
                    current_pos = 0

            position.iloc[i] = current_pos

        df['position'] = position
        df['strategy_ret'] = position.shift(1) * df['ret']

        return df

    def analyze_gap_fills(self, daily_data : pd.DataFrame) -> pd.DataFrame:
        """
        Analyze opening gap fill statistics.
        daily_data: DataFrame with 'open', 'close', 'high', 'low'
        """
        gaps = (daily_data['open'] - daily_data['close'].shift(1)) / daily_data['close'].shift(1)

        # Did the gap fill ?
        # Gap up filled: daily low <= previous close
        # Gap down filled: daily high >= previous close
        gap_up = gaps > 0
        gap_down = gaps < 0

        prev_close = daily_data['close'].shift(1)

        fill_up = gap_up & (daily_data['low'] <= prev_close)
        fill_down = gap_down & (daily_data['high'] >= prev_close)
        filled = fill_up | fill_down

        results = pd.DataFrame({
            'gap': gaps,
            'gap_abs': gaps.abs(),
            'filled': filled,
            'gap_direction': np.where(gap_up, 'up', np.where(gap_down, 'down', 'flat'))
        })

        # Statistics
        for direction in ['up', 'down']:
            subset = results[results['gap_direction'] == direction]
            fill_rate = subset['filled'].mean()
            avg_gap = subset['gap_abs'].mean()
            print(f"Gap {direction.upper()}: fill rate = {fill_rate:.1%}, avg gap = {avg_gap:.2%}")

        return results

