import numpy as np
import pandas as pd
from hmmlearn import hmm
from sklearn.preprocessing import StandardScaler

class RegimeDetector:
    """
    HMM-based regime detection for adaptive mean-reversion strategies.
    """

    def __init__(self, n_regimes: int = 2, n_iter: int = 100, covariance_type: str = 'full'):
        self.n_regimes = n_regimes
        self.n_iter = n_iter
        self.covariance_type = covariance_type
        self.model = None
        self.scaler = StandardScaler()

    def fit(self, returns: pd.Series, features: pd.DataFrame = None):
        """
        Fit HMM to return series.
        features : Optional additional features (volatility, volume, etc.)
        """
        # Prepare features
        base_features = pd.DataFrame({
            'returns': returns,
            'abs_returns': returns.abs(),
            'rolling_vol': returns.rolling(20).std()
        }).dropna()

        if features is not None:
            base_features = pd.concat([base_features, features], axis=1).dropna()

        X = self.scaler.fit_transform(base_features.values)

        # Fit HMM
        self.model = hmm.GaussianHMM(
            n_components=self.n_regimes,
            covariance_type=self.covariance_type,
            n_iter=self.n_iter,
            random_state=42
        )
        self.model.fit(X)

        # Decode states
        states = self.model.predict(X)

        # Label regimes by volatility (low vol = MR regime)
        state_vols = {}
        for s in range(self.n_regimes):
            mask = states == s
            state_vols[s] = base_features['rolling_vol'][mask].mean()

        # Sort states: 0 = lowest vol (most MR), K-1 = highest vol
        self.vol_order = sorted(state_vols.keys(), key=lambda k: state_vols[k])

        return base_features.index, states

    def predict_regime(self, returns: pd.Series, features: pd.DataFrame = None) -> pd.DataFrame:
        """
        Predict regime probabilities for new data.
        Returns DataFrame with regime probabilities and dominant regime.
        """
        base_features = pd.DataFrame({
            'returns': returns,
            'abs_returns': returns.abs(),
            'rolling_vol': returns.rolling(20).std()
        })

        if features is not None:
            base_features = pd.concat([base_features, features], axis=1)

        base_features = base_features.dropna()
        X = self.scaler.transform(base_features.values)

        probs = self.model.predict_proba(X)
        states = self.model.predict(X)

        result = pd.DataFrame(
            probs,
            index=base_features.index,
            columns=[f'P_state_{i}' for i in range(self.n_regimes)]
        )
        result['regime'] = states

        # MR probability = probability of being in low-vol state
        mr_state = self.vol_order[0]
        result['mr_probability'] = result[f'P_state_{mr_state}']
        result['trending_probability'] = 1 - result['mr_probability']

        return result


class AdaptiveMeanReversionStrategy:
    """
    Mean-reversion strategy that adapts to detected regime.
    Scales position size by regime probability.
    """

    def __init__(
        self,
        base_entry_z: float = 2.0,
        base_exit_z: float = 0.5,
        min_mr_prob: float = 0.4,
        max_position: float = 1.0
    ):
        self.base_entry_z = base_entry_z
        self.base_exit_z = base_exit_z
        self.min_mr_prob = min_mr_prob
        self.max_position = max_position

    def compute_adaptive_position(self, zscore: pd.Series, mr_probability: pd.Series) -> pd.Series:
        """
        Compute position scaled by regime probability.

        Position = sign(trade) * |trade_size| * mr_probability
        """
        position = pd.Series(0.0, index=zscore.index)
        current_pos = 0

        for i in range(len(zscore)):
            z = zscore.iloc[i]
            mr_prob = mr_probability.iloc[i]

            if np.isnan(z) or np.isnan(mr_prob):
                position.iloc[i] = 0
                continue

            # Adjust thresholds: widen in low-confidence regimes
            adj_factor = 1 + 0.5 * (1 - mr_prob)  # widen by up to 50%
            entry_z = self.base_entry_z * adj_factor
            exit_z = self.base_exit_z

            # Position logic
            if current_pos == 0:
                if mr_prob >= self.min_mr_prob:
                    if z < -entry_z:
                        current_pos = 1
                    elif z > entry_z:
                        current_pos = -1
            elif current_pos == 1:
                if z >= -exit_z or mr_prob < self.min_mr_prob * 0.5:
                    current_pos = 0
            elif current_pos == -1:
                if z <= exit_z or mr_prob < self.min_mr_prob * 0.5:
                    current_pos = 0

            # Scale by MR probability
            position.iloc[i] = current_pos * mr_prob * self.max_position

        return position

    def vix_regime_filter(self, vix: pd.Series) -> pd.Series:
        """
        Simple VIX-based regime filter.
        Returns scaling factor [0, 1].
        """
        scale = pd.Series(1.0, index=vix.index)
        scale[vix >= 20] = 0.6
        scale[vix >= 25] = 0.3
        scale[vix >= 35] = 0.0  # No mean reversion in crisis
        return scale

