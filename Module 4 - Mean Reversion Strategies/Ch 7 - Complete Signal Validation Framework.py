import numpy as np
import pandas as pd
from scipy import stats
from scipy.stats import norm

class SignalValidator:
    """
    Comprehensive signal validation for mean-reversion strategies.
    Implements IC analysis, walk-forward testing, and multiple-testing correction.
    """

    def compute_ic(self, predictions: pd.DataFrame, realizations: pd.DataFrame) -> pd.Series:
        """
        Compute IC (rank correlation) at each time period.
        predictions, realizations: shape (T, N) - assets as columns
        """
        ic_series = []

        for date in predictions.index:
            pred = predictions.loc[date].dropna()
            real = realizations.loc[date, pred.index].dropna()
            common = pred.index.intersection(real.index)

            if len(common) < 5:
                ic_series.append(np.nan)
                continue

            rho, _ = stats.spearmanr(pred[common], real[common])
            ic_series.append(rho)

        return pd.Series(ic_series, index=predictions.index, name='IC')

    def ic_report(self, ic: pd.Series) -> dict:
        """Full IC diagnostic report."""
        ic_clean = ic.dropna()
        mean_ic = ic_clean.mean()
        std_ic = ic_clean.std()
        icir = mean_ic / std_ic if std_ic > 0 else 0

        # t-test: is mean IC significantly different from 0?
        t_stat, p_value = stats.ttest_1samp(ic_clean, 0)

        # IC decay: rolling IC over different horizons
        positive_pct = (ic_clean > 0).mean()

        print(f"\nIC Analysis Report ")
        print(f"{'='*40}")
        print(f" Mean IC: {mean_ic:.4f}")
        print(f"Std IC: {std_ic:.4f}")
        print(f"IC IR: {icir:.4f}")
        print(f"t-stat: {t_stat:.3f} (p={p_value:.4f})")
        print(f"% Positive IC: {positive_pct * 100:.1f}%")

        quality = (
            "EXCELLENT" if abs(icir) > 1.5 else
            "GOOD" if abs(icir) > 1.0 else
            "MODERATE" if abs(icir) > 0.5 else
            "WEAK"
        )
        print(f" Signal Quality: {quality}")

        return {
            'mean_ic': mean_ic,
            'std_ic': std_ic,
            'icir': icir,
            't_stat': t_stat,
            'p_value': p_value,
            'quality': quality
        }

    def walk_forward_validation(self,
                                signal_fn,
                                data: pd.DataFrame,
                                n_folds: int = 5,
                                min_train_periods: int = 252) -> dict:
        """
        Walk-forward validation.
        signal_fn: function (train_data) -> signal (pd.Series)
        """
        T = len(data)
        fold_size = (T - min_train_periods) // n_folds

        oos_returns = []
        is_sharpes = []
        oos_sharpes = []

        for fold in range(n_folds):
            train_end = min_train_periods + fold * fold_size
            test_end = train_end + fold_size

            if test_end > T:
                break

            train = data.iloc[:train_end]
            test = data.iloc[train_end:test_end]

            # Fit on train, evaluate on test
            try:
                is_signal, is_ret = signal_fn(train)
                oos_signal, oos_ret = signal_fn(test)

                is_sr = (is_ret.mean() / is_ret.std() * np.sqrt(252) if is_ret.std() > 0 else 0)
                oos_sr = (oos_ret.mean() / oos_ret.std() * np.sqrt(252) if oos_ret.std() > 0 else 0)

                is_sharpes.append(is_sr)
                oos_sharpes.append(oos_sr)
                oos_returns.extend(oos_ret.tolist())

            except Exception as e:
                print(f" Fold {fold} failed: {e}")
                continue

        # Aggregate OOS performance
        oos_ret_series = pd.Series(oos_returns)
        oos_total_sr = (oos_ret_series.mean() / oos_ret_series.std() * np.sqrt(252) if len(oos_ret_series) > 10 else 0)

        avg_is_sr = np.mean(is_sharpes) if is_sharpes else 0
        decay_ratio = oos_total_sr / avg_is_sr if avg_is_sr != 0 else 0

        result = {
            'avg_is_sharpe': avg_is_sr,
            'oos_sharpe': oos_total_sr,
            'decay_ratio': decay_ratio,
            'n_folds': len(is_sharpes)
        }

        print(f"\nWalk-Forward Validation ")
        print(f"{'='*40}")
        print(f"Avg IS Sharpe: {avg_is_sr:.3f}")
        print(f"OOS Sharpe: {oos_total_sr:.3f}")
        print(f" Decay Ratio: {decay_ratio:.3f}")
        verdict = "PASS" if decay_ratio > 0.5 else "CAUTION" if decay_ratio > 0.3 else "FAIL"
        print(f" Verdict: {verdict}")

        return result

    def deflated_sharpe_ratio(self, sr: float, T: int, n_trials: int,
                              skew: float = 0, kurt: float = 3) -> float:
        """
        Compute Deflated Sharpe Ratio (Bailey & Lopez de Prado, 2014).
        """
        # Benchmark SR: expected max from n_trials noise strategies
        sr_benchmark = norm.ppf(1 - 1/n_trials) * np.sqrt(
            (1 + (1/T) * np.log(n_trials)) / (T - 1)
        )

        # DSR
        numerator = (sr - sr_benchmark) * np.sqrt(T - 1)
        denominator = np.sqrt(1 - skew * sr + (kurt - 1) / 4 * sr ** 2)

        if denominator <= 0:
            return 0.0

        dsr = norm.cdf(numerator / denominator)

        print(f"\nDeflated Sharpe Ratio Analysis ")
        print(f"{'='*40}")
        print(f" Observed SR: {sr:.4f}")
        print(f" Benchmark SR: {sr_benchmark:.4f} ({n_trials} trials)")
        print(f"DSR: {dsr:.4f}")
        print(f" Significant: {'YES (>95%)' if dsr > 0.95 else 'NO'}")

        return dsr

    def benjamini_hochberg(self, p_values: np.ndarray, fdr_level: float = 0.05) -> np.ndarray:
        """
        BH procedure for controlling FDR when testing many pairs.
        Returns boolean array indicating which hypotheses to reject.
        """
        M = len(p_values)
        sorted_idx = np.argsort(p_values)
        sorted_p = p_values[sorted_idx]

        thresholds = np.arange(1, M + 1) / M * fdr_level
        below = sorted_p <= thresholds

        if below.any():
            k_star = np.max(np.where(below)[0])
            reject = np.zeros(M, dtype=bool)
            reject[sorted_idx[:k_star + 1]] = True
        else:
            reject = np.zeros(M, dtype=bool)

        n_rejected = reject.sum()
        print(f"\nBenjamini-Hochberg FDR Correction ")
        print(f"{'='*40}")
        print(f" Total hypotheses: {M}")
        print(f" Rejected at FDR={fdr_level}: {n_rejected} ({n_rejected/M*100:.1f}%) ")

        return reject

