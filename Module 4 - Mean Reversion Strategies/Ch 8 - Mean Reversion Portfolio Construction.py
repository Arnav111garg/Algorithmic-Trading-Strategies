import numpy as np
import pandas as pd
from scipy.optimize import minimize

class MeanReversionPortfolio:
    """
    Portfolio construction and optimization for mean-reversion strategies.
    """

    def __init__(self, target_volatility: float = 0.10,
                 max_pair_weight: float = 0.15,
                 kelly_fraction: float = 0.25):
        self.target_volatility = target_volatility
        self.max_pair_weight = max_pair_weight
        self.kelly_fraction = kelly_fraction

    def compute_kalman_hedge_ratio(self, Y: pd.Series, Z: pd.Series,
                                   delta: float = 1e-4) -> pd.DataFrame:
        """
        Dynamic hedge ratio via Kalman filter.
        State: [alpha, beta]
        """
        n = len(Y)
        y = Y.values
        x = Z.values

        # State: [alpha, beta]
        theta = np.zeros((n, 2))
        P = np.zeros((n, 2, 2))

        theta[0] = [0, 1]  # initial: alpha=0, beta=1
        P[0] = np.eye(2)   # initial uncertainty

        Q = delta / (1 - delta) * np.eye(2)  # state noise

        hedge_ratios = np.zeros(n)
        alphas = np.zeros(n)
        spreads = np.zeros(n)

        for t in range(1, n):
            H = np.array([[1, x[t]]])  # observation matrix

            # Predict
            theta_pred = theta[t-1]
            P_pred = P[t-1] + Q

            # Innovation
            innov = y[t] - H @ theta_pred
            innov_var = H @ P_pred @ H.T + 1.0  # obs noise = 1.0

            # Kalman gain
            K = P_pred @ H.T / innov_var

            # Update
            theta[t] = theta_pred + K.flatten() * innov
            P[t] = (np.eye(2) - K @ H) @ P_pred

            alphas[t] = theta[t, 0]
            hedge_ratios[t] = theta[t, 1]
            spreads[t] = y[t] - theta[t, 0] - theta[t, 1] * x[t]

        return pd.DataFrame({
            'alpha': alphas,
            'hedge_ratio': hedge_ratios,
            'spread': spreads
        }, index=Y.index)

    def inverse_volatility_weights(self, returns: pd.DataFrame,
                                   vol_window: int = 60) -> pd.DataFrame:
        """
        Inverse volatility weights across pairs.
        """
        rolling_vol = returns.rolling(vol_window).std()
        inv_vol = 1.0 / rolling_vol.replace(0, np.nan)
        weights = inv_vol.div(inv_vol.sum(axis=1), axis=0)
        return weights

    def equal_risk_contribution(self, cov_matrix: np.ndarray,
                                 max_iter: int = 1000) -> np.ndarray:
        """
        Equal Risk Contribution (ERC / Risk Parity) weights.
        Spinu (2013) algorithm.
        """
        n = cov_matrix.shape[0]
        w = np.ones(n) / n  # equal weight start

        for _ in range(max_iter):
            # Marginal risk contributions
            sigma_p = np.sqrt(w @ cov_matrix @ w)
            mrc = cov_matrix @ w / sigma_p

            # Risk contributions
            rc = w * mrc

            # Update: scale toward equal risk
            w_new = w * (1.0 / (n * rc / rc.mean()))
            w_new = w_new / w_new.sum()  # normalize

            if np.max(np.abs(w_new - w)) < 1e-8:
                break
            w = w_new

        return w

    def kelly_size(self, expected_return: pd.Series,
                   volatility: pd.Series) -> pd.Series:
        """
        Kelly-optimal position size scaled to target volatility.
        """
        kelly_f = (expected_return / (volatility ** 2)) * self.kelly_fraction

        # Vol-scale to target
        vol_scale = self.target_volatility / volatility
        kelly_f_scaled = np.minimum(kelly_f, vol_scale)

        # Cap individual pair weights
        kelly_f_scaled = np.minimum(kelly_f_scaled, self.max_pair_weight)
        return kelly_f_scaled

    def construct_portfolio(self, pair_signals: pd.DataFrame,
                            pair_returns: pd.DataFrame,
                            method: str = 'erc') -> pd.DataFrame:
        """
        Construct portfolio weights from pair signals and method.
        pair_signals: DataFrame (T, N) - position signals per pair (-1, 0, +1)
        pair_returns: DataFrame (T, N) - spread returns per pair
        method: 'erc', 'inv_vol', 'equal'
        """
        T, N = pair_signals.shape

        if method == 'equal':
            base_weights = pd.DataFrame(
                np.ones((T, N)) / N,
                index=pair_signals.index,
                columns=pair_signals.columns
            )

        elif method == 'inv_vol':
            base_weights = self.inverse_volatility_weights(pair_returns)

        elif method == 'erc':
            # Compute ERC weights using rolling covariance
            rolling_window = 60
            base_weights = pd.DataFrame(index=pair_signals.index,
                                        columns=pair_signals.columns,
                                        dtype=float)

            for i in range(rolling_window, T):
                window_rets = pair_returns.iloc[i - rolling_window : i].dropna(axis=1)

                if window_rets.shape[1] < 2:
                    base_weights.iloc[i] = 1.0 / N
                    continue

                cov = window_rets.cov().values
                # Regularize
                cov = cov + 1e-6 * np.eye(len(cov))

                try:
                    w_erc = self.equal_risk_contribution(cov)
                    for j, col in enumerate(window_rets.columns):
                        base_weights.loc[pair_signals.index[i], col] = w_erc[j]
                except:
                    base_weights.iloc[i] = 1.0 / N

            base_weights = base_weights.fillna(1.0 / N)

        # Apply signals to weights (long / short direction)
        portfolio_weights = base_weights * pair_signals
        # Normalize to target volatility
        port_vol = (portfolio_weights * pair_returns.shift(-1)).sum(axis=1).std()
        if port_vol > 0:
            portfolio_weights = portfolio_weights * (self.target_volatility / (port_vol * np.sqrt(252)))

        return portfolio_weights

