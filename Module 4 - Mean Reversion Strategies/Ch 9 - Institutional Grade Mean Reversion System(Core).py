import numpy as np
import pandas as pd
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple
from enum import Enum

class TradeStatus(Enum):
    FLAT = 0
    LONG = 1
    SHORT = -1

@dataclass
class PairBook:
    """
    Tracks a single pair's state in the mean-reversion book.
    """
    name: str
    hedge_ratio: float
    spread_mean: float
    spread_std: float
    half_life: float
    status: TradeStatus = TradeStatus.FLAT
    entry_z: float = 0.0
    entry_spread: float = 0.0
    pnl: float = 0.0
    max_pnl: float = 0.0
    current_drawdown: float = 0.0

    def update_pnl(self, spread: float) -> float:
        """Update P&L for current spread value."""
        if self.status == TradeStatus.FLAT:
            return 0.0

        trade_pnl = (spread - self.entry_spread) * int(self.status.value)
        self.pnl = trade_pnl
        self.max_pnl = max(self.max_pnl, trade_pnl)
        self.current_drawdown = trade_pnl - self.max_pnl
        return trade_pnl


class InstitutionalMRSystem:
    """
    Institutional-grade mean-reversion system.

    Features:
    - Multi-pair universe management
    - Factor neutralization
    - Dynamic regime filtering
    - Sophisticated risk controls
    - Transaction cost optimization
    """

    def __init__(
        self,
        # Signal params
        entry_z: float = 2.0,
        exit_z: float = 0.5,
        stop_z: float = 3.5,

        # Risk params
        max_port_vol: float = 0.08, # 8% annual target
        max_pair_gross_exp: float = 0.05, # 5% per pair
        max_total_gross_exp: float = 1.5, # 150% total
        max_pair_drawdown: float = 0.02, # 2% DD stops pair
        max_port_drawdown: float = 0.05, # 5% DD halves book

        # Regime params
        vix_halt_threshold: float = 35.0,
        min_regime_prob: float = 0.45,

        # Cost params
        transaction_cost_bps: float = 3.0,
        min_holding_periods: int = 2
    ):
        self.entry_z = entry_z
        self.exit_z = exit_z
        self.stop_z = stop_z
        self.max_port_vol = max_port_vol
        self.max_pair_gross_exp = max_pair_gross_exp
        self.max_total_gross_exp = max_total_gross_exp
        self.max_pair_drawdown = max_pair_drawdown
        self.max_port_drawdown = max_port_drawdown
        self.vix_halt_threshold = vix_halt_threshold
        self.min_regime_prob = min_regime_prob
        self.transaction_cost_bps = transaction_cost_bps / 10000
        self.min_holding_periods = min_holding_periods

        # State
        self.pair_books: Dict[str, PairBook] = {}
        self.portfolio_hwm: float = 0.0
        self.portfolio_pnl: float = 0.0
        self.halted: bool = False
        self.periods_in_trade: Dict[str, int] = {}

    def register_pair(
        self, name: str, hedge_ratio: float,
        spread_mean: float, spread_std: float,
        half_life: float
    ) -> None:
        """Register a pair in the system."""
        self.pair_books[name] = PairBook(
            name=name,
            hedge_ratio=hedge_ratio,
            spread_mean=spread_mean,
            spread_std=spread_std,
            half_life=half_life
        )
        self.periods_in_trade[name] = 0

    def compute_z_score(self, pair_name: str, spread: float) -> float:
        """Compute z-score for a pair."""
        book = self.pair_books[pair_name]
        return (spread - book.spread_mean) / book.spread_std

    def check_risk_limits(
        self, vix: float, portfolio_dd: float
    ) -> Tuple[bool, str]:
        """
        Check all risk limits. Returns (can_trade, reason).
        """
        if vix >= self.vix_halt_threshold:
            return False, f"VIX ={vix:.1f} >= halt threshold {self.vix_halt_threshold}"

        if portfolio_dd <= -self.max_port_drawdown:
            return False, f"Portfolio DD ={portfolio_dd:.2%} exceeded {self.max_port_drawdown:.2%}"

        # Compute total gross exposure
        total_exp = sum(
            1.0 for b in self.pair_books.values()
            if b.status != TradeStatus.FLAT
        ) * self.max_pair_gross_exp

        if total_exp >= self.max_total_gross_exp:
            return False, f"Max gross exposure reached: {total_exp:.1%}"

        return True, "OK"

    def on_bar(
        self,
        spread_updates: Dict[str, float],
        vix: float,
        mr_probabilities: Dict[str, float] = None
    ) -> Dict[str, float]:
        """
        Process one time bar for all pairs.
        Returns target positions (in spread units) for each pair.
        """
        portfolio_dd = min(0.0, self.portfolio_pnl - self.portfolio_hwm)
        can_trade, risk_reason = self.check_risk_limits(vix, portfolio_dd)

        if not can_trade and portfolio_dd <= -self.max_port_drawdown:
            # Emergency: flatten all positions by 50%
            print(f"RISK ALERT: {risk_reason} - Scaling down book by 50%")
            self.halted = True

        target_positions = {}
        total_pnl_delta = 0.0

        for pair_name, spread in spread_updates.items():
            book = self.pair_books.get(pair_name)
            if book is None:
                continue

            z = self.compute_z_score(pair_name, spread)

            # Update P&L
            pair_pnl = book.update_pnl(spread)

            # Regime filter
            mr_prob = 1.0
            if mr_probabilities:
                mr_prob = mr_probabilities.get(pair_name, 0.5)

            tradeable = (
                can_trade and
                mr_prob >= self.min_regime_prob and
                not self.halted
            )

            # Per-pair drawdown stop
            if book.current_drawdown <= -self.max_pair_drawdown:
                if book.status != TradeStatus.FLAT:
                    print(f"Pair stop-loss triggered: {pair_name} DD ={book.current_drawdown:.4f}")
                book.status = TradeStatus.FLAT
                self.periods_in_trade[pair_name] = 0

            # Trading logic
            new_position = 0.0

            if book.status == TradeStatus.FLAT:
                if tradeable:
                    if z < -self.entry_z:
                        book.status = TradeStatus.LONG
                        book.entry_z = z
                        book.entry_spread = spread
                        book.pnl = 0.0
                        book.max_pnl = 0.0
                        self.periods_in_trade[pair_name] = 1
                        new_position = self.max_pair_gross_exp * mr_prob

                    elif z > self.entry_z:
                        book.status = TradeStatus.SHORT
                        book.entry_z = z
                        book.entry_spread = spread
                        book.pnl = 0.0
                        book.max_pnl = 0.0
                        self.periods_in_trade[pair_name] = 1
                        new_position = -self.max_pair_gross_exp * mr_prob

            elif book.status == TradeStatus.LONG:
                self.periods_in_trade[pair_name] += 1

                # Min holding period check
                min_held = self.periods_in_trade[pair_name] >= self.min_holding_periods

                if (z >= -self.exit_z and min_held) or z < -self.stop_z:
                    book.status = TradeStatus.FLAT
                    self.periods_in_trade[pair_name] = 0
                    new_position = 0.0
                else:
                    new_position = self.max_pair_gross_exp * mr_prob

            elif book.status == TradeStatus.SHORT:
                self.periods_in_trade[pair_name] += 1
                min_held = self.periods_in_trade[pair_name] >= self.min_holding_periods

                if (z <= self.exit_z and min_held) or z > self.stop_z:
                    book.status = TradeStatus.FLAT
                    self.periods_in_trade[pair_name] = 0
                    new_position = 0.0
                else:
                    new_position = -self.max_pair_gross_exp * mr_prob

            # Scale down if halted
            if self.halted:
                new_position *= 0.5

            target_positions[pair_name] = new_position
            total_pnl_delta += pair_pnl

        # Update portfolio P&L
        self.portfolio_pnl += total_pnl_delta
        self.portfolio_hwm = max(self.portfolio_hwm, self.portfolio_pnl)

        return target_positions

    def get_portfolio_summary(self) -> pd.DataFrame:
        """Summary of all pair books."""
        records = []
        for name, book in self.pair_books.items():
            records.append({
                'pair': name,
                'status': book.status.name,
                'half_life': book.half_life,
                'current_pnl': book.pnl,
                'max_pnl': book.max_pnl,
                'drawdown': book.current_drawdown,
                'periods_held': self.periods_in_trade.get(name, 0)
            })
        return pd.DataFrame(records).set_index('pair')

