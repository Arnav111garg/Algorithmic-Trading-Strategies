import numpy as np
import pandas as pd
from statsmodels.tsa.stattools import adfuller

# ---- Ornstein-Uhlenbeck simulation (Euler-Maruyama) ----------------------
def simulate_ou(kappa, mu, sigma, S0, T, dt=1/252):
    """
    Simulate OU process. kappa=mean-reversion speed, mu=long-run mean,
    sigma=diffusion, S0=initial value, T=years, dt=time step.
    """
    N = int(T / dt)
    S = np.zeros(N)
    S[0] = S0
    sqrt_dt = np.sqrt(dt)
    for t in range(1, N):
        S[t] = S[t-1] + kappa*(mu - S[t-1])*dt + sigma*np.random.randn()*sqrt_dt
    return S

# ---- OU parameter estimation via OLS (Vasicek regression) ----------------
def fit_ou_ols(spread, dt=1/252):
    """
    Regress dS = a + b*S_lag + eps.
    Returns kappa, mu, sigma, half_life (in days).
    """
    y = np.diff(spread) # dS[t]
    x = spread[:-1] # S[t]
    b, a = np.polyfit(x, y, 1) # y = b*x + a
    kappa = -b / dt
    mu = -a / b
    sigma = np.std(y - (a + b*x)) / np.sqrt(dt)
    half_life = np.log(2) / max(kappa, 1e-10)
    return {
        "kappa": kappa,
        "mu": mu,
        "sigma": sigma,
        "half_life_years": half_life,
        "half_life_days": half_life * 252
    }

# ---- Performance metrics -------------------------------------------------
def perf_metrics(returns, rf=0.04, freq=252):
    mu = returns.mean() * freq
    sig = returns.std(ddof=1) * np.sqrt(freq)
    sr = (mu - rf) / sig
    neg = returns[returns < 0]
    sig_d = neg.std(ddof=1) * np.sqrt(freq) if len(neg) > 1 else np.nan
    sortino = (mu - rf) / sig_d
    cum = np.cumprod(1 + returns)
    roll_max = np.maximum.accumulate(cum)
    max_dd = ((cum - roll_max) / roll_max).min()
    calmar = (cum[-1]**(freq/len(returns)) - 1) / abs(max_dd)
    return pd.Series({
        "Ann Return": mu,
        "Ann Vol": sig,
        "Sharpe": sr,
        "Sortino": sortino,
        "Max DD": max_dd,
        "Calmar": calmar,
        "Hit Rate": (returns > 0).mean()
    })

# Example
np.random.seed(42)
spread = simulate_ou(kappa=50, mu=0.0, sigma=0.05, S0=0.1, T=2)
params = fit_ou_ols(spread)
print(f"Kappa={params['kappa']:.1f} Half-life={params['half_life_days']:.1f}d")

# ADF test for stationarity
adf = adfuller(spread, maxlag=1)
print(f"ADF stat={adf[0]:.3f} p-value={adf[1]:.4f}")

