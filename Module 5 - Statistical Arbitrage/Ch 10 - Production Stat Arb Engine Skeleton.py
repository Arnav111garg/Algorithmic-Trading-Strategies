import numpy as np
import pandas as pd
from dataclasses import dataclass, field
from typing import Dict, Optional

@dataclass
class StrategyConfig:
    """Complete strategy configuration."""
    min_adv_M: float = 10.0 # Minimum ADV ($M)
    min_price: float = 5.0 # Minimum stock price
    n_pca_factors: int = 15 # PCA factors
    pca_window_days: int = 252 # Rolling PCA window
    ou_window_days: int = 60 # OU estimation window
    entry_s_score: float = 1.25 # Entry s-score threshold
    exit_s_score: float = 0.75 # Exit s-score threshold
    stop_s_score: float = 3.5 # Stop-loss s-score
    max_gross_leverage: float = 6.0
    max_net_leverage: float = 0.10
    max_position_pct: float = 0.02 # Max |weight| per stock
    max_drawdown_pct: float = 0.05
    daily_var_limit_pct: float = 0.01
    max_adv_participation: float = 0.10
    target_aum_M: float = 500.0

class ProductionStatArbEngine:
    """
    Production-grade statistical arbitrage engine.
    Pipeline: data -> signal -> optimisation -> execution -> risk.
    """
    def __init__(self, config: StrategyConfig):
        self.config = config
        self.al_model = None
        self.risk_mgr = StatArbRiskManager(
            aum=config.target_aum_M * 1e6,
            max_drawdown=config.max_drawdown_pct)
        self.positions: Dict[str, float] = {}
        self.pnl_log = []

    def initialise(self, prices: pd.DataFrame, adv: pd.Series) -> None:
        """Full model training on historical data."""
        log_ret = np.log(prices).diff().dropna()
        filtered = prices.columns[adv > self.config.min_adv_M*1e6]
        log_ret = log_ret[filtered]
        self.al_model = AvellanedaLee(
            n_factors=self.config.n_pca_factors,
            entry_s=self.config.entry_s_score,
            exit_s=self.config.exit_s_score)
        self.al_model.fit(log_ret)
        print(f"Model fitted. Universe: {len(filtered)} stocks. "
              f"Factors: {self.config.n_pca_factors}.")

    def step(self, prices: pd.DataFrame, adv: pd.Series,
             Sigma: np.ndarray, B: np.ndarray) -> dict:
        """Execute one trading day's signal, portfolio, and risk decisions."""
        log_ret = np.log(prices).diff().dropna()
        s_scores = self.al_model.compute_s_scores(log_ret)
        signals = self.al_model.signals(s_scores)
        # Use latest signal as alpha vector
        latest_signal = signals.iloc[-1]
        alpha = -latest_signal.values # long negative s-scores (cheap)
        # Optimise portfolio
        N = len(alpha)
        result = market_neutral_portfolio(
            alpha=alpha, Sigma=Sigma, B=B,
            lam=2.0, max_lev=self.config.max_gross_leverage/2,
            max_w=self.config.max_position_pct)
        w_opt = result["weights"]
        # Risk check: scale down if daily vol limit breached
        port_var = w_opt.values @ Sigma @ w_opt.values
        port_vol = np.sqrt(port_var)
        if port_vol > self.config.daily_var_limit_pct:
            w_opt *= self.config.daily_var_limit_pct / port_vol
        # Compute orders (vs current positions)
        cur_w = pd.Series(self.positions, dtype=float).reindex(
            prices.columns).fillna(0)
        delta = w_opt - cur_w
        # Cap by ADV participation
        aum = self.risk_mgr.aum
        max_trade = self.config.max_adv_participation * adv
        orders = (delta * aum).clip(-max_trade, max_trade)
        self.positions = w_opt.to_dict()
        return {"s_scores": s_scores.iloc[-1], "weights": w_opt,
                "orders": orders, "gross_lev": w_opt.abs().sum(),
                "net_exp": w_opt.sum(), "port_vol_daily": port_vol}

