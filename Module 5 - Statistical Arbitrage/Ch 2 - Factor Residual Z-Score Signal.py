import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression

def compute_rv_signal(returns, factor_returns, lookback=60, zscore_win=20):
    """
    Compute relative value z-scores for a universe of stocks.
    1. Rolling OLS of stock returns on factors.
    2. Accumulate residuals over zscore_win.
    3. Z-score normalise.

    returns : (T x N) DataFrame of stock returns
    factor_returns: (T x K) DataFrame of factor returns
    """
    T, N = returns.shape
    resid_store = pd.DataFrame(index=returns.index, columns=returns.columns, dtype=float)
    for t in range(lookback, T):
        win = slice(t - lookback, t)
        X = factor_returns.iloc[win].values
        for col in returns.columns:
            y = returns[col].iloc[win].values
            reg = LinearRegression(fit_intercept=True).fit(X, y)
            y_hat = reg.predict(factor_returns.iloc[t:t+1].values)
            resid_store.loc[returns.index[t], col] = returns[col].iloc[t] - y_hat[0]
    # Z-score
    cum_r = resid_store.rolling(zscore_win).sum()
    std_r = resid_store.rolling(zscore_win).std()
    return cum_r / std_r # positive = overvalued (short), negative = long

def portfolio_weights(signals, threshold=1.0):
    """Dollar-neutral portfolio: long z<-threshold, short z>+threshold."""
    weights = pd.DataFrame(0.0, index=signals.index, columns=signals.columns)
    for idx in signals.index:
        sig = signals.loc[idx]
        longs = sig[sig < -threshold]
        shorts = sig[sig > threshold]
        if len(longs) > 0 and len(shorts) > 0:
            w = pd.Series(0.0, index=sig.index)
            w[longs.index] = 1.0 / len(longs)
            w[shorts.index] = -1.0 / len(shorts)
            weights.loc[idx] = w
    return weights

