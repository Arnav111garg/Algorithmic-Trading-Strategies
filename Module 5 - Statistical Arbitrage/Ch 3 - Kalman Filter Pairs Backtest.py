import numpy as np
import pandas as pd

class KalmanFilterHedgeRatio:
    """Dynamic hedge ratio via Kalman filter. State = [alpha, beta]."""
    def __init__(self, delta=1e-5):
        self.Q = delta / (1 - delta) * np.eye(2) # State noise
        self.R = 1.0 # Obs noise
        self.theta = np.zeros(2)
        self.P = np.ones((2,2)) * 1e-3

    def update(self, P_A, P_B):
        H = np.array([1.0, P_B])
        # Predict
        P_pred = self.P + self.Q
        # Innovation
        nu = P_A - H @ self.theta
        S = H @ P_pred @ H.T + self.R
        # Update
        K = P_pred @ H.T / S
        self.theta += K * nu
        self.P = (np.eye(2) - np.outer(K, H)) @ P_pred
        # Adaptive R (tracks innovation variance)
        self.R = 0.99 * self.R + 0.01 * nu**2
        return {"alpha": self.theta[0], "beta": self.theta[1], "spread": nu}

def pairs_backtest(P_A, P_B, entry_z=2.0, exit_z=0.5, stop_z=3.5):
    """Full pairs backtest with Kalman dynamic hedge ratio."""
    kf = KalmanFilterHedgeRatio()
    spreads = []
    for pa, pb in zip(P_A, P_B):
        spreads.append(kf.update(pa, pb)["spread"])
    spreads = np.array(spreads)

    # Rolling z-score
    roll_std = pd.Series(spreads).rolling(20).std().values
    zscore = spreads / (roll_std + 1e-10)

    # Signal
    position = np.zeros(len(zscore))
    pos = 0
    for t in range(20, len(zscore)):
        z = zscore[t]
        if pos == 0:
            if z > entry_z: pos = -1 # spread too wide
            if z < -entry_z: pos = 1 # spread too narrow
        else:
            if abs(z) < exit_z: pos = 0
            if abs(z) > stop_z: pos = 0
        position[t] = pos

    pnl = position * np.concatenate([[0], np.diff(spreads)])
    return pd.DataFrame({"spread": spreads, "zscore": zscore, "position": position, "pnl": pnl})

