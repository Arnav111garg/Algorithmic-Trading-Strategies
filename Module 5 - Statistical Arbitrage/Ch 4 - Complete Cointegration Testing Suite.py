import numpy as np
import pandas as pd
from statsmodels.tsa.stattools import adfuller
from statsmodels.tsa.vector_ar.vecm import coint_johansen

def engle_granger_test(price_A, price_B, significance=0.05):
    """
    Engle-Granger two-step cointegration test on log prices.
    Returns hedge ratio, ADF stat, p-value, residuals, half-life.
    """
    log_A = np.log(price_A.values)
    log_B = np.log(price_B.values)
    beta = np.polyfit(log_B, log_A, 1) # log_A = b*log_B + a
    resid = log_A - np.polyval(beta, log_B)
    adf = adfuller(resid, maxlags=1, regression='c', autolag='AIC')
    # Half-life via AR(1) on residuals
    rho, _ = np.polyfit(resid[:-1], resid[1:], 1)
    hl = -np.log(2) / np.log(abs(rho)) if abs(rho) < 1 else np.inf
    return {"hedge_ratio": round(beta[0], 4),
            "intercept": round(beta[1], 4),
            "residuals": resid,
            "adf_statistic": round(adf[0], 4),
            "p_value": round(adf[1], 4),
            "critical_5pct": adf[4]['5%'],
            "is_cointegrated": adf[1] < significance,
            "half_life_days": round(hl * 252, 1) if hl != np.inf else np.inf}

def johansen_test(prices_df, det_order=0, k_ar_diff=1):
    """
    Johansen cointegration test for multiple assets.
    prices_df : (T x n) DataFrame of log prices.
    det_order : -1 no constant, 0 constant, 1 linear trend.
    """
    result = coint_johansen(prices_df, det_order, k_ar_diff)
    n = prices_df.shape[1]
    print(f"\n{'Johansen Cointegration Test':=^60}")
    print(f"{'r=0?':>6} {'Trace Stat':>12} {'5% CV':>10} {'Reject?':>10}")
    for r in range(n):
        rej = result.lr1[r] > result.cvt[r, 1]
        print(f"{r:>6} {result.lr1[r]:>12.3f} {result.cvt[r,1]:>10.3f} "
              f"{'YES' if rej else 'NO':>10}")
    rank = int((result.lr1 > result.cvt[:, 1]).sum())
    return {"coint_rank_95pct": rank,
            "eigenvalues": result.eig,
            "trace_stats": result.lr1,
            "coint_vectors": result.evec, # columns = coint vectors
            "adj_speed_alpha": result.meth} # pi = alpha * beta^T

