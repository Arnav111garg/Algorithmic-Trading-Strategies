import numpy as np
import pandas as pd
from arch import arch_model
from hmmlearn.hmm import GaussianHMM

class SpreadAnalyzer:
    """Complete spread modeling and signal generation toolkit."""
    def __init__(self, spread):
        self.spread = spread.dropna()

    def fit_garch(self, p=1, q=1):
        """Fit GARCH(p,q); return conditional volatility and AIC."""
        ds = self.spread.diff().dropna() * 100 # % for numerical stability
        model = arch_model(ds, vol='Garch', p=p, q=q, dist='t')
        result = model.fit(disp='off')
        return {"params": result.params.to_dict(),
                "aic": result.aic,
                "bic": result.bic,
                "cond_vol": result.conditional_volatility / 100}

    def fit_hmm(self, n_regimes=2):
        """Fit Gaussian HMM to spread levels; detect mean-shift regimes."""
        X = self.spread.values.reshape(-1, 1)
        m = GaussianHMM(n_components=n_regimes, covariance_type="full",
                        n_iter=500, random_state=42)
        m.fit(X)
        states = m.predict(X)
        means_ = m.means_.flatten()
        variances = np.array([C[0,0] for C in m.covars_])
        return {"hidden_states": states,
                "means": means_, "variances": variances,
                "transition_matrix": m.transmat_,
                "normal_regime": int(np.argmin(variances))}

    def signal(self, entry_z=2.0, exit_z=0.5, roll_win=20, use_garch_scale=True):
        """Generate long/short signal with optional GARCH z-score scaling."""
        roll_mu = self.spread.rolling(roll_win).mean()
        roll_std = self.spread.rolling(roll_win).std()
        if use_garch_scale:
            garch = self.fit_garch()
            cv = pd.Series(garch["cond_vol"], index=self.spread.diff().dropna().index)
            cv = cv.reindex(self.spread.index).bfill()
            roll_std = roll_std * cv / cv.mean() # scale by GARCH vol
        zscore = (self.spread - roll_mu) / roll_std
        signal = pd.Series(0.0, index=self.spread.index)
        pos = 0
        for t in self.spread.index:
            z = zscore.loc[t] if not np.isnan(zscore.loc[t]) else 0
            if pos == 0:
                if z < -entry_z: pos = 1
                elif z > entry_z: pos = -1
            else:
                if abs(z) < exit_z: pos = 0
            signal.loc[t] = pos
        return signal, zscore

