import numpy as np
import pandas as pd
from sklearn.decomposition import PCA

class AvellanedaLee:
    """
    PCA-based Statistical Arbitrage (Avellaneda & Lee 2010).
    Operates on a universe of stocks.
    """
    def __init__(self, n_factors=15, entry_s=1.25, exit_s=0.75):
        self.n_factors = n_factors
        self.entry_s = entry_s
        self.exit_s = exit_s
        self.pca = None
        self.ou_params = {} # {ticker: ou_params dict}

    def fit(self, returns):
        """Fit PCA on historical log returns (T x N DataFrame)."""
        R_std = (returns - returns.mean()) / (returns.std() + 1e-10)
        self.pca = PCA(n_components=self.n_factors)
        self.pca.fit(R_std.values)
        # Factor and residual returns
        F_mat = self.pca.transform(R_std.values)
        reconst = F_mat @ self.pca.components_
        resid = (R_std.values - reconst) * returns.std().values
        self.resid_df = pd.DataFrame(resid, index=returns.index,
                                    columns=returns.columns)
        # Fit OU to cumulative residuals
        for col in returns.columns:
            cum = self.resid_df[col].cumsum().values
            self.ou_params[col] = fit_ou_ols(cum) # from Section 6.1
        return self

    def compute_s_scores(self, returns):
        """Out-of-sample s-scores for each stock."""
        R_std = (returns - returns.mean()) / (returns.std() + 1e-10)
        F_new = self.pca.transform(R_std.values)
        reconst = F_new @ self.pca.components_
        resid = (R_std.values - reconst) * returns.std().values
        resid_df = pd.DataFrame(resid, index=returns.index,
                                columns=returns.columns)
        scores = pd.DataFrame(index=returns.index,
                              columns=returns.columns, dtype=float)
        for col in returns.columns:
            p = self.ou_params.get(col, {})
            k = max(p.get("kappa", 1e-6), 1e-8)
            s = p.get("sigma", 1.0)
            sig_eq = s / np.sqrt(2 * k)
            X = resid_df[col].cumsum().values
            scores[col] = X / (sig_eq + 1e-10)
        return scores

    def signals(self, s_scores):
        """Convert s-scores to long/short position signals."""
        sigs = pd.DataFrame(0.0, index=s_scores.index,
                            columns=s_scores.columns)
        pos = pd.Series(0.0, index=s_scores.columns)
        for t in s_scores.index:
            s = s_scores.loc[t]
            pos[s < -self.entry_s] = 1 # long cheap stocks
            pos[s > self.entry_s] = -1 # short expensive stocks
            pos[(pos>0) & (s>-self.exit_s)] = 0 # exit long
            pos[(pos<0) & (s< self.exit_s)] = 0 # exit short
            sigs.loc[t] = pos.copy()
        return sigs

