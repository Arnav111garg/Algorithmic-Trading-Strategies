import numpy as np
import pandas as pd
import cvxpy as cp

def market_neutral_portfolio(alpha, Sigma, B, lam=2.0, max_lev=2.0, max_w=0.05):
    """
    Factor-neutral mean-variance optimisation.
    alpha : (N,) expected alpha
    Sigma : (N,N) covariance
    B : (N,K) factor exposure matrix
    lam : risk aversion (larger = less risk)
    """
    N, K = B.shape
    w = cp.Variable(N)
    obj = cp.Maximize(w @ alpha - (lam/2) * cp.quad_form(w, Sigma))
    cons = [w @ np.ones(N) == 0, # dollar neutral
            B.T @ w == np.zeros(K), # factor neutral
            cp.norm(w, 1) <= max_lev, # gross leverage
            w >= -max_w, w <= max_w] # position limits
    prob = cp.Problem(obj, cons)
    prob.solve(solver=cp.OSQP, eps_abs=1e-8, eps_rel=1e-8)
    if prob.status not in ["optimal", "optimal_inaccurate"]:
        return {"status": prob.status, "weights": None}
    w_opt = np.array(w.value).flatten()
    ex_var = w_opt @ Sigma @ w_opt
    return {"status": prob.status,
            "weights": pd.Series(w_opt),
            "ex_return": (w_opt @ alpha) * 252,
            "ex_vol": np.sqrt(ex_var * 252),
            "ex_sharpe": (w_opt @ alpha) / np.sqrt(ex_var),
            "factor_resid": np.abs(B.T @ w_opt).max(), # Should be <1e-6
            "gross_lev": np.abs(w_opt).sum(),
            "long_count": (w_opt > 1e-4).sum(),
            "short_count": (w_opt < -1e-4).sum()}

