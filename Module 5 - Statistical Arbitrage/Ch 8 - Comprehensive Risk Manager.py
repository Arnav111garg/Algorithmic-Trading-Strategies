import numpy as np
import pandas as pd
from scipy.stats import norm

class StatArbRiskManager:
    """Real-time risk management for a stat-arb book."""
    def __init__(self, aum=1e8, var_level=0.99,
                 max_drawdown=0.05, max_position_pct=0.02):
        self.aum = aum
        self.var_level = var_level
        self.max_dd = max_drawdown
        self.max_pos = max_position_pct
        self.daily_pnl = []
        self.peak_value = aum

    def risk_metrics(self, returns, method='historical'):
        """Compute VaR and CVaR."""
        if method == 'historical':
            sr = np.sort(returns)
            idx = int((1 - self.var_level) * len(sr))
            var = -sr[idx]; es = -sr[:idx].mean()
        else:
            mu, sig = returns.mean(), returns.std(ddof=1)
            z = norm.ppf(1 - self.var_level)
            var = -(mu + z*sig)
            es = -(mu - sig*norm.pdf(z)/(1 - self.var_level))
        return {"VaR_pct": var, "VaR_$": var*self.aum,
                "CVaR_pct": es, "CVaR_$": es*self.aum}

    def update_drawdown(self, current_pnl):
        """Track drawdown; alert if limit breached."""
        self.daily_pnl.append(current_pnl)
        cur = self.aum + sum(self.daily_pnl)
        self.peak_value = max(self.peak_value, cur)
        dd = (cur - self.peak_value) / self.peak_value
        return {"drawdown_pct": round(dd*100, 3),
                "alert": dd < -self.max_dd,
                "action": "REDUCE_BOOK" if dd < -self.max_dd else "OK"}

    def ou_position_size(self, spread, ou_params, risk_aversion=2.0):
        """Kelly-optimal position size for OU spread."""
        kappa = ou_params["kappa"]
        mu = ou_params["mu"]
        sigma = ou_params["sigma"]
        optimal_dollars = kappa*(mu - spread) / (risk_aversion*sigma**2/252)
        return float(np.clip(optimal_dollars, -self.max_pos*self.aum,
                             self.max_pos*self.aum))

    def dynamic_stop(self, spread, ou_params, adv_ratio=0.05):
        """Liquidity-adjusted dynamic stop-loss level."""
        sig_eq = ou_params["sigma"] / np.sqrt(2*ou_params["kappa"])
        base = 3 * sig_eq
        liq = 1 + 2 * adv_ratio # widen for illiquid positions
        final = base * liq
        return {"final_stop": final,
                "triggered": abs(spread) > final}

    def crowding_alert(self, my_signal, peer_signals):
        """Flag if signal is crowded (high correlation with peers)."""
        if peer_signals is None or peer_signals.empty:
            return {"crowding_score": 0.0, "alert": False}
        corr = peer_signals.corrwith(my_signal).mean()
        alert = corr > 0.6 # Threshold: 60% peer correlation
        size_adj = max(0.1, 1 - corr)
        return {"crowding_score": round(corr, 3),
                "alert": alert, "size_adjustment": round(size_adj, 3)}

