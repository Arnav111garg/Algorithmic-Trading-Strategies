import numpy as np
import pandas as pd
from scipy.optimize import brentq

class CapacityAnalyzer:
    """Strategy capacity and market impact analysis toolkit."""
    def __init__(self, alpha_bps, pair_adv, pair_vol,
                 turnover_frac, eta=0.2, spread_cost_bps=1.0):
        self.alpha = alpha_bps / 1e4 # daily alpha (fraction)
        self.adv = pair_adv # ADV in dollars
        self.vol = pair_vol # daily spread vol
        self.turnover = turnover_frac # fraction of portfolio traded/day
        self.eta = eta # impact coefficient
        self.spread_cost = spread_cost_bps/1e4 # one-way cost

    def market_impact(self, aum):
        """Square-root model: daily impact cost as fraction of portfolio."""
        daily_trade = aum * self.turnover
        participation = daily_trade / max(self.adv, 1)
        return self.eta * self.vol * np.sqrt(participation)

    def total_cost(self, aum):
        return self.spread_cost + self.market_impact(aum)

    def capacity(self):
        """AUM at which net alpha = 0."""
        try:
            return brentq(lambda x: self.alpha - self.total_cost(x),
                          1e4, 1e12, xtol=1e3)
        except ValueError:
            return np.nan

    def alpha_decay_curve(self, aum_range):
        """Net alpha (ann bps) vs AUM for a range of AUMs."""
        cap = self.capacity()
        rows = []
        for aum in aum_range:
            net_a = (self.alpha - self.total_cost(aum)) * 252 * 1e4
            rows.append({"AUM_$M": aum/1e6,
                         "Gross_alpha_ann_bps": self.alpha*252*1e4,
                         "Total_cost_ann_bps": self.total_cost(aum)*252*1e4,
                         "Net_alpha_ann_bps": net_a})
        return pd.DataFrame(rows), cap

    def flam_analysis(self, ic, n_bets, tc_coef=0.8):
        """Apply Fundamental Law of Active Management."""
        ir_theoretical = ic * np.sqrt(n_bets)
        ir_realised = tc_coef * ir_theoretical
        alpha_ann_bps = ir_realised * self.vol * np.sqrt(252) * 1e4
        return {"IR_theoretical": round(ir_theoretical, 3),
                "IR_realised": round(ir_realised, 3),
                "IC": ic,
                "N_bets": n_bets,
                "Transfer_coeff": tc_coef,
                "alpha_ann_bps": round(alpha_ann_bps, 1)}

# Example
ca = CapacityAnalyzer(alpha_bps=3.5, pair_adv=50e6,
                      pair_vol=0.015, turnover_frac=0.20, eta=0.15)
cap = ca.capacity()
print(f"Strategy capacity: ${cap/1e6:.1f}M")
flam = ca.flam_analysis(ic=0.05, n_bets=500)
print(f"Realised IR: {flam['IR_realised']:.3f} "
      f"Alpha: {flam['alpha_ann_bps']:.0f} bps/year")

