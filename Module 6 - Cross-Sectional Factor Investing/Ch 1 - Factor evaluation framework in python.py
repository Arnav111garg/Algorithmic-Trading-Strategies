import numpy as np
import pandas as pd
from scipy import stats

class FactorEvaluator:
    """Production-grade factor evaluation framework."""

    def __init__(self, factor_scores: pd.DataFrame, returns: pd.DataFrame):
        """
        Parameters:
        -----------
        factor_scores : DataFrame (dates x stocks)
        returns : DataFrame (dates x stocks), forward returns
        """
        self.scores = factor_scores
        self.returns = returns

    def compute_ic_series(self, method='spearman'):
        """Compute time series of Information Coefficients."""
        ic_series = []
        for date in self.scores.index:
            if date not in self.returns.index:
                continue
            scores = self.scores.loc[date].dropna()
            rets = self.returns.loc[date].dropna()
            common = scores.index.intersection(rets.index)
            if len(common) < 10:
                continue
            if method == 'spearman':
                ic, _ = stats.spearmanr(scores[common], rets[common])
            else:
                ic, _ = stats.pearsonr(scores[common], rets[common])
            ic_series.append({'date': date, 'ic': ic, 'n_stocks': len(common)})
        return pd.DataFrame(ic_series).set_index('date')

    def ic_summary(self):
        """Full IC statistics: mean, std, IR, t-stat, % positive."""
        ic_df = self.compute_ic_series()
        ic = ic_df['ic']
        n = len(ic)
        mean_ic = ic.mean()
        std_ic = ic.std()
        ir = mean_ic / std_ic if std_ic > 0 else np.nan
        t_stat = mean_ic / (std_ic / np.sqrt(n))
        pct_pos = (ic > 0).mean()
        return {
            'Mean IC': round(mean_ic, 4),
            'Std IC': round(std_ic, 4),
            'IR (ICIR)': round(ir, 3),
            'T-Statistic': round(t_stat, 3),
            '% Positive IC': round(pct_pos, 3),
            'Annualized IC': round(mean_ic * np.sqrt(12), 4)
        }

    def quintile_analysis(self):
        """Quintile return spreads and monotonicity."""
        results = {}
        for date in self.scores.index:
            if date not in self.returns.index:
                continue
            scores = self.scores.loc[date].dropna()
            rets = self.returns.loc[date].dropna()
            common = scores.index.intersection(rets.index)
            if len(common) < 50:
                continue
            df = pd.DataFrame({'score': scores[common], 'ret': rets[common]})
            df['quintile'] = pd.qcut(df['score'], 5, labels=False)
            q_rets = df.groupby('quintile')['ret'].mean()
            results[date] = q_rets.values
        result_df = pd.DataFrame(results).T
        result_df.columns = [f'Q{i+1}' for i in range(5)]
        summary = result_df.mean()
        summary['Q5-Q1 Spread'] = summary['Q5'] - summary['Q1']
        return summary

