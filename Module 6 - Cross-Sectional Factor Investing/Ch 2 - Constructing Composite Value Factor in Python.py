import pandas as pd
import numpy as np

class ValueFactorConstructor:
    """Institutional-grade value factor construction."""

    def __init__(self, fundamentals: pd.DataFrame, prices: pd.DataFrame):
        """
        fundamentals: MultiIndex (date, ticker) with columns:
        ['book_equity', 'earnings_ttm', 'ebitda_ttm',
         'fcf_ttm', 'revenue_ttm', 'net_debt',
         'dividends_ttm', 'net_buybacks_ttm', 'sector']
        prices: MultiIndex (date, ticker) with column 'close'
        """
        self.fund = fundamentals
        self.prices = prices

    def compute_market_cap(self):
        """Market cap = price * shares outstanding (approximated here)."""
        return self.prices['close']

    def compute_ev(self, date, ticker):
        """Enterprise Value = Market Cap + Net Debt."""
        mc = self.prices.loc[(date, ticker), 'close']
        nd = self.fund.loc[(date, ticker), 'net_debt']
        return mc + nd

    def book_to_market(self, date):
        """Cross-sectional B/M ratio, winsorized."""
        be = self.fund.loc[date, 'book_equity']
        mc = self.prices.loc[date, 'close']
        bm = be / mc
        return self._winsorize_zscore(bm)

    def earnings_yield(self, date):
        """TTM earnings yield = EPS_TTM / Price."""
        ep = self.fund.loc[date, 'earnings_ttm']
        mc = self.prices.loc[date, 'close']
        ey = ep / mc
        # Exclude negative earnings to avoid short/long confusion
        ey = ey[ey > 0]
        return self._winsorize_zscore(ey)

    def ebitda_ev_yield(self, date):
        """EBITDA/EV yield."""
        ebitda = self.fund.loc[date, 'ebitda_ttm']
        mc = self.prices.loc[date, 'close']
        nd = self.fund.loc[date, 'net_debt']
        ev = mc + nd
        yield_ = ebitda / ev
        yield_ = yield_[yield_ > 0]
        return self._winsorize_zscore(yield_)

    def fcf_yield(self, date):
        """Free cash flow yield = FCF_TTM / Market Cap."""
        fcf = self.fund.loc[date, 'fcf_ttm']
        mc = self.prices.loc[date, 'close']
        return self._winsorize_zscore(fcf / mc)

    def shareholder_yield(self, date):
        """Dividends + net buybacks, normalized by market cap."""
        div = self.fund.loc[date, 'dividends_ttm']
        buyb = self.fund.loc[date, 'net_buybacks_ttm']
        mc = self.prices.loc[date, 'close']
        sy = (div + buyb) / mc
        return self._winsorize_zscore(sy)

    def composite_value(self, date, sector_neutral=True):
        """
        Equal-weight composite of 5 value signals.
        sector_neutral = True: z-score within sector.
        """
        signals = {
            'bm': self.book_to_market(date),
            'ey': self.earnings_yield(date),
            'evebitda': self.ebitda_ev_yield(date),
            'fcfy': self.fcf_yield(date),
            'sy': self.shareholder_yield(date),
        }
        df = pd.DataFrame(signals)

        if sector_neutral:
            sectors = self.fund.loc[date, 'sector']
            df = df.groupby(sectors).transform(
                lambda x: (x - x.mean()) / (x.std() + 1e-8)
            )

        # Rank each signal, then average
        ranked = df.rank(pct=True) * 2 - 1  # Scale to [-1, 1]
        composite = ranked.mean(axis=1)
        return composite

    @staticmethod
    def _winsorize_zscore(series: pd.Series, clip=0.01) -> pd.Series:
        """Winsorize at clip %, then z-score."""
        lo = series.quantile(clip)
        hi = series.quantile(1 - clip)
        clipped = series.clip(lo, hi)
        return (clipped - clipped.mean()) / (clipped.std() + 1e-8)

