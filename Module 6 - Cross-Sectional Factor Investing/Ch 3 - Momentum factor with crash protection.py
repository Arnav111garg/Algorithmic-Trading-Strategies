import numpy as np
import pandas as pd

class MomentumFactorConstructor:
    """Institutional momentum factor with crash protection."""

    def __init__(self, returns: pd.DataFrame):
        """
        returns: DataFrame (dates x tickers), daily or monthly returns
        """
        self.returns = returns

    def price_momentum_12_1(self, lookback=12, skip=1):
        """Standard 12-1 momentum (monthly frequency)."""
        compound = (1 + self.returns).rolling(lookback).apply(
            np.prod, raw=True
        ) - 1
        # Skip the most recent month
        return compound.shift(skip)

    def risk_adjusted_momentum(self, lookback=12, skip=1, vol_window=3):
        """
        Momentum divided by trailing volatility.
        vol_window in months.
        """
        mom = self.price_momentum_12_1(lookback, skip)
        # Monthly realized vol = std of monthly returns * sqrt(12)
        vol = self.returns.rolling(vol_window).std() * np.sqrt(12)
        return mom / (vol + 1e-8)

    def residual_momentum(self, market_returns: pd.Series, lookback=12, skip=1):
        """Market-beta-adjusted residual momentum."""
        residuals = pd.DataFrame(index=self.returns.index, columns=self.returns.columns)
        for ticker in self.returns.columns:
            y = self.returns[ticker].dropna()
            x = market_returns.loc[y.index]
            # Rolling OLS (use last 36 months for beta estimation)
            for t_idx in range(36, len(y)):
                window = slice(t_idx - 36, t_idx)
                y_w = y.iloc[window]
                x_w = x.iloc[window]
                beta = np.cov(y_w, x_w)[0, 1] / np.var(x_w)
                resid = y.iloc[t_idx] - beta * x.iloc[t_idx]
                residuals.loc[y.index[t_idx], ticker] = resid

        # Cumulate residuals over lookback window, skip 1 month
        return residuals.rolling(lookback - skip).sum().shift(skip)

    def volatility_scaled_momentum(self, mom_portfolio_returns: pd.Series, target_vol: float = 0.12):
        """
        Barroso-Santa-Clara (2015) volatility scaling.
        Scales the long-short momentum portfolio weight.

        Parameters:
        -----------
        mom_portfolio_returns : Monthly returns of raw L-S momentum
        target_vol : Target annualized vol (default 12%)

        Returns:
        --------
        scaled_weights : Time series of portfolio weights
        scaled_returns : Vol-scaled momentum returns
        """
        # Realized variance (6-month window, annualized)
        realized_var = mom_portfolio_returns.rolling(6).var() * 12
        target_var = target_vol ** 2
        weights = (target_var / realized_var).shift(1)  # t-1 weight
        weights = weights.clip(0, 2)  # Cap leverage at 2x
        scaled_ret = weights * mom_portfolio_returns
        return weights, scaled_ret

    def momentum_state(self, market_returns: pd.Series, vol_regime_window: int = 6) -> pd.Series:
        """
        Classify momentum crash regime:
        - 'bear_high_vol': Dangerous (potential crash)
        - 'normal': Standard regime
        """
        mkt_vol = market_returns.rolling(vol_regime_window).std() * np.sqrt(12)
        mkt_ret = market_returns.rolling(vol_regime_window).sum()

        state = pd.Series('normal', index=market_returns.index)
        # High vol + market in recovery = crash risk
        state[(mkt_vol > mkt_vol.quantile(0.75)) & (mkt_ret > 0)] = 'bear_high_vol'
        return state

