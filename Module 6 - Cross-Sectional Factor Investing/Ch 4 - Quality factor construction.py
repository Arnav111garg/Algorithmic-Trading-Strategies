import numpy as np
import pandas as pd

class QualityFactorConstructor:
    """Institutional-grade quality factor (QMJ-style)."""

    def __init__(self, fundamentals: pd.DataFrame):
        self.data = fundamentals

    def gross_profitability(self, date):
        """Gross Profit / Total Assets."""
        gp = self.data.loc[date, 'gross_profit']
        ta = self.data.loc[date, 'total_assets']
        return self._zscore(gp / ta)

    def roe(self, date):
        """Return on Equity."""
        ni = self.data.loc[date, 'net_income']
        be = self.data.loc[date, 'book_equity']
        return self._zscore(ni / (np.abs(be) + 1))

    def roa(self, date):
        """Return on Assets."""
        ni = self.data.loc[date, 'net_income']
        ta = self.data.loc[date, 'total_assets']
        return self._zscore(ni / ta)

    def cash_flow_to_assets(self, date):
        """Operating Cash Flow / Total Assets."""
        cfo = self.data.loc[date, 'operating_cash_flow']
        ta = self.data.loc[date, 'total_assets']
        return self._zscore(cfo / ta)

    def accruals(self, date):
        """
        Low accruals = high quality (NEGATIVE sign: low accrual is good).
        Cash-flow accruals = (Net Income - CFO) / Total Assets.
        """
        ni = self.data.loc[date, 'net_income']
        cfo = self.data.loc[date, 'operating_cash_flow']
        ta = self.data.loc[date, 'total_assets']
        acc = (ni - cfo) / ta
        return self._zscore(-acc)  # Negate: low accruals = high quality

    def piotroski_score(self, date) -> pd.Series:
        """9-signal Piotroski F-Score."""
        d = self.data.loc[date]
        roa = d['net_income'] / d['total_assets']
        d_roa = roa - self.data.loc[date - pd.DateOffset(years=1), 'net_income'] / \
                self.data.loc[date - pd.DateOffset(years=1), 'total_assets']
        cfoa = d['operating_cash_flow'] / d['total_assets']
        acc = cfoa - roa
        lev = d['long_term_debt'] / d['total_assets']
        d_lev = lev - (self.data.loc[date - pd.DateOffset(years=1), 'long_term_debt'] /
                       self.data.loc[date - pd.DateOffset(years=1), 'total_assets'])
        cr = d['current_assets'] / d['current_liabilities']
        d_cr = cr - (self.data.loc[date - pd.DateOffset(years=1), 'current_assets'] /
                     self.data.loc[date - pd.DateOffset(years=1), 'current_liabilities'])
        gm = d['gross_profit'] / d['revenue']
        d_gm = gm - (self.data.loc[date - pd.DateOffset(years=1), 'gross_profit'] /
                     self.data.loc[date - pd.DateOffset(years=1), 'revenue'])
        at = d['revenue'] / d['total_assets']
        d_at = at - (self.data.loc[date - pd.DateOffset(years=1), 'revenue'] /
                     self.data.loc[date - pd.DateOffset(years=1), 'total_assets'])
        share_iss = d['shares_outstanding'] <= \
                    self.data.loc[date - pd.DateOffset(years=1), 'shares_outstanding']

        score = ((roa > 0).astype(int) +
                 (d_roa > 0).astype(int) +
                 (cfoa > 0).astype(int) +
                 (acc > 0).astype(int) +
                 (d_lev < 0).astype(int) +
                 (d_cr > 0).astype(int) +
                 share_iss.astype(int) +
                 (d_gm > 0).astype(int) +
                 (d_at > 0).astype(int))
        return score

    def composite_quality(self, date):
        """
        QMJ-style composite quality score.
        Profitability, Growth, Safety dimensions.
        """
        # Profitability
        prof = pd.DataFrame({
            'gp': self.gross_profitability(date),
            'roe': self.roe(date),
            'roa': self.roa(date),
            'cfoa': self.cash_flow_to_assets(date),
            'acc': self.accruals(date)
        }).mean(axis=1)

        return self._zscore(prof)

    @staticmethod
    def _zscore(series: pd.Series) -> pd.Series:
        s = series.replace([np.inf, -np.inf], np.nan).dropna()
        lo, hi = s.quantile(0.01), s.quantile(0.99)
        s = s.clip(lo, hi)
        return (s - s.mean()) / (s.std() + 1e-8)

