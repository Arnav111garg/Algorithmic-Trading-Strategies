import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression

class LowVolatilityFactors:
    """Betting Against Beta and related low-vol factors."""

    def __init__(self, daily_returns: pd.DataFrame, market_returns: pd.Series):
        self.rets = daily_returns
        self.mkt = market_returns

    def rolling_beta(self, window: int = 252) -> pd.DataFrame:
        """Rolling market beta using OLS."""
        betas = pd.DataFrame(index=self.rets.index, columns=self.rets.columns, dtype=float)
        for t in range(window, len(self.rets)):
            y_slice = self.rets.iloc[t - window : t]
            x_slice = self.mkt.iloc[t - window : t]
            for ticker in self.rets.columns:
                y = y_slice[ticker].dropna()
                x = x_slice.loc[y.index]
                if len(y) < window * 0.5:
                    continue
                cov = np.cov(y, x)[0, 1]
                var = np.var(x) + 1e-12
                betas.iloc[t][ticker] = cov / var
        return betas

    def vasicek_adjusted_beta(self, raw_betas: pd.DataFrame, shrink: float = 0.6) -> pd.DataFrame:
        """Shrink betas toward 1.0 (Vasicek adjustment)."""
        return shrink * raw_betas + (1 - shrink) * 1.0

    def historical_volatility(self, window: int = 252, annualize: bool = True) -> pd.DataFrame:
        """Annualized historical volatility."""
        vol = self.rets.rolling(window).std()
        if annualize:
            vol = vol * np.sqrt(252)
        return vol

    def idiosyncratic_vol(self, ff3_factors: pd.DataFrame, window: int = 60) -> pd.DataFrame:
        """
        Idiosyncratic vol = std of residuals from FF3 model.
        ff3_factors : DataFrame with columns ['MKT','SMB','HML']
        """
        idio_vol = pd.DataFrame(index=self.rets.index, columns=self.rets.columns, dtype=float)
        for t in range(window, len(self.rets)):
            y_slice = self.rets.iloc[t - window : t]
            x_slice = ff3_factors.iloc[t - window : t]
            for ticker in self.rets.columns:
                y = y_slice[ticker].dropna()
                x = x_slice.loc[y.index]
                if len(y) < 20:
                    continue
                reg = LinearRegression(fit_intercept=True)
                reg.fit(x.values, y.values)
                residuals = y.values - reg.predict(x.values)
                idio_vol.iloc[t][ticker] = residuals.std() * np.sqrt(252)
        return idio_vol

    def bab_factor(self, rebalance_freq: str = 'M') -> pd.Series:
        """
        Betting Against Beta portfolio monthly return.
        Returns : Series of BAB factor monthly returns.
        """
        betas = self.vasicek_adjusted_beta(self.rolling_beta())
        betas_monthly = betas.resample(rebalance_freq).last()
        rets_monthly = self.rets.resample(rebalance_freq).apply(
            lambda x: (1 + x).prod() - 1
        )
        mkt_monthly = self.mkt.resample(rebalance_freq).apply(
            lambda x: (1 + x).prod() - 1
        )

        bab_returns = []
        for date in betas_monthly.index[:-1]:
            b = betas_monthly.loc[date].dropna()
            b = b[(b > 0) & (b < 5)]  # Remove extreme betas
            median_b = b.median()
            low_b = b[b <= median_b]
            high_b = b[b > median_b]

            # Scale to unit beta
            w_low = (1 / low_b) / (1 / low_b).sum()
            w_high = -(1 / high_b) / (1 / high_b).sum()

            next_date = betas_monthly.index[
                betas_monthly.index.get_loc(date) + 1
            ]
            if next_date not in rets_monthly.index:
                continue
            r_next = rets_monthly.loc[next_date]
            r_mkt = mkt_monthly.loc[next_date]

            # Excess returns
            r_f = 0  # Approximate risk-free rate (simplify)
            r_low = w_low.dot(r_next.loc[w_low.index] - r_f)
            r_high = w_high.dot(r_next.loc[w_high.index] - r_f)
            beta_low = low_b.mean()
            beta_high = high_b.mean()

            bab_ret = r_low / beta_low + r_high / beta_high
            bab_returns.append({'date': next_date, 'bab_ret': bab_ret})

        return pd.DataFrame(bab_returns).set_index('date')['bab_ret']

