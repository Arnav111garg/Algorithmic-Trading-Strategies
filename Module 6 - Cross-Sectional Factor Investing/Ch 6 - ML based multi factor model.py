import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor
from sklearn.linear_model import LassoCV, RidgeCV
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import TimeSeriesSplit

class MLMultiFactorModel:
    """
    Machine learning ensemble for combining cross-sectional factors.
    Uses time-series cross-validation to avoid look-ahead bias.
    """

    def __init__(self, factor_names: list, horizon: int = 1):
        """
        factor_names : list of factor signal column names
        horizon : forward return horizon (months)
        """
        self.factors = factor_names
        self.horizon = horizon
        self.models = {}
        self.scalers = {}

    def prepare_panel(self, factor_df: pd.DataFrame, returns_df: pd.DataFrame) -> pd.DataFrame:
        """
        Prepare aligned factor scores and forward returns.
        Both are MultiIndex: (date, ticker).
        """
        y = returns_df.shift(-self.horizon)  # Forward returns
        # Stack to long format
        X_long = factor_df.stack().reset_index()
        y_long = y.stack().reset_index()
        X_long.columns = ['date', 'ticker'] + self.factors
        y_long.columns = ['date', 'ticker', 'fwd_ret']

        merged = pd.merge(X_long, y_long, on=['date', 'ticker']).dropna()
        return merged

    def train_lasso_factor_model(self, data: pd.DataFrame, n_splits: int = 5) -> pd.DataFrame:
        """
        LASSO regression for sparse factor combination.
        Time-series cross-validation preserves temporal structure.
        """
        tscv = TimeSeriesSplit(n_splits=n_splits)
        dates = data['date'].unique()

        all_predictions = []
        # Standard time-series split fallback/dummy split
        split_idx = int(len(dates) * 0.8)
        train_dates = dates[:split_idx]
        val_dates = dates[split_idx:]

        train = data[data['date'].isin(train_dates)]
        val = data[data['date'].isin(val_dates)]

        X_tr = train[self.factors].values
        y_tr = train['fwd_ret'].values
        X_val = val[self.factors].values

        scaler = StandardScaler()
        X_tr_s = scaler.fit_transform(X_tr)
        X_val_s = scaler.transform(X_val)

        model = LassoCV(cv=5, max_iter=10000)
        model.fit(X_tr_s, y_tr)

        preds = model.predict(X_val_s)
        val = val.copy()
        val['predicted_score'] = preds
        all_predictions.append(val)

        # Store coefficients for interpretability
        coefs = pd.Series(model.coef_, index=self.factors)
        print("LASSO coefficients:")
        print(coefs.sort_values(ascending=False))

        return pd.concat(all_predictions)

    def train_gradient_boost(self, data: pd.DataFrame) -> pd.DataFrame:
        """
        Gradient Boosting for nonlinear factor interactions.
        Key: captures factor interaction effects (e.g., value * quality).
        """
        train = data[data['date'] < data['date'].quantile(0.8)]
        val = data[data['date'] >= data['date'].quantile(0.8)]

        X_tr = train[self.factors].values
        y_tr = train['fwd_ret'].values
        X_val = val[self.factors].values

        gb = GradientBoostingRegressor(
            n_estimators=200,
            max_depth=3,  # Shallow trees to avoid overfitting
            learning_rate=0.01,
            subsample=0.8,  # Stochastic gradient boosting
            min_samples_leaf=50  # Regularization for finance panels
        )
        gb.fit(X_tr, y_tr)

        # Feature importance
        importance = pd.Series(gb.feature_importances_, index=self.factors)
        print("Factor Importance (GBM):")
        print(importance.sort_values(ascending=False))

        val = val.copy()
        val['predicted_score'] = gb.predict(X_val)
        return val

    def factor_interaction_terms(self, data: pd.DataFrame) -> pd.DataFrame:
        """
        Add pairwise interaction terms: Value * Quality, Value * Momentum, etc.
        These capture nonlinear combinations documented in research.
        """
        result = data.copy()
        for i, f1 in enumerate(self.factors):
            for f2 in self.factors[i+1:]:
                result[f'{f1}_x_{f2}'] = data[f1] * data[f2]
        return result

