import numpy as np
import pandas as pd
from hmmlearn import hmm

class FactorTimer:
    """
    Factor timing overlay using valuation, macro, and vol signals.
    IMPORTANT: All signals are constructed to avoid look-ahead bias.
    """

    def __init__(self, factor_returns: pd.DataFrame, macro_data: pd.DataFrame):
        self.f_rets = factor_returns  # Monthly factor returns
        self.macro = macro_data        # Macro variables (monthly)

    def value_spread_timing(
        self,
        factor: str = 'HML',
        spread_series: pd.Series = None,
        threshold: float = 1.0
    ) -> pd.Series:
        """
        Scale factor exposure based on value spread.
        Reduce exposure when spread is compressed (expensive),
        increase when spread is wide (cheap).
        """
        z_spread = (spread_series - spread_series.expanding().mean()) / \
                   spread_series.expanding().std()
        z_spread = z_spread.shift(1)  # Use only past info

        # Scale: 0.5x at z=-1, 1.0x at z=0, 1.5x at z=+1
        scale = 1.0 + 0.5 * z_spread.clip(-2, 2) / 2
        return scale

    def volatility_scaled_momentum(
        self,
        window: int = 6,
        target_vol: float = 0.12
    ) -> pd.Series:
        """Barroso-Santa-Clara vol scaling for momentum factor."""
        mom_rets = self.f_rets['MOM']
        real_var = mom_rets.rolling(window).var() * 12
        scale = (target_vol ** 2 / real_var).shift(1)
        scale = scale.clip(0, 2)
        return scale

    def macro_regime_model(self, n_states: int = 2) -> pd.Series:
        """
        Hidden Markov Model regime classification using macro features.

        Returns: Series of regime labels (0=expansion, 1=recession)
        """
        features = self.macro[['yield_spread', 'credit_spread', 'unemployment_change', 'ism']].dropna()

        model = hmm.GaussianHMM(
            n_components=n_states,
            covariance_type='full',
            n_iter=100,
            random_state=42
        )
        model.fit(features.values)

        regimes = pd.Series(
            model.predict(features.values),
            index=features.index,
            name='regime'
        )

        # Label regimes: lower mean yield spread = recession
        mean_0 = self.macro.loc[features.index[regimes == 0], 'yield_spread'].mean()
        mean_1 = self.macro.loc[features.index[regimes == 1], 'yield_spread'].mean()

        if mean_0 < mean_1:
            regimes = 1 - regimes  # Flip: 0=recession, 1=expansion

        return regimes

    def regime_conditional_exposure(self, regimes: pd.Series) -> pd.DataFrame:
        """
        Regime-conditional factor tilts.
        Recession: overweight Quality, Low-Vol; underweight Value, Momentum
        Expansion: overweight Value, Momentum; underweight Quality, Low-Vol
        """
        # Base exposures
        base = {'Value': 1.0, 'Momentum': 1.0, 'Quality': 1.0, 'LowVol': 1.0}

        # Regime adjustments (additive)
        expansion_adj = {'Value': 0.3, 'Momentum': 0.3, 'Quality': -0.2, 'LowVol': -0.2}
        recession_adj = {'Value': -0.3, 'Momentum': -0.3, 'Quality': 0.2, 'LowVol': 0.2}

        exposures = pd.DataFrame(index=regimes.index, columns=list(base.keys()))

        for date, regime in regimes.items():
            adj = expansion_adj if regime == 1 else recession_adj
            for factor in base:
                exposures.loc[date, factor] = base[factor] + adj[factor]

        return exposures.shift(1)  # Use prior month's regime (no look-ahead)

    def combined_timing_strategy(
        self,
        value_spread: pd.Series,
        regimes: pd.Series
    ) -> pd.DataFrame:
        """
        Combine vol-scaling for momentum with value-spread timing for value.

        Returns: DataFrame of monthly timing adjustments by factor.
        """
        factors = ['Value', 'Momentum', 'Quality', 'LowVol']
        scale = pd.DataFrame(1.0, index=self.f_rets.index, columns=factors)

        # 1. Value: scale by value spread
        scale['Value'] = self.value_spread_timing('HML', value_spread)

        # 2. Momentum: vol scaling
        scale['Momentum'] = self.volatility_scaled_momentum()

        # 3. Regime-conditional (Quality, LowVol)
        regime_exp = self.regime_conditional_exposure(regimes)
        for f in ['Quality', 'LowVol']:
            if f in regime_exp.columns:
                scale[f] = regime_exp[f]

        return scale

