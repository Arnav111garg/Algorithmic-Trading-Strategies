import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.covariance import LedoitWolf

class BarraStyleRiskModel:
    """
    Fundamental + Statistical factor risk model.
    Computes covariance matrix, risk attribution, and factor returns.
    """

    def __init__(self, returns: pd.DataFrame, factor_exposures: pd.DataFrame):
        """
        returns : (T x N) matrix of daily returns
        factor_exposures : (N x K) matrix of factor loadings (z-scored)
        """
        self.returns = returns
        self.exposures = factor_exposures
        self.N = returns.shape[1]
        self.K = factor_exposures.shape[1]

    def estimate_factor_returns_wls(self, date: pd.Timestamp, mkt_caps: pd.Series) -> tuple:
        """
        Cross-sectional WLS regression to extract factor returns.
        Weight = sqrt(market cap).
        """
        r = self.returns.loc[date].dropna()
        X = self.exposures.loc[r.index].dropna()
        common = r.index.intersection(X.index)
        r = r[common]
        X = X.loc[common]
        mc = mkt_caps.loc[common].fillna(1)

        W = np.diag(np.sqrt(mc.values))
        Xv = X.values
        rv = r.values

        XtWX = Xv.T @ W @ Xv
        XtWr = Xv.T @ W @ rv

        # Regularized solve (Ridge regularization)
        lambda_reg = 1e-4 * np.trace(XtWX) / self.K
        f_hat = np.linalg.solve(XtWX + lambda_reg * np.eye(self.K), XtWr)

        residuals = rv - Xv @ f_hat
        return pd.Series(f_hat, index=X.columns), pd.Series(residuals, index=common)

    def estimate_factor_cov(self, factor_returns_ts: pd.DataFrame, halflife: int = 252) -> np.ndarray:
        """
        Exponentially-weighted factor covariance matrix.
        halflife in trading days.
        """
        T = len(factor_returns_ts)
        decay = 0.5 ** (1.0 / halflife)
        weights = np.array([decay ** (T - 1 - t) for t in range(T)])
        weights /= weights.sum()

        X = factor_returns_ts.values
        mu = (weights[:, None] * X).sum(axis=0)
        X_demeaned = X - mu
        F = (weights[:, None, None] * X_demeaned[:, :, None] * X_demeaned[:, None, :]).sum(axis=0)

        return F  # (K x K)

    def estimate_idiosyncratic_vol(self, residuals_ts: pd.DataFrame, halflife: int = 126) -> pd.Series:
        """Exponentially-weighted idiosyncratic volatility."""
        T = len(residuals_ts)
        decay = 0.5 ** (1.0 / halflife)
        weights = np.array([decay ** (T - 1 - t) for t in range(T)])
        weights /= weights.sum()

        var = (weights[:, None] * residuals_ts.values ** 2).sum(axis=0)
        return pd.Series(np.sqrt(var * 252), index=residuals_ts.columns)

    def covariance_matrix(self, factor_cov: np.ndarray, idio_vol: pd.Series) -> np.ndarray:
        """
        Full covariance matrix: Sigma = X * F * X' + Delta
        """
        X = self.exposures.loc[idio_vol.index].values  # (N x K)
        Delta = np.diag((idio_vol.values / np.sqrt(252)) ** 2)  # Daily
        Sigma = X @ factor_cov @ X.T + Delta
        return Sigma

    def risk_attribution(self, weights: pd.Series, factor_cov: np.ndarray, idio_vol: pd.Series) -> dict:
        """
        Full portfolio risk decomposition.
        weights : active portfolio weights (sum to 0 for L-S)
        """
        common = weights.index.intersection(self.exposures.index).intersection(idio_vol.index)
        w = weights.loc[common].values[:, None]  # (N x 1)
        X = self.exposures.loc[common].values  # (N x K)
        d = (idio_vol.loc[common].values / np.sqrt(252)) ** 2  # Daily var

        F = factor_cov

        factor_var = float(w.T @ X @ F @ X.T @ w)
        idio_var = float(w.T @ np.diag(d) @ w)
        total_var = factor_var + idio_var
        total_vol = np.sqrt(total_var * 252)  # Annualized

        # Per-factor attribution
        factor_betas = X.T @ w  # (K x 1): portfolio factor exposure

        return {
            'total_vol_annualized': total_vol,
            'factor_risk_pct': factor_var / total_var,
            'idio_risk_pct': idio_var / total_var,
            'factor_contributions': pd.Series(
                np.diag(np.outer(factor_betas.flatten(), (F @ factor_betas).flatten())) / total_var,
                index=self.exposures.columns
            )
        }

