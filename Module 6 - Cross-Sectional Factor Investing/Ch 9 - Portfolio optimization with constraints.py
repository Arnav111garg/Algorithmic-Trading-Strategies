import numpy as np
import pandas as pd
import cvxpy as cp
from scipy.optimize import minimize

class FactorPortfolioOptimizer:
    """
    Production-grade portfolio optimizer for factor strategies.
    Uses CVXPY for convex problems.
    """

    def __init__(
        self,
        alpha: pd.Series,
        sigma: np.ndarray,
        factor_exposures: pd.DataFrame = None,
        prev_weights: pd.Series = None
    ):
        """
        alpha : (N,) expected returns / alpha scores
        sigma : (N x N) covariance matrix (annualized)
        factor_exposures : (N x K) for neutralization constraints
        prev_weights : (N,) prior weights (for TC penalty)
        """
        self.alpha = alpha
        self.sigma = sigma
        self.X = factor_exposures
        self.w_prev = prev_weights if prev_weights is not None else pd.Series(0.0, index=alpha.index)
        self.N = len(alpha)

    def optimize(
        self,
        gamma: float = 1.0,
        lambda_tc: float = 0.0,
        gross_exposure: float = 1.0,
        max_position: float = 0.05,
        dollar_neutral: bool = True,
        sector_neutral: bool = False,
        sector_labels: pd.Series = None,
        factor_neutral: bool = False,
        target_factor_exp: np.ndarray = None
    ) -> pd.Series:
        """
        Solve the constrained mean-variance optimization.

        Returns : Optimal weights as pd.Series.
        """
        N = self.N
        w = cp.Variable(N)
        alpha_v = self.alpha.values
        w_prev_v = self.w_prev.reindex(self.alpha.index).fillna(0).values

        # --- Objective ---
        port_return = alpha_v @ w
        port_risk = cp.quad_form(w, self.sigma)
        tc_penalty = lambda_tc * cp.norm1(w - w_prev_v)
        objective = cp.Maximize(port_return - (gamma / 2) * port_risk - tc_penalty)

        # --- Constraints ---
        constraints = []

        # Dollar neutral
        if dollar_neutral:
            constraints.append(cp.sum(w) == 0)

        # Gross exposure
        constraints.append(cp.norm1(w) <= 2 * gross_exposure)

        # Position limits
        constraints.append(cp.abs(w) <= max_position)

        # Sector neutral
        if sector_neutral and sector_labels is not None:
            for sector in sector_labels.unique():
                mask = (sector_labels == sector).values
                constraints.append(cp.sum(w[mask]) == 0)

        # Factor neutral (zero factor exposure)
        if factor_neutral and self.X is not None:
            X_v = self.X.reindex(self.alpha.index).fillna(0).values
            tgt = target_factor_exp if target_factor_exp is not None else np.zeros(self.X.shape[1])
            constraints.append(X_v.T @ w == tgt)

        # --- Solve ---
        prob = cp.Problem(objective, constraints)
        prob.solve(solver=cp.CLARABEL, verbose=False)

        if prob.status not in ['optimal', 'optimal_inaccurate']:
            print(f"Warning: Solver status = {prob.status}")
            return self.w_prev

        return pd.Series(w.value, index=self.alpha.index)

    def optimize_risk_parity(self) -> pd.Series:
        """
        Risk parity: equal risk contribution from each stock.
        Solved via sequential quadratic programming.
        """
        Sigma = self.sigma
        N = self.N

        def risk_contributions(w):
            port_var = w @ Sigma @ w
            MCR = Sigma @ w / np.sqrt(port_var)
            return w * MCR  # Per-stock risk contribution

        def objective(w):
            rc = risk_contributions(w)
            target = np.sqrt(w @ Sigma @ w) / N
            return np.sum((rc - target) ** 2)

        w0 = np.ones(N) / N
        bounds = [(0, 0.1)] * N  # Long only, max 10%
        constraints_opt = [{'type': 'eq', 'fun': lambda w: np.sum(w) - 1}]

        result = minimize(
            objective,
            w0,
            method='SLSQP',
            bounds=bounds,
            constraints=constraints_opt,
            options={'maxiter': 1000, 'ftol': 1e-9}
        )

        return pd.Series(result.x, index=self.alpha.index)

    def turnover_report(self, new_weights: pd.Series) -> dict:
        """Compute portfolio turnover and transition cost."""
        trade = new_weights - self.w_prev.reindex(new_weights.index).fillna(0)
        one_way_turnover = trade.abs().sum() / 2
        return {
            'one_way_turnover': one_way_turnover,
            'two_way_turnover': trade.abs().sum(),
            'n_trades': (trade.abs() > 1e-4).sum(),
            'max_single_trade': trade.abs().max()
        }

