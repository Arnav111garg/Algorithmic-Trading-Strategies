import numpy as np
from collections import deque
from dataclasses import dataclass
from typing import Optional
import heapq

@dataclass
class Order:
    order_id: int
    side: str  # 'buy' or 'sell'
    price: float
    quantity: int
    timestamp: float
    order_type: str = 'limit'  # 'limit' or 'market'

@dataclass
class Trade:
    aggressor_id: int
    passive_id: int
    price: float
    quantity: int
    timestamp: float

class PriceLevel:
    """FIFO queue at a single price level."""
    def __init__(self, price: float):
        self.price = price
        self.orders: deque[Order] = deque()
        self.total_qty: int = 0

    def add_order(self, order: Order):
        self.orders.append(order)
        self.total_qty += order.quantity

    def consume(self, qty: int) -> list[Trade]:
        trades = []
        remaining = qty
        while self.orders and remaining > 0:
            o = self.orders[0]
            fill = min(remaining, o.quantity)
            trades.append(Trade(
                aggressor_id=-1,  # filled by caller
                passive_id=o.order_id,
                price=self.price,
                quantity=fill,
                timestamp=0.0
            ))
            o.quantity -= fill
            self.total_qty -= fill
            remaining -= fill
            if o.quantity == 0:
                self.orders.popleft()
        return trades

class OrderBook:
    """
    Continuous Double Auction with FIFO price-time priority.
    bids: max-heap (negate price), asks: min-heap
    """
    def __init__(self, symbol: str):
        self.symbol = symbol
        self.bids: dict[float, PriceLevel] = {}  # price -> PriceLevel
        self.asks: dict[float, PriceLevel] = {}
        self._bid_prices: list[float] = []  # max-heap: store -price
        self._ask_prices: list[float] = []  # min-heap
        self.trades: list[Trade] = []
        self._next_id = 0

    def best_bid(self) -> Optional[float]:
        while self._bid_prices and -self._bid_prices[0] not in self.bids:
            heapq.heappop(self._bid_prices)
        return -self._bid_prices[0] if self._bid_prices else None

    def best_ask(self) -> Optional[float]:
        while self._ask_prices and self._ask_prices[0] not in self.asks:
            heapq.heappop(self._ask_prices)
        return self._ask_prices[0] if self._ask_prices else None

    def mid_price(self) -> Optional[float]:
        bb, ba = self.best_bid(), self.best_ask()
        if bb is not None and ba is not None:
            return (bb + ba) / 2.0
        return None

    def spread(self) -> Optional[float]:
        bb, ba = self.best_bid(), self.best_ask()
        if bb is not None and ba is not None:
            return ba - bb
        return None

    def submit_limit_order(self, side: str, price: float, qty: int, ts: float) -> list[Trade]:
        self._next_id += 1
        order = Order(self._next_id, side, price, qty, ts, 'limit')
        trades = []

        if side == 'buy':
            # Try to match against asks
            while qty > 0:
                ba = self.best_ask()
                if ba is None or price < ba:
                    break
                level = self.asks[ba]
                new_trades = level.consume(qty)
                for t in new_trades:
                    t.aggressor_id = order.order_id
                    t.timestamp = ts
                    qty -= t.quantity
                    trades.append(t)
                if level.total_qty == 0:
                    del self.asks[ba]
            # Rest in book if unfilled
            if qty > 0:
                order.quantity = qty
                if price not in self.bids:
                    self.bids[price] = PriceLevel(price)
                    heapq.heappush(self._bid_prices, -price)
                self.bids[price].add_order(order)

        elif side == 'sell':
            # Try to match against bids
            while qty > 0:
                bb = self.best_bid()
                if bb is None or price > bb:
                    break
                level = self.bids[bb]
                new_trades = level.consume(qty)
                for t in new_trades:
                    t.aggressor_id = order.order_id
                    t.timestamp = ts
                    qty -= t.quantity
                    trades.append(t)
                if level.total_qty == 0:
                    del self.bids[bb]
            if qty > 0:
                order.quantity = qty
                if price not in self.asks:
                    self.asks[price] = PriceLevel(price)
                    heapq.heappush(self._ask_prices, price)
                self.asks[price].add_order(order)

        self.trades.extend(trades)
        return trades

    def submit_market_order(self, side: str, qty: int, ts: float) -> list[Trade]:
        # Market order at extreme price
        price = 1e12 if side == 'buy' else -1e12
        return self.submit_limit_order(side, price, qty, ts)

    def snapshot(self, depth: int = 5) -> dict:
        """Return top-of-book snapshot."""
        bids_sorted = sorted(self.bids.keys(), reverse=True)[:depth]
        asks_sorted = sorted(self.asks.keys())[:depth]
        return {
            'bids': [(p, self.bids[p].total_qty) for p in bids_sorted],
            'asks': [(p, self.asks[p].total_qty) for p in asks_sorted],
            'mid': self.mid_price(),
            'spread': self.spread(),
        }

# Example usage
if __name__ == "__main__":
    book = OrderBook("AAPL")

    # Seed the book
    for p, q in [(99.90, 100), (99.80, 200), (99.70, 300)]:
        book.submit_limit_order('buy', p, q, 0.0)
    for p, q in [(100.10, 150), (100.20, 250), (100.30, 200)]:
        book.submit_limit_order('sell', p, q, 0.0)

    snap = book.snapshot()
    print(f"Mid: {snap['mid']:.4f}, Spread: {snap['spread']:.4f}")
    print(f"Bids: {snap['bids']}")
    print(f"Asks: {snap['asks']}")

    # Submit a market buy
    trades = book.submit_market_order('buy', 200, 1.0)
    for t in trades:
        print(f"Trade: {t.quantity} @ {t.price}")

