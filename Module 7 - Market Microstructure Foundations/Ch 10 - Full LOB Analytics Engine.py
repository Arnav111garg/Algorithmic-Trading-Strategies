# Example: live processing loop
def run_microstructure_analytics(feed: list) -> None:
    """
    Simulate processing a market data feed.
    """
    engine = MicrostructureAnalytics(symbol="SPY")

    for event in feed:
        engine.update(
            bid=event['bid'], ask=event['ask'],
            bid_qty=event['bid_qty'], ask_qty=event['ask_qty'],
            trade_price=event.get('trade_price'),
            trade_qty=event.get('trade_qty'),
            timestamp=event.get('timestamp'),
        )

    # Final metrics
    metrics = engine.metrics()
    regime = engine.regime()
    toxic = engine.is_toxic_flow()
    print(f"Symbol: SPY | Regime: {regime} | Toxic: {toxic}")
    for k, v in metrics.items():
        print(f"  {k}: {v:.6f}" if isinstance(v, float) else f"  {k}: {v}")

