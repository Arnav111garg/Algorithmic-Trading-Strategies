import numpy as np
import pandas as pd
from typing import Optional, List, Dict, Tuple
from dataclasses import dataclass, field
from collections import deque
import warnings
warnings.filterwarnings('ignore')

class MicrostructureAnalytics:
    """
    Comprehensive real-time microstructure analytics engine.
    Designed for integration with live market data feeds.
    """
    def __init__(self, symbol: str, lookback: int = 500):
        self.symbol = symbol
        self.lookback = lookback

        # Rolling buffers
        self._prices = deque(maxlen=lookback)
        self._returns = deque(maxlen=lookback)
        self._volumes = deque(maxlen=lookback)
        self._directions = deque(maxlen=lookback)
        self._spreads = deque(maxlen=lookback)
        self._obi = deque(maxlen=lookback)
        self._timestamps = deque(maxlen=lookback)

        # State
        self._last_mid: Optional[float] = None
        self._trade_count = 0

    def update(self, bid: float, ask: float,
               bid_qty: float, ask_qty: float,
               trade_price: Optional[float] = None,
               trade_qty: Optional[float] = 0,
               timestamp: Optional[float] = None):
        """
        Process a new market data event.
        """
        if timestamp is None:
            timestamp = self._trade_count

        mid = (bid + ask) / 2.0
        spread = ask - bid

        # OBI
        total_qty = bid_qty + ask_qty
        obi = (bid_qty - ask_qty) / total_qty if total_qty > 0 else 0.0

        # Record
        self._spreads.append(spread)
        self._obi.append(obi)
        self._timestamps.append(timestamp)

        # Process trade
        if trade_price is not None and trade_qty and trade_qty > 0:
            direction = 1.0 if trade_price >= mid else -1.0
            self._prices.append(trade_price)
            self._directions.append(direction)
            self._volumes.append(trade_qty)
            if self._last_mid is not None:
                self._returns.append(mid - self._last_mid)
            self._trade_count += 1

        self._last_mid = mid

    def metrics(self) -> Dict:
        """Compute all microstructure metrics."""
        result = {}

        arr_s = np.array(self._spreads)
        arr_obi = np.array(self._obi)
        arr_r = np.array(self._returns)
        arr_v = np.array(self._volumes)
        arr_d = np.array(self._directions)

        if len(arr_s) > 10:
            result['avg_spread'] = np.mean(arr_s)
            result['spread_99pct'] = np.percentile(arr_s, 99)

        if len(arr_obi) > 10:
            result['avg_obi'] = np.mean(arr_obi)
            result['obi_std'] = np.std(arr_obi)
            result['micro_price_bias'] = np.mean(arr_obi)  # proxy

        if len(arr_r) > 20:
            result['realized_vol'] = np.std(arr_r) * np.sqrt(len(arr_r))

        # Roll spread
        dp = arr_r
        if len(dp) > 2:
            cov = np.cov(dp[:-1], dp[1:])[0, 1]
            result['roll_spread'] = 2 * np.sqrt(-cov) if cov < 0 else 0.0

        # AR(1) coefficient (mean reversion)
        if len(dp) > 10:
            result['price_ar1'] = np.corrcoef(dp[:-1], dp[1:])[0, 1]

        if len(arr_v) > 10 and len(arr_d) > 10:
            n = min(len(arr_v), len(arr_d))
            signed_vol = arr_v[-n:] * arr_d[-n:]
            result['trade_imbalance'] = (
                signed_vol.sum() / arr_v[-n:].sum()
                if arr_v[-n:].sum() > 0 else 0
            )

        # Amihud
        if len(arr_r) > 0:
            nr = min(len(arr_r), n if 'n' in locals() else len(arr_r))
            result['amihud_illiq'] = (
                np.mean(np.abs(arr_r[-nr:]) / (arr_v[-nr:] + 1e-10)) * 1e6
            )

        return result

    def is_toxic_flow(self, vpin_threshold: float = 0.65) -> bool:
        """Quick toxic flow check based on trade imbalance proxy."""
        m = self.metrics()
        return abs(m.get('trade_imbalance', 0)) > vpin_threshold

    def regime(self) -> str:
        """Classify current market regime."""
        m = self.metrics()
        spread_elevated = (
            m.get('avg_spread', 0) > 2 * np.median(list(self._spreads))
            if len(self._spreads) > 50 else False
        )
        vol_spike = (
            m.get('realized_vol', 0) > 2 * (
                np.std(list(self._returns)[:len(self._returns) // 2]) *
                np.sqrt(len(self._returns) // 2) + 1e-10
            )
        )
        mean_reverting = m.get('price_ar1', 0) < -0.1

        if spread_elevated or (vol_spike and self.is_toxic_flow()):
            return 'STRESSED'
        elif mean_reverting and not spread_elevated:
            return 'QUIET_MM'
        elif vol_spike and not self.is_toxic_flow():
            return 'VOLATILE_FAIR'
        else:
            return 'NORMAL'

