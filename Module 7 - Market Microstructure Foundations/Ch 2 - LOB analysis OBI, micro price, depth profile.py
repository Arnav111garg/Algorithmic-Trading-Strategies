import numpy as np
import pandas as pd
from dataclasses import dataclass
from typing import List, Tuple

@dataclass
class LOBSnapshot:
    timestamp: float
    bids: List[Tuple[float, int]]  # (price, qty) sorted desc
    asks: List[Tuple[float, int]]  # (price, qty) sorted asc

    @property
    def best_bid(self) -> float:
        return self.bids[0][0] if self.bids else np.nan

    @property
    def best_ask(self) -> float:
        return self.asks[0][0] if self.asks else np.nan

    @property
    def mid(self) -> float:
        return (self.best_bid + self.best_ask) / 2.0

    @property
    def spread(self) -> float:
        return self.best_ask - self.best_bid

    def idx(self, depth: int = 1) -> float:
        """Alias or helper if needed."""
        return self.obi(depth)

    def obi(self, depth: int = 1) -> float:
        """Order Book Imbalance at given depth."""
        bid_vol = sum(q for _, q in self.bids[:depth])
        ask_vol = sum(q for _, q in self.asks[:depth])
        total = bid_vol + ask_vol
        return (bid_vol - ask_vol) / total if total > 0 else 0.0

    def micro_price(self) -> float:
        """Stoikov micro-price (top-of-book)."""
        qb = self.bids[0][1] if self.bids else 0
        qa = self.asks[0][1] if self.asks else 0
        total = qb + qa
        if total == 0:
            return self.mid
        return (self.best_ask * qb + self.best_bid * qa) / total

    def weighted_mid(self, depth: int = 5) -> float:
        """Volume-weighted mid using top 'depth' levels."""
        bid_vwap = np.sum([p * q for p, q in self.bids[:depth]])
        ask_vwap = np.sum([p * q for p, q in self.asks[:depth]])
        bid_vol = np.sum([q for _, q in self.bids[:depth]])
        ask_vol = np.sum([q for _, q in self.asks[:depth]])
        if bid_vol + ask_vol == 0:
            return self.mid
        return (bid_vwap + ask_vwap) / (bid_vol + ask_vol)

    def depth_profile(self, n_levels: int = 10) -> pd.DataFrame:
        """Cumulative depth on both sides."""
        records = []
        cum_bid = cum_ask = 0
        for i in range(n_levels):
            bp, bq = self.bids[i] if i < len(self.bids) else (np.nan, 0)
            ap, aq = self.asks[i] if i < len(self.asks) else (np.nan, 0)
            cum_bid += bq
            cum_ask += aq
            records.append({
                'level': i + 1,
                'bid_price': bp,
                'bid_qty': bq,
                'cum_bid': cum_bid,
                'ask_price': ap,
                'ask_qty': aq,
                'cum_ask': cum_ask
            })
        return pd.DataFrame(records)

def obi_price_prediction(snapshots: List[LOBSnapshot], future_prices: List[float], depth: int = 5) -> dict:
    """
    Regress future price change on OBI.
    Returns regression coefficients and R^2.
    """
    from sklearn.linear_model import LinearRegression

    X = np.array([[s.obi(depth)] for s in snapshots[:-1]])
    y = np.array([future_prices[i + 1] - future_prices[i] for i in range(len(future_prices) - 1)])
    reg = LinearRegression().fit(X, y)
    ss_res = np.sum((y - reg.predict(X)) ** 2)
    ss_tot = np.sum((y - y.mean()) ** 2)
    r2 = 1 - ss_res / ss_tot if ss_tot > 0 else 0.0
    return {'coef': reg.coef_[0], 'intercept': reg.intercept_, 'R2': r2}

