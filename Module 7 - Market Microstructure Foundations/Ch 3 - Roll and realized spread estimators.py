import numpy as np
import pandas as pd
from scipy.optimize import minimize_scalar

def roll_spread(prices: np.ndarray) -> float:
    """
    Roll (1984) spread estimator from transaction prices.
    S = 2 * sqrt ( -Cov (dP_t , dP_{t -1}) )
    """
    dp = np.diff(prices)
    cov = np.cov(dp[:-1], dp[1:])[0, 1]
    if cov >= 0:
        return 0.0  # Roll estimator not defined (cov must be negative)
    return 2.0 * np.sqrt(-cov)

def effective_spread(trades: pd.DataFrame) -> pd.Series:
    """
    Compute effective spread from trade data.
    trades must have columns : 'price', 'direction' (+1/-1), 'mid'
    """
    return 2 * trades['direction'] * (trades['price'] - trades['mid'])

def realized_spread(trades: pd.DataFrame, tau_idx: int = 5) -> pd.Series:
    """
    Compute realized spread : 2* direction *( price_t - mid_ {t+tau })
    Measures market maker profit after price impact.
    """
    mid_future = trades['mid'].shift(-tau_idx)
    return 2 * trades['direction'] * (trades['price'] - mid_future)

def price_impact(trades: pd.DataFrame, tau_idx: int = 5) -> pd.Series:
    """
    Adverse selection ( price impact ) = EffSpread - RealSpread
    = 2* direction *( mid_ {t+tau } - mid_t )
    """
    eff = effective_spread(trades)
    real = realized_spread(trades, tau_idx)
    return eff - real

def huang_stoll_decomposition(trades: pd.DataFrame) -> dict:
    """
    Huang-Stoll (1997) spread decomposition via OLS.
    Estimates lambda ( adverse selection ) and theta ( order processing ).
    """
    from sklearn.linear_model import LinearRegression

    # dM_ {t+1} = lambda * s/2 * phi_t + noise
    dm = np.diff(trades['mid'].values)
    phi = trades['direction'].values[:-1]
    half_spread = trades['price'].values[:-1] - trades['mid'].values[:-1]

    # Regress midprice change on direction * half-spread
    X = (phi * half_spread).reshape(-1, 1)
    reg = LinearRegression().fit(X, dm)
    lam = reg.coef_[0]  # adverse selection fraction

    return {
        'lambda_adverse_selection': lam,
        'theta_order_processing': max(0.0, 1.0 - lam),
        'adverse_selection_pct': f"{lam * 100:.1f}%"
    }

# Spread normalization
def relative_spread(bid: float, ask: float) -> float:
    """ Relative quoted spread in basis points ."""
    return (ask - bid) / ((ask + bid) / 2) * 10000

def log_spread(bid: float, ask: float) -> float:
    """Log quoted spread ( scale invariant )."""
    return np.log(ask) - np.log(bid)

