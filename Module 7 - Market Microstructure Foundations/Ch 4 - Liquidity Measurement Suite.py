import numpy as np
import pandas as pd
from scipy import stats

def amihud_illiquidity(returns: pd.Series, dollar_volume: pd.Series, window: int = 21) -> pd.Series:
    """
    Amihud (2002) illiquidity ratio.
    ILLIQ_t = mean (| R_t | / DollarVol_t ) over [t- window +1 , t]
    """
    ratio = returns.abs() / (dollar_volume + 1e-10)  # avoid div by zero
    return ratio.rolling(window).mean() * 1e6  # scale to per million

def kyle_lambda(price_changes: np.ndarray, signed_order_flow: np.ndarray) -> dict:
    """
    Estimate Kyle's lambda via OLS:
    dp_t = lambda * OrderFlow_t + eps_t
    """
    from sklearn.linear_model import LinearRegression
    X = signed_order_flow.reshape(-1, 1)
    y = price_changes
    reg = LinearRegression(fit_intercept=True).fit(X, y)
    y_pred = reg.predict(X)
    ss_res = np.sum((y - y_pred) ** 2)
    ss_tot = np.sum((y - y.mean()) ** 2)
    return {
        'lambda': reg.coef_[0],
        'R2': 1.0 - (ss_res / ss_tot if ss_tot > 0 else 0.0),
        'intercept': reg.intercept_,
        't_stat': reg.coef_[0] / (np.std(y - y_pred) / np.sqrt(len(y) * np.var(X)) if np.var(X) > 0 and len(y) > 0 else 1.0)
    }

def liquidity_adjusted_var(position_value: float, spread_bps: float, vol_daily: float, confidence: float = 0.95, horizon_days: int = 1, impact_bps: float = 0.0) -> dict:
    """
    Liquidity-adjusted VaR.
    Adds half-spread + market impact to standard VaR.
    """
    z = stats.norm.ppf(confidence)
    market_var = position_value * vol_daily * np.sqrt(horizon_days) * z
    bid_ask_cost = position_value * (spread_bps / 10000.0) / 2.0
    impact_cost = position_value * (impact_bps / 10000.0)
    lvar = market_var + bid_ask_cost + impact_cost
    return {
        'market_VaR': market_var,
        'bid_ask_cost': bid_ask_cost,
        'impact_cost': impact_cost,
        'LVaR': lvar,
        'liquidity_premium_pct': (bid_ask_cost + impact_cost) / market_var * 100.0 if market_var > 0 else 0.0
    }

def volume_at_price(snapshots: list) -> pd.DataFrame:
    """
    Build Volume-at-Price profile from LOB snapshots.
    Returns distribution of liquidity across price levels.
    """
    records = []
    for snap in snapshots:
        mid = snap.mid
        for p, q in snap.bids:
            records.append({'dist_from_mid': p - mid, 'qty': q, 'side': 'bid', 'mid': mid})
        for p, q in snap.asks:
            records.append({'dist_from_mid': p - mid, 'qty': q, 'side': 'ask', 'mid': mid})
    df = pd.DataFrame(records)
    if df.empty:
        return pd.DataFrame(columns=['side', 'dist_from_mid', 'qty'])
    # Average qty at each tick distance
    profile = df.groupby(['side', 'dist_from_mid'])['qty'].mean().reset_index()
    return profile

