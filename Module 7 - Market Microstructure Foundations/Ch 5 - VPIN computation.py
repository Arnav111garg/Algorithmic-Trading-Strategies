import numpy as np
import pandas as pd
from scipy.special import erf

def bulk_classification(df_ticks: pd.DataFrame, bucket_size: int = None) -> pd.DataFrame:
    """
    Easley - Lopez de Prado - O'Hara VPIN (2012).
    df_ticks : DataFrame with ['price', 'volume', 'timestamp']
    Returns DataFrame with VPIN per volume bucket.
    """
    if bucket_size is None:
        bucket_size = int(df_ticks['volume'].sum() / 50)

    # Assign trades to buckets
    df = df_ticks.copy()
    df['cum_vol'] = df['volume'].cumsum()
    df['bucket'] = (df['cum_vol'] / bucket_size).astype(int)

    # Compute bucket-level statistics
    buckets = df.groupby('bucket').agg(
        total_vol=('volume', 'sum'),
        price_open=('price', 'first'),
        price_close=('price', 'last'),
    ).reset_index()

    # Bucket returns and vol
    buckets['return'] = (buckets['price_close'] - buckets['price_open']) / buckets['price_open']
    buckets['sigma_bucket'] = buckets['return'].rolling(50).std().fillna(buckets['return'].std())

    # Bulk volume classification
    def classify(row):
        z = row['return'] / (row['sigma_bucket'] * np.sqrt(2) + 1e-12)
        V_buy = row['total_vol'] / 2 * (1 + erf(z))
        V_sell = row['total_vol'] - V_buy
        return pd.Series({'V_buy': V_buy, 'V_sell': V_sell})

    classified = buckets.apply(classify, axis=1)
    buckets = pd.concat([buckets, classified], axis=1)

    # Rolling VPIN over L buckets
    L = 50
    buckets['abs_imbalance'] = np.abs(buckets['V_buy'] - buckets['V_sell'])
    buckets['VPIN'] = (
        buckets['abs_imbalance'].rolling(L).sum() / (L * bucket_size)
    )

    return buckets[['bucket', 'total_vol', 'return', 'V_buy', 'V_sell', 'VPIN']].dropna()

def order_flow_toxicity_signal(vpin_series: pd.Series, threshold_hi: float = 0.60, threshold_lo: float = 0.40) -> pd.Series:
    """
    Convert VPIN to trading signal for spread adjustment.
    Returns: 'widen' (toxic), 'normal', 'tighten' (quiet).
    """
    signal = pd.Series('normal', index=vpin_series.index)
    signal[vpin_series > threshold_hi] = 'widen'
    signal[vpin_series < threshold_lo] = 'tighten'
    return signal

