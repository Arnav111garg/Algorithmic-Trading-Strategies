import numpy as np
from scipy.integrate import quad
from dataclasses import dataclass

@dataclass
class AlmgrenChrissParams:
    sigma: float      # daily vol (fraction)
    gamma: float      # permanent impact coefficient
    eta: float        # temporary impact coefficient
    epsilon: float    # fixed spread cost per share
    tau: float = 1.0  # time between trades (days)

def almgren_chriss_trajectory(X: float, T: float, params: AlmgrenChrissParams, lam: float, N: int = 100) -> dict:
    """
    Compute Almgren-Chriss optimal execution trajectory.
    X: total shares, T: time horizon (days), lam: risk aversion,
    N: number of time steps.
    Returns trajectory, expected cost, cost variance.
    """
    tau = T / N
    eta_tilde = params.eta - 0.5 * params.gamma * tau
    if eta_tilde > 0:
        kappa_sq = lam * (params.sigma ** 2) / eta_tilde
    else:
        kappa_sq = 0.0

    kappa = np.sqrt(max(kappa_sq, 0.0))
    t_arr = np.linspace(0, T, N + 1)

    if kappa < 1e-8:
        # TWAP limit
        x_arr = X * (1 - t_arr / T)
    else:
        x_arr = X * np.sinh(kappa * (T - t_arr)) / np.sinh(kappa * T)

    # Trading rates (per interval)
    n_arr = np.diff(x_arr) * (-1) # shares sold in each interval

    # Expected cost
    perm_cost = params.gamma * (X ** 2) / 2
    temp_cost = (params.eta / tau) * np.sum(n_arr ** 2)
    E_cost = perm_cost + temp_cost

    # Cost variance
    Var_cost = (params.sigma ** 2) * tau * np.sum(x_arr[:-1] ** 2)

    return {
        'trajectory': x_arr,
        'n_per_interval': n_arr,
        'time': t_arr,
        'kappa': kappa,
        'E_cost': E_cost,
        'Var_cost': Var_cost,
        'E_cost_bps': E_cost / (X * 1.0) * 1e4, # assuming S0 = 1
        'Std_cost': np.sqrt(Var_cost),
    }

def sqrt_impact(Q: float, V_daily: float, sigma: float, gamma: float = 0.3) -> float:
    """
    Square-root market impact law.
    Q: order size, V_daily: avg daily vol,
    sigma: daily vol (fraction), gamma: scaling factor.
    Returns: price impact in fraction of price.
    """
    return gamma * sigma * np.sqrt(abs(Q) / V_daily) * np.sign(Q)

def implementation_shortfall(exec_prices: np.ndarray, exec_sizes: np.ndarray, arrival_price: float, total_shares: float) -> dict:
    """
    Compute implementation shortfall metrics.
    exec_prices: prices of each fill
    exec_sizes: quantities of each fill
    arrival_price: price when decision was made
    total_shares: total order size (shares)
    """
    filled = exec_sizes.sum()
    unfilled = total_shares - filled

    # VWAP of execution
    vwap_exec = np.dot(exec_prices, exec_sizes) / filled if filled > 0 else 0.0

    # Slippage vs arrival
    slippage_bps = (vwap_exec - arrival_price) / arrival_price * 10000

    # IS = market impact + delay + opportunity
    market_impact = (vwap_exec - arrival_price) * filled

    return {
        'filled_qty': filled,
        'unfilled_qty': unfilled,
        'fill_rate': filled / total_shares,
        'vwap_execution': vwap_exec,
        'arrival_price': arrival_price,
        'slippage_bps': slippage_bps,
        'market_impact_cost': market_impact,
    }

