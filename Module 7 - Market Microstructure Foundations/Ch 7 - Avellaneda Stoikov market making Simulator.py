import numpy as np
from dataclasses import dataclass

@dataclass
class ASParams:
    gamma: float = 0.1       # risk aversion
    k: float = 1.5           # market order arrival sensitivity
    A: float = 140.0         # base market order arrival rate
    sigma: float = 2.0       # price diffusion (per unit time)
    T: float = 1.0           # trading horizon

def avellaneda_stoikov_quotes(S: float, q: float, t: float, params: ASParams) -> dict:
    """
    Compute AS optimal bid and ask given current state.
    S: current mid-price
    q: current inventory
    t: current time (0 to T)
    Returns bid, ask, spread, reservation_price.
    """
    p = params
    T_rem = p.T - t

    # Reservation price (inventory adjustment)
    r = S - q * p.gamma * (p.sigma ** 2) * T_rem

    # Optimal spread
    delta = p.gamma * (p.sigma ** 2) * T_rem + (2.0 / p.gamma) * np.log(1.0 + p.gamma / p.k)

    bid = r - delta / 2.0
    ask = r + delta / 2.0

    # Arrival rate at optimal quotes
    lam_bid = p.A * np.exp(-p.k * delta / 2.0)
    lam_ask = p.A * np.exp(-p.k * delta / 2.0)

    return {
        'bid': bid,
        'ask': ask,
        'reservation_price': r,
        'spread': delta,
        'half_spread': delta / 2.0,
        'lam_bid': lam_bid,
        'lam_ask': lam_ask,
        'inventory_skew': -q * p.gamma * (p.sigma ** 2) * T_rem,
    }

def simulate_as_market_maker(params: ASParams, n_steps: int = 1000, dt: float = 0.001, seed: int = 42) -> dict:
    """
    Monte Carlo simulation of A-S market maker.
    Returns: PnL series, inventory series, quote series.
    """
    np.random.seed(seed)
    S = 100.0
    q = 0.0
    X = 0.0 # cash
    pnl_series = [X + q * S]
    inv_series = [q]
    times = [0.0]

    for i in range(n_steps):
        t = i * dt
        quotes = avellaneda_stoikov_quotes(S, q, t, params)

        # Price diffusion
        dW = np.random.randn() * params.sigma * np.sqrt(dt)
        S = S + dW

        # Market order arrivals (Poisson)
        n_buy = np.random.poison(quotes['lam_ask'] * dt)
        n_sell = np.random.poisson(quotes['lam_bid'] * dt)

        # Update cash and inventory
        X += n_buy * quotes['ask']      # cash in from sells to buyers
        X -= n_sell * quotes['bid']     # cash out from buys from sellers
        q += n_sell - n_buy             # inventory: buy from sellers, sell to buyers

        pnl_series.append(X + q * S)    # mark-to-market PnL
        inv_series.append(q)
        times.append(t)

    return {
        'pnl': np.array(pnl_series),
        'inventory': np.array(inv_series),
        'times': np.array(times),
        'final_pnl': pnl_series[-1],
        'max_inventory': max(abs(np.array(inv_series))),
        'sharpe': (np.mean(np.diff(pnl_series)) / (np.std(np.diff(pnl_series)) + 1e-10) * np.sqrt(252 / dt)),
    }

