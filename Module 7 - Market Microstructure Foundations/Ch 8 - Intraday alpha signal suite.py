import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression, Ridge
from sklearn.preprocessing import StandardScaler

def compute_ofi(lob_snapshots: pd.DataFrame, depth: int = 5) -> pd.Series:
    """
    Multi-level Order Flow Imbalance.
    lob_snapshots : DataFrame indexed by time with columns
    bid_qty_1..depth, ask_qty_1..depth, bid_px_1..depth, ask_px_1..depth
    """
    rho = 0.5  # geometric decay for levels
    ofi_components = []

    for level in range(1, depth + 1):
        bq = lob_snapshots[f'bid_qty_{level}']
        aq = lob_snapshots[f'ask_qty_{level}']
        # Changes in queue sizes (OFI uses incremental changes)
        delta_bq = bq.diff().fillna(0)
        delta_aq = aq.diff().fillna(0)
        weight = rho ** (level - 1)
        ofi_components.append(weight * (delta_bq - delta_aq))

    return pd.concat(ofi_components, axis=1).sum(axis=1)

def trade_imbalance(trades: pd.DataFrame, window: int = 20) -> pd.Series:
    """
    Rolling trade imbalance signal.
    trades : DataFrame with 'quantity' and 'direction' (+1/-1).
    """
    signed_vol = trades['quantity'] * trades['direction']
    total_vol = trades['quantity']
    return (signed_vol.rolling(window).sum() / total_vol.rolling(window).sum()).fillna(0)

def alpha_decay_halflife(signal: pd.Series, returns: pd.Series, max_lag: int = 60) -> float:
    """
    Estimate alpha signal half-life by computing IC at multiple lags.
    Returns estimated half-life in periods.
    """
    ics = []
    lags = range(1, max_lag + 1)
    for lag in lags:
        ic = signal.corr(returns.shift(-lag))
        ics.append(ic if not np.isnan(ic) else 0)

    ics = np.array(ics)
    # Fit exponential decay : IC(tau) = IC0 * exp(-tau/half_life)
    from scipy.optimize import curve_fit
    try:
        def exp_decay(tau, ic0, half_life):
            return ic0 * np.exp(-tau / half_life)
        popt, _ = curve_fit(exp_decay, list(lags), ics, p0=[ics[0], 20.0], maxfev=5000)
        return popt[1]  # half-life in periods
    except:
        return np.nan

def optimal_execution_horizon(signal_halflife: float, transaction_cost_bps: float, signal_strength_bps: float) -> float:
    """
    Optimal holding period given alpha decay and transaction cost.
    Returns : optimal hold time in same units as signal_halflife.
    """
    if signal_strength_bps <= transaction_cost_bps:
        return 0.0  # No holding is profitable
    return signal_halflife * np.log(signal_strength_bps / transaction_cost_bps)

def information_ratio_by_holding(signal: pd.Series, returns: pd.Series, horizons: list, tc_bps: float = 5.0) -> pd.DataFrame:
    """
    Compute IR for different holding horizons.
    tc_bps : round-trip transaction cost in basis points.
    """
    results = []
    for h in horizons:
        fwd_ret = returns.rolling(h).sum().shift(-h)
        valid = signal.notna() & fwd_ret.notna()
        ic = signal[valid].corr(fwd_ret[valid])
        vol_fwd = fwd_ret[valid].std()
        # Expected return from signal
        alpha_bps = ic * vol_fwd * 1e4
        net_alpha_bps = alpha_bps - tc_bps
        ir = net_alpha_bps / (vol_fwd * 1e4 + 1e-10) * np.sqrt(252)

        results.append({
            'horizon': h,
            'IC': ic,
            'alpha_bps': alpha_bps,
            'net_alpha_bps': net_alpha_bps,
            'IR': ir
        })
    return pd.DataFrame(results)

