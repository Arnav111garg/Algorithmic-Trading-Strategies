import numpy as np
import pandas as pd
from scipy.stats import norm
from scipy.special import logsumexp

class GaussianHMM:
    """
    Gaussian Hidden Markov Model for market regime detection.
    Uses Baum-Welch (EM) for parameter estimation.
    """
    def __init__(self, n_states: int = 2, n_iter: int = 100, tol: float = 1e-6):
        self.K = n_states
        self.n_iter = n_iter
        self.tol = tol

    def _initialize(self, X: np.ndarray):
        N = len(X)
        K = self.K
        # Random initialization with k-means-like init
        sorted_idx = np.argsort(np.abs(X))
        self.mu = np.array([
            np.mean(X[sorted_idx[:N // K]]),
            np.mean(X[sorted_idx[N // K:]])
        ])
        self.sigma = np.array([
            np.std(X[sorted_idx[:N // K]]) + 1e-4,
            np.std(X[sorted_idx[N // K:]]) + 1e-4
        ])
        # Transition matrix: mostly stay in same state
        self.A = np.ones((K, K)) * 0.05 / (K - 1)
        np.fill_diagonal(self.A, 0.95)
        self.pi0 = np.ones(K) / K  # initial state distribution

    def _log_emission(self, X: np.ndarray) -> np.ndarray:
        """Log emission probabilities. Shape (N, K)."""
        return np.column_stack([
            norm.logpdf(X, self.mu[k], self.sigma[k])
            for k in range(self.K)
        ])

    def _forward(self, log_B: np.ndarray):
        N, K = log_B.shape
        log_alpha = np.full((N, K), -np.inf)
        log_alpha[0] = np.log(self.pi0 + 1e-300) + log_B[0]
        log_A = np.log(self.A + 1e-300)
        for t in range(1, N):
            for j in range(K):
                log_alpha[t, j] = logsumexp(log_alpha[t - 1] + log_A[:, j]) + log_B[t, j]
        return log_alpha

    def _backward(self, log_B: np.ndarray):
        N, K = log_B.shape
        log_beta = np.zeros((N, K))
        log_A = np.log(self.A + 1e-300)
        for t in range(N - 2, -1, -1):
            for i in range(K):
                log_beta[t, i] = logsumexp(log_A[i, :] + log_B[t + 1, :] + log_beta[t + 1, :])
        return log_beta

    def fit(self, X: np.ndarray):
        self._initialize(X)
        prev_ll = -np.inf

        for iteration in range(self.n_iter):
            log_B = self._log_emission(X)
            log_alpha = self._forward(log_B)
            log_beta = self._backward(log_B)

            # Log-likelihood
            ll = logsumexp(log_alpha[-1])

            # Posterior state probabilities (gamma)
            log_gamma = log_alpha + log_beta
            log_gamma -= logsumexp(log_gamma, axis=1, keepdims=True)
            gamma = np.exp(log_gamma)

            # M-step: update parameters
            self.mu = np.sum(gamma * X[:, None], axis=0) / (gamma.sum(axis=0) + 1e-300)
            self.sigma = np.sqrt(
                np.sum(gamma * (X[:, None] - self.mu) ** 2, axis=0) / (gamma.sum(axis=0) + 1e-300)
            ) + 1e-4

            # Update transition matrix
            N, K = log_B.shape
            log_A = np.log(self.A + 1e-300)
            xi_sum = np.zeros((K, K))
            for t in range(N - 1):
                xi = log_alpha[t, :, None] + log_A + log_B[t + 1, None, :] + log_beta[t + 1, None, :]
                xi -= logsumexp(xi.ravel())
                xi_sum += np.exp(xi)
            self.A = xi_sum / (xi_sum.sum(axis=1, keepdims=True) + 1e-300)

            if abs(ll - prev_ll) < self.tol:
                break
            prev_ll = ll

        self.log_likelihood_ = ll
        return self

    def predict_proba(self, X: np.ndarray) -> np.ndarray:
        """Return smoothed posterior probabilities of each state."""
        log_B = self._log_emission(X)
        log_alpha = self._forward(log_B)
        log_beta = self._backward(log_B)
        log_gamma = log_alpha + log_beta
        log_gamma -= logsumexp(log_gamma, axis=1, keepdims=True)
        return np.exp(log_gamma)

    def predict(self, X: np.ndarray) -> np.ndarray:
        """Viterbi decoding: most likely state sequence."""
        return np.argmax(self.predict_proba(X), axis=1)

def regime_adaptive_position_size(base_size: float, regime_proba: np.ndarray, calm_state: int = 0) -> float:
    """
    Scale position size by probability of being in calm regime.
    """
    p_calm = regime_proba[calm_state]
    return base_size * p_calm

