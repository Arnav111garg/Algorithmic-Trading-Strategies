import numpy as np
import pandas as pd
from scipy.stats import norm

def lee_ready_classify(trades: pd.DataFrame) -> pd.Series:
    """
    Lee-Ready trade classification.
    Requires columns: price, bid, ask
    Returns: Series of {+1, -1}
    """
    mid = (trades['ask'] + trades['bid']) / 2.0
    direction = pd.Series(0.0, index=trades.index, dtype=float)

    # Quote test
    above_mid = trades['price'] > mid
    below_mid = trades['price'] < mid
    direction[above_mid] = 1.0
    direction[below_mid] = -1.0

    # Tick test for at-midpoint trades
    at_mid = ~above_mid & ~below_mid

    for idx in trades.index[at_mid]:
        pos = trades.index.get_loc(idx)
        # Find last non-zero tick
        for j in range(pos - 1, -1, -1):
            dp = trades['price'].iloc[pos] - trades['price'].iloc[j]
            if dp > 0:
                direction.iloc[pos] = 1.0
                break
            elif dp < 0:
                direction.iloc[pos] = -1.0
                break

    return direction

def bvc_classify(ohlcv: pd.DataFrame, window: int = 50) -> pd.DataFrame:
    """
    Bulk Volume Classification (Easley, Lopez de Prado, O’Hara 2012).
    Requires columns: close, volume
    """
    df = ohlcv.copy()
    df['price_change'] = df['close'].diff()
    df['sigma'] = df['price_change'].rolling(window).std()
    df['z'] = df['price_change'] / df['sigma']
    df['buy_volume'] = df['volume'] * norm.cdf(df['z'])
    df['sell_volume'] = df['volume'] * (1 - norm.cdf(df['z']))
    df['signed_flow'] = df['buy_volume'] - df['sell_volume']
    df['order_imbalance'] = df['signed_flow'] / df['volume']
    return df[['buy_volume', 'sell_volume', 'signed_flow', 'order_imbalance']].dropna()

# Example Usage
np.random.seed(42)
n = 500
prices = 100 + np.cumsum(np.random.randn(n) * 0.05)
volumes = np.random.lognormal(mean=7, sigma=1, size=n)

ohlcv = pd.DataFrame({
    'close': prices,
    'volume': volumes
})
result = bvc_classify(ohlcv)
print("Mean Order Imbalance:", result['order_imbalance'].mean())
print("Std Order Imbalance:", result['order_imbalance'].std())

