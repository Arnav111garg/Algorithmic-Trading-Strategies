import numpy as np
import pandas as pd

# Dollar Bar Construction
def build_dollar_bars(trades: pd.DataFrame, target_dollar: float = 1e6) -> pd.DataFrame:
    """
    Build dollar bars from tick data.
    trades: DataFrame with columns [timestamp, price, volume, direction]
    target_dollar: target dollar value per bar
    """
    bars = []
    if len(trades) == 0:
        return pd.DataFrame()

    bar_open = trades['price'].iloc[0]
    bar_high = bar_open
    bar_low = bar_open
    cum_dollar = 0.0
    cum_buy_vol = 0.0
    cum_sell_vol = 0.0
    bar_start = trades['timestamp'].iloc[0]

    for _, row in trades.iterrows():
        dollar_val = row['price'] * row['volume']
        cum_dollar += dollar_val
        if row['direction'] > 0:
            cum_buy_vol += row['volume']
        else:
            cum_sell_vol += row['volume']
        bar_high = max(bar_high, row['price'])
        bar_low = min(bar_low, row['price'])

        if cum_dollar >= target_dollar:
            total_vol = cum_buy_vol + cum_sell_vol
            bars.append({
                'timestamp': row['timestamp'],
                'open': bar_open,
                'high': bar_high,
                'low': bar_low,
                'close': row['price'],
                'buy_volume': cum_buy_vol,
                'sell_volume': cum_sell_vol,
                'total_volume': total_vol,
                'dollar_volume': cum_dollar,
                'OI': cum_buy_vol - cum_sell_vol,
                'OIR': (cum_buy_vol - cum_sell_vol) / total_vol if total_vol > 0 else 0
            })
            # Reset
            bar_open = row['price']
            bar_high = row['price']
            bar_low = row['price']
            cum_dollar = 0.0
            cum_buy_vol = 0.0
            cum_sell_vol = 0.0
            bar_start = row['timestamp']

    return pd.DataFrame(bars)

# VPIN Computation
def compute_vpin(trades: pd.DataFrame, bucket_volume: float, window: int = 50) -> pd.Series:
    """
    Compute VPIN using BVC for direction estimation.
    """
    from scipy.stats import norm
    df = trades.copy()
    df['price_change'] = df['price'].diff()
    df['sigma'] = df['price_change'].rolling(50).std()
    df['sigma'] = df['sigma'].fillna(method='bfill')
    df['z'] = df['price_change'] / (df['sigma'] + 1e-10)
    df['buy_vol'] = df['volume'] * norm.cdf(df['z'])
    df['sell_vol'] = df['volume'] * norm.cdf(-df['z'])

    # Build volume buckets
    buckets = []
    cum_buy = 0.0
    cum_sell = 0.0
    cum_vol = 0.0

    for _, row in df.iterrows():
        cum_buy += row['buy_vol']
        cum_sell += row['sell_vol']
        cum_vol += row['volume']

        while cum_vol >= bucket_volume:
            fraction = bucket_volume / cum_vol
            buckets.append(abs(cum_buy * fraction - cum_sell * fraction))
            cum_buy *= (1 - fraction)
            cum_sell *= (1 - fraction)
            cum_vol -= bucket_volume

    vpin_series = pd.Series(buckets)
    vpin = vpin_series.rolling(window).mean() / bucket_volume
    return vpin

# Predictive Regression
def oir_predictive_regression(bars: pd.DataFrame, n_lags: int = 5) -> dict:
    """Test OIR's predictive power for future returns."""
    from sklearn.linear_model import LinearRegression
    from sklearn.metrics import r2_score

    df = bars.copy()
    df['ret'] = df['close'].pct_change()
    df['fwd_ret'] = df['ret'].shift(-1)

    # Lagged OIR features
    for k in range(1, n_lags + 1):
        df[f'OIR_lag{k}'] = df['OIR'].shift(k)

    df = df.dropna()
    feature_cols = [f'OIR_lag{k}' for k in range(1, n_lags + 1)]

    X = df[feature_cols].values
    y = df['fwd_ret'].values

    model = LinearRegression().fit(X, y)
    r2 = r2_score(y, model.predict(X))

    return {
        'coefficients': dict(zip(feature_cols, model.coef_)),
        'intercept': model.intercept_,
        'R2': r2,
        'IC': np.corrcoef(df['OIR_lag1'], df['fwd_ret'])[0, 1]
    }

