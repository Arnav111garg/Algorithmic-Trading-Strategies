import numpy as np
import pandas as pd
from dataclasses import dataclass
from typing import List, Tuple, Optional

@dataclass
class LOBSnapshot:
    """Single limit order book snapshot."""
    timestamp: float
    bids: List[Tuple[float, float]]  # [(price, qty), ...]
    asks: List[Tuple[float, float]]  # [(price, qty), ...]

    @property
    def best_bid(self):
        return self.bids[0][0] if self.bids else np.nan

    @property
    def best_ask(self):
        return self.asks[0][0] if self.asks else np.nan

    @property
    def mid(self):
        return (self.best_bid + self.best_ask) / 2

    @property
    def spread(self):
        return self.best_ask - self.best_bid

    @property
    def bid_qty(self):
        return self.bids[0][1] if self.bids else 0.0

    @property
    def ask_qty(self):
        return self.asks[0][1] if self.asks else 0.0


def compute_ofi(prev: LOBSnapshot, curr: LOBSnapshot) -> float:
    """
    Compute OFI between two consecutive LOB snapshots (Cont et al. 2014).
    """
    # Bid contribution
    if curr.best_bid > prev.best_bid:
        e_b = curr.bid_qty
    elif curr.best_bid == prev.best_bid:
        e_b = curr.bid_qty - prev.bid_qty
    else:
        e_b = -prev.bid_qty

    # Ask contribution
    if curr.best_ask > prev.best_ask:
        e_a = -prev.ask_qty
    elif curr.best_ask == prev.best_ask:
        e_a = prev.ask_qty - curr.ask_qty
    else:
        e_a = curr.ask_qty

    return e_b - e_a


def compute_multi_level_ofi(prev: LOBSnapshot, curr: LOBSnapshot, levels: int = 5) -> float:
    """
    Multi-level OFI across top L price levels.
    """
    # Build price-to-qty maps
    prev_bid_map = {p: q for p, q in prev.bids[:levels]}
    curr_bid_map = {p: q for p, q in curr.bids[:levels]}
    prev_ask_map = {p: q for p, q in prev.asks[:levels]}
    curr_ask_map = {p: q for p, q in curr.asks[:levels]}

    all_bid_prices = set(prev_bid_map) | set(curr_bid_map)
    all_ask_prices = set(prev_ask_map) | set(curr_ask_map)

    ofi = 0.0
    for p in all_bid_prices:
        prev_q = prev_bid_map.get(p, 0.0)
        curr_q = curr_bid_map.get(p, 0.0)
        ofi += curr_q - prev_q

    for p in all_ask_prices:
        prev_q = prev_ask_map.get(p, 0.0)
        curr_q = curr_ask_map.get(p, 0.0)
        ofi -= (curr_q - prev_q)

    return ofi


def compute_queue_imbalance(snapshot: LOBSnapshot) -> float:
    """Queue imbalance at best bid/ask."""
    bid_q = snapshot.bid_qty
    ask_q = snapshot.ask_qty
    denom = bid_q + ask_q
    return (bid_q - ask_q) / denom if denom > 0 else 0.0


def ofi_price_regression(lob_snapshots: List[LOBSnapshot], horizon: int = 10) -> dict:
    """
    Estimate theta in: delta_p = theta * OFI + epsilon
    over 'horizon' snapshots.
    """
    from sklearn.linear_model import LinearRegression
    from sklearn.metrics import r2_score

    n = len(lob_snapshots)
    ofi_list = []
    dp_list = []

    for i in range(1, n - horizon):
        ofi_val = sum(compute_ofi(lob_snapshots[j - 1], lob_snapshots[j]) for j in range(i, i + 1))
        dp_val = lob_snapshots[i + horizon].mid - lob_snapshots[i].mid
        ofi_list.append(ofi_val)
        dp_list.append(dp_val)

    X = np.array(ofi_list).reshape(-1, 1)
    y = np.array(dp_list)

    if len(X) < 10:
        return {}

    model = LinearRegression().fit(X, y)
    r2 = r2_score(y, model.predict(X))

    return {
        'theta': model.coef_[0],
        'R2': r2,
        'n_obs': len(y)
    }

