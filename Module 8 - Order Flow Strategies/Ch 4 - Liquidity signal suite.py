import numpy as np
import pandas as pd

def compute_effective_spread(trades: pd.DataFrame) -> pd.Series:
    """Effective half-spread for each trade."""
    mid = (trades['ask'] + trades['bid']) / 2.0
    return 2 * trades['direction'] * (trades['price'] - mid)

def compute_price_impact(trades: pd.DataFrame, horizon_seconds: float = 5.0) -> pd.Series:
    """
    Price impact: 2 * d * (mid_{t+tau} - mid_t).
    Uses forward mid-quote at horizon_seconds.
    """
    trades = trades.sort_values('timestamp').copy()
    mid = (trades['ask'] + trades['bid']) / 2.0
    trades['mid'] = mid

    impacts = np.full(len(trades), np.nan)
    for i, (idx, row) in enumerate(trades.iterrows()):
        future = trades[
            (trades['timestamp'] > row['timestamp']) &
            (trades['timestamp'] <= row['timestamp'] + horizon_seconds)
        ]
        if len(future) > 0:
            future_mid = future['mid'].iloc[-1]
            impacts[i] = 2 * row['direction'] * (future_mid - row['mid'])

    return pd.Series(impacts, index=trades.index)

def amihud_illiquidity(daily_data: pd.DataFrame, window: int = 20) -> pd.Series:
    """
    Amihud (2002) illiquidity ratio, rolling window.
    daily_data: DataFrame with columns [return, dollar_volume]
    """
    illiq = daily_data['return'].abs() / daily_data['dollar_volume']
    return illiq.rolling(window).mean() * 1e6  # Scale to bps/$M

def depth_weighted_mid(bid_price: float, ask_price: float, bid_qty: float, ask_qty: float) -> float:
    """Depth-weighted midpoint."""
    return (ask_qty * bid_price + bid_qty * ask_price) / (ask_qty + bid_qty)

def liquidity_signal_dashboard(lob_data: pd.DataFrame) -> pd.DataFrame:
    """
    Compute a full suite of real-time liquidity signals.
    lob_data columns: timestamp, bid, ask, bid_qty, ask_qty,
    last_price, last_qty, direction
    """
    df = lob_data.copy()
    df['mid'] = (df['bid'] + df['ask']) / 2
    df['spread'] = df['ask'] - df['bid']
    df['spread_bps'] = df['spread'] / df['mid'] * 1e4

    # Queue imbalance
    df['QI'] = (df['bid_qty'] - df['ask_qty']) / (df['bid_qty'] + df['ask_qty'] + 1e-10)

    # Depth-weighted mid
    df['DWM'] = (df['ask_qty'] * df['bid'] + df['bid_qty'] * df['ask']) / (df['ask_qty'] + df['bid_qty'] + 1e-10)
    df['DWM_vs_mid'] = df['DWM'] - df['mid']

    # Rolling effective spread
    df['eff_spread'] = 2 * df['direction'] * (df['last_price'] - df['mid'])
    df['eff_spread_ma'] = df['eff_spread'].rolling(20).mean()

    # Top-of-book depth
    df['TOB_depth'] = df['bid_qty'] + df['ask_qty']
    df['depth_zscore'] = (df['TOB_depth'] - df['TOB_depth'].rolling(100).mean()) / (df['TOB_depth'].rolling(100).std() + 1e-10)

    # VPIN-like toxicity (simplified rolling version)
    df['signed_vol'] = df['last_qty'] * df['direction']
    df['abs_signed_vol'] = df['signed_vol'].abs()
    df['total_vol'] = df['last_qty']
    df['VPIN_proxy'] = (df['abs_signed_vol'].rolling(50).sum() / df['total_vol'].rolling(50).sum())

    return df[['timestamp', 'spread_bps', 'QI', 'DWM_vs_mid', 'eff_spread_ma', 'depth_zscore', 'VPIN_proxy']]

