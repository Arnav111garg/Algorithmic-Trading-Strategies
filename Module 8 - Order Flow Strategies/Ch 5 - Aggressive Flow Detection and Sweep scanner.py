import numpy as np
import pandas as pd
from collections import deque

class SweepDetector:
    """
    Real-time sweep detection from L3 (order-by-order) data.
    """
    def __init__(
        self,
        time_window_ms: float = 50.0,
        min_levels: int = 2
    ):
        self.time_window_ms = time_window_ms
        self.min_levels = min_levels
        self.recent_trades = deque()
        self.sweeps = []

    def process_trade(
        self,
        timestamp: float,
        price: float,
        qty: float,
        direction: int,
        prev_ask: float,
        prev_bid: float,
        tick_size: float = 0.01
    ) -> dict | None:
        """
        Process incoming trade. Returns sweep dict if sweep detected.
        direction: +1 for buy, -1 for sell
        """
        # Remove old trades outside window
        cutoff = timestamp - self.time_window_ms / 1000.0
        while self.recent_trades and self.recent_trades[0]['ts'] < cutoff:
            self.recent_trades.popleft()

        self.recent_trades.append({
            'ts': timestamp,
            'price': price,
            'qty': qty,
            'dir': direction
        })

        # Check for sweep: multiple trades at increasing prices
        # (for buys) in short window
        same_dir = [t for t in self.recent_trades if t['dir'] == direction]
        if len(same_dir) < self.min_levels:
            return None

        prices = [t['price'] for t in same_dir]
        if direction == 1:  # Buy sweep
            price_range = max(prices) - min(prices)
        else:  # Sell sweep
            price_range = min(prices) - max(prices)

        levels_swept = abs(price_range) / tick_size

        if levels_swept >= self.min_levels:
            total_qty = sum(t['qty'] for t in same_dir)
            sweep = {
                'timestamp': timestamp,
                'direction': direction,
                'levels_swept': levels_swept,
                'total_qty': total_qty,
                'price_range': abs(price_range),
                'intensity': levels_swept * total_qty
            }
            self.sweeps.append(sweep)
            return sweep
        return None


def aggressive_flow_ratio(
    trades: pd.DataFrame,
    lob: pd.DataFrame,
    window: int = 100
) -> pd.Series:
    """
    Compute Aggressive Flow Ratio (AFR) on rolling window.
    trades: [timestamp, direction, is_aggressive]
    """
    df = trades.copy()
    df['agg_buy'] = ((df['direction'] == 1) & df['is_aggressive']).astype(float)
    df['agg_sell'] = ((df['direction'] == -1) & df['is_aggressive']).astype(float)
    df['passive'] = (~df['is_aggressive']).astype(float)

    rolling_ab = df['agg_buy'].rolling(window).sum()
    rolling_as = df['agg_sell'].rolling(window).sum()
    rolling_pas = df['passive'].rolling(window).sum()

    afr = (rolling_ab - rolling_as) / (rolling_ab + rolling_as + rolling_pas + 1e-10)
    return afr


def classify_aggression(
    trades: pd.DataFrame,
    lob: pd.DataFrame
) -> pd.DataFrame:
    """
    Label each trade by aggression level.
    Returns trades with 'aggression_level' column (0=passive, k=k levels swept).
    """
    merged = pd.merge_asof(
        trades.sort_values('timestamp'),
        lob.sort_values('timestamp'),
        on='timestamp',
        direction='backward'
    )

    def get_levels_swept(row):
        if row['direction'] == 1:  # Buy
            if row['price'] > row['ask']:
                return int((row['price'] - row['ask']) / row.get('tick_size', 0.01)) + 1
            elif row['price'] == row['ask']:
                return 1
            else:
                return 0
        else:  # Sell
            if row['price'] < row['bid']:
                return int((row['bid'] - row['price']) / row.get('tick_size', 0.01)) + 1
            elif row['price'] == row['bid']:
                return 1
            else:
                return 0

    merged['aggression_level'] = merged.apply(get_levels_swept, axis=1)
    merged['is_aggressive'] = merged['aggression_level'] >= 1
    return merged

