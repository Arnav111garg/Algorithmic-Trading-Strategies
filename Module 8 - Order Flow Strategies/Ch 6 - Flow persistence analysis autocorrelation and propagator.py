import numpy as np
import pandas as pd
from scipy.optimize import curve_fit
import warnings

# Long-Memory Tests
def compute_hurst_exponent(
    series: np.ndarray,
    min_lag: int = 2,
    max_lag: int = 100
) -> float:
    """
    Estimate Hurst exponent using R/S analysis.
    """
    lags = range(min_lag, max_lag + 1)
    rs_vals = []

    for lag in lags:
        # Split series into blocks of size lag
        n_blocks = len(series) // lag
        if n_blocks < 2:
            continue

        rs_block = []
        for b in range(n_blocks):
            block = series[b * lag : (b + 1) * lag]
            mean_b = np.mean(block)
            cumdev = np.cumsum(block - mean_b)
            R = np.max(cumdev) - np.min(cumdev)
            S = np.std(block, ddof=1)
            if S > 0:
                rs_block.append(R / S)

        if rs_block:
            rs_vals.append((lag, np.mean(rs_block)))

    if len(rs_vals) < 3:
        return np.nan

    lags_arr, rs_arr = zip(*rs_vals)
    log_lags = np.log(lags_arr)
    log_rs = np.log(rs_arr)
    H, _ = np.polyfit(log_lags, log_rs, 1)
    return H


def flow_autocorrelation(
    directions: np.ndarray,
    max_lag: int = 500
) -> tuple:
    """
    Compute autocorrelation function of order flow signs.
    Returns lags, ACF, and power-law fit.
    """
    n = len(directions)
    acf_vals = []
    mean_d = np.mean(directions)
    var_d = np.var(directions)

    for lag in range(1, min(max_lag + 1, n // 10)):
        cov = np.mean((directions[: n - lag] - mean_d) * (directions[lag:] - mean_d))
        acf_vals.append(cov / var_d)

    lags = np.arange(1, len(acf_vals) + 1)

    # Fit power law : C * lag^(-gamma)
    def power_law(x, C, gamma):
        return C * np.power(x, -gamma)

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        try:
            popt, _ = curve_fit(power_law, lags, acf_vals, p0=[0.1, 0.5])
            C_fit, gamma_fit = popt
        except RuntimeError:
            C_fit, gamma_fit = np.nan, np.nan

    return lags, np.array(acf_vals), C_fit, gamma_fit


def fit_propagator(
    prices: np.ndarray,
    directions: np.ndarray,
    sizes: np.ndarray,
    max_lag: int = 100
) -> np.ndarray:
    """
    Estimate the propagator G(lag) using the empirical price impact
    response function.
    G(lag) = E[delta_p_{n+lag} * epsilon_n] / E[epsilon_n^2]
    """
    epsilon = directions * np.sqrt(np.abs(sizes))  # size-adjusted flow

    G = np.zeros(max_lag + 1)
    dp = np.diff(prices)  # price changes between consecutive trades
    var_eps = np.var(epsilon)

    for lag in range(max_lag + 1):
        if lag == 0:
            # G(0) : price change at same trade
            G[0] = np.mean(dp[: len(epsilon) - 1] * epsilon[:-1]) / var_eps
        else:
            n = len(epsilon) - lag
            G[lag] = np.mean(dp[lag : lag + n] * epsilon[:n]) / var_eps

    return G


def flow_momentum_signal(
    oir: pd.Series,
    lookback: int = 30,
    decay: float = 0.1
) -> pd.Series:
    """
    Exponentially-weighted flow momentum signal.
    """
    return oir.ewm(span=lookback).mean()


# Demonstration
def demo_flow_persistence(n_trades: int = 5000):
    """
    Simulate order flow with long memory and demonstrate persistence.
    Uses ARFIMA (0, d, 0) process for long-memory.
    """
    from scipy.signal import fftconvolve

    # Generate long-memory noise via fractional differencing (simplified)
    d = 0.3  # fractional difference parameter, H = d + 0.5 = 0.8
    k = np.arange(1, n_trades)
    frac_diff_coefs = np.concatenate([[1], np.cumprod((k - 1 - d) / k)])

    iid_noise = np.random.choice([-1, 1], size=2 * n_trades)
    long_mem = fftconvolve(iid_noise, frac_diff_coefs)[:n_trades]
    directions = np.sign(long_mem).astype(int)

    H = compute_hurst_exponent(directions.astype(float))
    lags, acf, C, gamma = flow_autocorrelation(directions)

    return {
        'hurst': H,
        'gamma': gamma,
        'C': C,
        'acf_lag1': acf[0] if len(acf) > 0 else np.nan,
        'n_trades': n_trades
    }

