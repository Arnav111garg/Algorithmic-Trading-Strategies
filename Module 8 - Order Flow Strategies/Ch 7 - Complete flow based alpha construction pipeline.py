import numpy as np
import pandas as pd
from scipy import stats
import warnings

class FlowAlphaEngine:
    """
    Production-quality flow-based alpha generation engine.
    """
    def __init__(
        self,
        cofi_window: int = 50,
        vpin_window: int = 100,
        decay_alpha: float = 0.05
    ):
        self.cofi_window = cofi_window
        self.vpin_window = vpin_window
        self.decay_alpha = decay_alpha

    def compute_all_signals(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Compute all flow-based alpha signals.
        df: DataFrame with columns [OIR, price, buy_vol, sell_vol,
        total_vol, direction, qty]
        """
        out = df.copy()

        # Signal 1: COFI
        out['COFI'] = df['OIR'].rolling(self.cofi_window).sum()
        out['COFI_z'] = (out['COFI'] - out['COFI'].rolling(200).mean()) / (out['COFI'].rolling(200).std() + 1e-10)

        # Signal 2: OFI Acceleration
        out['OIR_ewm'] = df['OIR'].ewm(span=10).mean()
        out['ACC'] = out['OIR_ewm'].diff()
        out['ACC_z'] = out['ACC'] / (out['ACC'].rolling(100).std() + 1e-10)

        # Signal 3: Flow-Price Divergence
        out['ret'] = df['price'].pct_change()
        out['flow_sign'] = np.sign(df['OIR'])
        out['price_sign'] = np.sign(out['ret'])
        out['FPD'] = out['flow_sign'] - out['price_sign']

        # Signal 4: VPIN Proxy
        out['abs_oi'] = (df['buy_vol'] - df['sell_vol']).abs()
        out['VPIN'] = out['abs_oi'].rolling(self.vpin_window).sum() / df['total_vol'].rolling(self.vpin_window).sum()
        out['VPIN_pctile'] = out['VPIN'].rank(pct=True)
        out['high_info'] = (out['VPIN_pctile'] > 0.5).astype(float)

        # Signal 5: VPIN-conditioned momentum
        out['VM'] = out['COFI_z'] * out['high_info']

        # Composite Signal
        # Standardize each component
        for col in ['COFI_z', 'ACC_z', 'FPD', 'VM']:
            mu = out[col].rolling(500).mean()
            sig = out[col].rolling(500).std()
            out[f'{col}_norm'] = (out[col] - mu) / (sig + 1e-10)

        weights = np.array([0.35, 0.25, 0.15, 0.25])
        signal_cols = ['COFI_z_norm', 'ACC_z_norm', 'FPD_norm', 'VM_norm']

        available = [c for c in signal_cols if c in out.columns]
        composite = sum(weights[i] * out[c] for i, c in enumerate(available) if not out[c].isna().all())
        out['composite_alpha'] = composite

        return out

    def compute_ic_decay(
        self,
        signals: pd.DataFrame,
        signal_col: str,
        max_horizon: int = 100
    ) -> pd.Series:
        """
        Compute IC at multiple forward horizons to measure signal decay.
        """
        ic_dict = {}
        price = signals['price']
        alpha = signals[signal_col].dropna()

        for h in range(1, max_horizon + 1):
            fwd_ret = price.pct_change(h).shift(-h)
            common = alpha.index.intersection(fwd_ret.dropna().index)
            if len(common) < 30:
                continue
            ic, p_val = stats.pearsonr(alpha[common], fwd_ret[common])
            ic_dict[h] = ic

        return pd.Series(ic_dict)

    def backtest_signal(
        self,
        signals: pd.DataFrame,
        signal_col: str,
        holding_periods: int = 5,
        n_quantiles: int = 5
    ) -> dict:
        """
        Simple quantile-based signal backtest.
        """
        df = signals.copy()
        df['fwd_ret'] = df['price'].pct_change(holding_periods).shift(-holding_periods)
        df = df.dropna(subset=[signal_col, 'fwd_ret'])

        # Assign quantiles
        df['quantile'] = pd.qcut(
            df[signal_col],
            q=n_quantiles,
            labels=False,
            duplicates='drop'
        )

        # Mean return by quantile
        qt_returns = df.groupby('quantile')['fwd_ret'].agg(['mean', 'std', 'count'])

        # Long-short portfolio : top vs bottom quantile
        top = df[df['quantile'] == df['quantile'].max()]['fwd_ret']
        bottom = df[df['quantile'] == df['quantile'].min()]['fwd_ret']

        ls_returns = top.values[:min(len(top), len(bottom))] - bottom.values[:min(len(top), len(bottom))]
        ic, _ = stats.pearsonr(df[signal_col], df['fwd_ret'])

        return {
            'IC': ic,
            'IR': np.mean(ls_returns) / (np.std(ls_returns) + 1e-10),
            'LS_mean_return': np.mean(ls_returns),
            'LS_sharpe': np.mean(ls_returns) / (np.std(ls_returns) + 1e-10) * np.sqrt(252),
            'quantile_returns': qt_returns.to_dict()
        }


# Multi-Asset Flow Alpha with Cross-Sectional Ranking
def cross_sectional_flow_alpha(
    universe: dict,
    lookback: int = 20
) -> pd.Series:
    """
    Cross-sectional flow alpha: rank stocks by their OIR relative to the universe.

    universe : { ticker : DataFrame with 'OIR' column }
    Returns : Series indexed by ticker with z-scored alpha values
    """
    oir_means = {}
    for ticker, df in universe.items():
        recent = df['OIR'].tail(lookback)
        oir_means[ticker] = recent.mean()

    oir_series = pd.Series(oir_means)

    # Cross-sectional z-score
    alpha = (oir_series - oir_series.mean()) / (oir_series.std() + 1e-10)
    return alpha.sort_values(ascending=False)

