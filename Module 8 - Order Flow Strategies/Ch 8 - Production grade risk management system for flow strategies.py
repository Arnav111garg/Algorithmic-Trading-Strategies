import numpy as np
import pandas as pd
from dataclasses import dataclass, field
from typing import Dict, Optional
from enum import Enum

class RiskStatus(Enum):
    GREEN = "green"
    YELLOW = "yellow"  # Reduce size
    RED = "red"        # No new positions
    BLACK = "black"    # Exit all positions immediately

@dataclass
class RiskLimits:
    max_position_shares: float = 10_000.0
    max_position_dollars: float = 1_000_000.0
    max_drawdown_dollars: float = 50_000.0
    max_daily_loss: float = 25_000.0
    max_orders_per_sec: float = 10.0
    max_spread_bps: float = 20.0
    max_position_pct_adv: float = 0.05  # 5% of ADV
    vpin_yellow_pctile: float = 0.75
    vpin_red_pctile: float = 0.90
    vpin_black_pctile: float = 0.95
    kelly_fraction: float = 0.25

@dataclass
class StrategyState:
    position: float = 0.0
    cash: float = 0.0
    peak_pnl: float = 0.0
    daily_pnl: float = 0.0
    n_orders_window: int = 0
    last_order_ts: float = 0.0
    order_timestamps: list = field(default_factory=list)
    status: RiskStatus = RiskStatus.GREEN

class FlowRiskManager:
    """
    Production risk manager for order flow strategies.
    Implements pre-trade checks, VPIN-based scaling, and real-time monitoring.
    """
    def __init__(self, limits: RiskLimits):
        self.limits = limits
        self.state = StrategyState()
        self.risk_log: list = []

    def check_order(
        self,
        order_size: float,
        order_price: float,
        direction: int,
        current_spread_bps: float,
        vpin_percentile: float,
        current_adv: float,
        timestamp: float
    ) -> dict:
        """
        Run all pre-trade checks. Returns decision dict.
        """
        checks = {}
        blocked = False
        block_reason = []

        # 1. VPIN-based status
        if vpin_percentile > self.limits.vpin_black_pctile:
            self.state.status = RiskStatus.BLACK
            blocked = True
            block_reason.append(f"VPIN={vpin_percentile:.3f} > BLACK threshold")
        elif vpin_percentile > self.limits.vpin_red_pctile:
            self.state.status = RiskStatus.RED
            blocked = True
            block_reason.append(f"VPIN={vpin_percentile:.3f} > RED threshold")
        elif vpin_percentile > self.limits.vpin_yellow_pctile:
            self.state.status = RiskStatus.YELLOW
        else:
            self.state.status = RiskStatus.GREEN

        # 2. Spread check
        if current_spread_bps > self.limits.max_spread_bps:
            blocked = True
            block_reason.append(f"Spread={current_spread_bps:.1f}bps > max={self.limits.max_spread_bps}bps")

        # 3. Position limit check
        new_pos = self.state.position + direction * order_size
        if abs(new_pos) > self.limits.max_position_shares:
            blocked = True
            block_reason.append(f"Position={new_pos:.0f} > max={self.limits.max_position_shares:.0f}")

        # 4. Dollar position check
        new_pos_dollars = abs(new_pos) * order_price
        if new_pos_dollars > self.limits.max_position_dollars:
            blocked = True
            block_reason.append(f"DollarPos=${new_pos_dollars:,.0f} > max=${self.limits.max_position_dollars:,.0f}")

        # 5. Drawdown check
        current_pnl = self.state.daily_pnl
        if current_pnl < -self.limits.max_daily_loss:
            blocked = True
            block_reason.append(f"DailyLoss=${abs(current_pnl):,.0f} > max=${self.limits.max_daily_loss:,.0f}")

        # 6. Order rate check (sliding window)
        self.state.order_timestamps = [
            ts for ts in self.state.order_timestamps
            if timestamp - ts <= 1.0
        ]
        if len(self.state.order_timestamps) >= self.limits.max_orders_per_sec:
            blocked = True
            block_reason.append(f"OrderRate={len(self.state.order_timestamps)}/s > max={self.limits.max_orders_per_sec}/s")

        # 7. ADV concentration check
        if current_adv > 0:
            pos_as_pct_adv = abs(new_pos) / current_adv
            if pos_as_pct_adv > self.limits.max_position_pct_adv:
                blocked = True
                block_reason.append(f"PosAsADV%={pos_as_pct_adv:.3f} > max={self.limits.max_position_pct_adv:.3f}")

        # 8. Compute size-adjusted order (VPIN scaling)
        vpin_scalar = self._vpin_risk_scalar(vpin_percentile)
        adjusted_size = order_size * vpin_scalar

        # 9. Kelly-based size recommendation
        kelly_size = order_size * self.limits.kelly_fraction
        final_size = min(adjusted_size, kelly_size)

        decision = {
            'allowed': not blocked,
            'block_reasons': block_reason,
            'original_size': order_size,
            'adjusted_size': final_size if not blocked else 0.0,
            'vpin_scalar': vpin_scalar,
            'risk_status': self.state.status.value,
            'timestamp': timestamp
        }

        if not blocked:
            self.state.order_timestamps.append(timestamp)

        self.risk_log.append(decision)
        return decision

    def _vpin_risk_scalar(self, vpin_percentile: float) -> float:
        """Compute VPIN-based position size scalar."""
        if vpin_percentile <= self.limits.vpin_yellow_pctile:
            return 1.0
        elif vpin_percentile <= self.limits.vpin_red_pctile:
            # Linear decay from 1.0 to 0.1
            t = (vpin_percentile - self.limits.vpin_yellow_pctile) / (self.limits.vpin_red_pctile - self.limits.vpin_yellow_pctile)
            return 1.0 - 0.9 * t
        else:
            return 0.0

    def update_pnl(self, trade_pnl: float, timestamp: float):
        """Update P&L after a fill."""
        self.state.daily_pnl += trade_pnl
        self.state.peak_pnl = max(self.state.peak_pnl, self.state.daily_pnl)
        current_dd = self.state.peak_pnl - self.state.daily_pnl

        if current_dd > self.limits.max_drawdown_dollars:
            self.state.status = RiskStatus.BLACK
            self.risk_log.append({
                'event': 'DRAWDOWN_BREACH',
                'drawdown': current_dd,
                'timestamp': timestamp
            })

    def get_risk_report(self) -> dict:
        """Generate current risk status summary."""
        return {
            'status': self.state.status.value,
            'position': self.state.position,
            'daily_pnl': self.state.daily_pnl,
            'peak_pnl': self.state.peak_pnl,
            'drawdown': self.state.peak_pnl - self.state.daily_pnl,
            'n_risk_events': len([e for e in self.risk_log if not e.get('allowed', True)])
        }

