import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import chi2

class InstitutionalFlowDetector:
    """
    Detect and characterize institutional execution programmes
    from order flow data.
    """
    def __init__(
        self,
        consistency_window: int = 50,
        round_lot_sizes: list = None,
        min_programme_size_adv: float = 0.002
    ):
        self.consistency_window = consistency_window
        self.round_lot_sizes = round_lot_sizes or [100, 500, 1000, 5000, 10000]
        self.min_programme_size = min_programme_size_adv

    def directional_consistency(self, oir: pd.Series) -> pd.Series:
        """
        CDIR: fraction of recent bars with positive OIR.
        Values near 1 or 0 suggest institutional one-way flow.
        """
        positive = (oir > 0).astype(float)
        return positive.rolling(self.consistency_window).mean()

    def round_lot_intensity(self, trade_sizes: pd.Series) -> pd.Series:
        """
        Measure excess mass at round lot sizes (institutional footprint).
        """
        def round_lot_fraction(window):
            if len(window) == 0:
                return 0.0
            is_round = window.apply(
                lambda q: any(abs(q - lot) < 5 for lot in self.round_lot_sizes)
            )
            return is_round.mean()
        return trade_sizes.rolling(self.consistency_window).apply(round_lot_fraction, raw=False)

    def intraday_volume_deviation(
        self,
        volumes: pd.Series,
        time_of_day: pd.Series,
        normal_profile: pd.Series
    ) -> pd.Series:
        """
        Detect systematic volume anomalies vs expected intraday profile.
        normal_profile: average volume per minute-of-day
        """
        # Map current volume to expected
        expected = time_of_day.map(normal_profile.to_dict())
        deviation = (volumes - expected) / (expected + 1e-10)
        return deviation.rolling(20).mean()

    def fit_ac_trajectory(
        self,
        cum_signed_flow: np.ndarray,
        time_grid: np.ndarray
    ) -> dict:
        """
        Fit Almgren-Chriss trajectory to observed cumulative signed flow.
        Estimates: X (programme size), kappa (risk-aversion parameter),
        T (programme duration).
        """
        t = time_grid
        T = t[-1]

        def ac_trajectory(t_arr, X, kappa, T_end):
            """Almgren-Chriss optimal inventory trajectory."""
            # Remaining inventory at time t
            denom = np.sinh(kappa * T_end)
            if abs(denom) < 1e-10:
                return X * (1 - t_arr / T_end)  # TWAP limit
            return X * np.sinh(kappa * (T_end - t_arr)) / denom

        def residuals(params):
            X, kappa, T_end = params
            if T_end <= 0 or kappa < 0 or X < 0:
                return 1e10
            pred = X - ac_trajectory(t, X, kappa, T_end)
            return np.sum((cum_signed_flow - pred) ** 2)

        # Initial guess
        X0 = cum_signed_flow[-1]
        p0 = [abs(X0), 0.3, T]

        try:
            result = minimize(
                residuals, p0, method='Nelder-Mead',
                options={'maxiter': 1000, 'xatol': 1e-4}
            )
            X_fit, kappa_fit, T_fit = result.x

            pred = X_fit - ac_trajectory(t, X_fit, kappa_fit, T_fit)
            ss_res = np.sum((cum_signed_flow - pred) ** 2)
            ss_tot = np.sum((cum_signed_flow - np.mean(cum_signed_flow)) ** 2)
            r2 = 1 - ss_res / (ss_tot + 1e-10)

            # High R2 + realistic kappa = institutional programme detected
            is_institutional = (r2 > 0.85) and (0.01 < kappa_fit < 5.0)

            return {
                'programme_size': X_fit,
                'kappa': kappa_fit,
                'programme_duration': T_fit,
                'r2': r2,
                'is_institutional': is_institutional,
                'completion_pct': cum_signed_flow[-1] / (X_fit + 1e-10)
            }
        except Exception as e:
            return {'is_institutional': False, 'error': str(e)}

    def compute_dark_flow_ratio(
        self,
        all_trades: pd.DataFrame,
        mid: pd.Series,
        tol_bps: float = 0.5
    ) -> pd.Series:
        """
        Identify dark pool prints and compute DVFR.
        Dark prints: trades at or near midpoint, size > top-of-book.
        """
        df = all_trades.copy()
        if 'mid' not in df.columns:
            df['mid'] = mid

        # Dark pool proxy : at-mid trades
        tol = df['mid'] * tol_bps / 10000
        df['is_dark'] = (df['price'] - df['mid']).abs() <= tol
        rolling_dark = (df['volume'] * df['is_dark']).rolling(50).sum()
        rolling_total = df['volume'].rolling(50).sum()

        dvfr = rolling_dark / (rolling_total + 1e-10)
        return dvfr

    def institutional_composite_score(
        self,
        oir: pd.Series,
        trade_sizes: pd.Series,
        volumes: pd.Series,
        time_of_day: pd.Series = None,
        normal_profile: pd.Series = None
    ) -> pd.Series:
        """
        Combine multiple institutional flow signals into one score.
        """
        cdir = self.directional_consistency(oir).abs()
        rlint = self.round_lot_intensity(trade_sizes)

        # Normalize each component
        def normalize(s):
            return (s - s.rolling(500).mean()) / (s.rolling(500).std() + 1e-10)

        score = 0.5 * normalize(cdir) + 0.5 * normalize(rlint)
        return score


# Worked Example : Front-Running Institutional VWAP
def institutional_front_run_strategy(
    bars: pd.DataFrame,
    detector: InstitutionalFlowDetector,
    risk_manager
) -> pd.DataFrame:
    """
    Strategy that enters positions in the direction of detected institutional flow
    and exits when the programme appears complete.
    """
    df = bars.copy()
    df['CDIR'] = detector.directional_consistency(df['OIR'])
    df['inst_score'] = detector.institutional_composite_score(
        df['OIR'],
        df['trade_size'] if 'trade_size' in df else df['total_volume'],
        df['total_volume']
    )

    df['signal'] = 0.0
    df['position'] = 0.0

    for i in range(100, len(df)):
        row = df.iloc[i]

        # Entry : strong institutional signal
        if row['CDIR'] > 0.80 and row['inst_score'] > 1.5:
            df.loc[df.index[i], 'signal'] = 1.0  # Long
        elif row['CDIR'] < 0.20 and row['inst_score'] > 1.5:
            df.loc[df.index[i], 'signal'] = -1.0  # Short

        # Exit : CDIR reverts to neutral
        elif 0.40 < row['CDIR'] < 0.60:
            df.loc[df.index[i], 'signal'] = 0.0
        else:
            df.loc[df.index[i], 'signal'] = df['signal'].iloc[i - 1]

    df['position'] = df['signal'].shift(1)
    df['ret'] = df['close'].pct_change()
    df['strategy_ret'] = df['position'] * df['ret']

    return df[['signal', 'position', 'ret', 'strategy_ret', 'CDIR', 'inst_score']]

