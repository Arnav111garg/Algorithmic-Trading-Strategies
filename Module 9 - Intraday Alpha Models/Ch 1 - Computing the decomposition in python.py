import pandas as pd
import numpy as np

def session_returns(bars: pd.DataFrame) -> pd.DataFrame:
    """
    bars : DataFrame indexed by timestamp , columns [ 'open','high','low','close' ] , one row per minute , for a single liquid ticker , RTH only (9:30 -16:00 ET).
    Returns a DataFrame indexed by date with overnight / intraday log returns .
    """
    bars = bars.sort_index()
    bars['date'] = bars.index.date
    daily = bars.groupby('date').agg(
        open_px=('open', 'first'),
        close_px=('close', 'last')
    )
    daily['prev_close'] = daily['close_px'].shift(1)
    daily['r_overnight'] = np.log(daily['open_px'] / daily['prev_close'])
    daily['r_intraday'] = np.log(daily['close_px'] / daily['open_px'])
    daily['r_total'] = daily['r_overnight'] + daily['r_intraday']
    return daily.dropna()

