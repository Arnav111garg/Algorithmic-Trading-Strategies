import numpy as np
import pandas as pd

def capacity_curve(
    aum_grid: np.ndarray,
    target_participation: float,
    adv_dollars: float,
    sigma_daily: float,
    Y: float,
    gross_edge_bps: float,
    decay_half_aum: float = None
) -> pd.DataFrame:
    """
    aum_grid : candidate AUM levels (in dollars) to evaluate.
    target_participation : fraction of ADV the strategy trades per day at this AUM
                           (i.e., implied order size as a fraction of ADV).
    adv_dollars : average daily dollar volume of the traded universe.
    sigma_daily : average daily volatility (decimal, e.g. 0.015 for 1.5%).
    Y: square-root law calibration constant.
    gross_edge_bps : average gross (no-impact) per-trade edge in basis points.
    decay_half_aum : if provided, gross edge is halved every time AUM doubles past
                     this level (simple crowding-decay proxy; set None to ignore).
    """
    rows = []
    for aum in aum_grid:
        q_over_v = target_participation * (aum / adv_dollars)
        impact_bps = 2 * Y * sigma_daily * np.sqrt(max(q_over_v, 0.0)) * 1e4

        edge = gross_edge_bps
        if decay_half_aum:
            doublings = np.log2(max(aum / decay_half_aum, 1.0))
            edge = gross_edge_bps * (0.5 ** max(doublings, 0.0))

        net_edge = edge - impact_bps
        rows.append({
            'aum': aum,
            'gross_edge_bps': edge,
            'impact_bps': impact_bps,
            'net_edge_bps': net_edge
        })
    return pd.DataFrame(rows)

