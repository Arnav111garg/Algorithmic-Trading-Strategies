import numpy as np
import pandas as pd

def intraday_momentum_signal(
    bars: pd.DataFrame,
    vol_lookback_days: int = 20,
    entry_z: float = 1.0,
    exit_z: float = 0.2,
    cost_bps: float = 1.0
) -> pd.DataFrame:
    """
    bars : 1-min RTH bars , single name/future , columns [ 'open','high','low','close','volume' ].
    Builds a z-scored momentum-since-open signal and a simple threshold trading rule.
    """
    bars = bars.copy()
    bars['date'] = bars.index.date
    bars['minute_of_day'] = bars.groupby('date').cumcount()
    bars['day_open'] = bars.groupby('date')['open'].transform('first')
    bars['ret_since_open'] = np.log(bars['close'] / bars['day_open'])

    # Time-of-day seasonal vol: std of ret_since_open at each minute index,
    # estimated from a trailing window of prior days (no look-ahead).
    bars['minute_idx'] = bars.groupby('date').cumcount()
    seasonal_vol = (
        bars.groupby('minute_idx')['ret_since_open']
        .apply(lambda s: s.shift(1).rolling(vol_lookback_days).std())
    )
    bars['seasonal_vol'] = seasonal_vol.reset_index(level=0, drop=True)
    bars['z'] = bars['ret_since_open'] / bars['seasonal_vol'].replace(0, np.nan)

    # Simple long / flat / short threshold rule with hysteresis (enter at |z| > entry_z,
    # exit only once |z| < exit_z) to avoid churn from noisy in/out flips.
    pos = np.zeros(len(bars))
    state = 0
    for i, z in enumerate(bars['z'].values):
        if np.isnan(z):
            pos[i] = state
            continue
        if state == 0 and z > entry_z:
            state = 1
        elif state == 0 and z < -entry_z:
            state = -1
        elif state != 0 and abs(z) < exit_z:
            state = 0
        pos[i] = state
    bars['position'] = pos

    bars['fwd_ret'] = bars['close'].shift(-1) / bars['close'] - 1
    bars['turnover'] = bars['position'].diff().abs().fillna(0)
    bars['pnl_bps'] = bars['position'] * bars['fwd_ret'] * 1e4 - bars['turnover'] * cost_bps

    return bars

