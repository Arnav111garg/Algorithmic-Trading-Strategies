import numpy as np
import pandas as pd

def fit_ou_params(x: np.ndarray, dt: float) -> tuple[float, float]:
    """
    AR(1)-based OU parameter estimation : x_t = x_{t-1} e^{-kappa dt} + noise.
    Returns (kappa, half_life_in_same_units_as_dt).
    """
    x_lag, x_now = x[:-1], x[1:]
    # OLS of x_now on x_lag (no intercept , assuming long-run mean 0)
    phi = np.dot(x_lag, x_now) / np.dot(x_lag, x_lag)
    phi = np.clip(phi, 1e-6, 0.999999)  # guard against explosive / degenerate fits
    kappa = -np.log(phi) / dt
    half_life = np.log(2) / kappa
    return kappa, half_life

def vwap_reversion_signal(bars: pd.DataFrame, lookback: int = 60) -> pd.Series:
    """
    bars : 1-min bars with ['close','volume']. Rolling intraday VWAP (reset daily)
    used as the fair-value anchor ; signal = -zscore(close - vwap).
    """
    bars = bars.copy()
    bars['date'] = bars.index.date
    pv = bars['close'] * bars['volume']
    bars['cum_pv'] = pv.groupby(bars['date']).cumsum()
    bars['cum_vol'] = bars['volume'].groupby(bars['date']).cumsum()
    bars['vwap'] = bars['cum_pv'] / bars['cum_vol']
    bars['dev'] = np.log(bars['close'] / bars['vwap'])
    bars['dev_z'] = (bars['dev'] - bars['dev'].rolling(lookback).mean()) / bars['dev'].rolling(lookback).std()
    return -bars['dev_z']  # negative deviation -> long signal

