import numpy as np
import pandas as pd

def atr(bars: pd.DataFrame, window: int = 14) -> pd.Series:
    high, low, close = bars['high'], bars['low'], bars['close']
    prev_close = close.shift(1)
    tr = pd.concat([
        high - low,
        (high - prev_close).abs(),
        (low - prev_close).abs()
    ], axis=1).max(axis=1)
    return tr.rolling(window).mean()

def vol_breakout_signal(
    bars: pd.DataFrame,
    atr_window: int = 30,
    m: float = 1.5,
    vol_confirm_mult: float = 1.3
) -> pd.Series:
    """
    bars : 1-min bars with OHLCV , multi-day , single name .
    Long when close breaks m*ATR above a trailing reference AND volume
    confirms ( current bar volume > vol_confirm_mult * trailing avg volume ).
    """
    bars = bars.copy()
    bars['atr'] = atr(bars, atr_window)
    bars['ref'] = bars['close'].rolling(atr_window).mean().shift(1)  # no look-ahead
    bars['upper'] = bars['ref'] + m * bars['atr']
    bars['lower'] = bars['ref'] - m * bars['atr']
    bars['avg_vol'] = bars['volume'].rolling(atr_window).mean().shift(1)

    vol_confirm = bars['volume'] > vol_confirm_mult * bars['avg_vol']

    long_signal = (bars['close'] > bars['upper']) & vol_confirm
    short_signal = (bars['close'] < bars['lower']) & vol_confirm
    sig = pd.Series(0, index=bars.index)
    sig[long_signal] = 1
    sig[short_signal] = -1
    return sig

