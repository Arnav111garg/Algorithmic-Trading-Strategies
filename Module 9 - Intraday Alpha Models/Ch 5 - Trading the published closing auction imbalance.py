import numpy as np
import pandas as pd

def imbalance_signal(
    imbalance_pct: pd.Series,
    price_path_5min: pd.Series,
    z_window: int = 60
) -> pd.Series:
    """
    imbalance_pct : published net imbalance as a % of round -lot eligible volume ,
    sampled every update from ~15:50 to 15:59:50 ET.
    price_path_5min : contemporaneous mid - price changes in the same window , used
    only for diagnostic purposes (NOT as a backtest exit price --
    you must model your actual achievable fill at/ near the close ).
    Returns a z- scored " follow the imbalance " signal : long if strong net buy
    imbalance , short if strong net sell imbalance .
    """
    z = (imbalance_pct - imbalance_pct.rolling(z_window).mean()) / imbalance_pct.rolling(z_window).std()
    return z.clip(-3, 3)  # winsorize extreme prints ( data errors , late corrections )

