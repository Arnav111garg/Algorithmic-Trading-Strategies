import numpy as np
import pandas as pd

def seasonal_vol_curve(bars: pd.DataFrame, lookback_days: int = 60) -> pd.Series:
    """
    bars : 1-min RTH bars , multi-day , single instrument , column 'close'.
    Returns, for each minute-of-day index, the trailing-lookback median absolute
    1-min log return (robust to outlier days like FOMC, earnings, flash moves).
    """
    bars = bars.copy()
    bars['date'] = bars.index.date
    bars['logret'] = np.log(bars['close']).groupby(bars['date']).diff()
    bars['minute_idx'] = bars.groupby('date').cumcount()

    def trailing_robust_vol(s: pd.Series) -> pd.Series:
        # shift(1) ensures today's bar never sees today's own contribution
        return s.shift(1).rolling(lookback_days).apply(
            lambda w: 1.4826 * np.median(np.abs(w - np.median(w)))
        ) # MAD -> sigma

    curve = bars.groupby('minute_idx')['logret'].apply(trailing_robust_vol)
    return curve.reset_index(level=0, drop=True)

