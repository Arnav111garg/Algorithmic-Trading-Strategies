import pandas as pd
import numpy as np

EVENT_VOL_MULTIPLIERS = {
    'FOMC': 2.6,
    'NFP': 2.1,
    'CPI': 2.3,
    'EARNINGS': 3.5,
    'DEFAULT': 1.0
}

def event_adjusted_size(
    base_signal: float,
    base_vol: float,
    minutes_to_event: float,
    event_type: str,
    window_minutes: int = 30
) -> float:
    """
    Shrinks (or, for momentum/post-news continuation strategies, could amplify)
    position size as a function of proximity to a known scheduled event.

    Conservative default here: shrink size ahead of the event, since most
    pre-event positioning is pure binary-outcome risk, not alpha.
    """
    mult = EVENT_VOL_MULTIPLIERS.get(event_type, EVENT_VOL_MULTIPLIERS['DEFAULT'])
    if abs(minutes_to_event) <= window_minutes:
        risk_scalar = 1.0 / mult  # de-lever into known event vol expansion
    else:
        risk_scalar = 1.0
    return base_signal * risk_scalar

