import json

EXTRACTION_PROMPT = """
You are a financial analyst assistant . Read the earnings call excerpt and
respond ONLY with a JSON object with these fields :
{
" guidance_direction ": " raised " | " lowered " | " maintained " | " unclear ",
" guidance_vs_consensus ": " above " | " below " | " in_line " | " unclear ",
" magnitude_pct ": <float or null > ,
" key_risk_flags ": [ < short strings >] ,
" confidence ": <float 0 -1 , your own confidence in this extraction >
}
Do not include any text outside the JSON object .
Excerpt :
---
{ transcript_excerpt }
---
"""

def structured_extraction_to_signal(llm_json: dict, confidence_floor: float = 0.7) -> float:
    """
    Converts a ( validated ) LLM structured extraction into a bounded trading
    signal in [ -1 , 1]. Returns 0.0 (no trade ) below the confidence floor --
    this gate is the single most important risk control in the pipeline .
    """
    if llm_json.get("confidence", 0.0) < confidence_floor:
        return 0.0

    direction_map = {"raised": 1.0, "lowered": -1.0, "maintained": 0.0, "unclear": 0.0}
    vs_consensus_map = {"above": 1.0, "below": -1.0, "in_line": 0.0, "unclear": 0.0}

    direction_val = llm_json.get("guidance_direction", "").strip()
    vs_consensus_val = llm_json.get("guidance_vs_consensus", "").strip()

    base = 0.5 * direction_map.get(direction_val, 0.0) + 0.5 * vs_consensus_map.get(vs_consensus_val, 0.0)
    mag = llm_json.get("magnitude_pct") or 0.0
    return float(max(-1.0, min(1.0, base * (1 + min(abs(mag), 10.0) / 10.0))))

